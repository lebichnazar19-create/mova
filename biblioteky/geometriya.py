"""Бібліотека «геометрія» — геометрія на площині (0.8; з 1.5 — бібліотека).

У програмі: підключи("геометрія"). Дає тип Точка(x, y) — незмінне
значення з полями x, y, друкується як (3, 4); арифметика у ВМ: а + б,
а - б, точка * число, число * точка, точка / число, -точка, а == б
(з допуском 1e-9) — і дії вимірювання/перетворення/прямих нижче.

Усі кути — в градусах, проти годинникової стрілки від осі x. Усі
перетворення повертають нову Точку (або новий список точок), не міняючи
стару. Помилки — ПомилкаВиконання з поясненням.

Імена, що збігаються з іншими режимами (кут — креслення, зсунь — ескіз,
довжина — мовна), розрізняються за кількістю/типом аргументів — див.
СПІЛЬНІ внизу і yadro/biblioteka.py; «поверни» — ключове слово мови,
тому обертання зветься оберни().
"""

import math

from yadro.biblioteka import Значення
from yadro.errors import ПомилкаВиконання

ДОПУСК = 1e-9


def _чисто(v):
    """Прибрати шум обчислень: 3.0000000000000004 -> 3, 0.1+0.2 -> 0.3."""
    if isinstance(v, bool):
        raise ПомилкаВиконання("Координата точки має бути числом, а не логічним значенням.")
    if isinstance(v, int):
        return v
    if isinstance(v, float):
        r = round(v, 9)
        if r == int(r) and abs(r) < 1e15:
            return int(r)
        return r
    raise ПомилкаВиконання(f"Координата точки має бути числом, а не {_тип(v)}.")


def _тип(x):
    from yadro.vm import _тип_укр
    return _тип_укр(x)


class Точка(Значення):
    __slots__ = ("x", "y")
    ТИП = "Точка"
    ПОЛЯ = ("x", "y")

    def __init__(self, x, y):
        object.__setattr__(self, "x", _чисто(x))
        object.__setattr__(self, "y", _чисто(y))

    def __setattr__(self, імя, значення):
        raise ПомилкаВиконання(
            "Точка незмінна: замість «т.x = …» створи нову — Точка(…, т.y), зсунь(т, dx, dy) тощо."
        )

    def __eq__(self, інша):
        # список [x, y] теж вважається тією самою точкою — креслення й ескіз
        # історично працювали зі списками, і старі програми/тести їх порівнюють
        if isinstance(інша, (list, tuple)) and len(інша) == 2:
            try:
                інша = Точка(інша[0], інша[1])
            except ПомилкаВиконання:
                return False
        return (
            isinstance(інша, Точка)
            and abs(self.x - інша.x) <= ДОПУСК
            and abs(self.y - інша.y) <= ДОПУСК
        )

    def __getitem__(self, i):
        """т[0] / т[1] — як у списку [x, y] (сумісність зі старими програмами)."""
        if i in (0, -2):
            return self.x
        if i in (1, -1):
            return self.y
        raise ПомилкаВиконання(f"У Точки є лише т[0] (x) і т[1] (y), індексу {до_рядка_індексу(i)} немає.")

    def __setitem__(self, i, значення):
        raise ПомилкаВиконання("Точка незмінна: замість «т[0] = …» створи нову Точка(x, y).")

    def __len__(self):
        return 2

    def __iter__(self):
        yield self.x
        yield self.y

    def __hash__(self):
        return hash((round(self.x, 9), round(self.y, 9)))

    def __repr__(self):
        return f"({self.x}, {self.y})"

    # арифметику VM віддає операторам Python (yadro/biblioteka.py:Значення);
    # помилки типів — звідси, з поясненням
    def __add__(self, інша):
        if not isinstance(інша, Точка):
            raise ПомилкаВиконання(f"Не можна скласти Точку і {_тип(інша)} — точку можна додати лише до точки.")
        return Точка(self.x + інша.x, self.y + інша.y)

    def __radd__(self, інша):
        raise ПомилкаВиконання(f"Не можна скласти {_тип(інша)} і Точку — точку можна додати лише до точки.")

    def __sub__(self, інша):
        if not isinstance(інша, Точка):
            raise ПомилкаВиконання(f"Не можна відняти {_тип(інша)} від Точки — від точки можна відняти лише точку.")
        return Точка(self.x - інша.x, self.y - інша.y)

    def __rsub__(self, інша):
        raise ПомилкаВиконання(f"Не можна відняти Точку від {_тип(інша)} — від точки можна відняти лише точку.")

    def __mul__(self, k):
        if isinstance(k, bool) or not isinstance(k, (int, float)):
            raise ПомилкаВиконання(f"Не можна помножити Точку на {_тип(k)} — множник має бути числом.")
        return Точка(self.x * k, self.y * k)

    __rmul__ = __mul__

    def __truediv__(self, k):
        if isinstance(k, bool) or not isinstance(k, (int, float)):
            raise ПомилкаВиконання(f"Не можна поділити Точку на {_тип(k)} — дільник має бути числом.")
        if k == 0:
            raise ПомилкаВиконання("Ділення точки на нуль.")
        return Точка(self.x / k, self.y / k)

    def __rtruediv__(self, інше):
        raise ПомилкаВиконання(f"Не можна поділити {_тип(інше)} на Точку.")

    def __neg__(self):
        return Точка(-self.x, -self.y)


def до_рядка_індексу(i):
    return repr(i) if isinstance(i, str) else str(i)


def є_точка(x):
    return isinstance(x, Точка)


def xy(значення, назва="точка"):
    """(x, y) з Точки або списку [x, y] — для креслення/ескізу, які приймають
    обидві форми. Інакше — ПомилкаВиконання з поясненням."""
    if isinstance(значення, Точка):
        return значення.x, значення.y
    if isinstance(значення, (list, tuple)) and len(значення) == 2:
        x, y = значення
        for к in (x, y):
            if isinstance(к, bool) or not isinstance(к, (int, float)):
                raise ПомилкаВиконання(f"«{назва}» має бути Точкою або списком [x, y] з чисел.")
        return x, y
    raise ПомилкаВиконання(f"«{назва}» має бути Точкою (Точка(x, y)) або списком [x, y], а не {_тип(значення)}.")


def _точка(x, дія, що="точку"):
    if not isinstance(x, Точка):
        raise ПомилкаВиконання(f"«{дія}» очікує {що} (Точка(x, y)), а отримала {_тип(x)}.")
    return x


def _число(x, дія, що="число"):
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        raise ПомилкаВиконання(f"«{дія}» очікує число як {що}, а отримала {_тип(x)}.")
    return x


def _точка_або_список(x, дія):
    """Для перетворень: одна точка -> False, список точок -> True."""
    if isinstance(x, list):
        for е in x:
            _точка(е, дія, "точку в списку")
        return True
    _точка(x, дія)
    return False


# ---- 1. вимірювання ---------------------------------------------------------

def точка(x, y):
    return Точка(x, y)


def довжина(т):
    """Відстань від початку координат (0, 0)."""
    _точка(т, "довжина")
    return _чисто(math.hypot(т.x, т.y))


def відстань(а, б):
    _точка(а, "відстань", "першу точку")
    _точка(б, "відстань", "другу точку")
    return _чисто(math.hypot(б.x - а.x, б.y - а.y))


def середина(а, б):
    _точка(а, "середина", "першу точку")
    _точка(б, "середина", "другу точку")
    return Точка((а.x + б.x) / 2, (а.y + б.y) / 2)


def кут(а, б):
    """Кут напрямку від а до б у градусах від осі x (0..360)."""
    _точка(а, "кут", "першу точку")
    _точка(б, "кут", "другу точку")
    if а == б:
        raise ПомилкаВиконання("«кут» між однаковими точками не визначений.")
    г = math.degrees(math.atan2(б.y - а.y, б.x - а.x)) % 360
    return _чисто(г)


def полярні(радіус, кут_град):
    _число(радіус, "полярні", "радіус")
    _число(кут_град, "полярні", "кут у градусах")
    р = math.radians(кут_град)
    return Точка(радіус * math.cos(р), радіус * math.sin(р))


# ---- 2. перетворення ---------------------------------------------------------

def зсунь(т, dx, dy):
    _число(dx, "зсунь", "dx")
    _число(dy, "зсунь", "dy")
    if _точка_або_список(т, "зсунь"):
        return [Точка(е.x + dx, е.y + dy) for е in т]
    return Точка(т.x + dx, т.y + dy)


def оберни(т, кут_град, навколо=None):
    """Обертання на кут (градуси, проти годинникової) навколо точки
    (типово — початку координат)."""
    _число(кут_град, "оберни", "кут у градусах")
    ц = Точка(0, 0) if навколо is None else _точка(навколо, "оберни", "точку-центр")
    р = math.radians(кут_град)
    c, s = math.cos(р), math.sin(р)

    def одна(е):
        dx, dy = е.x - ц.x, е.y - ц.y
        return Точка(ц.x + dx * c - dy * s, ц.y + dx * s + dy * c)

    if _точка_або_список(т, "оберни"):
        return [одна(е) for е in т]
    return одна(т)


def масштабуй(т, k, навколо=None):
    _число(k, "масштабуй", "коефіцієнт")
    ц = Точка(0, 0) if навколо is None else _точка(навколо, "масштабуй", "точку-центр")

    def одна(е):
        return Точка(ц.x + (е.x - ц.x) * k, ц.y + (е.y - ц.y) * k)

    if _точка_або_список(т, "масштабуй"):
        return [одна(е) for е in т]
    return одна(т)


# ---- 3. прямі й перетини -------------------------------------------------------

def _пряма(а, б, дія):
    _точка(а, дія, "першу точку прямої")
    _точка(б, дія, "другу точку прямої")
    if а == б:
        raise ПомилкаВиконання(f"«{дія}»: дві точки прямої збігаються ({а}) — пряма не визначена.")


def перетин_прямих(а1, а2, б1, б2):
    """Точка перетину прямих (а1 а2) і (б1 б2) або ніщо, якщо паралельні."""
    _пряма(а1, а2, "перетин_прямих")
    _пряма(б1, б2, "перетин_прямих")
    d1x, d1y = а2.x - а1.x, а2.y - а1.y
    d2x, d2y = б2.x - б1.x, б2.y - б1.y
    знам = d1x * d2y - d1y * d2x
    if abs(знам) <= ДОПУСК * max(1.0, abs(d1x) + abs(d1y)) * max(1.0, abs(d2x) + abs(d2y)):
        return None
    t = ((б1.x - а1.x) * d2y - (б1.y - а1.y) * d2x) / знам
    return Точка(а1.x + t * d1x, а1.y + t * d1y)


def перпендикуляр(а, б, т):
    """Основа перпендикуляра з точки т на пряму (а б)."""
    _пряма(а, б, "перпендикуляр")
    _точка(т, "перпендикуляр", "точку")
    dx, dy = б.x - а.x, б.y - а.y
    t = ((т.x - а.x) * dx + (т.y - а.y) * dy) / (dx * dx + dy * dy)
    return Точка(а.x + t * dx, а.y + t * dy)


def відстань_до_прямої(т, а, б):
    _точка(т, "відстань_до_прямої", "точку")
    _пряма(а, б, "відстань_до_прямої")
    dx, dy = б.x - а.x, б.y - а.y
    return _чисто(abs(dx * (т.y - а.y) - dy * (т.x - а.x)) / math.hypot(dx, dy))


def паралельна(а, б, відступ):
    """Пара точок прямої, паралельної (а б), зсунутої на відступ ліворуч
    від напрямку а->б (від'ємний відступ — праворуч)."""
    _пряма(а, б, "паралельна")
    _число(відступ, "паралельна", "відступ")
    dx, dy = б.x - а.x, б.y - а.y
    д = math.hypot(dx, dy)
    nx, ny = -dy / д * відступ, dx / д * відступ
    return [Точка(а.x + nx, а.y + ny), Точка(б.x + nx, б.y + ny)]


def перетин_кола_з_прямою(центр, r, а, б):
    """Список із 0, 1 або 2 точок перетину кола (центр, r) з прямою (а б)."""
    _точка(центр, "перетин_кола_з_прямою", "центр кола")
    _число(r, "перетин_кола_з_прямою", "радіус")
    if r < 0:
        raise ПомилкаВиконання("«перетин_кола_з_прямою»: радіус не може бути від'ємним.")
    _пряма(а, б, "перетин_кола_з_прямою")
    основа = перпендикуляр(а, б, центр)
    h = math.hypot(основа.x - центр.x, основа.y - центр.y)
    if h > r + ДОПУСК:
        return []
    if abs(h - r) <= ДОПУСК:
        return [основа]
    dx, dy = б.x - а.x, б.y - а.y
    д = math.hypot(dx, dy)
    ux, uy = dx / д, dy / д
    l = math.sqrt(max(r * r - h * h, 0.0))
    return [Точка(основа.x - ux * l, основа.y - uy * l), Точка(основа.x + ux * l, основа.y + uy * l)]


