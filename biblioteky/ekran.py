"""Бібліотека «екран» — малювання на полотні застосунку (1.5).

У програмі: підключи("екран"). Полотно — те саме, що показує креслення в
застосунках, зроблених із програми (vidzhety.ПолотноКреслення через
polotno.py); другого полотна немає. Координати — пікселі, (0, 0) — лівий
верхній кут, y росте вниз (як у екран()/полотно()); розмір дає застосунок
(ширина(), висота()). Дії лише накопичують фігури, а онови() показує
накопичене; очисти() — прибрати все.

Якщо застосунок не запущений (REPL, термінал, тести) — режим симуляції,
як у плати: нічого не падає, розмір типовий (ТИПОВИЙ_РОЗМІР), онови()
складає кадри в список КАДРИ (останні КАДРІВ_МАКС), щоб тести бачили,
що показав би застосунок.

Застосунок під'єднується через задати_показ(показ, розмір): показ(кадр)
отримує словник у форматі drafting.для_екрана() (ширина, висота, фон,
лінії, фігури; Y вгору), розмір() повертає (ширина, висота) полотна в
пікселях. zapusk.виконати_код робить це сам (при_кресленні, розмір_екрана).

Спільні імена: коло(x, y, r) і лінія(x1, y1, x2, y2) — тут; з кольором
(4 і 6 аргументів) — малювання у SVG (yadro/drawing.py), як і раніше.
"""

from yadro import drawing
from yadro.errors import ПомилкаВиконання

ТИПОВИЙ_РОЗМІР = (360, 480)   # симуляція: полотна немає
ФОН = "#FFFFFF"
ЧОРНИЙ = "#000000"
ШИРИНА_ЛІНІЇ_PX = 2           # стала в пікселях, як контур креслення
КАДРІВ_МАКС = 100

_показ = None          # callable(кадр) — застосунок малює кадр на полотні
_розмір_екрана = None  # callable() -> (ширина, висота) у пікселях
_розмір = None         # (ширина, висота) — визначається при першому зверненні
_колір = ЧОРНИЙ
_фігури = []
КАДРИ = []             # симуляція: кадри, які показав би застосунок


def скинути():
    """Новий запуск: без фігур, чорний колір, без полотна (симуляція)."""
    global _показ, _розмір_екрана, _розмір, _колір
    _показ = None
    _розмір_екрана = None
    _розмір = None
    _колір = ЧОРНИЙ
    _фігури.clear()
    КАДРИ.clear()


def задати_показ(показ, розмір=None):
    """Під'єднати полотно застосунку: показ(кадр) і розмір() -> (ш, в)."""
    global _показ, _розмір_екрана, _розмір
    _показ = показ
    _розмір_екрана = розмір
    _розмір = None


def є_полотно():
    return _показ is not None


# ---- допоміжне -------------------------------------------------------------

def _тип(x):
    from yadro.vm import _тип_укр
    return _тип_укр(x)


def _число(x, дія, що):
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        raise ПомилкаВиконання(f"«{дія}»: {що} має бути числом, а не {_тип(x)}.")
    return x


def _невідʼємне(x, дія, що):
    _число(x, дія, що)
    if x < 0:
        raise ПомилкаВиконання(f"«{дія}»: {що} не може бути від'ємним ({x}).")
    return x


def _розмір_полотна():
    """(ширина, висота): від застосунку або типовий у симуляції."""
    global _розмір
    if _розмір is None:
        розмір = None
        if _розмір_екрана is not None:
            try:
                розмір = _розмір_екрана()
            except Exception:
                розмір = None
        if розмір is not None:
            ш, в = int(розмір[0]), int(розмір[1])
            розмір = (ш, в) if ш >= 1 and в >= 1 else None
        _розмір = розмір or ТИПОВИЙ_РОЗМІР
    return _розмір


def _додати(фігура):
    фігура["колір"] = _колір
    _фігури.append(фігура)
    return None


def _прямокутник(x, y, ш, в, дія, залитий):
    _число(x, дія, "x")
    _число(y, дія, "y")
    _число(ш, дія, "ширина")
    _число(в, дія, "висота")
    if ш < 0:          # від'ємна ширина — прямокутник ліворуч від x
        x, ш = x + ш, -ш
    if в < 0:
        y, в = y + в, -в
    return _додати({"тип": "прямокутник", "x": x, "y": y, "ш": ш, "в": в,
                    "залитий": залитий, "ширина_px": ШИРИНА_ЛІНІЇ_PX})


def _коло(x, y, r, дія, залитий):
    _число(x, дія, "x")
    _число(y, дія, "y")
    _невідʼємне(r, дія, "радіус")
    return _додати({"тип": "коло", "cx": x, "cy": y, "r": r, "залитий": залитий, "ширина_px": ШИРИНА_ЛІНІЇ_PX})


# ---- дії мови ----------------------------------------------------------------

def ширина():
    return _розмір_полотна()[0]


def висота():
    return _розмір_полотна()[1]


def колір(червоний, зелений=None, синій=None):
    """колір(ч, з, с) — складові 0..255; або колір("синій") / колір("#FF00AA")."""
    global _колір
    if isinstance(червоний, str) and зелений is None and синій is None:
        _колір = drawing._колір(червоний)
        return None
    складові = []
    for назва, з in (("червоний", червоний), ("зелений", зелений), ("синій", синій)):
        if isinstance(з, bool) or not isinstance(з, (int, float)):
            raise ПомилкаВиконання(
                f"«колір» очікує три числа від 0 до 255 (червоний, зелений, синій) або назву кольору, "
                f"а {назва} — {_тип(з)}."
            )
        if not 0 <= з <= 255:
            raise ПомилкаВиконання(f"«колір»: {назва} має бути від 0 до 255, а не {з}.")
        складові.append(int(round(з)))
    _колір = "#{:02X}{:02X}{:02X}".format(*складові)
    return None


def крапка(x, y):
    _число(x, "крапка", "x")
    _число(y, "крапка", "y")
    return _додати({"тип": "прямокутник", "x": x, "y": y, "ш": 1, "в": 1, "залитий": True})


def лінія(x1, y1, x2, y2):
    for назва, з in (("x1", x1), ("y1", y1), ("x2", x2), ("y2", y2)):
        _число(з, "лінія", назва)
    return _додати({"тип": "лінія", "точки": [x1, y1, x2, y2], "ширина_px": ШИРИНА_ЛІНІЇ_PX})


def прямокутник(x, y, ш, в):
    return _прямокутник(x, y, ш, в, "прямокутник", False)


def заливка(x, y, ш, в):
    return _прямокутник(x, y, ш, в, "заливка", True)


def коло(x, y, r):
    return _коло(x, y, r, "коло", False)


def круг(x, y, r):
    return _коло(x, y, r, "круг", True)


def очисти():
    _фігури.clear()
    return None


def кадр():
    """Накопичене у форматі полотна (drafting.для_екрана(), Y вгору)."""
    ш, в = _розмір_полотна()
    фігури = []
    for ф in _фігури:
        ф = dict(ф)
        if ф["тип"] == "прямокутник":
            ф["y"] = в - ф["y"] - ф["в"]
        elif ф["тип"] == "коло":
            ф["cy"] = в - ф["cy"]
        elif ф["тип"] == "лінія":
            x1, y1, x2, y2 = ф["точки"]
            ф["точки"] = [x1, в - y1, x2, в - y2]
        фігури.append(ф)
    return {"ширина": ш, "висота": в, "фон": ФОН, "лінії": ЧОРНИЙ, "фігури": фігури}


def онови():
    """Показати намальоване: на полотні застосунку або (симуляція) у КАДРИ."""
    к = кадр()
    if _показ is not None:
        _показ(к)
    else:
        КАДРИ.append(к)
        del КАДРИ[:-КАДРІВ_МАКС]
    return None


