"""Компілятор: AST -> байткод для стекової VM.

Формат результату описаний у ТЗ (розділ 5):
    {"версія": 1, "константи": [...], "код": [[опкод, аргумент], ...]}

Опкоди ADD/SUB/.../CALL/CALL_NATIVE/HALT — точно за ТЗ. Додатково введені
(бо потрібні для дій і списків, яких немає в мінімальному наборі ТЗ):
    MAKE_FUNCTION [ім'я, параметри, адреса_тіла]  — реєструє дію
    MAKE_LIST     кількість_елементів             — збирає список зі стека
    INDEX_GET / INDEX_SET                         — робота з елементом списку
"""

from . import аст as А
from .вбудовані import ІМЕНА_NATIVE
from .помилки import ПомилкаКомпіляції

_БІНАРНІ_ОПКОДИ = {
    "+": "ADD", "-": "SUB", "*": "MUL", "/": "DIV", "%": "MOD",
    "==": "EQ", "!=": "NEQ", "<": "LT", ">": "GT", "<=": "LTE", ">=": "GTE",
}
_ЛОГІЧНІ_ОПКОДИ = {"і": "AND", "або": "OR"}


class Компілятор:
    def __init__(self):
        self.константи = []
        self.код = []
        self.позиції = []        # [рядок, позиція] для кожної інструкції в self.код — для повідомлень VM
        self.цикли = []          # стек активних циклів: {"перерви": [...], "продовж": [...]}
        self.сталі_поточні = set()
        self.глибина_дій = 0
        self._лічильник_тимч = 0
        self._поточний_рядок = 0
        self._поточна_кол = 0

    # ---- допоміжне -------------------------------------------------------

    def _константа(self, значення):
        for i, наявна in enumerate(self.константи):
            if type(наявна) is type(значення) and наявна == значення:
                return i
        self.константи.append(значення)
        return len(self.константи) - 1

    def _emit(self, опкод, аргумент=None):
        self.код.append([опкод, аргумент])
        self.позиції.append([self._поточний_рядок, self._поточна_кол])
        return len(self.код) - 1

    def _тут(self):
        return len(self.код)

    def _патч(self, idx, ціль):
        self.код[idx][1] = ціль

    def _помилка(self, повідомлення, вузол):
        raise ПомилкаКомпіляції(повідомлення, getattr(вузол, "рядок", 0), getattr(вузол, "позиція", 0))

    # ---- вхідна точка ------------------------------------------------------

    def компілювати(self, програма: А.Програма):
        for інстр in програма.тіло:
            self._інструкція(інстр)
        self._emit("HALT", None)
        return {
            "версія": 1,
            "константи": self.константи,
            "код": self.код,
            "позиції": self.позиції,
        }

    # ---- інструкції ----------------------------------------------------------

    def _інструкція(self, вузол):
        self._поточний_рядок = getattr(вузол, "рядок", self._поточний_рядок)
        self._поточна_кол = getattr(вузол, "позиція", self._поточна_кол)
        тип = type(вузол)
        обробник = getattr(self, f"_і_{тип.__name__}", None)
        if обробник is None:
            self._помилка(f"Компілятор не вміє обробляти вузол {тип.__name__}", вузол)
        обробник(вузол)

    def _і_Хай(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)
        self.сталі_поточні.discard(вузол.імя)

    def _і_Стала(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)
        self.сталі_поточні.add(вузол.імя)

    def _і_Присвоєння(self, вузол):
        if вузол.імя in self.сталі_поточні:
            self._помилка(f"Не можна змінити сталу «{вузол.імя}»", вузол)
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)

    def _і_ПрисвоєнняІндекс(self, вузол):
        self._вираз(вузол.колекція)
        self._вираз(вузол.індекс)
        self._вираз(вузол.вираз)
        self._emit("INDEX_SET", None)

    def _і_ВиразІнструкція(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("POP", None)

    def _і_Якщо(self, вузол):
        self._вираз(вузол.умова)
        jf = self._emit("JUMP_FALSE", None)
        for s in вузол.тіло:
            self._інструкція(s)
        if вузол.інакше is None:
            self._патч(jf, self._тут())
            return
        j_кінець = self._emit("JUMP", None)
        self._патч(jf, self._тут())
        if isinstance(вузол.інакше, list):
            for s in вузол.інакше:
                self._інструкція(s)
        else:
            self._інструкція(вузол.інакше)  # вкладений Якщо — «інакше якщо»
        self._патч(j_кінець, self._тут())

    def _і_Поки(self, вузол):
        старт = self._тут()
        self._вираз(вузол.умова)
        jf = self._emit("JUMP_FALSE", None)
        self.цикли.append({"перерви": [], "продовж": []})
        for s in вузол.тіло:
            self._інструкція(s)
        цикл = self.цикли.pop()
        self._emit("JUMP", старт)
        кінець = self._тут()
        self._патч(jf, кінець)
        for idx in цикл["перерви"]:
            self._патч(idx, кінець)
        for idx in цикл["продовж"]:
            self._патч(idx, старт)

    def _і_Для(self, вузол):
        n = self._лічильник_тимч
        self._лічильник_тимч += 1
        список_var = f"@список_{n}"
        індекс_var = f"@індекс_{n}"

        self._вираз(вузол.ітерований)
        self._emit("STORE_VAR", список_var)
        self._emit("PUSH_CONST", self._константа(0))
        self._emit("STORE_VAR", індекс_var)

        старт = self._тут()
        self._emit("PUSH_VAR", індекс_var)
        self._emit("PUSH_VAR", список_var)
        self._emit("CALL_NATIVE", ["довжина", 1])
        self._emit("LT", None)
        jf = self._emit("JUMP_FALSE", None)

        self._emit("PUSH_VAR", список_var)
        self._emit("PUSH_VAR", індекс_var)
        self._emit("INDEX_GET", None)
        self._emit("STORE_VAR", вузол.імя)

        self.цикли.append({"перерви": [], "продовж": []})
        for s in вузол.тіло:
            self._інструкція(s)
        цикл = self.цикли.pop()

        продовж_ціль = self._тут()
        self._emit("PUSH_VAR", індекс_var)
        self._emit("PUSH_CONST", self._константа(1))
        self._emit("ADD", None)
        self._emit("STORE_VAR", індекс_var)
        self._emit("JUMP", старт)

        кінець = self._тут()
        self._патч(jf, кінець)
        for idx in цикл["перерви"]:
            self._патч(idx, кінець)
        for idx in цикл["продовж"]:
            self._патч(idx, продовж_ціль)

    def _і_Перервись(self, вузол):
        if not self.цикли:
            self._помилка("«перервись» використано поза циклом", вузол)
        idx = self._emit("JUMP", None)
        self.цикли[-1]["перерви"].append(idx)

    def _і_Продовж(self, вузол):
        if not self.цикли:
            self._помилка("«продовж» використано поза циклом", вузол)
        idx = self._emit("JUMP", None)
        self.цикли[-1]["продовж"].append(idx)

    def _і_Дія(self, вузол):
        if вузол.імя in ІМЕНА_NATIVE:
            self._помилка(
                f"Не можна оголосити дію «{вузол.імя}»: це ім'я вже зайняте "
                f"вбудованою функцією. Оберіть інше ім'я для власної дії.",
                вузол,
            )
        зробити = self._emit("MAKE_FUNCTION", [вузол.імя, list(вузол.параметри), None])
        j = self._emit("JUMP", None)
        старт_тіла = self._тут()
        self.код[зробити][1][2] = старт_тіла

        попередні_сталі, попередні_цикли, попередня_глибина = (
            self.сталі_поточні, self.цикли, self.глибина_дій
        )
        self.сталі_поточні, self.цикли = set(), []
        self.глибина_дій += 1

        for s in вузол.тіло:
            self._інструкція(s)

        self.глибина_дій = попередня_глибина
        self.цикли = попередні_цикли
        self.сталі_поточні = попередні_сталі

        # неявне «поверни ніщо», якщо тіло дії доходить до кінця
        self._emit("PUSH_CONST", self._константа(None))
        self._emit("RETURN", None)
        self._патч(j, self._тут())

    def _і_Поверни(self, вузол):
        if self.глибина_дій == 0:
            self._помилка("«поверни» використано поза дією", вузол)
        if вузол.вираз is not None:
            self._вираз(вузол.вираз)
        else:
            self._emit("PUSH_CONST", self._константа(None))
        self._emit("RETURN", None)

    # ---- вирази ------------------------------------------------------------

    def _вираз(self, вузол):
        self._поточний_рядок = getattr(вузол, "рядок", self._поточний_рядок)
        self._поточна_кол = getattr(вузол, "позиція", self._поточна_кол)
        тип = type(вузол)
        обробник = getattr(self, f"_в_{тип.__name__}", None)
        if обробник is None:
            self._помилка(f"Компілятор не вміє обробляти вираз {тип.__name__}", вузол)
        обробник(вузол)

    def _в_ЧислоЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_РядокЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_БулЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_НіщоЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(None))

    def _в_СписокЛіт(self, вузол):
        for е in вузол.елементи:
            self._вираз(е)
        self._emit("MAKE_LIST", len(вузол.елементи))

    def _в_Змінна(self, вузол):
        self._emit("PUSH_VAR", вузол.імя)

    def _в_Унарний(self, вузол):
        self._вираз(вузол.операнд)
        self._emit("NEG" if вузол.оп == "-" else "NOT", None)

    def _в_Бінарний(self, вузол):
        self._вираз(вузол.ліво)
        self._вираз(вузол.право)
        self._emit(_БІНАРНІ_ОПКОДИ[вузол.оп], None)

    def _в_Логічний(self, вузол):
        self._вираз(вузол.ліво)
        self._вираз(вузол.право)
        self._emit(_ЛОГІЧНІ_ОПКОДИ[вузол.оп], None)

    def _в_Індекс(self, вузол):
        self._вираз(вузол.колекція)
        self._вираз(вузол.індекс)
        self._emit("INDEX_GET", None)

    def _в_Виклик(self, вузол):
        for а in вузол.аргументи:
            self._вираз(а)
        if вузол.імя in ІМЕНА_NATIVE:
            self._emit("CALL_NATIVE", [вузол.імя, len(вузол.аргументи)])
        else:
            self._emit("CALL", [вузол.імя, len(вузол.аргументи)])


def компілювати(програма: А.Програма):
    return Компілятор().компілювати(програма)
