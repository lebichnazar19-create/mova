"""Парсер: перетворює потік токенів на AST."""

from .лексер import токенізувати
from .помилки import ПомилкаРозбору
from . import аст as А


class Парсер:
    def __init__(self, токени, рядки_джерела=None):
        self.токени = токени
        self.і = 0
        self.рядки_джерела = рядки_джерела or []

    # ---- допоміжне -----------------------------------------------------

    def _поточний(self):
        return self.токени[self.і]

    def _пік(self, зсув=1):
        j = self.і + зсув
        if j < len(self.токени):
            return self.токени[j]
        return self.токени[-1]

    def _далі(self):
        tok = self.токени[self.і]
        if tok.тип != "КІНЕЦЬ":
            self.і += 1
        return tok

    def _збіг(self, *типи):
        if self._поточний().тип in типи:
            return self._далі()
        return None

    def _текст_рядка(self, номер):
        if 1 <= номер <= len(self.рядки_джерела):
            return self.рядки_джерела[номер - 1]
        return ""

    def _помилка(self, повідомлення, tok=None):
        tok = tok or self._поточний()
        raise ПомилкаРозбору(повідомлення, tok.рядок, tok.позиція, self._текст_рядка(tok.рядок))

    def _очікувати(self, тип, повідомлення):
        if self._поточний().тип != тип:
            self._помилка(повідомлення)
        return self._далі()

    # ---- вхідна точка ---------------------------------------------------

    def парсити(self):
        інструкції = []
        while self._поточний().тип != "КІНЕЦЬ":
            інструкції.append(self._інструкція())
        return А.Програма(інструкції)

    def _блок(self):
        self._очікувати("ВІДСТУП_ВПЕРЕД", "Очікувався блок з відступом (наступний рядок має бути глибше)")
        інструкції = []
        while self._поточний().тип not in ("ВІДСТУП_НАЗАД", "КІНЕЦЬ"):
            інструкції.append(self._інструкція())
        self._очікувати("ВІДСТУП_НАЗАД", "Очікувалось завершення блоку (менший відступ)")
        return інструкції

    # ---- інструкції -------------------------------------------------------

    def _інструкція(self):
        tok = self._поточний()
        якщо_тип = tok.тип
        if якщо_тип == "ХАЙ":
            return self._хай_чи_стала(А.Хай, "ХАЙ")
        if якщо_тип == "СТАЛА":
            return self._хай_чи_стала(А.Стала, "СТАЛА")
        if якщо_тип == "ДІЯ":
            return self._дія()
        if якщо_тип == "ПОВЕРНИ":
            return self._поверни()
        if якщо_тип == "ЯКЩО":
            return self._якщо()
        if якщо_тип == "ПОКИ":
            return self._поки()
        if якщо_тип == "ДЛЯ":
            return self._для()
        if якщо_тип == "ПЕРЕРВИСЬ":
            self._далі()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «перервись»")
            return А.Перервись(рядок=tok.рядок, позиція=tok.позиція)
        if якщо_тип == "ПРОДОВЖ":
            self._далі()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «продовж»")
            return А.Продовж(рядок=tok.рядок, позиція=tok.позиція)

        return self._вираз_чи_присвоєння()

    def _хай_чи_стала(self, клас, тип_токена):
        tok = self._далі()  # ХАЙ / СТАЛА
        імя_tok = self._очікувати("ІМЯ", "Очікувалось ім'я змінної")
        self._очікувати("ПРИСВОЄННЯ", f"Очікувався знак «=» після імені «{імя_tok.значення}»")
        вираз = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
        return клас(імя_tok.значення, вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _вираз_чи_присвоєння(self):
        tok = self._поточний()
        вираз = self._вираз()
        if self._поточний().тип == "ПРИСВОЄННЯ":
            self._далі()
            права = self._вираз()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
            if isinstance(вираз, А.Змінна):
                return А.Присвоєння(вираз.імя, права, рядок=tok.рядок, позиція=tok.позиція)
            if isinstance(вираз, А.Індекс):
                return А.ПрисвоєнняІндекс(
                    вираз.колекція, вираз.індекс, права, рядок=tok.рядок, позиція=tok.позиція
                )
            self._помилка("Ліворуч від «=» має бути змінна або елемент списку", tok)
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
        return А.ВиразІнструкція(вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _дія(self):
        tok = self._далі()  # ДІЯ
        імя_tok = self._очікувати("ІМЯ", "Очікувалось ім'я дії")
        self._очікувати("ЛПАР", "Очікувалась «(» після імені дії")
        параметри = []
        if self._поточний().тип != "ППАР":
            параметри.append(self._очікувати("ІМЯ", "Очікувалось ім'я параметра").значення)
            while self._збіг("КОМА"):
                параметри.append(self._очікувати("ІМЯ", "Очікувалось ім'я параметра").значення)
        self._очікувати("ППАР", "Очікувалась «)»")
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після оголошення дії")
        тіло = self._блок()
        return А.Дія(імя_tok.значення, параметри, тіло, рядок=tok.рядок, позиція=tok.позиція)

    def _поверни(self):
        tok = self._далі()  # ПОВЕРНИ
        вираз = None
        if self._поточний().тип != "НОВИЙ_РЯДОК":
            вираз = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «поверни»")
        return А.Поверни(вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _якщо(self):
        tok = self._далі()  # ЯКЩО
        умова = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після умови «якщо»")
        тіло = self._блок()
        інакше = None
        if self._поточний().тип == "ІНАКШЕ":
            self._далі()
            if self._поточний().тип == "ЯКЩО":
                інакше = self._якщо()
            else:
                self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «інакше»")
                інакше = self._блок()
        return А.Якщо(умова, тіло, інакше, рядок=tok.рядок, позиція=tok.позиція)

    def _поки(self):
        tok = self._далі()  # ПОКИ
        умова = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після умови «поки»")
        тіло = self._блок()
        return А.Поки(умова, тіло, рядок=tok.рядок, позиція=tok.позиція)

    def _для(self):
        tok = self._далі()  # ДЛЯ
        імя_tok = self._очікувати("ІМЯ", "Очікувалось ім'я змінної циклу")
        self._очікувати("У", "Очікувалось «у» після імені змінної в «для»")
        ітерований = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «для ... у ...»")
        тіло = self._блок()
        return А.Для(імя_tok.значення, ітерований, тіло, рядок=tok.рядок, позиція=tok.позиція)

    # ---- вирази (за пріоритетом, знизу вгору) -----------------------------

    def _вираз(self):
        return self._або()

    def _або(self):
        ліво = self._і()
        while self._поточний().тип == "АБО":
            tok = self._далі()
            право = self._і()
            ліво = А.Логічний("або", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _і(self):
        ліво = self._не()
        while self._поточний().тип == "І":
            tok = self._далі()
            право = self._не()
            ліво = А.Логічний("і", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _не(self):
        if self._поточний().тип == "НЕ":
            tok = self._далі()
            операнд = self._не()
            return А.Унарний("не", операнд, рядок=tok.рядок, позиція=tok.позиція)
        return self._порівняння()

    _ПОРІВНЯННЯ = {
        "РІВНО": "==",
        "НЕРІВНО": "!=",
        "МЕНШЕ": "<",
        "БІЛЬШЕ": ">",
        "МЕНШЕ_РІВНО": "<=",
        "БІЛЬШЕ_РІВНО": ">=",
    }

    def _порівняння(self):
        ліво = self._додавання()
        while self._поточний().тип in self._ПОРІВНЯННЯ:
            tok = self._далі()
            право = self._додавання()
            ліво = А.Бінарний(self._ПОРІВНЯННЯ[tok.тип], ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _додавання(self):
        ліво = self._множення()
        while self._поточний().тип in ("ПЛЮС", "МІНУС"):
            tok = self._далі()
            право = self._множення()
            оп = "+" if tok.тип == "ПЛЮС" else "-"
            ліво = А.Бінарний(оп, ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _множення(self):
        ліво = self._унарний()
        while self._поточний().тип in ("ЗІРКА", "СЛЕШ", "ВІДСОТОК"):
            tok = self._далі()
            оп = {"ЗІРКА": "*", "СЛЕШ": "/", "ВІДСОТОК": "%"}[tok.тип]
            право = self._унарний()
            ліво = А.Бінарний(оп, ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _унарний(self):
        if self._поточний().тип == "МІНУС":
            tok = self._далі()
            операнд = self._унарний()
            return А.Унарний("-", операнд, рядок=tok.рядок, позиція=tok.позиція)
        return self._постфікс()

    def _постфікс(self):
        вираз = self._первинний()
        while True:
            if self._поточний().тип == "ЛДУЖКА":
                tok = self._далі()
                if self._поточний().тип == "ДВОКРАПКА":
                    # [:кінець] або [:] — початок пропущено
                    self._далі()
                    кінець = None
                    if self._поточний().тип != "ПДУЖКА":
                        кінець = self._вираз()
                    self._очікувати("ПДУЖКА", "Очікувалась «]»")
                    вираз = А.Зріз(вираз, None, кінець, рядок=tok.рядок, позиція=tok.позиція)
                else:
                    перший = self._вираз()
                    if self._поточний().тип == "ДВОКРАПКА":
                        self._далі()
                        кінець = None
                        if self._поточний().тип != "ПДУЖКА":
                            кінець = self._вираз()
                        self._очікувати("ПДУЖКА", "Очікувалась «]»")
                        вираз = А.Зріз(вираз, перший, кінець, рядок=tok.рядок, позиція=tok.позиція)
                    else:
                        self._очікувати("ПДУЖКА", "Очікувалась «]»")
                        вираз = А.Індекс(вираз, перший, рядок=tok.рядок, позиція=tok.позиція)
            else:
                break
        return вираз

    def _аргументи_виклику(self):
        аргументи = []
        self._очікувати("ЛПАР", "Очікувалась «(»")
        if self._поточний().тип != "ППАР":
            аргументи.append(self._вираз())
            while self._збіг("КОМА"):
                аргументи.append(self._вираз())
        self._очікувати("ППАР", "Очікувалась «)»")
        return аргументи

    def _первинний(self):
        tok = self._поточний()

        if tok.тип == "ЧИСЛО":
            self._далі()
            return А.ЧислоЛіт(tok.значення, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "РЯДОК":
            self._далі()
            return А.РядокЛіт(tok.значення, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ІСТИНА":
            self._далі()
            return А.БулЛіт(True, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ХИБА":
            self._далі()
            return А.БулЛіт(False, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "НІЩО":
            self._далі()
            return А.НіщоЛіт(рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ЛПАР":
            self._далі()
            вираз = self._вираз()
            self._очікувати("ППАР", "Очікувалась «)»")
            return вираз
        if tok.тип == "ЛДУЖКА":
            self._далі()
            елементи = []
            if self._поточний().тип != "ПДУЖКА":
                елементи.append(self._вираз())
                while self._збіг("КОМА"):
                    елементи.append(self._вираз())
            self._очікувати("ПДУЖКА", "Очікувалась «]»")
            return А.СписокЛіт(елементи, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип in ("ІМЯ", "ДРУКУЙ", "ПИТАЙ"):
            self._далі()
            if self._поточний().тип == "ЛПАР":
                аргументи = self._аргументи_виклику()
                return А.Виклик(tok.значення, аргументи, рядок=tok.рядок, позиція=tok.позиція)
            return А.Змінна(tok.значення, рядок=tok.рядок, позиція=tok.позиція)

        self._помилка(f"Неочікуваний символ у виразі: «{tok.значення if tok.значення is not None else tok.тип}»")


def парсити_текст(джерело):
    токени = токенізувати(джерело)
    парсер = Парсер(токени, джерело.split("\n"))
    return парсер.парсити()
