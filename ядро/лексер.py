"""Лексер: перетворює текст програми на мові «Мова» на потік токенів.

Блоки визначаються відступами (як у Python), без двокрапок і крапок з комою.
"""

from dataclasses import dataclass

from .ключові import КЛЮЧОВІ_СЛОВА
from .помилки import ПомилкаРозбору


@dataclass
class Токен:
    тип: str
    значення: object
    рядок: int
    позиція: int

    def __repr__(self):
        return f"Токен({self.тип}, {self.значення!r}, {self.рядок}:{self.позиція})"


ОДИНАРНІ_ЗНАКИ = {
    "+": "ПЛЮС",
    "-": "МІНУС",
    "*": "ЗІРКА",
    "/": "СЛЕШ",
    "%": "ВІДСОТОК",
    "(": "ЛПАР",
    ")": "ППАР",
    ",": "КОМА",
    "[": "ЛДУЖКА",
    "]": "ПДУЖКА",
    ":": "ДВОКРАПКА",
}

# знаки, які можуть бути початком дво-символьного оператора
СКЛАДЕНІ_ЗНАКИ = {
    "==": "РІВНО",
    "!=": "НЕРІВНО",
    "<=": "МЕНШЕ_РІВНО",
    ">=": "БІЛЬШЕ_РІВНО",
}

ПОРІВНЯННЯ_ОДИНАРНІ = {
    "<": "МЕНШЕ",
    ">": "БІЛЬШЕ",
    "=": "ПРИСВОЄННЯ",
}


def _цифра(ч):
    return "0" <= ч <= "9"


def _початок_ідентифікатора(ч):
    return ч.isalpha() or ч == "_"


def _продовження_ідентифікатора(ч):
    return ч.isalnum() or ч == "_"


class Лексер:
    def __init__(self, джерело):
        self.джерело = джерело
        self.рядки = джерело.split("\n")
        self.позиція = 0
        self.рядок = 1
        self.колонка = 1
        self.токени = []
        self.стек_відступів = [0]
        self.дужки_рівень = 0  # всередині ( ) [ ] переноси рядків не важливі

    def _рядок_тексту(self, номер):
        if 1 <= номер <= len(self.рядки):
            return self.рядки[номер - 1]
        return ""

    def помилка(self, повідомлення, рядок=None, позиція=None):
        рядок = рядок if рядок is not None else self.рядок
        позиція = позиція if позиція is not None else self.колонка
        raise ПомилкаРозбору(повідомлення, рядок, позиція, self._рядок_тексту(рядок))

    def _пік(self, зсув=0):
        і = self.позиція + зсув
        if і < len(self.джерело):
            return self.джерело[і]
        return ""

    def _далі(self):
        ч = self._пік()
        self.позиція += 1
        if ч == "\n":
            self.рядок += 1
            self.колонка = 1
        else:
            self.колонка += 1
        return ч

    def _додати(self, тип, значення, рядок=None, позиція=None):
        self.токени.append(Токен(тип, значення, рядок or self.рядок, позиція or self.колонка))

    def токенізувати(self):
        на_початку_рядка = True
        while self.позиція < len(self.джерело):
            if на_початку_рядка and self.дужки_рівень == 0:
                if not self._обробити_відступ():
                    continue
                на_початку_рядка = False

            ч = self._пік()
            if ч == "":
                break

            if ч == "\n":
                self._далі()
                if self.дужки_рівень == 0:
                    self._додати("НОВИЙ_РЯДОК", None)
                    на_початку_рядка = True
                continue

            if ч in " \t":
                self._далі()
                continue

            if ч == "#":
                while self._пік() not in ("\n", ""):
                    self._далі()
                continue

            if _цифра(ч):
                self._число()
                continue

            if ч in ("\"", "'"):
                self._рядок()
                continue

            if _початок_ідентифікатора(ч):
                self._ідентифікатор_або_слово()
                continue

            self._знак()

        # закрити відкриті блоки в кінці файлу
        if self.токени and self.токени[-1].тип != "НОВИЙ_РЯДОК":
            self._додати("НОВИЙ_РЯДОК", None)
        while len(self.стек_відступів) > 1:
            self.стек_відступів.pop()
            self._додати("ВІДСТУП_НАЗАД", None)
        self._додати("КІНЕЦЬ", None)
        return self.токени

    def _обробити_відступ(self):
        """Порахувати відступ поточного рядка. Повертає False, якщо рядок
        порожній/коментар і його треба просто пропустити."""
        рядок_старту = self.рядок
        рівень = 0
        зсув = 0
        while True:
            ч = self._пік(зсув)
            if ч == " ":
                рівень += 1
                зсув += 1
            elif ч == "\t":
                рівень += 8 - (рівень % 8)
                зсув += 1
            else:
                break

        # пропустити порожній рядок або рядок з коментарем — не впливає на відступ
        решта = self._пік(зсув)
        if решта in ("\n", "") or решта == "#":
            for _ in range(зсув):
                self._далі()
            if решта == "#":
                while self._пік() not in ("\n", ""):
                    self._далі()
            if self._пік() == "\n":
                self._далі()
            elif self._пік() == "":
                pass
            return False

        for _ in range(зсув):
            self._далі()

        поточний = self.стек_відступів[-1]
        if рівень > поточний:
            self.стек_відступів.append(рівень)
            self._додати("ВІДСТУП_ВПЕРЕД", None, рядок_старту, 1)
        else:
            while рівень < self.стек_відступів[-1]:
                self.стек_відступів.pop()
                self._додати("ВІДСТУП_НАЗАД", None, рядок_старту, 1)
            if рівень != self.стек_відступів[-1]:
                self.помилка("Неузгоджений відступ", рядок_старту, зсув + 1)
        return True

    def _число(self):
        рядок, поз = self.рядок, self.колонка
        текст = ""
        while _цифра(self._пік()):
            текст += self._далі()
        якщо_дробове = False
        if self._пік() == "." and _цифра(self._пік(1)):
            якщо_дробове = True
            текст += self._далі()
            while _цифра(self._пік()):
                текст += self._далі()
        значення = float(текст) if якщо_дробове else int(текст)
        self._додати("ЧИСЛО", значення, рядок, поз)

    def _рядок(self):
        рядок, поз = self.рядок, self.колонка
        лапка = self._далі()
        текст = ""
        екрановані = {"n": "\n", "t": "\t", '"': '"', "'": "'", "\\": "\\"}
        while True:
            ч = self._пік()
            if ч == "":
                self.помилка("Рядок не закрито лапкою", рядок, поз)
            if ч == лапка:
                self._далі()
                break
            if ч == "\n":
                self.помилка("Рядок не може продовжуватись на новому рядку", рядок, поз)
            if ч == "\\":
                self._далі()
                екр = self._далі()
                текст += екрановані.get(екр, екр)
                continue
            текст += self._далі()
        self._додати("РЯДОК", текст, рядок, поз)

    def _ідентифікатор_або_слово(self):
        рядок, поз = self.рядок, self.колонка
        текст = ""
        while _продовження_ідентифікатора(self._пік()):
            текст += self._далі()
        if текст in КЛЮЧОВІ_СЛОВА:
            self._додати(КЛЮЧОВІ_СЛОВА[текст], текст, рядок, поз)
        else:
            self._додати("ІМЯ", текст, рядок, поз)

    def _знак(self):
        рядок, поз = self.рядок, self.колонка
        два = self._пік() + self._пік(1)
        if два in СКЛАДЕНІ_ЗНАКИ:
            self._далі()
            self._далі()
            self._додати(СКЛАДЕНІ_ЗНАКИ[два], два, рядок, поз)
            return

        ч = self._пік()
        if ч in "([":
            self.дужки_рівень += 1
        elif ч in ")]":
            self.дужки_рівень = max(0, self.дужки_рівень - 1)

        if ч in ОДИНАРНІ_ЗНАКИ:
            self._далі()
            self._додати(ОДИНАРНІ_ЗНАКИ[ч], ч, рядок, поз)
            return
        if ч in ПОРІВНЯННЯ_ОДИНАРНІ:
            self._далі()
            self._додати(ПОРІВНЯННЯ_ОДИНАРНІ[ч], ч, рядок, поз)
            return

        self._далі()
        self.помилка(f"Невідомий символ «{ч}»", рядок, поз)


def токенізувати(джерело):
    return Лексер(джерело).токенізувати()
