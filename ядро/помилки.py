"""Спільні класи помилок мови «Мова».

Усі повідомлення — українською, з номером рядка і колонки та стрілкою під
проблемним місцем, коли відомий текст рядка джерела.
"""


class ПомилкаМови(Exception):
    ЗАГОЛОВОК = "Помилка"

    def __init__(self, повідомлення, рядок=0, позиція=0, текст_рядка=""):
        self.повідомлення = повідомлення
        self.рядок = рядок
        self.позиція = позиція
        self.текст_рядка = текст_рядка
        super().__init__(self.форматувати())

    def форматувати(self):
        if self.рядок:
            частини = [f"{self.ЗАГОЛОВОК} в рядку {self.рядок}, позиція {self.позиція}:"]
            if self.текст_рядка:
                частини.append("    " + self.текст_рядка)
                зсув = max(0, self.позиція - 1)
                частини.append("    " + " " * зсув + "^")
        else:
            частини = [f"{self.ЗАГОЛОВОК}:"]
        частини.append(self.повідомлення)
        return "\n".join(частини)

    def __str__(self):
        return self.форматувати()


class ПомилкаРозбору(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка розбору"


class ПомилкаКомпіляції(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка компіляції"


class ПомилкаВиконання(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка виконання"
