def _точка_xy(значення, назва):
    if not isinstance(значення, list) or len(значення) != 2:
        raise ПомилкаВиконання(f"«{назва}» має бути списком [x, y].")
    _число(значення[0], f"{назва}[0]")
    _число(значення[1], f"{назва}[1]")
    return значення[0], значення[1]


def виміряй(точка1, точка2):
    """Миттєва: відстань між двома точками [x, y]. Нічого не малює."""
    x1, y1 = _точка_xy(точка1, "точка1")
    x2, y2 = _точка_xy(точка2, "точка2")
    return math.hypot(x2 - x1, y2 - y1)


def виміряй_кут(точка1, вершина, точка2):
    """Миттєва: кут (у градусах, 0..180) при вершині між променями до
    точка1 і точка2. Нічого не малює."""
    x1, y1 = _точка_xy(точка1, "точка1")
    xv, yv = _точка_xy(вершина, "вершина")
    x2, y2 = _точка_xy(точка2, "точка2")
    v1x, v1y = x1 - xv, y1 - yv
    v2x, v2y = x2 - xv, y2 - yv
    if math.hypot(v1x, v1y) < 1e-9 or math.hypot(v2x, v2y) < 1e-9:
        raise ПомилкаВиконання("виміряй_кут(): точка збігається з вершиною.")
    θ1, θ2 = math.atan2(v1y, v1x), math.atan2(v2y, v2x)
    δ = ((θ2 - θ1 + math.pi) % (2 * math.pi)) - math.pi
    return abs(math.degrees(δ))


def кут(точка1, вершина, точка2, радіус):
    """Постійна: дуга з двома стрілками й значенням кута в градусах —
    число завжди береться з реальних координат (як і в розмір())."""
    _перевірити_аркуш()
    x1, y1 = _точка_xy(точка1, "точка1")
    xv, yv = _точка_xy(вершина, "вершина")
    x2, y2 = _точка_xy(точка2, "точка2")
    _число(радіус, "радіус")
    if радіус <= 0:
        raise ПомилкаВиконання("Радіус має бути додатним числом.")

    V = _до_аркуша(xv, yv)
    P1 = _до_аркуша(x1, y1)
    P2 = _до_аркуша(x2, y2)
    v1x, v1y = P1[0] - V[0], P1[1] - V[1]
    v2x, v2y = P2[0] - V[0], P2[1] - V[1]
    if math.hypot(v1x, v1y) < 1e-9 or math.hypot(v2x, v2y) < 1e-9:
        raise ПомилкаВиконання("кут(): точка збігається з вершиною.")

    θ1 = math.atan2(v1y, v1x)
    θ2 = math.atan2(v2y, v2x)
    δ = ((θ2 - θ1 + math.pi) % (2 * math.pi)) - math.pi   # (-π, π], коротший шлях
    значення = abs(math.degrees(δ))

    A = (V[0] + радіус * math.cos(θ1), V[1] + радіус * math.sin(θ1))
    B = (V[0] + радіус * math.cos(θ2), V[1] + радіус * math.sin(θ2))
    A_px, B_px = _до_px(*A), _до_px(*B)
    sweep = 1 if δ > 0 else 0
    r_px = _мм_px(радіус)

    _елементи.append(
        f'<path d="M {A_px[0]},{A_px[1]} A {r_px},{r_px} 0 0,{sweep} {B_px[0]},{B_px[1]}" '
        f'fill="none" stroke="{_аркуш["лінії"]}" stroke-width="{_мм_px(ТОВЩИНА_ТОНКА_ММ)}"/>'
    )

    def тангенс(θ, проти_годинникової):
        return (-math.sin(θ), math.cos(θ)) if проти_годинникової else (math.sin(θ), -math.cos(θ))

    вперед_ccw = δ > 0
    напрям_A = tuple(-c for c in тангенс(θ1, вперед_ccw))  # назовні = проти напряму дуги
    напрям_B = тангенс(θ2, вперед_ccw)                      # назовні = за напрямом дуги
    _елементи.append(_стрілка_polygon(A_px, _напрям_px(*напрям_A)))
    _елементи.append(_стрілка_polygon(B_px, _напрям_px(*напрям_B)))

    ТЕКСТ_ВІДСТУП_ММ = 1.0 + РОЗМІР_ШРИФТУ_ММ * 0.3
    сер_кут = θ1 + δ / 2
    сер_точка = (
        V[0] + (радіус + ТЕКСТ_ВІДСТУП_ММ) * math.cos(сер_кут),
        V[1] + (радіус + ТЕКСТ_ВІДСТУП_ММ) * math.sin(сер_кут),
    )
    сер_px = _до_px(*сер_точка)
    текст = _форматувати_число(значення) + "°"
    _елементи.append(_текст_тег(сер_px[0], сер_px[1], текст, _мм_px(РОЗМІР_ШРИФТУ_ММ)))
    return None


def виноска(x, y, текст):
    _перевірити_аркуш()
    _число(x, "x")
    _число(y, "y")
    if not isinstance(текст, str):
        raise ПомилкаВиконання("виноска() очікує рядок як текст.")

    ТОЧКА = _до_аркуша(x, y)
    КУТ = math.radians(45.0)
    dirx, diry = math.cos(КУТ), math.sin(КУТ)
    ДІАГОНАЛЬ_ММ = 8.0
    ПОЛИЦЯ_ММ = max(10.0, len(текст) * РОЗМІР_ШРИФТУ_ММ * 0.62)

    КОЛІНО = (ТОЧКА[0] + dirx * ДІАГОНАЛЬ_ММ, ТОЧКА[1] + diry * ДІАГОНАЛЬ_ММ)
    КІНЕЦЬ_ПОЛИЦІ = (КОЛІНО[0] + ПОЛИЦЯ_ММ, КОЛІНО[1])  # поличка завжди горизонтальна

    точка_px, коліно_px, кінець_px = _до_px(*ТОЧКА), _до_px(*КОЛІНО), _до_px(*КІНЕЦЬ_ПОЛИЦІ)

    _елементи.append(_лінія_px(точка_px, коліно_px, ТОВЩИНА_ТОНКА_ММ))
    _елементи.append(_лінія_px(коліно_px, кінець_px, ТОВЩИНА_ТОНКА_ММ))

    dx, dy = коліно_px[0] - точка_px[0], коліно_px[1] - точка_px[1]
    L = math.hypot(dx, dy) or 1.0
    _елементи.append(_стрілка_polygon(точка_px, (-dx / L, -dy / L)))

    текст_px = (коліно_px[0] + _мм_px(1.0), коліно_px[1] - _мм_px(1.0))
    _елементи.append(
        _текст_тег(текст_px[0], текст_px[1], текст, _мм_px(РОЗМІР_ШРИФТУ_ММ), anchor="start", baseline="alphabetic")
    )
    return None


def штамп(назва, матеріал, масштаб):
    _перевірити_аркуш()
    for нм, зн in (("назва", назва), ("матеріал", матеріал), ("масштаб", масштаб)):
        if not isinstance(зн, str):
            raise ПомилкаВиконання(f"штамп(): «{нм}» має бути рядком.")

    ліво, низ, праворуч, верх, середина_у, поділ_x = _штамп_геометрія()
    розмір_px = _мм_px(РОЗМІР_ШРИФТУ_ММ)

    px, py = _до_px((ліво + праворуч) / 2, (середина_у + верх) / 2)
    _елементи.append(_текст_тег(px, py, назва, розмір_px))

    px, py = _до_px((ліво + поділ_x) / 2, (низ + середина_у) / 2)
    _елементи.append(_текст_тег(px, py, матеріал, розмір_px))

    px, py = _до_px((поділ_x + праворуч) / 2, (низ + середина_у) / 2)
    _елементи.append(_текст_тег(px, py, масштаб, розмір_px))
    return None


