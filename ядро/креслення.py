def розмір(x1, y1, x2, y2, відступ):
    _перевірити_аркуш()
    for нм, зн in (("x1", x1), ("y1", y1), ("x2", x2), ("y2", y2), ("відступ", відступ)):
        _число(зн, нм)

    A = _до_аркуша(x1, y1)
    B = _до_аркуша(x2, y2)
    dx, dy = B[0] - A[0], B[1] - A[1]
    довжина = math.hypot(dx, dy)
    if довжина < 1e-9:
        raise ПомилкаВиконання("розмір(): початкова і кінцева точки збігаються.")
    ux, uy = dx / довжина, dy / довжина
    nx, ny = -uy, ux

    сторона = 1.0 if відступ >= 0 else -1.0
    ЗАЗОР_ММ, ПЕРЕБІГ_ММ = 1.0, 2.0

    def зсунути(точка, вел):
        return (точка[0] + nx * вел, точка[1] + ny * вел)

    A_o, B_o = зсунути(A, відступ), зсунути(B, відступ)
    вин_A1, вин_A2 = зсунути(A, ЗАЗОР_ММ * сторона), зсунути(A, відступ + ПЕРЕБІГ_ММ * сторона)
    вин_B1, вин_B2 = зсунути(B, ЗАЗОР_ММ * сторона), зсунути(B, відступ + ПЕРЕБІГ_ММ * сторона)

    p = lambda т: _до_px(*т)
    A_o_px, B_o_px = p(A_o), p(B_o)

    _елементи.append(_лінія_px(p(вин_A1), p(вин_A2), ТОВЩИНА_ТОНКА_ММ))
    _елементи.append(_лінія_px(p(вин_B1), p(вин_B2), ТОВЩИНА_ТОНКА_ММ))
    _елементи.append(_лінія_px(A_o_px, B_o_px, ТОВЩИНА_ТОНКА_ММ))
    _елементи.extend(_стрілки_обабіч_px(A_o_px, B_o_px))

    текст = _форматувати_число(довжина)
    _елементи.append(_текст_вздовж_px(A_o_px, B_o_px, текст))
    return None


def розмір_радіус(x, y, радіус):
    _перевірити_аркуш()
    _число(x, "x")
    _число(y, "y")
    _число(радіус, "радіус")
    if радіус <= 0:
        raise ПомилкаВиконання("Радіус має бути додатним числом.")

    ЦЕНТР = _до_аркуша(x, y)
    КУТ = math.radians(45.0)
    dirx, diry = math.cos(КУТ), math.sin(КУТ)
    ЗАПАС_ММ = 8.0

    точка_на_колі = (ЦЕНТР[0] + dirx * радіус, ЦЕНТР[1] + diry * радіус)
    кінець_виноски = (ЦЕНТР[0] + dirx * (радіус + ЗАПАС_ММ), ЦЕНТР[1] + diry * (радіус + ЗАПАС_ММ))

    точка_px, кінець_px = _до_px(*точка_на_колі), _до_px(*кінець_виноски)
    _елементи.append(_лінія_px(точка_px, кінець_px, ТОВЩИНА_ТОНКА_ММ))

    dx, dy = кінець_px[0] - точка_px[0], кінець_px[1] - точка_px[1]
    L = math.hypot(dx, dy) or 1.0
    _елементи.append(_стрілка_polygon(точка_px, (-dx / L, -dy / L)))

    відступ_px = _мм_px(1.0)
    текст_px = (кінець_px[0] + (dx / L) * відступ_px, кінець_px[1] + (dy / L) * відступ_px)
    текст = "R" + _форматувати_число(радіус)
    _елементи.append(_текст_тег(текст_px[0], текст_px[1], текст, _мм_px(РОЗМІР_ШРИФТУ_ММ), anchor="start"))
    return None


