"""Запуск програми мовою «Мова» з рядка тексту — без Kivy і без консолі.

Окремий від main.py, щоб цю логіку можна було тестувати на комп'ютері
без дисплея (main.py імпортує Kivy на верхньому рівні). Нічого з yadro/
не змінює: лише створює ВМ у симуляційному режимі (без_пристрою=True,
як `мова.py --без-пристрою`) і підміняє їй «питай» — на Android немає
stdin, тож замість зависання чи EOFError показуємо зрозуміле повідомлення.

Виконання можна перервати ззовні (кнопка «Стоп»): виклик отримує ВМ через
`при_старті(вм)` і з іншого потоку виставляє `вм.зупинено = True`.
"""

import io
import queue
import traceback
from contextlib import redirect_stderr, redirect_stdout

ПОВІДОМЛЕННЯ_ПИТАЙ = (
    "«питай» поки не працює в застосунку: ввід з клавіатури під час "
    "виконання ще не підтримується. Задай значення прямо в коді, "
    "наприклад: хай імя = \"Оля\""
)

ПОВІДОМЛЕННЯ_ЗУПИНЕНО = "Виконання зупинено."


def виконати_код(текст, при_старті=None, тека=None, питай=None, кнопка=None, оновити_вивід=None,
                 при_кресленні=None, розмір_екрана=None):
    """Компілює й виконує текст програми. Повертає (вивід, успіх).

    `при_кресленні(креслення)` — застосунок показує словник у форматі
    drafting.для_екрана() на полотні: після запуску — креслення (аркуш),
    а під час запуску — кадри бібліотеки «екран» з кожного онови().
    `розмір_екрана()` -> (ширина, висота) полотна в пікселях для
    ширина()/висота() тієї бібліотеки; без обох — режим симуляції
    (biblioteky/ekran.py).

    `тека` — база для відносних шляхів у файлових функціях мови
    (прочитай_файл/запиши_файл/...): у застосунку це user_data_dir.

    `питай(запит)` — як програма отримує відповідь на «питай("…")»:
    викликається в потоці виконання, має повернути рядок (застосунок
    показує поле вводу й чекає на «Надіслати»). Без нього «питай» дає
    зрозуміле повідомлення про недоступність. Запит і відповідь
    друкуються у вивід, як у консолі.

    У вивід потрапляє все, що надрукувала програма (друкуй тощо), а в разі
    помилки — і її текст після вже надрукованого. Жоден виняток звідси
    не виходить: помилки мови показуються коротко (як у консолі), інші
    винятки — з повним traceback, щоб можна було зрозуміти причину.

    `при_старті(вм)` викликається перед запуском уже скомпільованої
    програми — так викликач (main.py) отримує ВМ і може зупинити її
    (`вм.зупинено = True`) з іншого потоку."""
    буфер = io.StringIO()
    черга = queue.Queue()
    try:
        _скинути_графіку(тека)
        _підʼєднати_екран(при_кресленні, розмір_екрана)
        from yadro.errors import ПомилкаМови
        from yadro.kompilyator import компілювати
        from yadro.parser import парсити_текст
        from yadro.vm import ВМ, ВиконанняЗупинено

        байткод = компілювати(парсити_текст(текст))
        вм = ВМ(без_пристрою=True, тека_файлів=тека)
        вм._native["питай"] = _обгорнути_питай(питай) if питай is not None else _питай_недоступно
        if кнопка is not None:
            def при_кнопці(напис, імя_дії):
                кнопка(напис, lambda: черга.put(імя_дії))
            вм.при_кнопці = при_кнопці
        if при_старті is not None:
            при_старті(вм)
        with redirect_stdout(буфер), redirect_stderr(буфер):
            вм.виконати(байткод)
            _показати_креслення(при_кресленні)
            if кнопка is not None and вм.кнопки:
                _чекати_кнопок(вм, черга, буфер, оновити_вивід, при_кресленні)
        return буфер.getvalue(), True
    except Exception as e:
        _показати_креслення(при_кресленні)
        вивід = буфер.getvalue()
        if вивід and not вивід.endswith("\n"):
            вивід += "\n"
        try:
            from yadro.errors import ПомилкаМови
            from yadro.vm import ВиконанняЗупинено
            є_помилка_мови = isinstance(e, ПомилкаМови)
            є_зупинка = isinstance(e, ВиконанняЗупинено)
        except Exception:
            є_помилка_мови = є_зупинка = False
        if є_зупинка:
            вивід += ПОВІДОМЛЕННЯ_ЗУПИНЕНО + "\n"
        elif є_помилка_мови:
            вивід += str(e) + "\n"
        else:
            вивід += "Внутрішня помилка:\n" + traceback.format_exc()
        return вивід, False


def _скинути_графіку(тека):
    """Новий запуск — чистий аркуш/ескіз/малюнок; файли покажи() — у теку
    застосунку (домашня тека в APK може бути недоступна для запису)."""
    try:
        from pathlib import Path
        from yadro import biblioteka, drafting, drawing, sketch
        drafting.скинути()
        sketch.скинути()
        drawing.скинути()
        biblioteka.модуль("екран").скинути()
        if тека:
            drafting.ШЛЯХ_ФАЙЛУ = Path(тека) / "креслення.html"
            drawing.ШЛЯХ_ФАЙЛУ = Path(тека) / "малюнок.html"
    except Exception:
        pass


def _підʼєднати_екран(при_кресленні, розмір_екрана):
    """Бібліотека «екран» малює на тому самому полотні, що й креслення."""
    if при_кресленні is None:
        return
    try:
        from yadro import biblioteka
        biblioteka.модуль("екран").задати_показ(при_кресленні, розмір_екрана)
    except Exception:
        pass


def _показати_креслення(при_кресленні):
    if при_кресленні is None:
        return
    try:
        from yadro import drafting
        креслення = drafting.для_екрана()
    except Exception:
        креслення = None
    if креслення is not None:
        при_кресленні(креслення)


def _чекати_кнопок(вм, черга, буфер, оновити_вивід, при_кресленні=None):
    """Основний код виконано, кнопки є: чекати натискань, поки не «Стоп»."""
    from yadro.vm import ВиконанняЗупинено

    if оновити_вивід is not None:
        оновити_вивід(буфер.getvalue())
    while True:
        if вм.зупинено:
            raise ВиконанняЗупинено()
        try:
            імя_дії = черга.get(timeout=0.1)
        except queue.Empty:
            continue
        вм.викликати_дію(імя_дії)
        _показати_креслення(при_кресленні)
        if оновити_вивід is not None:
            оновити_вивід(буфер.getvalue())


def _питай_недоступно(*args):
    from yadro.errors import ПомилкаВиконання
    raise ПомилкаВиконання(ПОВІДОМЛЕННЯ_ПИТАЙ)


def _обгорнути_питай(питай):
    from yadro.vm import до_рядка

    def _питай(*args):
        запит = до_рядка(args[0]) if args else ""
        відповідь = питай(запит)
        if відповідь is None:
            відповідь = ""
        відповідь = str(відповідь)
        print(запит + відповідь)
        return відповідь

    return _питай
