"""Проєкти застосунку «Мова» — збережені програми за назвами. Без Kivy,
щоб логіку можна було тестувати на комп'ютері (тести/test_проєкти.py);
вікно зі списком — vikno_proektiv.py, прив'язка до редактора — main.py.

Проєкт — це файл тека_застосунку/програми/назва.мова (там само, де їх
клали старі «Зберегти»/«Відкрити», тож давні програми одразу видно у
списку). Поруч із текою «програми» лежать:
- проєкт.json — назва відкритого проєкту, щоб після перезапуску
  застосунок відкрив той самий;
- код.мова — чернетка: текст редактора після кожної зміни. Якщо
  застосунок закрили без збереження (або він упав), при наступному
  запуску чернетка потрапляє у відкритий проєкт — нічого не губиться.

Функції модуля працюють із файлами; клас Проєкти веде «відкритий
проєкт» для редактора (що відкрити при запуску, що відкрити після
видалення поточного тощо). Помилки, які треба показати людині, —
ПомилкаПроєкту з готовим текстом.
"""

import json
import re
from pathlib import Path

ТЕКА_ПРОГРАМ = "програми"
ФАЙЛ_СТАНУ = "проєкт.json"
ФАЙЛ_ЧЕРНЕТКИ = "код.мова"
РОЗШИРЕННЯ = ".мова"
ТИПОВА_НАЗВА = "Моя програма"
ПОШУК_ВІД = 10            # пошук з'являється, коли проєктів більше
МАКС_ДОВЖИНА_НАЗВИ = 60

_ЗАБОРОНЕНО_В_НАЗВІ = re.compile(r'[\\/:*?"<>|\x00-\x1f]')


class ПомилкаПроєкту(Exception):
    """Дію з проєктом не виконано; текст — пояснення для людини."""


# ---- назви -----------------------------------------------------------------

def безпечна_назва(назва):
    """Назва проєкту -> ім'я файлу без розширення: без роздільників шляху
    і службових символів, обрізана; порожня -> None."""
    назва = _ЗАБОРОНЕНО_В_НАЗВІ.sub("", (назва or "")).strip().strip(".").strip()
    if назва.endswith(РОЗШИРЕННЯ):
        назва = назва[: -len(РОЗШИРЕННЯ)].strip().strip(".").strip()
    return назва[:МАКС_ДОВЖИНА_НАЗВИ].strip() or None


def _перевірена_назва(назва):
    ім_я = безпечна_назва(назва)
    if ім_я is None:
        raise ПомилкаПроєкту("Назва порожня або непридатна — введи хоча б одну літеру.")
    return ім_я


def _тека_програм(тека):
    return Path(тека) / ТЕКА_ПРОГРАМ


def _файл(тека, назва):
    return _тека_програм(тека) / f"{назва}{РОЗШИРЕННЯ}"


def _ключ(назва):
    return назва.casefold()


_АБЕТКА = "абвгґдеєжзиіїйклмнопрстуфхцчшщьюя"


def _за_абеткою(назва):
    """Ключ сортування за українською абеткою: у Юнікоді «ґ», «є», «і»,
    «ї» стоять після «я», тож звичайне сортування ставить «Ігри» в кінець
    списку. Цифри й латинка — перед кирилицею."""
    ключ = []
    for символ in _ключ(назва):
        місце = _АБЕТКА.find(символ)
        if місце >= 0:
            ключ.append((1, місце))
        else:
            ключ.append((0 if ord(символ) < 0x400 else 2, ord(символ)))
    return ключ


# ---- список і пошук ----------------------------------------------------------

def список(тека):
    """Назви проєктів (без .мова) за українською абеткою, без огляду на
    регістр."""
    т = _тека_програм(тека)
    if not т.is_dir():
        return []
    return sorted((ф.name[: -len(РОЗШИРЕННЯ)] for ф in т.glob(f"*{РОЗШИРЕННЯ}") if ф.is_file()),
                  key=lambda н: (_за_абеткою(н), н))


def шукати(назви, запит):
    """Назви, що містять запит (без огляду на регістр); порожній запит —
    усі. Спершу ті, що з нього починаються."""
    запит = _ключ((запит or "").strip())
    if not запит:
        return list(назви)
    знайдені = [н for н in назви if запит in _ключ(н)]
    return sorted(знайдені, key=lambda н: not _ключ(н).startswith(запит))


def потрібен_пошук(назви):
    return len(назви) > ПОШУК_ВІД


def _наявна(тека, назва):
    """Назва наявного проєкту, що збігається з цією без огляду на регістр
    («гра» і «Гра» — одна назва: так їх не сплутати у списку), або None."""
    ключ = _ключ(назва)
    for н in список(тека):
        if _ключ(н) == ключ:
            return н
    return None


def існує(тека, назва):
    ім_я = безпечна_назва(назва)
    return ім_я is not None and _наявна(тека, ім_я) is not None


def вільна_назва(тека, основа=ТИПОВА_НАЗВА):
    """Основа, а якщо така назва вже є — «основа 2», «основа 3»…"""
    основа = безпечна_назва(основа) or ТИПОВА_НАЗВА
    зайняті = {_ключ(н) for н in список(тека)}
    назва, номер = основа, 1
    while _ключ(назва) in зайняті:
        номер += 1
        хвіст = f" {номер}"
        назва = основа[: МАКС_ДОВЖИНА_НАЗВИ - len(хвіст)].rstrip() + хвіст
    return назва


# ---- дії з файлами ------------------------------------------------------------

def прочитати(тека, назва):
    """Текст проєкту або None, якщо такого немає."""
    ім_я = безпечна_назва(назва)
    if ім_я is None:
        return None
    ф = _файл(тека, ім_я)
    if not ф.is_file():
        return None
    return ф.read_text(encoding="utf-8")


def зберегти(тека, назва, текст):
    """Записати текст проєкту (створює або замінює); повертає назву."""
    ім_я = _перевірена_назва(назва)
    _тека_програм(тека).mkdir(parents=True, exist_ok=True)
    ф = _файл(тека, ім_я)
    # спершу поруч, потім підміна: вимкнений посеред запису телефон не
    # лишить від програми порожній файл
    тимчасовий = ф.with_name(ф.name + ".нове")
    тимчасовий.write_text(текст, encoding="utf-8")
    тимчасовий.replace(ф)
    return ім_я


def створити(тека, назва, текст=""):
    """Новий проєкт; назва має бути вільна. Повертає назву."""
    ім_я = _перевірена_назва(назва)
    if _наявна(тека, ім_я) is not None:
        raise ПомилкаПроєкту(f"Проєкт «{_наявна(тека, ім_я)}» уже є — вибери іншу назву.")
    return зберегти(тека, ім_я, текст)


def перейменувати(тека, стара, нова):
    """Перейменувати проєкт; повертає нову назву."""
    стара_назва = _перевірена_назва(стара)
    нова_назва = _перевірена_назва(нова)
    ф = _файл(тека, стара_назва)
    if not ф.is_file():
        raise ПомилкаПроєкту(f"Проєкту «{стара_назва}» немає.")
    if нова_назва == стара_назва:
        return нова_назва
    зайнята = _наявна(тека, нова_назва)
    if зайнята is not None and зайнята != стара_назва:
        raise ПомилкаПроєкту(f"Проєкт «{зайнята}» уже є — вибери іншу назву.")
    ф.rename(_файл(тека, нова_назва))
    return нова_назва


def копія(тека, назва):
    """Зробити копію проєкту під назвою «назва (копія)», «назва (копія 2)»…
    Повертає назву копії."""
    ім_я = _перевірена_назва(назва)
    текст = прочитати(тека, ім_я)
    if текст is None:
        raise ПомилкаПроєкту(f"Проєкту «{ім_я}» немає.")
    хвіст = " (копія)"
    основа = ім_я[: МАКС_ДОВЖИНА_НАЗВИ - len(хвіст) - 4].rstrip() + хвіст
    зайняті = {_ключ(н) for н in список(тека)}
    нова, номер = основа, 1
    while _ключ(нова) in зайняті:
        номер += 1
        нова = f"{основа[:-1]} {номер})"
    return зберегти(тека, нова, текст)


def видалити(тека, назва):
    """Видалити проєкт назавжди."""
    ім_я = _перевірена_назва(назва)
    ф = _файл(тека, ім_я)
    if not ф.is_file():
        raise ПомилкаПроєкту(f"Проєкту «{ім_я}» немає.")
    ф.unlink()


# ---- відкритий проєкт ----------------------------------------------------------

class Проєкти:
    """Проєкти редактора: список і той, що зараз відкритий (self.поточний).

    почати() викликається раз при запуску застосунку й повертає текст для
    редактора; далі редактор кличе чернетка(текст) на кожну зміну і
    зберегти(текст) — коли програму запускають, застосунок згортають чи
    закривають і перед показом списку проєктів. Дії, що міняють відкритий
    проєкт (відкрити, новий, видалити поточний), повертають текст, який
    редактор має показати."""

    def __init__(self, тека, початковий_код=""):
        self.тека = Path(тека)
        self.початковий_код = початковий_код
        self.поточний = None

    # ---- стан на диску ----

    def _прочитати_стан(self):
        try:
            дані = json.loads((self.тека / ФАЙЛ_СТАНУ).read_text(encoding="utf-8"))
            назва = дані.get("поточний")
            return назва if isinstance(назва, str) else None
        except Exception:
            return None

    def _записати_стан(self):
        try:
            self.тека.mkdir(parents=True, exist_ok=True)
            (self.тека / ФАЙЛ_СТАНУ).write_text(
                json.dumps({"поточний": self.поточний}, ensure_ascii=False), encoding="utf-8")
        except OSError:
            pass

    def _прочитати_чернетку(self):
        try:
            return (self.тека / ФАЙЛ_ЧЕРНЕТКИ).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            return None

    def чернетка(self, текст):
        """Запам'ятати текст редактора (на кожну зміну) — страховка, якщо
        застосунок закриють без збереження."""
        try:
            self.тека.mkdir(parents=True, exist_ok=True)
            (self.тека / ФАЙЛ_ЧЕРНЕТКИ).write_text(текст, encoding="utf-8")
        except OSError:
            pass

    def _стати(self, назва, текст):
        self.поточний = назва
        self._записати_стан()
        self.чернетка(текст)
        return текст

    # ---- запуск застосунку ----

    def почати(self):
        """Визначити відкритий проєкт і повернути його текст.

        Є запам'ятаний проєкт — він, із текстом чернетки, якщо вона
        свіжіша за файл. Немає (перший запуск після оновлення зі старих
        «Зберегти»/«Відкрити» або стан загубився): чернетка, що збігається
        з якимось проєктом, відкриває його; інша непорожня чернетка стає
        новим проєктом «Моя програма»; без чернетки — перший проєкт зі
        списку, а якщо список порожній — «Моя програма» з початковим
        кодом."""
        назви = список(self.тека)
        чернетка = self._прочитати_чернетку()
        назва = self._прочитати_стан()
        if назва in назви:
            текст = чернетка if чернетка is not None else прочитати(self.тека, назва)
        elif чернетка is not None and чернетка.strip():
            назва = next((н for н in назви if прочитати(self.тека, н) == чернетка), None)
            if назва is None:
                назва = вільна_назва(self.тека)
            текст = чернетка
        elif назви:
            назва = назви[0]
            текст = прочитати(self.тека, назва)
        else:
            назва = ТИПОВА_НАЗВА
            текст = self.початковий_код
        if прочитати(self.тека, назва) != текст:
            зберегти(self.тека, назва, текст)
        return self._стати(назва, текст)

    # ---- дії редактора ----

    def зберегти(self, текст):
        """Зберегти текст у відкритий проєкт. Повертає True, якщо вдалося."""
        if self.поточний is None:
            return False
        self.чернетка(текст)
        try:
            зберегти(self.тека, self.поточний, текст)
            return True
        except (OSError, ПомилкаПроєкту):
            return False

    def список(self, запит=""):
        return шукати(список(self.тека), запит)

    def потрібен_пошук(self):
        return потрібен_пошук(список(self.тека))

    def відкрити(self, назва):
        """Зробити проєкт відкритим; повертає його текст."""
        текст = прочитати(self.тека, назва)
        if текст is None:
            raise ПомилкаПроєкту(f"Проєкту «{назва}» немає.")
        return self._стати(безпечна_назва(назва), текст)

    def новий(self, назва):
        """Створити порожній проєкт і відкрити його; повертає його назву."""
        ім_я = створити(self.тека, назва, "")
        self._стати(ім_я, "")
        return ім_я

    def перейменувати(self, стара, нова):
        була_поточна = безпечна_назва(стара) == self.поточний
        нова_назва = перейменувати(self.тека, стара, нова)
        if була_поточна:
            self.поточний = нова_назва
            self._записати_стан()
        return нова_назва

    def копія(self, назва):
        return копія(self.тека, назва)

    def видалити(self, назва):
        """Видалити проєкт. Якщо це був відкритий — відкривається перший
        зі списку (або новий порожній «Моя програма», коли список
        спорожнів) і повертається його текст; інакше — None."""
        був_поточний = безпечна_назва(назва) == self.поточний
        видалити(self.тека, назва)
        if not був_поточний:
            return None
        назви = список(self.тека)
        if назви:
            return self.відкрити(назви[0])
        self.новий(ТИПОВА_НАЗВА)
        return ""
