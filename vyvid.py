"""Вікно виводу без Kivy: межа кількості рядків і розкладка довгого тексту
на шматки, з яких на екрані існують лише видимі.

Навіщо. Раніше весь вивід був одним Label — однією текстурою. Текстура
має найбільший розмір (на телефонах 4096–8192 px), тож після кількох
сотень рядків текст обрізався або ставав чорним прямокутником, а кожне
оновлення перемальовувало все одразу. Тепер:

  * обрізати() лишає останні «межа» рядків (типово 10000, задається в
    «Налаштуваннях», зберігається в налаштування.json поруч із токеном);
  * Розкладка ділить текст на шматки приблизно по РЯДІВ_У_ШМАТКУ екранних
    рядів і знає висоту кожного; віджет (vidzhety.ТекстВиводу) створює
    Label лише для шматків у вікні прокрутки, тож і час, і пам'ять
    залежать від розміру екрана, а не від довжини виводу.

Висота шматка спершу оцінюється (ряди × висота ряду, з урахуванням
переносу довгих рядків), а коли шматок уперше намальовано — уточнюється
справжньою висотою текстури (уточнити()).

Тестується на комп'ютері: тести/test_вивід.py.
"""

import json
from bisect import bisect_left, bisect_right
from itertools import accumulate
from pathlib import Path

МЕЖА_ТИПОВА = 10000
МЕЖА_МІН = 100
МЕЖА_МАКС = 100000
РЯДІВ_У_ШМАТКУ = 30     # екранних рядів в одному Label: текстура лишається малою

ФАЙЛ_НАЛАШТУВАНЬ = "налаштування.json"   # той самий, що в github.py
КЛЮЧ_МЕЖІ = "рядків_виводу"


# ---- межа -----------------------------------------------------------------------

def межа_з_тексту(текст):
    """Число з поля вводу -> межа в [МЕЖА_МІН, МЕЖА_МАКС]; не число — None.
    Пробіли всередині дозволені («10 000»)."""
    цифри = "".join(str(текст).split())
    if not цифри.isdecimal():
        return None
    return min(max(int(цифри), МЕЖА_МІН), МЕЖА_МАКС)


def прочитати_межу(тека):
    try:
        дані = json.loads((Path(тека) / ФАЙЛ_НАЛАШТУВАНЬ).read_text(encoding="utf-8"))
        межа = межа_з_тексту(дані.get(КЛЮЧ_МЕЖІ))
    except Exception:
        межа = None
    return межа or МЕЖА_ТИПОВА


def зберегти_межу(тека, межа):
    """Дописує межу в налаштування.json, не чіпаючи решти (токен, репо)."""
    ф = Path(тека) / ФАЙЛ_НАЛАШТУВАНЬ
    try:
        дані = json.loads(ф.read_text(encoding="utf-8"))
        if not isinstance(дані, dict):
            дані = {}
    except Exception:
        дані = {}
    дані[КЛЮЧ_МЕЖІ] = int(межа)
    Path(тека).mkdir(parents=True, exist_ok=True)
    ф.write_text(json.dumps(дані, ensure_ascii=False, indent=2), encoding="utf-8")


def кількість_рядків(текст):
    if not текст:
        return 0
    return текст.count("\n") + (0 if текст.endswith("\n") else 1)


def обрізати(текст, межа=МЕЖА_ТИПОВА):
    """Останні «межа» рядків тексту; якщо щось відрізано — перший рядок
    каже скільки. Не ділить увесь текст на рядки: шукає початок хвоста з
    кінця, тож час залежить від межі, а не від довжини виводу."""
    всього = кількість_рядків(текст)
    if всього <= межа:
        return текст
    поз = len(текст) - (1 if текст.endswith("\n") else 0)
    for _ in range(межа):
        поз = текст.rfind("\n", 0, поз)
    return f"… показано останні {межа} рядків із {всього}\n" + текст[поз + 1:]


# ---- розкладка --------------------------------------------------------------------

def шматки(текст, стовпців=40, рядів=РЯДІВ_У_ШМАТКУ):
    """[(текст_шматка, екранних_рядів), …]. Рядок, довший за «стовпців»,
    рахується за кілька рядів (перенос); рядок, що сам довший за цілий
    шматок, ріжеться на частини — інакше один такий рядок знову дав би
    завелику текстуру."""
    if not текст:
        return []
    стовпців = max(1, int(стовпців))
    найдовший = стовпців * рядів
    рядки = текст.split("\n")
    if рядки[-1] == "":
        рядки.pop()
    результат = []
    поточні, набрано = [], 0

    def закрити():
        nonlocal поточні, набрано
        if поточні:
            результат.append(("\n".join(поточні), набрано))
            поточні, набрано = [], 0

    for рядок in рядки:
        довжина = len(рядок)
        if довжина <= стовпців:
            поточні.append(рядок)
            набрано += 1
        elif довжина <= найдовший:
            поточні.append(рядок)
            набрано += -(-довжина // стовпців)
        else:
            закрити()
            for поч in range(0, довжина, найдовший):
                частина = рядок[поч:поч + найдовший]
                результат.append((частина, -(-len(частина) // стовпців)))
            continue
        if набрано >= рядів:
            закрити()
    закрити()
    return результат


class Розкладка:
    """Шматки тексту одне під одним: висоти, відступи від верху і які з
    них потрапляють у вікно прокрутки."""

    def __init__(self, текст="", межа=МЕЖА_ТИПОВА, стовпців=40, висота_ряду=1.0):
        частини = шматки(обрізати(текст, межа), стовпців)
        self.тексти = [т for т, _ in частини]
        self.висоти = [р * висота_ряду for _, р in частини]
        self._верхи = None

    def __len__(self):
        return len(self.тексти)

    def _відступи(self):
        if self._верхи is None:
            self._верхи = [0.0] + list(accumulate(self.висоти))
        return self._верхи

    @property
    def всього(self):
        return self._відступи()[-1]

    def верх(self, і):
        """Відстань від верху тексту до верху шматка і."""
        return self._відступи()[і]

    def видимі(self, верх, низ):
        """range шматків, що перетинають смугу [верх, низ] (від верху тексту)."""
        if not self.тексти:
            return range(0)
        в = self._відступи()
        перший = max(0, bisect_right(в, верх) - 1)
        останній = min(len(self.тексти), bisect_left(в, низ))
        перший = min(перший, len(self.тексти) - 1)
        return range(перший, max(останній, перший + 1))

    def уточнити(self, і, висота):
        """Справжня висота намальованого шматка. True — якщо вона змінилась
        (тоді відступи наступних шматків і загальна висота інші)."""
        if abs(self.висоти[і] - висота) < 0.5:
            return False
        self.висоти[і] = висота
        self._верхи = None
        return True
