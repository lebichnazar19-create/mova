@pytest.mark.parametrize("код, вид", ВИПАДКИ)
def test_помилка_дає_приклад_і_пояснення(код, вид):
    приклад, пояснення = ПРИКЛАДИ[вид]
    e = помилка(код)
    текст = str(e)
    # три частини: що очікувалось (повідомлення), приклад, пояснення
    assert e.повідомлення and e.повідомлення in текст
    assert "Правильно:" in текст
    assert блок_правильно(текст) == приклад
    assert текст.splitlines()[-1] == "Пояснення: " + пояснення
    assert e.приклад == приклад and e.пояснення == пояснення


def test_усі_види_покрито():
    покриті = {вид for _, вид in ВИПАДКИ}
    assert покриті == set(ПРИКЛАДИ), (
        f"без тесту: {set(ПРИКЛАДИ) - покриті}; без ключа: {покриті - set(ПРИКЛАДИ)}"
    )


@pytest.mark.parametrize("вид", sorted(ПРИКЛАДИ))
def test_приклад_справді_розбирається(вид):
    приклад, пояснення = ПРИКЛАДИ[вид]
    парсити_текст(приклад + "\n")
    assert пояснення.endswith(".") and len(пояснення) < 200


def test_формат_рядок_позиція_стрілка_потім_підказка():
    текст = str(помилка("хай 5 = 5"))
    рядки = текст.splitlines()
    assert рядки[0] == "Помилка розбору в рядку 1, позиція 5:"
    assert рядки[1] == "    хай 5 = 5"
    assert рядки[2] == "        ^"
    assert рядки[3] == "Очікувалось ім'я змінної, а тут «5»"
    assert рядки[4] == "Правильно:"
    assert рядки[5] == "    хай х = 5"
    assert рядки[6].startswith("Пояснення: ")
    assert len(рядки) == 7


def test_багаторядковий_приклад_з_відступом():
    рядки = str(помилка("дія ф\n    поверни 1")).splitlines()
    i = рядки.index("Правильно:")
    assert рядки[i + 1:i + 3] == ["    дія квадрат(х)", "        поверни х * х"]


def test_обірваний_рядок_показує_кінець_того_ж_рядка():
    # токен кінця рядка стоїть на наступному рядку, але людині бракує
    # чогось у кінці цього — стрілка одразу після останнього символу
    e = помилка("хай х = т.")
    assert e.рядок == 1 and e.позиція == 11
    рядки = str(e).splitlines()
    assert рядки[1] == "    хай х = т." and рядки[2] == "              ^"
    assert "а тут кінець рядка" in e.повідомлення
    e = помилка("дія ф\n    поверни 1")
    assert e.рядок == 1 and e.позиція == 6


def test_приклад_з_довідки_для_вбудованої_дії():
    # для вбудованих дій і типів приклад — з довідки, не зі словника
    e = помилка("корінь 4")
    assert e.приклад == "корінь(16)" and "Правильно:\n    корінь(16)" in str(e)
    e = помилка("Точка т")
    assert e.приклад.startswith("хай т = Точка(")


def test_ключове_слово_у_виразі_дає_його_приклад():
    e = помилка("хай х = якщо")
    assert блок_правильно(str(e)) == ПРИКЛАДИ["якщо"][0]


def test_помилка_лексера_без_підказки():
    with pytest.raises(ПомилкаРозбору) as info:
        токенізувати("хай х = 1 ~ 2")
    текст = str(info.value)
    assert "Правильно:" not in текст and "Пояснення:" not in текст
    assert info.value.приклад is None and info.value.пояснення is None


def test_повідомлення_без_підказки_у_редакторі():
    # редактор показує лише ЗАГОЛОВОК: повідомлення — приклад туди не потрапляє
    e = помилка("хай 5 = 5")
    assert "Правильно" not in e.повідомлення and "\n" not in e.повідомлення
