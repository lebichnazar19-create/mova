"""Розумні помилки розбору: до «що очікувалось» додано приклад правильного
запису конструкції (блок «Правильно:») і рядок пояснення. Приклади живуть
в одному словнику yadro.parser.ПРИКЛАДИ — ключ це вид конструкції. Тут:
на кожен ключ — тест, що помилковий код дає підказку саме з його прикладом;
що всі ключі покрито; що кожен приклад справді розбирається; формат виводу."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаРозбору
from yadro.lexer import токенізувати
from yadro.parser import ПРИКЛАДИ, парсити_текст


def помилка(код):
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст(код if код.endswith("\n") else код + "\n")
    return info.value


def блок_правильно(текст):
    """Рядки прикладу з блоку «Правильно:» (без відступу на 4 пробіли)."""
    рядки = текст.splitlines()
    початок = рядки.index("Правильно:") + 1
    приклад = []
    for р in рядки[початок:]:
        if р.startswith("Пояснення: "):
            break
        assert р.startswith("    "), р
        приклад.append(р[4:])
    return "\n".join(приклад)


