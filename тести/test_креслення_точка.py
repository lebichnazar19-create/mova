def test_вузол_повертає_точку_і_приймає_точку():
    е.вузол("а", Точка(3, 4))
    е.вузол("б", 1, 1)
    assert isinstance(е.вузол("а"), Точка) and е.вузол("а") == Точка(3, 4)
    assert е.вузол("а") == [3, 4]          # старі порівняння зі списком працюють
    assert е.вузол("а")[0] == 3 and е.вузол("а")[1] == 4
    with pytest.raises(ПомилкаВиконання):
        е.вузол("в", "не точка")


def test_вузол_у_програмі_індексується_і_йде_в_геометрію(capsys):
    вивід = запустити(
        'вузол("а", Точка(0, 0))\nвузол("б", 3, 4)\n'
        'хай а = вузол("а")\nхай б = вузол("б")\n'
        'друкуй(а, б[0], б[1], відстань(а, б), середина(а, б), довжина(б))\n',
        capsys,
    )
    assert вивід.strip() == "(0, 0) 3 4 5 (1.5, 2) 5"


# ---- креслення: усі дії приймають Точку або [x, y] --------------------------------

def test_контур_приймає_точки_і_списки_упереміш():
    к.аркуш(100, 80, 2)
    до = len(к._елементи)
    к.контур([Точка(0, 0), [40, 0], Точка(40, 30)])
    assert len(к._елементи) == до + 1
    assert типи_фігур()[-1] == "ламана"
    with pytest.raises(ПомилкаВиконання) as info:
        к.контур([Точка(0, 0), "не точка"])
    assert "Точкою" in str(info.value)


def test_розмір_у_двох_формах_дає_однаковий_результат():
    к.аркуш(100, 80, 2)
    к.розмір(0, 0, 40, 0, -10)
    старі = list(к._елементи)
    к.аркуш(100, 80, 2)
    к.розмір(Точка(0, 0), Точка(40, 0), -10)
    assert к._елементи == старі
    к.аркуш(100, 80, 2)
    к.розмір([0, 0], [40, 0], -10)
    assert к._елементи == старі
    with pytest.raises(ПомилкаВиконання):
        к.розмір(Точка(0, 0), Точка(40, 0))


def test_осьова_невидима_радіус_діаметр_виноска_вид_з_точками():
    к.аркуш(100, 80, 2)
    к.осьова(Точка(0, 10), Точка(50, 10))
    к.невидима([0, 20], [50, 20])
    к.розмір_радіус(Точка(30, 30), 5)
    к.розмір_діаметр(Точка(30, 30), 5)
    к.виноска(Точка(30, 30), "отвір")
    к.вид("спереду", Точка(10, 10))
    к.ізометрія(Точка(0, 0))
    типи = типи_фігур()
    assert типи.count("лінія") >= 6 and "текст" in типи and "трикутник" in типи
    # старі форми з голими числами теж
    к.осьова(0, 10, 50, 10)
    к.розмір_радіус(30, 30, 5)
    к.виноска(30, 30, "отвір")
    к.вид("спереду", 10, 10)


def test_виміряй_виміряй_кут_кут_приймають_точки():
    assert к.виміряй(Точка(0, 0), Точка(3, 4)) == 5
    assert к.виміряй([0, 0], Точка(3, 4)) == 5
    assert round(к.виміряй_кут(Точка(1, 0), Точка(0, 0), Точка(0, 1))) == 90
    к.аркуш(100, 80, 2)
    к.кут(Точка(10, 0), Точка(0, 0), Точка(0, 10), 5)
    assert "дуга" in типи_фігур()


def test_ескіз_у_креслення_через_точки(capsys):
    вивід = запустити(
        'вузол("а1", 0, 0)\nвузол("а2", 2, 39)\nвузол("б1", 48, 1)\nвузол("б2", 51, 40)\n'
        'сегмент("ліва", "а1", "а2")\nсегмент("права", "б1", "б2")\nсегмент("верх", "а2", "б2")\n'
        'вертикально("ліва")\nвертикально("права")\nрівні("ліва", "права")\nгоризонтально("верх")\nдовжина("ліва", 40)\n'
        "розвяжи()\n"
        "аркуш(150, 100, 3)\nвпиши_в_аркуш(10)\n"
        'контур([вузол("а1"), вузол("а2"), вузол("б2"), вузол("б1")])\n'
        'розмір(вузол("а1"), вузол("а2"), -10)\n'
        'друкуй(округли(відстань(вузол("а1"), вузол("а2"))))\n',
        capsys,
    )
    assert вивід.strip() == "40"
    assert "ламана" in типи_фігур()


