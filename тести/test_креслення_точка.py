def test_для_екрана_координати_в_мм_y_вгору():
    к.аркуш(100, 80, 2, "друк")
    к.контур([Точка(10, 10), Точка(30, 10), Точка(30, 20)])
    е_ = к.для_екрана()
    assert е_["ширина"] == 100 and е_["висота"] == 80 and е_["фон"].startswith("#")
    ламана = [ф for ф in е_["фігури"] if ф["тип"] == "ламана"][-1]
    assert [round(x, 6) for x in ламана["точки"]] == [10, 10, 30, 10, 30, 20] and ламана["замкнена"]
    рамка = [ф for ф in е_["фігури"] if ф["тип"] == "прямокутник"][0]
    assert рамка["x"] == к.ВІДСТУП_РАМКИ_ЛІВО_ММ and рамка["y"] == к.ВІДСТУП_РАМКИ_ІНШІ_ММ
    к.осьова(Точка(0, 5), Точка(50, 5))
    лінія = к.для_екрана()["фігури"][-1]
    assert лінія["тип"] == "лінія" and лінія["штрих"] and [round(x, 6) for x in лінія["точки"]] == [0, 5, 50, 5]
    к.виноска(Точка(20, 20), "напис")
    текст = [ф for ф in к.для_екрана()["фігури"] if ф["тип"] == "текст"][-1]
    assert текст["текст"] == "напис" and текст["вирівнювання"] == "початок"


def test_zapusk_віддає_креслення_застосунку_і_скидає_між_запусками():
    from zapusk import виконати_код

    отримано = []
    вивід, успіх = виконати_код(
        "аркуш(100, 80, 2)\nконтур([Точка(10, 10), Точка(50, 10), Точка(50, 40)])\n",
        при_кресленні=отримано.append,
    )
    assert успіх and len(отримано) == 1 and "ламана" in [ф["тип"] for ф in отримано[0]["фігури"]]
    вивід, успіх = виконати_код('друкуй("без креслення")', при_кресленні=отримано.append)
    assert успіх and len(отримано) == 1
    # помилка після аркуша — креслення все одно віддається
    вивід, успіх = виконати_код("аркуш(100, 80, 2)\nдрукуй(1 / 0)\n", при_кресленні=отримано.append)
    assert not успіх and len(отримано) == 2
