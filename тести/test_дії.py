"""Етап 4: дія/поверни, рекурсія, область видимості локальних змінних."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ядро.компілятор import компілювати
from ядро.парсер import парсити_текст
from ядро.вм import виконати_байткод


def запустити(джерело, capsys):
    байткод = компілювати(парсити_текст(джерело))
    виконати_байткод(байткод, без_пристрою=True)
    return capsys.readouterr().out


# ---- дизасемблер: у байткоді справді є MAKE_FUNCTION / CALL / RETURN --------

def test_дизасемблер_показує_make_function_call_return():
    # ім'я навмисно не "квадрат" — це тепер вбудована функція малювання
    # (ядро/малюнок.py), і виклик з таким іменем скомпілювався б у
    # CALL_NATIVE, а не в CALL, який тут перевіряється
    байткод = компілювати(
        парсити_текст("дія квадрат_числа(x)\n    поверни x * x\n\nдрукуй(квадрат_числа(5))\n")
    )
    коди = [і[0] for і in байткод["код"]]
    assert "MAKE_FUNCTION" in коди
    assert "CALL" in коди
    assert "RETURN" in коди

    make_idx = коди.index("MAKE_FUNCTION")
    імя, параметри, адреса = байткод["код"][make_idx][1]
    assert імя == "квадрат_числа"
    assert параметри == ["x"]
    # адреса тіла має вказувати на реальний початок тіла, а не в порожнечу
    assert байткод["код"][адреса][0] == "PUSH_VAR"

    call_idx = коди.index("CALL")
    call_імя, call_argc = байткод["код"][call_idx][1]
    assert (call_імя, call_argc) == ("квадрат_числа", 1)

    # тіло дії закінчується RETURN раніше, ніж CALL взагалі трапляється
    return_idx = коди.index("RETURN")
    assert return_idx < call_idx


# ---- рекурсія глибиною 10+ --------------------------------------------------

def test_рекурсія_факторіал_10(capsys):
    вивід = запустити(
        "дія факторіал(n)\n"
        "    якщо n <= 1\n"
        "        поверни 1\n"
        "    поверни n * факторіал(n - 1)\n"
        "друкуй(факторіал(10))\n",
        capsys,
    )
    assert вивід.strip() == "3628800"


def test_рекурсія_глибина_20_без_переповнення(capsys):
    # рахує глибину рекурсії явним лічильником, а не результатом обчислення —
    # перевіряє саме те, що ланцюжок викликів/повернень із 20 вкладених
    # кадрів відпрацьовує коректно (адреси повернення не плутаються)
    вивід = запустити(
        "дія глибина(n)\n"
        "    якщо n <= 0\n"
        "        поверни 0\n"
        "    поверни 1 + глибина(n - 1)\n"
        "друкуй(глибина(20))\n",
        capsys,
    )
    assert вивід.strip() == "20"


def test_взаємна_рекурсія_парне_непарне(capsys):
    # два різні виклики CALL по черзі — перевіряє, що функції коректно
    # знаходять одна одну незалежно від порядку MAKE_FUNCTION у коді
    вивід = запустити(
        "дія парне(n)\n"
        "    якщо n == 0\n"
        "        поверни істина\n"
        "    поверни непарне(n - 1)\n"
        "дія непарне(n)\n"
        "    якщо n == 0\n"
        "        поверни хиба\n"
        "    поверни парне(n - 1)\n"
        "друкуй(парне(12))\n",
        capsys,
    )
    assert вивід.strip() == "істина"


# ---- локальна змінна не затирає зовнішню з тим самим іменем -----------------

def test_хай_усередині_дії_не_змінює_зовнішню_змінну(capsys):
    вивід = запустити(
        "хай х = 5\n"
        "дія тест()\n"
        "    хай х = 100\n"
        "    поверни х\n"
        "друкуй(тест())\n"
        "друкуй(х)\n",
        capsys,
    )
    assert вивід.split() == ["100", "5"]


def test_параметр_з_іменем_зовнішньої_змінної_не_затирає_її(capsys):
    вивід = запустити(
        "хай значення = 1\n"
        "дія зіпсуй(значення)\n"
        "    значення = значення + 1\n"
        "    поверни значення\n"
        "друкуй(зіпсуй(10))\n"
        "друкуй(значення)\n",
        capsys,
    )
    assert вивід.split() == ["11", "1"]


def test_присвоєння_усередині_дії_без_хай_теж_локальне(capsys):
    # навіть без "хай" — перше присвоєння імені всередині дії створює
    # локальну змінну дії, а не пише в глобальну з тим самим іменем
    вивід = запустити(
        "хай лічильник = 0\n"
        "дія рахуй()\n"
        "    лічильник = 999\n"
        "    поверни лічильник\n"
        "друкуй(рахуй())\n"
        "друкуй(лічильник)\n",
        capsys,
    )
    assert вивід.split() == ["999", "0"]


def test_вкладені_виклики_не_плутають_локальні_змінні(capsys):
    # два активні кадри одночасно (зовнішній ще не повернувся) з однойменним
    # параметром — кожен кадр повинен бачити лише своє значення
    вивід = запустити(
        "дія зовнішня(n)\n"
        "    поверни n + внутрішня(n * 10)\n"
        "дія внутрішня(n)\n"
        "    поверни n + 1\n"
        "друкуй(зовнішня(3))\n",
        capsys,
    )
    # зовнішня(3): n=3 у зовнішньому кадрі; внутрішня(30): n=30 у своєму —
    # 3 + (30 + 1) = 34, а не, наприклад, 30 + (30+1), якби кадри плутались
    assert вивід.strip() == "34"
