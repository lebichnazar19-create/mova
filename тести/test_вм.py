import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.errors import ПомилкаВиконання
from yadro.vm import виконати_байткод


def запустити(джерело, capsys, без_пристрою=True):
    байткод = компілювати(парсити_текст(джерело))
    вм = виконати_байткод(байткод, без_пристрою=без_пристрою)
    return capsys.readouterr().out, вм


def test_арифметика(capsys):
    вивід, _ = запустити("друкуй(2 + 2 * 3)\n", capsys)
    assert вивід.strip() == "8"


def test_рядок_з_числом_конкатенація(capsys):
    вивід, _ = запустити('друкуй("заряд: " + 20)\n', capsys)
    assert вивід.strip() == "заряд: 20"


def test_якщо_інакше(capsys):
    вивід, _ = запустити(
        "хай х = 5\nякщо х > 10\n    друкуй(\"великий\")\nінакше\n    друкуй(\"малий\")\n",
        capsys,
    )
    assert вивід.strip() == "малий"


def test_поки_цикл(capsys):
    вивід, _ = запустити(
        "хай i = 0\nпоки i < 3\n    друкуй(i)\n    i = i + 1\n", capsys
    )
    assert вивід.split() == ["0", "1", "2"]


def test_перервись_і_продовж(capsys):
    вивід, _ = запустити(
        "для x у [1, 2, 3, 4, 5]\n"
        "    якщо x == 2\n"
        "        продовж\n"
        "    якщо x == 4\n"
        "        перервись\n"
        "    друкуй(x)\n",
        capsys,
    )
    assert вивід.split() == ["1", "3"]


def test_функція_і_рекурсія(capsys):
    вивід, _ = запустити(
        "дія фіб(n)\n"
        "    якщо n <= 1\n"
        "        поверни n\n"
        "    поверни фіб(n - 1) + фіб(n - 2)\n"
        "друкуй(фіб(8))\n",
        capsys,
    )
    assert вивід.strip() == "21"


def test_списки_і_індексація(capsys):
    вивід, _ = запустити(
        "хай сп = [10, 20, 30]\nсп[1] = 99\nдрукуй(сп[0], сп[1], сп[2], довжина(сп))\n",
        capsys,
    )
    assert вивід.strip() == "10 99 30 3"


def test_ділення_на_нуль_дає_помилку_виконання(capsys):
    байткод = компілювати(парсити_текст("друкуй(1 / 0)\n"))
    with pytest.raises(ПомилкаВиконання):
        виконати_байткод(байткод, без_пристрою=True)


def test_вібруй_у_симуляції_не_падає(capsys):
    вивід, _ = запустити('вібруй(200)\n', capsys)
    assert "симуляція" in вивід
    assert "200" in вивід


