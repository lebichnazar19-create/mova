import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from ядро import аст as А
from ядро.парсер import парсити_текст
from ядро.помилки import ПомилкаРозбору


def test_хай_і_арифметика():
    прог = парсити_текст("хай х = 2 + 2 * 3\n")
    інстр = прог.тіло[0]
    assert isinstance(інстр, А.Хай)
    assert інстр.імя == "х"
    assert isinstance(інстр.вираз, А.Бінарний)
    assert інстр.вираз.оп == "+"
    assert isinstance(інстр.вираз.право, А.Бінарний)
    assert інстр.вираз.право.оп == "*"


def test_якщо_інакше():
    прог = парсити_текст("якщо істина\n    друкуй(1)\nінакше\n    друкуй(2)\n")
    вузол = прог.тіло[0]
    assert isinstance(вузол, А.Якщо)
    assert isinstance(вузол.тіло[0], А.ВиразІнструкція)
    assert isinstance(вузол.інакше, list)


def test_інакше_якщо_ланцюг():
    прог = парсити_текст(
        "якщо а\n    друкуй(1)\nінакше якщо б\n    друкуй(2)\nінакше\n    друкуй(3)\n"
    )
    вузол = прог.тіло[0]
    assert isinstance(вузол.інакше, А.Якщо)
    assert isinstance(вузол.інакше.інакше, list)


def test_дія_і_поверни():
    прог = парсити_текст("дія квадрат(x)\n    поверни x * x\n")
    дія = прог.тіло[0]
    assert isinstance(дія, А.Дія)
    assert дія.імя == "квадрат"
    assert дія.параметри == ["x"]
    assert isinstance(дія.тіло[0], А.Поверни)


def test_для_у():
    прог = парсити_текст("для x у [1, 2, 3]\n    друкуй(x)\n")
    вузол = прог.тіло[0]
    assert isinstance(вузол, А.Для)
    assert вузол.імя == "x"
    assert isinstance(вузол.ітерований, А.СписокЛіт)


def test_виклик_з_аргументами():
    прог = парсити_текст("друкуй(1, 2, 3)\n")
    виклик = прог.тіло[0].вираз
    assert isinstance(виклик, А.Виклик)
    assert виклик.імя == "друкуй"
    assert len(виклик.аргументи) == 3


def test_індексація_і_присвоєння_індексу():
    прог = парсити_текст("сп[0] = 5\n")
    вузол = прог.тіло[0]
    assert isinstance(вузол, А.ПрисвоєнняІндекс)


def test_логічні_і_не():
    прог = парсити_текст("хай х = не істина і хиба або істина\n")
    вираз = прог.тіло[0].вираз
    assert isinstance(вираз, А.Логічний)
    assert вираз.оп == "або"


def test_помилка_без_відступу_після_якщо():
    with pytest.raises(ПомилкаРозбору):
        парсити_текст("якщо істина\nдрукуй(1)\n")


def test_перервись_поза_блоком_парситься_але_компілятор_відхилить():
    # парсер сам по собі не перевіряє контекст циклу — це робить компілятор
    прог = парсити_текст("перервись\n")
    assert isinstance(прог.тіло[0], А.Перервись)
