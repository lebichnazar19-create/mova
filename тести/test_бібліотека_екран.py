"""1.5: бібліотека «екран» (biblioteky/ekran.py) — малювання на полотні
застосунку через підключи("екран"); без застосунку — симуляція, як у плати."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

import polotno
from biblioteky import ekran as е
from yadro import biblioteka, drawing
from yadro.errors import ПомилкаВиконання
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод

ПІДКЛЮЧИ = 'підключи("екран")\n'


@pytest.fixture(autouse=True)
def _чисто():
    е.скинути()
    drawing.скинути()
    yield
    е.скинути()
    drawing.скинути()


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(ПІДКЛЮЧИ + джерело)), без_пристрою=True)
    return capsys.readouterr().out


def помилка(джерело, підключити=True):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст((ПІДКЛЮЧИ if підключити else "") + джерело)), без_пристрою=True)
    return str(info.value)


# ---- підключення і реєстр ------------------------------------------------------------

def test_без_підключення_підказка_і_реєстр():
    текст = помилка("крапка(1, 2)\n", підключити=False)
    assert "Невідома дія «крапка»" in текст and 'підключи("екран")' in текст
    # коло(x, y, r) без бібліотеки — це SVG-коло з неправильними аргументами, з тією ж підказкою
    текст = помилка("полотно(10, 10)\nколо(1, 2, 3)\n", підключити=False)
    assert "«коло»" in текст and 'підключи("екран")' in текст
    assert biblioteka.де("крапка") == "екран" and biblioteka.де("онови") == "екран"
    assert set(biblioteka.імена("екран")) == {
        "ширина", "висота", "колір", "крапка", "лінія", "прямокутник", "заливка", "коло", "круг", "очисти", "онови",
    }
    assert biblioteka.типи("екран") == set()
    from yadro import dovidka
    assert any(г.startswith("Екран") and 'підключи("екран")' in г for г, _ in dovidka.ГРУПИ)
    assert dovidka.приклад("онови") == "онови()"


# ---- симуляція: без застосунку нічого не падає ------------------------------------------

def test_симуляція_розмір_типовий_і_кадри_складаються(capsys):
    вивід = запустити("друкуй(ширина(), висота())\nкрапка(1, 2)\nонови()\nонови()\n", capsys)
    assert вивід.strip() == "360 480"
    assert not е.є_полотно() and len(е.КАДРИ) == 2
    кадр = е.КАДРИ[-1]
    assert (кадр["ширина"], кадр["висота"], кадр["фон"], кадр["лінії"]) == (360, 480, "#FFFFFF", "#000000")
    assert len(кадр["фігури"]) == 1


def test_кадри_не_ростуть_без_межі(capsys):
    запустити("для н у діапазон(0, 150)\n    онови()\n", capsys)
    assert len(е.КАДРИ) == е.КАДРІВ_МАКС


def test_фігури_у_кадрі_перевернуті_по_y_і_з_кольором(capsys):
    запустити(
        "колір(255, 0, 0)\n"
        "крапка(10, 20)\n"
        "лінія(0, 0, 100, 50)\n"
        "прямокутник(10, 10, 80, 40)\n"
        "колір(0, 0, 255)\n"
        "заливка(10, 10, 80, 40)\n"
        "коло(50, 60, 20)\n"
        "круг(50, 60, 20)\n"
        "онови()\n",
        capsys,
    )
    ф = е.КАДРИ[-1]["фігури"]
    в = 480
    assert ф[0] == {"тип": "прямокутник", "x": 10, "y": в - 20 - 1, "ш": 1, "в": 1, "залитий": True, "колір": "#FF0000"}
    assert ф[1] == {"тип": "лінія", "точки": [0, в, 100, в - 50], "ширина_px": 2, "колір": "#FF0000"}
    assert ф[2] == {"тип": "прямокутник", "x": 10, "y": в - 10 - 40, "ш": 80, "в": 40, "залитий": False,
                    "ширина_px": 2, "колір": "#FF0000"}
    assert ф[3]["залитий"] and ф[3]["колір"] == "#0000FF"
    assert ф[4] == {"тип": "коло", "cx": 50, "cy": в - 60, "r": 20, "залитий": False, "ширина_px": 2, "колір": "#0000FF"}
    assert ф[5]["тип"] == "коло" and ф[5]["залитий"]
    # накопичене малюється тим самим полотном, що й креслення
    команди = polotno.команди(е.КАДРИ[-1], 1.0)
    assert [к["тип"] for к in команди] == ["фон", "прямокутник", "лінія", "лінія", "прямокутник", "дуга", "круг"]
    assert команди[1]["колір"] == "#FF0000" and команди[-1]["колір"] == "#0000FF"


def test_очисти_прибирає_фігури_а_колір_лишається(capsys):
    запустити("колір(0, 128, 0)\nкрапка(1, 1)\nочисти()\nкрапка(2, 2)\nонови()\n", capsys)
    ф = е.КАДРИ[-1]["фігури"]
    assert len(ф) == 1 and ф[0]["x"] == 2 and ф[0]["колір"] == "#008000"


def test_колір_назвою_і_шістнадцятковий(capsys):
    запустити('колір("синій")\nкрапка(0, 0)\nколір("#AbCdEf")\nкрапка(0, 0)\nонови()\n', capsys)
    ф = е.КАДРИ[-1]["фігури"]
    assert ф[0]["колір"] == drawing.КОЛЬОРИ["синій"] and ф[1]["колір"] == "#AbCdEf"


def test_відʼємні_ширина_і_висота_розгортаються(capsys):
    запустити("заливка(50, 50, -20, -10)\nонови()\n", capsys)
    ф = е.КАДРИ[-1]["фігури"][0]
    assert (ф["x"], ф["ш"], ф["в"]) == (30, 20, 10) and ф["y"] == 480 - 40 - 10


# ---- помилки з поясненням ---------------------------------------------------------------

def test_помилки_кольору_радіуса_і_типів():
    assert "від 0 до 255" in помилка("колір(300, 0, 0)\n")
    assert "зелений — рядок" in помилка('колір(1, "а", 2)\n')
    assert "не може бути від'ємним" in помилка("коло(1, 1, -5)\n")
    assert "«крапка»: x має бути числом" in помилка('крапка("а", 1)\n')
    assert "«лінія»: y2 має бути числом" in помилка("лінія(1, 2, 3, істина)\n")
    assert 'Невідомий колір «фіолетовий»' in помилка('колір("фіолетовий")\n')


# ---- спільні імена: коло і лінія з кольором лишаються SVG-малюванням ------------------

def test_коло_і_лінія_з_кольором_ідуть_у_svg_малювання(capsys):
    запустити(
        "полотно(100, 100)\n"
        'коло(10, 10, 5, "синій")\nлінія(0, 0, 10, 10, "синій", 2)\n'
        "коло(10, 10, 5)\nлінія(0, 0, 10, 10)\nонови()\n",
        capsys,
    )
    assert [ф["тип"] for ф in drawing._фігури] == ["circle", "line"]
    assert [ф["тип"] for ф in е.КАДРИ[-1]["фігури"]] == ["коло", "лінія"]
    текст = помилка("коло(1, 2)\n")
    assert "«коло» приймає 3 аргументи" in текст and "4 аргументи" in текст


