def test_zapusk_підʼєднує_полотно_застосунку_і_скидає_між_запусками():
    from zapusk import виконати_код

    кадри = []
    вивід, успіх = виконати_код(
        ПІДКЛЮЧИ + "друкуй(ширина(), висота())\nкруг(10, 10, 5)\nонови()\nкрапка(0, 0)\nонови()\n",
        при_кресленні=кадри.append, розмір_екрана=lambda: (200.7, 100.2),
    )
    assert успіх and вивід.strip() == "200 100"
    assert len(кадри) == 2 and кадри[0]["ширина"] == 200 and кадри[0]["висота"] == 100
    assert [ф["тип"] for ф in кадри[1]["фігури"]] == ["коло", "прямокутник"]
    assert кадри[0]["фігури"][0]["cy"] == 100 - 10
    assert е.КАДРИ == []   # кадри пішли в застосунок, не в симуляцію
    # новий запуск — чисте полотно; помилка після онови() не ховає показане
    вивід, успіх = виконати_код(ПІДКЛЮЧИ + "онови()\nдрукуй(1 / 0)\n", при_кресленні=кадри.append)
    assert not успіх and len(кадри) == 3 and кадри[2]["фігури"] == []
    assert кадри[2]["ширина"] == 360   # без розмір_екрана — типовий розмір
    # без при_кресленні (редактор, консоль) — знову симуляція
    вивід, успіх = виконати_код(ПІДКЛЮЧИ + "онови()\n")
    assert успіх and len(кадри) == 3 and len(е.КАДРИ) == 1 and not е.є_полотно()


