def test_приклад_палець_коло_їде_за_пальцем():
    """Як у застосунку: програма в потоці крутить кадри, палець торкається
    полотна — круг наближається до нього; «Стоп» завершує цикл."""
    кадри = []
    вми = []
    код = (КОРІНЬ / "приклади" / "палець.мова").read_text(encoding="utf-8")
    результат = []
    потік = threading.Thread(
        target=lambda: результат.append(виконати_код(
            код, при_старті=вми.append, при_кресленні=кадри.append, розмір_екрана=lambda: (400, 600),
            показувати_креслення=False)),
        daemon=True,
    )
    потік.start()

    def чекати(умова):
        кінець = time.monotonic() + 5
        while not умова():
            assert time.monotonic() < кінець and потік.is_alive(), результат
            time.sleep(0.01)

    def круг_у_кадрі(кадр):
        (ф,) = кадр["фігури"]
        return ф["cx"], 600 - ф["cy"], ф["колір"]      # назад у координати програми (y вниз)

    чекати(lambda: len(кадри) >= 2)
    assert круг_у_кадрі(кадри[-1])[:2] == (200, 300)   # без дотику стоїть посередині
    колір_спокою = круг_у_кадрі(кадри[-1])[2]

    дотик_екрана(350, 100, True)
    чекати(lambda: abs(круг_у_кадрі(кадри[-1])[0] - 350) < 2 and abs(круг_у_кадрі(кадри[-1])[1] - 100) < 2)
    assert круг_у_кадрі(кадри[-1])[2] != колір_спокою

    дотик_екрана(350, 100, False)
    n = len(кадри)
    чекати(lambda: len(кадри) >= n + 2)
    x, y, колір_ = круг_у_кадрі(кадри[-1])
    assert abs(x - 350) < 2 and abs(y - 100) < 2 and колір_ == колір_спокою   # стоїть, де лишили

    вми[0].зупинено = True
    потік.join(3)
    assert not потік.is_alive()
    assert результат[0] == (ПОВІДОМЛЕННЯ_ЗУПИНЕНО + "\n", False)


