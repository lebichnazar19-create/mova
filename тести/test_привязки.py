def прямокутник_грубо():
    е.вузол("а", 0, 0)
    е.вузол("б", 50, 3)
    е.вузол("в", 48, 30)
    е.вузол("г", 2, 28)
    е.сегмент("низ", "а", "б")
    е.сегмент("права", "б", "в")
    е.сегмент("верх", "в", "г")
    е.сегмент("ліва", "г", "а")


def відстань(п, q):
    return math.hypot(q[0] - п[0], q[1] - п[1])


def test_на_відстані_між_вузлами():
    е.вузол("щиток", 0, 0)
    е.вузол("розетка", 100, 30)
    е.на_відстані("розетка", "щиток", 120)
    е.розвяжи()
    assert abs(відстань(е.вузол("розетка"), е.вузол("щиток")) - 120) < 1e-3


def test_на_відстані_від_прямої_відрізка():
    е.вузол("а", 0, 0)
    е.вузол("б", 100, 0)
    е.сегмент("підлога", "а", "б")
    е.горизонтально("підлога")
    е.вузол("розетка", 40, 10)
    е.на_відстані("розетка", "підлога", 30)
    е.розвяжи()
    assert abs(е.вузол("розетка").y - е.вузол("а").y - 30) < 1e-3


def test_паралельно_до_і_під_кутом_дають_прямокутник():
    прямокутник_грубо()
    е.горизонтально("низ")
    е.під_кутом("права", "низ", 90)
    е.паралельно_до("верх", "низ")
    е.паралельно_до("ліва", "права")
    е.довжина("низ", 50)
    е.довжина("права", 30)
    е.розвяжи()
    а, б, в, г = (е.вузол(н) for н in "абвг")
    assert abs(відстань(а, б) - 50) < 1e-3 and abs(відстань(б, в) - 30) < 1e-3
    assert abs(відстань(в, г) - 50) < 1e-3 and abs(відстань(г, а) - 30) < 1e-3
    assert abs(в.y - г.y) < 1e-3 and abs(а.y - б.y) < 1e-3   # верх паралельний низу
    assert abs(б.x - в.x) < 1e-3 and abs(г.x - а.x) < 1e-3   # боки вертикальні


def test_паралельно_до_протилежний_напрямок_теж_паралельний():
    е.вузол("а", 0, 0)
    е.вузол("б", 10, 0)
    е.вузол("в", 10, 5)
    е.вузол("г", 0, 6)
    е.сегмент("низ", "а", "б")
    е.сегмент("верх", "в", "г")   # напрямлений у зворотний бік
    е.горизонтально("низ")
    е.паралельно_до("верх", "низ")
    е.розвяжи()
    assert abs(е.вузол("в").y - е.вузол("г").y) < 1e-3


def test_на_стіні_кладе_вузол_на_відрізок_на_відстані_від_початку():
    прямокутник_грубо()
    е.горизонтально("низ")
    е.довжина("низ", 50)
    е.вузол("розетка", 10, 7)
    е.на_стіні("розетка", "низ", 12)
    е.розвяжи()
    а, б, р = е.вузол("а"), е.вузол("б"), е.вузол("розетка")
    assert abs(р.y - а.y) < 1e-3
    assert abs(відстань(а, р) - 12) < 1e-3
    assert min(а.x, б.x) - 1e-3 <= р.x <= max(а.x, б.x) + 1e-3


def test_помилки_прив_язок():
    прямокутник_грубо()
    with pytest.raises(ПомилкаВиконання) as info:
        е.на_відстані("нема", "а", 5)
    assert "немає ні вузла, ні відрізка" in str(info.value)
    with pytest.raises(ПомилкаВиконання) as info:
        е.на_відстані("низ", "а", 5)
    assert "має бути вузлом" in str(info.value)
    with pytest.raises(ПомилкаВиконання):
        е.на_відстані("а", "б", -1)
    with pytest.raises(ПомилкаВиконання):
        е.паралельно_до("низ", "нема")
    with pytest.raises(ПомилкаВиконання):
        е.на_стіні("а", "нема", 3)
    with pytest.raises(ПомилкаВиконання):
        е.на_стіні("низ", "верх", 3)
    with pytest.raises(ПомилкаВиконання):
        е.під_кутом("низ", "права", "90")


def test_суперечливі_прив_язки_дають_помилку():
    прямокутник_грубо()
    е.довжина("низ", 40)
    е.довжина("низ", 50)
    with pytest.raises(ПомилкаВиконання) as info:
        е.розвяжи()
    assert "суперечать" in str(info.value)


def test_розвязувач_доводить_похибку_майже_до_нуля():
    прямокутник_грубо()
    е.горизонтально("низ")
    е.під_кутом("права", "низ", 90)
    е.довжина("низ", 50)
    assert е.розвяжи() < 1e-8


