def _розмір(cols, lines):
    return os.terminal_size((cols, lines))


def _рядки_кадру(кадр):
    """Розібрати кадр (без жодного "\\n") на (номер_рядка, вміст) за
    абсолютними позиційними кодами курсора \\033[N;1H."""
    збіги = re.findall(r"\033\[(\d+);1H(.*?)(?=\033\[\d+;1H|$)", кадр, re.S)
    return [(int(n), вміст) for n, вміст in збіги]


# ---- _відрендерити_кадр: рендер і обрізання -----------------------------------

def test_кадр_це_один_рядок_без_переносів():
    # головна вимога: жодного "\n" усередині кадру — інакше рядково-
    # буферизований stdout для tty автоматично зробить проміжний flush на
    # кожному "\n" ще до явного flush() у тримай(), і це видно як мигання
    екран.екран(5, 3)
    кадр = екран._відрендерити_кадр(_розмір(20, 10))
    assert "\n" not in кадр


def test_кадр_вміщується_повністю_без_повідомлення():
    екран.екран(5, 3)
    кадр = екран._відрендерити_кадр(_розмір(20, 10))
    рядки = _рядки_кадру(кадр)
    assert [n for n, _ in рядки] == [1, 2, 3]  # рівно 3 рядки полотна
    assert "Не влізло" not in кадр
    # кожен рядок містить 5 клітинок (по 2 символи) + скидання + очищення до кінця рядка
    assert рядки[0][1].count("\033[48;2;") == 5


def test_кадр_обрізає_по_ширині_і_пише_повідомлення():
    екран.екран(10, 3)
    кадр = екран._відрендерити_кадр(_розмір(8, 10))  # влазить лише 4 клітинки в ширину
    рядки = _рядки_кадру(кадр)
    assert [n for n, _ in рядки] == [1, 2, 3, 4]
    assert рядки[0][1].count("\033[48;2;") == 4
    assert "6 кл. праворуч" in рядки[-1][1]
    assert "знизу" not in рядки[-1][1]


def test_кадр_обрізає_по_висоті_і_пише_повідомлення():
    екран.екран(5, 20)
    кадр = екран._відрендерити_кадр(_розмір(100, 10))
    рядки = _рядки_кадру(кадр)
    assert len(рядки) == 10  # 9 рядків полотна влізло + 1 рядок повідомлення
    assert рядки[-1][0] == 10
    assert "11 кл. знизу" in рядки[-1][1]
    assert "праворуч" not in рядки[-1][1]


def test_кадр_обрізає_і_по_ширині_і_по_висоті_одночасно():
    екран.екран(10, 20)
