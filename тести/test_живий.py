# ---- наскрізно через VM / CALL_NATIVE -----------------------------------------

def test_тримай_через_call_native_у_vm(monkeypatch, capsys):
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", lambda затримка: True)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    джерело = 'екран(3, 3)\nзапов_квадрат(0, 0, 1, "синій")\nтримай()\n'
    байткод = компілювати(парсити_текст(джерело))
    коди = [і[0] for і in байткод["код"]]
    assert коди.count("CALL_NATIVE") == 3
    assert "CALL" not in коди

    вм = ВМ(без_пристрою=True)
    вм.виконати(байткод)

    вивід = capsys.readouterr().out
    assert екран._ДОДОМУ in вивід
    assert екран._ПОКАЗАТИ_КУРСОР in вивід
