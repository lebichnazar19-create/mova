def test_кожен_рядок_полотна_закінчується_скиданням_і_очищенням():
    екран.екран(3, 2)
    кадр = екран._відрендерити_кадр(_розмір(50, 50))
    рядки = _рядки_кадру(кадр)
    for _, вміст in рядки:
        assert вміст.endswith("\033[0m\033[K")


# ---- перемальовування при зміні розміру термінала (розмір підмінюється) -------

def test_перемальовує_лише_коли_розмір_справді_змінився(monkeypatch, capsys):
    екран.екран(3, 2)

    послідовність_розмірів = [
        _розмір(40, 20),  # 1: перший кадр — завжди малюється
        _розмір(40, 20),  # 2: той самий розмір — БЕЗ перемальовування
        _розмір(60, 30),  # 3: розмір змінився (наче повернули телефон) — перемальовується
        _розмір(60, 30),  # 4: той самий — без перемальовування
    ]
    лічильник_розміру = {"i": 0}

    def фейковий_розмір():
        i = лічильник_розміру["i"]
        лічильник_розміру["i"] += 1
        return послідовність_розмірів[min(i, len(послідовність_розмірів) - 1)]

    # клавіша "q" спрацьовує рівно на 4-й перевірці — цикл встигає пройти
    # всі 4 розміри з послідовності вище
    лічильник_клавіші = {"i": 0}

    def фейкова_клавіша(затримка):
        лічильник_клавіші["i"] += 1
        return лічильник_клавіші["i"] >= 4

    monkeypatch.setattr(екран.shutil, "get_terminal_size", фейковий_розмір)
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", фейкова_клавіша)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()

    вивід = capsys.readouterr().out
    # перемальовувань має бути рівно 2 — на розмір (40,20) і на (60,30),
    # а не 4 (по кількості ітерацій циклу). Лічимо за позицією першого
    # рядка кадру (\033[1;1H) — вона з'являється рівно раз на кожен виклик
    # _відрендерити_кадр.
    assert вивід.count(екран._позиція(1)) == 2


def test_очищення_на_старті_чистить_і_буфер_прокрутки(monkeypatch, capsys):
    екран.екран(2, 2)
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", lambda затримка: True)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()

    вивід = capsys.readouterr().out
    # \033[3J (прокрутка) має йти РАЗОМ із \033[2J (видима частина) на
    # самому початку — інакше під полотном лишається старий вивід, який
    # фізично не в поточному екрані, а саме в прокрутці
    assert вивід.startswith("\033[3J\033[2J\033[H")


def test_кадр_записується_одним_write_а_не_порядково(monkeypatch):
    екран.екран(3, 2)
    монкейпатчений_розмір = _розмір(40, 20)
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: монкейпатчений_розмір)
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", lambda затримка: True)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    записи = []
    monkeypatch.setattr(sys.stdout, "write", lambda текст: записи.append(текст))

    екран.тримай()

    # рівно 3 виклики write за весь сеанс: 1) очищення+ховання курсора на
    # старті, 2) один суцільний кадр (жодного "\n" усередині нього),
    # 3) скидання кольорів+повернення курсора наприкінці — кадр цілого
    # полотна ніде не розбивається на окремі write по рядку
    assert len(записи) == 3
    кадровий_запис = записи[1]
    assert "\n" not in кадровий_запис
    assert кадровий_запис.count(екран._позиція(1)) == 1
    assert кадровий_запис.count(екран._позиція(2)) == 1


def test_тримай_ховає_і_повертає_курсор(monkeypatch, capsys):
    екран.екран(2, 2)
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", lambda затримка: True)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()

    вивід = capsys.readouterr().out
    assert екран._ПРИХОВАТИ_КУРСОР in вивід
    assert екран._ПОКАЗАТИ_КУРСОР in вивід
    # курсор має з'явитись знову ПІСЛЯ того, як його сховали
    assert вивід.index(екран._ПРИХОВАТИ_КУРСОР) < вивід.index(екран._ПОКАЗАТИ_КУРСОР)


