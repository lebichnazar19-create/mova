def _розмір(cols, lines):
    return os.terminal_size((cols, lines))


# ---- _відрендерити_кадр: рендер і обрізання -----------------------------------

def test_кадр_вміщується_повністю_без_повідомлення():
    екран.екран(5, 3)
    кадр = екран._відрендерити_кадр(_розмір(20, 10))
    assert кадр.startswith(екран._ДОДОМУ)
    рядки = кадр[len(екран._ДОДОМУ):].split("\n")
    assert len(рядки) == 3  # рівно 3 рядки полотна, без рядка-повідомлення
    assert "Не влізло" not in кадр
    # кожен рядок містить 5 клітинок (по 2 символи) + скидання + очищення до кінця рядка
    assert рядки[0].count("\033[48;2;") == 5


def test_кадр_обрізає_по_ширині_і_пише_повідомлення():
    екран.екран(10, 3)
    кадр = екран._відрендерити_кадр(_розмір(8, 10))  # влазить лише 4 клітинки в ширину
    рядки = кадр[len(екран._ДОДОМУ):].split("\n")
    assert len(рядки) == 4  # 3 рядки полотна + 1 рядок повідомлення
    assert рядки[0].count("\033[48;2;") == 4
    assert "6 кл. праворуч" in рядки[-1]
    assert "знизу" not in рядки[-1]


def test_кадр_обрізає_по_висоті_і_пише_повідомлення():
    екран.екран(5, 20)
    кадр = екран._відрендерити_кадр(_розмір(100, 10))
    рядки = кадр[len(екран._ДОДОМУ):].split("\n")
    assert len(рядки) == 10  # 9 рядків полотна влізло + 1 рядок повідомлення
    assert "11 кл. знизу" in рядки[-1]
    assert "праворуч" not in рядки[-1]


def test_кадр_обрізає_і_по_ширині_і_по_висоті_одночасно():
    екран.екран(10, 20)
    кадр = екран._відрендерити_кадр(_розмір(8, 10))
    рядки = кадр[len(екран._ДОДОМУ):].split("\n")
    assert len(рядки) == 10  # 9 рядків полотна + повідомлення
    assert "6 кл. праворуч" in рядки[-1]
    assert "11 кл. знизу" in рядки[-1]


def test_кожен_рядок_полотна_закінчується_скиданням_і_очищенням():
    екран.екран(3, 2)
    кадр = екран._відрендерити_кадр(_розмір(50, 50))
    рядки = кадр[len(екран._ДОДОМУ):].split("\n")
    for р in рядки:
        assert р.endswith("\033[0m\033[K")


# ---- перемальовування при зміні розміру термінала (розмір підмінюється) -------

def test_перемальовує_лише_коли_розмір_справді_змінився(monkeypatch, capsys):
    екран.екран(3, 2)

    послідовність_розмірів = [
        _розмір(40, 20),  # 1: перший кадр — завжди малюється
        _розмір(40, 20),  # 2: той самий розмір — БЕЗ перемальовування
        _розмір(60, 30),  # 3: розмір змінився (наче повернули телефон) — перемальовується
        _розмір(60, 30),  # 4: той самий — без перемальовування
    ]
    лічильник_розміру = {"i": 0}

    def фейковий_розмір():
        i = лічильник_розміру["i"]
        лічильник_розміру["i"] += 1
        return послідовність_розмірів[min(i, len(послідовність_розмірів) - 1)]

    # клавіша "q" спрацьовує рівно на 4-й перевірці — цикл встигає пройти
    # всі 4 розміри з послідовності вище
    лічильник_клавіші = {"i": 0}

    def фейкова_клавіша(затримка):
        лічильник_клавіші["i"] += 1
        return лічильник_клавіші["i"] >= 4

    monkeypatch.setattr(екран.shutil, "get_terminal_size", фейковий_розмір)
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", фейкова_клавіша)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()

    вивід = capsys.readouterr().out
    # перемальовувань має бути рівно 2 — на розмір (40,20) і на (60,30),
    # а не 4 (по кількості ітерацій циклу)
    assert вивід.count(екран._ДОДОМУ) == 2


def test_тримай_ховає_і_повертає_курсор(monkeypatch, capsys):
    екран.екран(2, 2)
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))
    monkeypatch.setattr(екран, "_клавіша_q_натиснута", lambda затримка: True)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()

    вивід = capsys.readouterr().out
    assert екран._ПРИХОВАТИ_КУРСОР in вивід
    assert екран._ПОКАЗАТИ_КУРСОР in вивід
    # курсор має з'явитись знову ПІСЛЯ того, як його сховали
    assert вивід.index(екран._ПРИХОВАТИ_КУРСОР) < вивід.index(екран._ПОКАЗАТИ_КУРСОР)


# ---- гарантоване прибирання (try/finally) навіть при помилці/Ctrl+C -----------

def test_ctrl_c_виходить_чисто_без_винятку(monkeypatch, capsys):
    екран.екран(2, 2)
    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))

    def кинути_переривання(затримка):
        raise KeyboardInterrupt

    monkeypatch.setattr(екран, "_клавіша_q_натиснута", кинути_переривання)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    екран.тримай()  # не повинно кинути KeyboardInterrupt назовні

    вивід = capsys.readouterr().out
    assert екран._ПОКАЗАТИ_КУРСОР in вивід
    assert "\033[0m" in вивід


def test_помилка_всередині_циклу_все_одно_повертає_курсор(monkeypatch, capsys):
    екран.екран(2, 2)

    def зламаний_розмір():
        raise RuntimeError("щось пішло не так")

    monkeypatch.setattr(екран.shutil, "get_terminal_size", зламаний_розмір)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: None)
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: None)

    with pytest.raises(RuntimeError):
        екран.тримай()  # сама помилка не проковтується...

    вивід = capsys.readouterr().out
    assert екран._ПОКАЗАТИ_КУРСОР in вивід  # ...але курсор все одно повернувся
    assert "\033[0m" in вивід


def test_відновити_термінал_викликається_навіть_при_помилці(monkeypatch, capsys):
    екран.екран(2, 2)
    виклики = []

    monkeypatch.setattr(екран.shutil, "get_terminal_size", lambda: _розмір(40, 20))

    def зламана_клавіша(затримка):
        raise RuntimeError("несподіванка")

    monkeypatch.setattr(екран, "_клавіша_q_натиснута", зламана_клавіша)
    monkeypatch.setattr(екран, "_налаштувати_термінал", lambda: "фейкові-налаштування")
    monkeypatch.setattr(екран, "_відновити_термінал", lambda н: виклики.append(н))

    with pytest.raises(RuntimeError):
        екран.тримай()

    assert виклики == ["фейкові-налаштування"]


