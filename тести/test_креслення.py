# ---- покажи(): зберігає файл і кличе пристрій.відкрий ------------------------

def test_покажи_зберігає_html_і_відкриває(tmp_path, monkeypatch):
    шлях = tmp_path / "тест_креслення.html"
    monkeypatch.setattr(к, "ШЛЯХ_ФАЙЛУ", шлях)
    виклики = []
    monkeypatch.setattr(пристрій, "відкрий", lambda ш: виклики.append(ш))

    к.аркуш(50, 50, 2)
    к.контур([[0, 0], [10, 0], [10, 10]])
    результат = к.покажи()

    assert шлях.exists()
    вміст = шлях.read_text(encoding="utf-8")
    assert вміст.lower().startswith("<!doctype html>")
    assert "<svg" in вміст
    assert виклики == [str(шлях)]
    assert результат == str(шлях)


# ---- наскрізно через CALL_NATIVE у VM -----------------------------------------

def test_креслення_через_call_native_у_vm(tmp_path, monkeypatch):
    monkeypatch.setattr(к, "ШЛЯХ_ФАЙЛУ", tmp_path / "з_вм.html")
    джерело = (
        'аркуш(100, 100, 2)\n'
        'контур([[0, 0], [50, 0], [50, 30], [0, 30]])\n'
        'розмір(0, 0, 50, 0, -10)\n'
        'штамп("Д", "Сталь", "1:1")\n'
        'покажи()\n'
    )
    байткод = компілювати(парсити_текст(джерело))
    коди = [і[0] for і in байткод["код"]]
    assert коди.count("CALL_NATIVE") == 5
    assert "CALL" not in коди

    вм = ВМ(без_пристрою=True)
    вм.виконати(байткод)

    вміст = (tmp_path / "з_вм.html").read_text(encoding="utf-8")
    assert "<svg" in вміст
    assert ">50<" in вміст
