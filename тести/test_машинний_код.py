лише_arm64 = pytest.mark.skipif(not mashyna.доступно(), reason="машинний код лише на ARM64")


def запустити(джерело, capsys):
    вм = виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out, вм


СУМА = (
    "{сл}дія сума(н)\n"
    "    хай с = 0\n"
    "    хай к = 1\n"
    "    поки к <= н\n"
    "        с = с + к\n"
    "        к = к + 1\n"
    "    поверни с\n"
)
НСД = (
    "{сл}дія нсд(а, б)\n"
    "    поки б != 0\n"
    "        хай т = б\n"
    "        б = а % б\n"
    "        а = т\n"
    "    поверни а\n"
)
ЗНАК = (
    "{сл}дія знак(х)\n"
    "    якщо х < 0\n"
    "        поверни -1\n"
    "    інакше якщо х == 0\n"
    "        поверни 0\n"
    "    інакше\n"
    "        поверни 1\n"
)
СКЛАДНА = (
    "{сл}дія складна(а, б)\n"
    "    хай р = 0\n"
    "    хай к = 0\n"
    "    поки істина\n"
    "        к = к + 1\n"
    "        якщо к > 50\n"
    "            перервись\n"
    "        якщо к % 2 == 0 і не (к % 3 == 0) або к == 7\n"
    "            продовж\n"
    "        р = р + (а * к - б) % 7 - к\n"
    "    поверни р\n"
)


def _обидва(шаблон, виклики, capsys):
    """Той самий код як «дія» і як «швидко дія» — вивід має збігатися."""
    вм_код = шаблон.format(сл="") + виклики
    шв_код = шаблон.format(сл="швидко ") + виклики
    вивід_вм, _ = запустити(вм_код, capsys)
    вивід_шв, вм = запустити(шв_код, capsys)
    return вивід_вм, вивід_шв, вм


@лише_arm64
def test_проба_повертає_42():
    д = mashyna.зібрати({"імя": "п", "параметри": [], "тіло": [{"тип": "Поверни", "вираз": {"тип": "ЧислоЛіт", "значення": 42}}]})
    assert д.виклик([]) == (0, 42)


@лише_arm64
@pytest.mark.parametrize("шаблон, виклики", [
    (СУМА, "друкуй(сума(0), сума(1), сума(10), сума(100000))\n"),
    (НСД, "друкуй(нсд(48, 18), нсд(-48, 18), нсд(7, 0), нсд(0, 0), нсд(1071, 462))\n"),
    (ЗНАК, "друкуй(знак(-5), знак(0), знак(9))\n"),
    (СКЛАДНА, "друкуй(складна(3, 5), складна(-4, 9), складна(0, 0), складна(100, -7))\n"),
])
def test_швидко_дорівнює_vm(шаблон, виклики, capsys):
    вивід_вм, вивід_шв, вм = _обидва(шаблон, виклики, capsys)
    assert вивід_шв == вивід_вм
    assert "машинна" in list(вм.функції.values())[0]   # справді зібрано


@лише_arm64
def test_остача_і_мінус_як_у_python(capsys):
    шаблон = "{сл}дія о(а, б)\n    поверни а % б\n{сл}дія м(а)\n    поверни -а\n"
    random.seed(7)
    пари = [(7, 3), (-7, 3), (7, -3), (-7, -3), (0, 5), (1, -1)] + [
        (random.randint(-10**6, 10**6), random.choice([-97, -2, 1, 3, 1000])) for _ in range(40)
    ]
    виклики = "".join(f"друкуй(о({а}, {б}), м({а}))\n" for а, б in пари)
    вивід_вм, вивід_шв, _ = _обидва(шаблон, виклики, capsys)
    assert вивід_шв == вивід_вм


