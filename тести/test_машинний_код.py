@pytest.mark.parametrize("код, причина", [
    ("швидко дія д(а)\n    поверни а / 2\n", "ділення «/»"),
    ("швидко дія д(а)\n    для х у [1]\n        поверни х\n    поверни а\n", "цикл «для»"),
    ("швидко дія д(а)\n    поверни рядок(а)\n", "виклик «рядок»"),
    ('швидко дія д(а)\n    поверни "а"\n', "рядок"),
    ("швидко дія д(а)\n    поверни а > 1\n", "порівняння «>» як значення"),
    ("швидко дія д(а)\n    поверни б\n", "змінна «б»"),
    ("швидко дія д(а)\n    поверни 1.5\n", "дробове число"),
])
def test_що_не_вкладається_попереджає_і_працює_через_vm(код, причина, capsys):
    if not mashyna.доступно():
        pytest.skip("лише ARM64")
    вивід, вм = запустити(код + "друкуй(1)\n", capsys)
    assert "Попередження: дію «д» не зібрано в машинний код" in вивід and причина in вивід
    assert "машинна" not in вм.функції["д"] and вивід.strip().endswith("1")


def test_швидко_не_перед_дією_помилка_розбору():
    from yadro.errors import ПомилкаРозбору
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("швидко хай х = 1\n")
    assert "«швидко» ставлять перед «дія»" in str(info.value)


def test_байткод_швидкої_дії_серіалізується_у_json():
    import json
    бк = компілювати(парсити_текст(СУМА.format(сл="швидко ")))
    json.dumps(бк, ensure_ascii=False)
    зробити = [к for к in бк["код"] if к[0] == "MAKE_FUNCTION"][0]
    assert len(зробити[1]) == 4 and зробити[1][3]["імя"] == "сума" and зробити[1][3]["тіло"][0]["тип"] == "Хай"


def test_repl_фрагмент_зі_швидко(capsys):
    from yadro.vm import ВМ
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст(СУМА.format(сл="швидко "))))
    вм.виконати_фрагмент(компілювати(парсити_текст("друкуй(сума(10))\n")))
    assert capsys.readouterr().out.strip().endswith("55")


def test_кодування_інструкцій_відомі_значення():
    # перевірка кількох кодувань проти відомих байтів (незалежно від платформи)
    assert mashyna._mov_imm(0, 42) == [0x52800540 | (1 << 31)] or mashyna._mov_imm(0, 42) == [0xD2800540]
    assert mashyna._RET == 0xD65F03C0
    assert mashyna._adds(0, 0, 1) == 0xAB010000
    assert mashyna._mov_imm(1, -1) == [0xD2FFFFE1 & 0xFFFFFFFF] or len(mashyna._mov_imm(1, -1)) == 4
