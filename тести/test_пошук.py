def test_прокрутка_ставить_рядок_посередині():
    # 100 рядків по 20, вікно 200: рядок 50 — посередині
    y = р.прокрутка_до_рядка(50, 20, 200, 100)
    assert y == 50 * 20 - 90
    assert y < 50 * 20 < y + 200


def test_прокрутка_не_виходить_за_початок_і_кінець():
    assert р.прокрутка_до_рядка(1, 20, 200, 100) == 0
    assert р.прокрутка_до_рядка(99, 20, 200, 100) == 100 * 20 - 200
    assert р.прокрутка_до_рядка(3, 20, 200, 5) == 0       # текст коротший за вікно


def test_прокрутка_вбік_лише_коли_не_видно():
    assert р.прокрутка_вбік(50, 90, 0, 300) == 0          # і так видно
    assert р.прокрутка_вбік(500, 540, 0, 300) == 500 - 75  # за правим краєм
    assert р.прокрутка_вбік(20, 60, 200, 300) == 0         # за лівим краєм
    нова = р.прокрутка_вбік(290, 330, 0, 300)              # кінець за краєм
    assert нова <= 290 and 330 <= нова + 300


