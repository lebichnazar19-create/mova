def усі(віджет):
    знайдені = [віджет]
    for дитина in віджет.children:
        знайдені += усі(дитина)
    return знайдені


def натиснути(панель, напис):
    for в in усі(панель):
        if type(в).__name__ == "Button" and в.text == напис:
            в.подія("on_release")
            return
    raise AssertionError(f"немає кнопки «{напис}»: {[в.text for в in усі(панель) if в.text]}")


