class _Годинник:
    def __init__(self):
        self.події = []

    def schedule_once(self, дія, затримка=0):
        self.події.append(дія)

    def минув_час(self):
        події, self.події = self.події, []
        for дія in події:
            дія(0)


class _Віджет:
    def __init__(self, **kw):
        self.children, self.обробники, self.text = [], {}, ""
        self.__dict__.update(kw)

    def add_widget(self, віджет):
        self.children.append(віджет)

    def clear_widgets(self):
        self.children = []

    def bind(self, **kw):
        for назва, дія in kw.items():
            self.обробники.setdefault(назва, []).append(дія)

    def подія(self, назва, *аргументи):
        for дія in self.обробники.get(назва, []):
            дія(self, *аргументи)

    def набрати(self, текст):
        self.text = текст
        self.подія("text", текст)


class ПолеКоду:
    """Те, що панелі треба від main.ПолеКоду."""

    def __init__(self, текст, панель=None):
        self.text_ = текст
        self.курсор = 0
        self.focus = False
        self.підсвітка = ([], 0, -1)
        self.переходи = []
        self.при_зміні = None

    @property
    def text(self):
        return self.text_

    @text.setter
    def text(self, текст):
        self.text_ = текст
        self.курсор = len(текст)          # як у Kivy: новий текст — курсор у кінець
        if self.при_зміні:
            self.при_зміні()

    def cursor_index(self):
        return self.курсор

    def показати_збіги(self, збіги, довжина, поточний):
        self.підсвітка = (list(збіги), довжина, поточний)

    def перейти(self, початок, кінець=None):
        self.курсор = початок
        self.переходи.append((початок, кінець))


