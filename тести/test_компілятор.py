"""Структурні тести компілятора для етапу 2: якщо/інакше, поки, порівняння,
логіка — перевіряють, що в байткоді справді з'являються JUMP і JUMP_FALSE,
а не просто що програма видає правильний вивід (це вже перевіряє test_вм.py)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ядро.компілятор import компілювати
from ядро.парсер import парсити_текст


def опкоди(джерело):
    байткод = компілювати(парсити_текст(джерело))
    return [інстр[0] for інстр in байткод["код"]]


def test_якщо_без_інакше_породжує_jump_false():
    коди = опкоди("якщо істина\n    друкуй(1)\n")
    assert "JUMP_FALSE" in коди
    # без "інакше" не потрібен зайвий безумовний JUMP навколо гілки
    assert "JUMP" not in коди


def test_якщо_без_інакше_адреса_jump_false_за_межі_тіла():
    байткод = компілювати(парсити_текст("якщо істина\n    друкуй(1)\nдрукуй(2)\n"))
    код = байткод["код"]
    idx_jf = next(i for i, ін in enumerate(код) if ін[0] == "JUMP_FALSE")
    ціль = код[idx_jf][1]
    # ціль переходу повинна вказувати рівно на початок другого друкуй(2)
    assert код[ціль][0] == "PUSH_CONST"


def test_якщо_з_інакше_має_і_jump_і_jump_false():
    коди = опкоди("якщо істина\n    друкуй(1)\nінакше\n    друкуй(2)\n")
    assert коди.count("JUMP_FALSE") == 1
    assert коди.count("JUMP") == 1  # безумовний стрибок у кінець з гілки "якщо"


def test_інакше_якщо_ланцюг_має_по_jump_false_на_кожну_умову():
    коди = опкоди(
        "якщо а\n    друкуй(1)\n"
        "інакше якщо б\n    друкуй(2)\n"
        "інакше якщо в\n    друкуй(3)\n"
        "інакше\n    друкуй(4)\n"
    )
    assert коди.count("JUMP_FALSE") == 3
    assert коди.count("JUMP") == 3


def test_поки_має_jump_false_і_jump_назад():
    байткод = компілювати(парсити_текст("поки істина\n    друкуй(1)\n"))
    код = байткод["код"]
    коди = [і[0] for і in код]
    assert "JUMP_FALSE" in коди
    idx_jump = next(i for i, ін in enumerate(код) if ін[0] == "JUMP")
    # JUMP циклу веде НАЗАД (адреса менша за власний індекс), на відміну від JUMP у "якщо"
    assert код[idx_jump][1] < idx_jump


def test_jump_false_у_поки_веде_після_циклу():
    байткод = компілювати(парсити_текст("поки істина\n    друкуй(1)\nдрукуй(2)\n"))
    код = байткод["код"]
    idx_jf = next(i for i, ін in enumerate(код) if ін[0] == "JUMP_FALSE")
    ціль = код[idx_jf][1]
    assert ціль > idx_jf
    assert код[-1][0] == "HALT"


def test_порівняння_компілюються_у_правильні_опкоди():
    відповідність = {
        "==": "EQ", "!=": "NEQ", "<": "LT", ">": "GT", "<=": "LTE", ">=": "GTE",
    }
    for знак, опкод in відповідність.items():
        коди = опкоди(f"друкуй(1 {знак} 2)\n")
        assert опкод in коди, f"{знак} -> {опкод}"


def test_логіка_компілюється_у_and_or_not():
    коди = опкоди("друкуй(не істина)\n")
    assert "NOT" in коди
    коди = опкоди("друкуй(істина і хиба)\n")
    assert "AND" in коди
    коди = опкоди("друкуй(істина або хиба)\n")
    assert "OR" in коди
