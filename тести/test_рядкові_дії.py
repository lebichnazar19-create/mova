"""0.7: рядкові вбудовані дії, перетворення, апостроф в іменах."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання
from yadro.kompilyator import компілювати
from yadro.lexer import токенізувати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


def помилка(джерело):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return str(info.value)


def test_розбий(capsys):
    вивід = запустити(
        'друкуй(розбий("а, б, в", ", "))\n'
        'друкуй(розбий("  один   два "))\n'
        'друкуй(розбий("абв", ""))\n'
        'друкуй(довжина(розбий("", ",")))\n',
        capsys,
    )
    assert вивід.strip().split("\n") == ["[а, б, в]", "[один, два]", "[а, б, в]", "1"]
    assert "очікує рядок" in помилка("розбий(5, ',')\n")


def test_зєднай_з_апострофом_в_імені(capsys):
    вивід = запустити(
        'друкуй(з\'єднай(["а", "б", "в"], "-"), з\'єднай([1, 2.5, істина]), з\'єднай([], ","))\n', capsys
    )
    assert вивід.split() == ["а-б-в", "12.5істина"]
    assert "очікує список" in помилка('з\'єднай("а", "-")\n')


def test_апостроф_у_власних_іменах_і_в_рядках(capsys):
    вивід = запустити(
        'хай ім\'я = "Оля"\n'
        'хай об\'єкт = {"ім\'я": ім\'я}\n'
        'друкуй(ім\'я, об\'єкт["ім\'я"], "П\'ятниця", \'а\')\n',
        capsys,
    )
    assert вивід.split() == ["Оля", "Оля", "П'ятниця", "а"]
    assert [т.значення for т in токенізувати("ім'я")][0] == "ім'я"
    # апостроф не «приклеюється», якщо далі не літера
    assert [т.тип for т in токенізувати("х'1'")][:2] == ["ІМЯ", "РЯДОК"]


def test_заміни_великими_малими_обріж(capsys):
    вивід = запустити(
        'друкуй(заміни("кіт і кіт", "кіт", "пес"))\n'
        'друкуй(великими("привіт, Оля"), малими("ПРИВІТ"))\n'
        'друкуй("[" + обріж("  так \\n") + "]")\n',
        capsys,
    )
    assert вивід.strip().split("\n") == ["пес і пес", "ПРИВІТ, ОЛЯ привіт", "[так]"]
    assert "порожній рядок" in помилка('заміни("а", "", "б")\n')


def test_починається_містить(capsys):
    вивід = запустити(
        'друкуй(починається("привіт", "при"), починається("привіт", "віт"))\n'
        'друкуй(містить("привіт", "ві"), містить("привіт", "x"), містить([1, 2], 2), містить({"а": 1}, "а"))\n',
        capsys,
    )
    assert вивід.split() == ["істина", "хиба", "істина", "хиба", "істина", "істина"]
    assert "очікує рядок" in помилка("містить(5, 5)\n")


def test_перетворення_число_текст_дробове(capsys):
    вивід = запустити(
        'друкуй(число("42") + 1, число("2.5") * 2, текст(42) + "!", текст([1, 2]), текст(ніщо))\n'
        'друкуй(дробове("3"), дробове(2), дробове("2,5"), дробове(" 1.5 "))\n',
        capsys,
    )
    assert вивід.strip().split("\n") == ["43 5.0 42! [1, 2] ніщо", "3.0 2.0 2.5 1.5"]
    assert "на дробове число" in помилка('дробове("абв")\n')
    assert "на число" in помилка('число("абв")\n')


def test_текст_з_пятьма_аргументами_лишається_малюванням():
    assert "1 аргумент" in помилка("текст(1, 2)\n")
    # 5 аргументів — малювання: без полотна дає його помилку, а не «текст»
    assert "полотно" in помилка('текст(1, 2, "а", 10, "чорний")\n').lower()
