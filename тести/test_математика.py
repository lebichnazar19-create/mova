"""0.7: математичні вбудовані дії та стала ПІ."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання, ПомилкаКомпіляції
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


def помилка(джерело):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return str(info.value)


def test_корінь(capsys):
    assert запустити("друкуй(корінь(16), корінь(2.25), корінь(0))\n", capsys).split() == ["4", "1.5", "0"]
    assert "від'ємного" in помилка("корінь(-4)\n")
    assert "очікує число" in помилка('корінь("4")\n')


def test_степінь(capsys):
    assert запустити("друкуй(степінь(2, 10), степінь(4, 0.5), степінь(2, -1))\n", capsys).split() == ["1024", "2", "0.5"]
    assert "не є дійсним" in помилка("степінь(-8, 0.5)\n")


def test_округли(capsys):
    вивід = запустити("друкуй(округли(3.14159, 2), округли(2.5), округли(-2.5), округли(2.4), округли(7))\n", capsys)
    assert вивід.split() == ["3.14", "3", "-3", "2", "7"]
    # цілий результат зі знаками — ціле: 5, а не 5.0
    assert запустити("друкуй(округли(5, 3), округли(2.999, 2), округли(2.5, 1))\n", capsys).split() == ["5", "3", "2.5"]
    assert "ціле число знаків" in помилка("округли(1.5, 1.5)\n")


def test_модуль(capsys):
    assert запустити("друкуй(модуль(-7), модуль(7), модуль(-1.5))\n", capsys).split() == ["7", "7", "1.5"]


def test_мінімум_максимум_числа_і_список(capsys):
    вивід = запустити("друкуй(мінімум(3, 1, 2), максимум(3, 1, 2), мінімум([5, 4]), максимум([5, 4]), мінімум(7))\n", capsys)
    assert вивід.split() == ["1", "3", "4", "5", "7"]
    assert "хоча б одне" in помилка("мінімум([])\n")
    assert "очікує число" in помилка('максимум(1, "2")\n')


def test_тригонометрія_і_пі(capsys):
    вивід = запустити(
        "друкуй(округли(синус(ПІ / 2)), округли(косинус(ПІ)), округли(тангенс(ПІ / 4), 6), округли(арктангенс2(1, 1), 4))\n"
        "друкуй(округли(ПІ, 5))\n",
        capsys,
    )
    assert вивід.split() == ["1", "-1", "1", "0.7854", "3.14159"]   # тангенс -> 1, не 1.0


def test_випадкове_ціле_і_дробове(capsys):
    вивід = запустити(
        "хай ок = істина\n"
        "для i у діапазон(50)\n"
        "    хай в = випадкове(1, 6)\n"
        "    якщо в < 1 або в > 6 або в != цілий(в)\n"
        "        ок = хиба\n"
        "хай д = випадкове(0.5, 1.5)\n"
        "друкуй(ок, д >= 0.5 і д <= 1.5, випадкове(3, 3))\n",
        capsys,
    )
    assert вивід.split() == ["істина", "істина", "3"]
    assert "більша за верхню" in помилка("випадкове(5, 1)\n")


def test_пі_можна_перекрити_але_не_присвоїти(capsys):
    assert запустити("стала ПІ = 3.14\nдрукуй(ПІ)\n", capsys).strip() == "3.14"
    assert запустити("хай ПІ = 3\nПІ = 4\nдрукуй(ПІ)\n", capsys).strip() == "4"
    with pytest.raises(ПомилкаКомпіляції) as info:
        компілювати(парсити_текст("ПІ = 3\n"))
    assert "сталу «ПІ»" in str(info.value)


def test_пі_у_дії_і_в_repl_фрагменті(capsys):
    from yadro.vm import ВМ

    assert запустити("дія к(r)\n    поверни округли(ПІ * r * r, 2)\nдрукуй(к(1))\n", capsys).strip() == "3.14"
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст("друкуй(округли(ПІ, 2))\n")))
    assert capsys.readouterr().out.strip() == "3.14"


def test_власну_дію_не_можна_назвати_як_вбудовану():
    with pytest.raises(ПомилкаКомпіляції):
        компілювати(парсити_текст("дія корінь(x)\n    поверни x\n"))
