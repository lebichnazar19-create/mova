"""Ключове слово на місці імені (хай для = 5) — зрозуміла помилка розбору."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаРозбору
from yadro.parser import парсити_текст


@pytest.mark.parametrize("джерело, слово, що", [
    ("хай для = 5\n", "для", "ім'я змінної"),
    ("стала друкуй = 3\n", "друкуй", "ім'я змінної"),
    ("дія якщо()\n    поверни 1\n", "якщо", "ім'я дії"),
    ("дія ф(поки)\n    поверни 1\n", "поки", "ім'я параметра"),
    ("дія ф(а, хай)\n    поверни 1\n", "хай", "ім'я параметра"),
    ("для дія у [1]\n    друкуй(1)\n", "дія", "ім'я змінної циклу"),
])
def test_ключове_слово_як_імя(джерело, слово, що):
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст(джерело)
    текст = str(info.value)
    assert f"«{слово}» — ключове слово" in текст
    assert що in текст
    assert "в рядку 1" in текст


def test_не_ключове_слово_дає_стару_помилку():
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("хай 5 = 5\n")
    assert "Очікувалось ім'я змінної" in str(info.value)
    assert "ключове слово" not in str(info.value)


def test_схоже_на_ключове_слово_дозволено():
    парсити_текст("хай хайдер = 1\nхай для_кого = 2\n")
