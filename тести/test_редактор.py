"""Редактор застосунку (redaktor.py) — усе, що перевіряється без екрана:
каркаси кнопок, автовідступ, автозакриття, перевірка коду, розбір
помилки з виводу, лексер підсвітки."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

import redaktor as р


# ---- каркаси -----------------------------------------------------------------

def test_кожна_кнопка_має_каркас_або_просту_вставку():
    for ключ in р.КНОПКИ:
        assert ключ in р.КАРКАСИ or ключ in р.ПРОСТІ_ВСТАВКИ, ключ
    for ключ in ("тип", "спробуй", "якщо помилка", "словник", "для", "друкуй"):
        assert ключ in р.КНОПКИ


def test_якщо_дає_умову_виділеною_і_відступ_на_новому_рядку():
    вставка, поч, кін = р.каркас("якщо", "", 0)
    assert вставка == "якщо умова\n    "
    assert вставка[поч:кін] == "умова"


def test_каркас_успадковує_відступ_поточного_рядка():
    текст = "дія ф()\n    "
    вставка, поч, кін = р.каркас("якщо", текст, len(текст))
    assert вставка == "якщо умова\n        "
    assert (текст + вставка)[поч:кін] == "умова"


def test_каркас_у_середині_тексту_індекси_абсолютні():
    текст = "x = 1\n\ny = 2"
    курсор = 6
    вставка, поч, кін = р.каркас("поки", текст, курсор)
    новий = текст[:курсор] + вставка + текст[курсор:]
    assert новий[поч:кін] == "умова"


def test_друкуй_курсор_між_лапками():
    вставка, поч, кін = р.каркас("друкуй", "", 0)
    assert вставка == 'друкуй("")' and поч == кін == len('друкуй("')


def test_дія_поки_для_тип_каркаси():
    assert р.каркас("дія", "", 0)[0] == "дія назва()\n    "
    assert р.каркас("поки", "", 0)[0] == "поки умова\n    "
    вставка, поч, кін = р.каркас("для", "", 0)
    assert вставка == "для елемент у список\n    " and вставка[поч:кін] == "елемент"
    вставка, поч, кін = р.каркас("тип", "", 0)
    assert вставка == "тип Назва\n    поле\n    " and вставка[поч:кін] == "Назва"


def test_спробуй_дає_обидва_блоки_і_курсор_у_першому():
    вставка, поч, кін = р.каркас("спробуй", "", 0)
    assert вставка == "спробуй\n    \nякщо помилка\n    друкуй(помилка)"
    assert поч == кін == len("спробуй\n    ")
    вставка, _, _ = р.каркас("спробуй", "  ", 2)
    assert вставка == "спробуй\n      \n  якщо помилка\n      друкуй(помилка)"


def test_словник_кинь_хай_поверни():
    assert р.каркас("словник", "", 0) == ("словник()", 8, 8)
    assert р.каркас("кинь", "", 0) == ('кинь("")', 6, 6)
    вставка, поч, кін = р.каркас("хай", "", 0)
    assert вставка == "хай назва = " and вставка[поч:кін] == "назва"
    assert р.каркас("поверни", "", 0) == ("поверни ", 8, 8)


def test_каркаси_без_двокрапок_компілюються_після_заповнення():
    # у мові немає «:» після умови — каркас має давати чинний код
    for ключ, заповнення in (("якщо", "1 > 0"), ("поки", "хиба"), ("дія", "ф")):
        вставка, поч, кін = р.каркас(ключ, "", 0)
        код = вставка[:поч] + заповнення + вставка[кін:] + "друкуй(1)\n"
        assert р.перевірити(код) is None, код
    вставка, поч, кін = р.каркас("для", "", 0)
    код = вставка[:поч] + "х" + вставка[кін:] + "друкуй(х)\n"
    assert р.перевірити("хай список = [1]\n" + код) is None
    вставка, _, _ = р.каркас("спробуй", "", 0)
    assert р.перевірити(вставка.replace("\n    \n", "\n    кинь(1)\n") + "\n") is None


# ---- автовідступ --------------------------------------------------------------

@pytest.mark.parametrize("рядок", [
    "якщо а > 1", "інакше", "інакше якщо б", "поки істина", "для х у список",
    "дія ф(а, б)", "тип Точка", "спробуй", "якщо помилка", "    якщо а",
])
def test_enter_після_рядка_що_відкриває_блок_додає_відступ(рядок):
    базовий = рядок[: len(рядок) - len(рядок.lstrip(" "))]
    assert р.автовідступ(рядок, len(рядок)) == "\n" + базовий + "    "


def test_enter_після_рядка_з_двокрапкою_теж_додає_відступ():
    assert р.автовідступ("якщо а:", 7) == "\n    "


def test_enter_після_звичайного_рядка_зберігає_відступ():
    assert р.автовідступ("    друкуй(1)", 13) == "\n    "
    assert р.автовідступ("х = 1", 5) == "\n"
    assert р.автовідступ("", 0) == "\n"


def test_enter_дивиться_лише_на_рядок_курсора():
    текст = "якщо а\n    х = 1"
    assert р.автовідступ(текст, len(текст)) == "\n    "
    assert р.автовідступ(текст, 6) == "\n    "   # курсор у кінці першого рядка


def test_ключове_слово_в_коментарі_чи_в_середині_не_відкриває_блок():
    assert р.автовідступ("х = 1  # якщо", 13) == "\n"
    assert р.автовідступ("якщось = 1", 10) == "\n"
    assert not р.відкриває_блок("# дія")


# ---- автозакриття ----------------------------------------------------------------

def test_відкривна_дужка_дає_пару_з_курсором_усередині():
    assert р.автозакриття("", 0, "(") == ("()", 1)
    assert р.автозакриття("x", 1, "[") == ("[]", 2)
    assert р.автозакриття("", 0, "{") == ("{}", 1)


def test_закривна_дужка_перед_такою_самою_лише_переступає():
    assert р.автозакриття("()", 1, ")") == ("", 2)
    assert р.автозакриття("[]", 1, "]") == ("", 2)
    assert р.автозакриття("{}", 1, "}") == ("", 2)
    assert р.автозакриття("(x", 2, ")") is None   # немає пари — вставити як є


def test_лапка_дає_пару_і_переступає_наявну():
    assert р.автозакриття("", 0, '"') == ('""', 1)
    assert р.автозакриття('""', 1, '"') == ("", 2)
    assert р.автозакриття('друкуй()', 7, '"') == ('""', 8)


def test_лапка_всередині_слова_не_парується():
    assert р.автозакриття("П", 1, '"') is None
    assert р.автозакриття("x", 0, '"') is None
    assert р.автозакриття("П'ят", 1, "'") is None  # апостроф ніколи не парується


def test_інші_символи_не_чіпаються():
    assert р.автозакриття("", 0, "a") is None
    assert р.автозакриття("", 0, "=") is None


# ---- перевірка коду й помилки ----------------------------------------------------

def test_перевірити_чинний_код():
    assert р.перевірити('друкуй("ок")\n') is None
    assert р.перевірити("") is None


def test_перевірити_помилка_розбору_дає_рядок_і_пояснення():
    рядок, пояснення = р.перевірити('друкуй(1)\nхай = 5\n')
    assert рядок == 2 and пояснення.startswith("Помилка розбору")


def test_перевірити_помилка_компіляції():
    рядок, пояснення = р.перевірити("друкуй(1)\nдрукуй(2)\nперервись\n")
    assert рядок == 3 and "перервись" in пояснення


def test_перевірити_рядок_не_виходить_за_межі_тексту():
    рядок, _ = р.перевірити("якщо 1")   # блок так і не відкрито — помилка в кінці
    assert 1 <= рядок <= 1


def test_помилка_з_виводу_виконання():
    вивід = (
        "до\n"
        "Помилка виконання в рядку 2, позиція 8:\n"
        "    друкуй(1 / 0)\n"
        "           ^\n"
        "Ділення на нуль.\n"
    )
    assert р.помилка_з_виводу(вивід) == (2, "Помилка виконання: Ділення на нуль.")


def test_помилка_з_виводу_без_помилки():
    assert р.помилка_з_виводу("привіт\n1 2 3\n") is None
    assert р.помилка_з_виводу("") is None


def test_помилка_з_виводу_zapusk_наскрізь():
    from zapusk import виконати_код

    вивід, успіх = виконати_код('друкуй("а")\nхай х = [1]\nдрукуй(х[5])')
    assert not успіх
    рядок, пояснення = р.помилка_з_виводу(вивід)
    assert рядок == 3 and "поза межами" in пояснення


# ---- підсвітка ---------------------------------------------------------------------

pygments = pytest.importorskip("pygments")


def _токени(код):
    from pygments import lex
    return [(str(т), з) for т, з in lex(код, р.МоваLexer()) if з.strip()]


def test_лексер_класи_токенів():
    токени = dict(
        (з, т) for т, з in _токени('хай х = "текст" # коментар\nдрукуй(х, 1.5, 42, істина)')
    )
    assert токени["хай"] == "Token.Keyword"
    assert токени["х"] == "Token.Name"
    assert токени['"текст"'] == "Token.Literal.String.Double"
    assert токени["# коментар"] == "Token.Comment.Single"
    assert токени["друкуй"] == "Token.Name.Builtin"
    assert токени["1.5"] == "Token.Literal.Number.Float"
    assert токени["42"] == "Token.Literal.Number.Integer"
    assert токени["істина"] == "Token.Keyword.Constant"


def test_лексер_усі_ключові_слова_мови_підсвічуються():
    from yadro.keywords import КЛЮЧОВІ_СЛОВА
    for слово in КЛЮЧОВІ_СЛОВА:
        (тип, значення), = _токени(слово)
        assert тип.startswith("Token.Keyword") or тип == "Token.Name.Builtin", слово


def test_лексер_ключове_слово_як_частина_імені_це_імя():
    assert _токени("якщось")[0][0] == "Token.Name"
    assert _токени("для_х")[0][0] == "Token.Name"


def test_лексер_незакритий_рядок_і_лапки_з_апострофом():
    assert _токени('"незакритий')[0][0] == "Token.Literal.String.Double"
    (тип, значення), = _токени('"П\'ятниця"')
    assert тип == "Token.Literal.String.Double" and значення == '"П\'ятниця"'
