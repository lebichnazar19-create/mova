# ---- базова логіка ------------------------------------------------------------

def test_малювання_без_полотна_дає_помилку():
    with pytest.raises(ПомилкаВиконання, match="полотно"):
        малюнок.квадрат(0, 0, 10, "синій")


def test_покажи_без_полотна_дає_помилку():
    with pytest.raises(ПомилкаВиконання, match="полотно"):
        малюнок.покажи()


def test_полотно_скидає_попередні_фігури():
    малюнок.полотно(100, 100)
    малюнок.квадрат(0, 0, 10, "синій")
    assert len(малюнок._фігури) == 1

    малюнок.полотно(50, 50)  # новий малюнок — старі фігури мають зникнути
    assert малюнок._фігури == []
    assert малюнок._полотно == {"ширина": 50, "висота": 50}


def test_полотно_вимагає_додатні_розміри():
    with pytest.raises(ПомилкаВиконання):
        малюнок.полотно(0, 100)
    with pytest.raises(ПомилкаВиконання):
        малюнок.полотно(100, -5)


# ---- кольори --------------------------------------------------------------------

@pytest.mark.parametrize("назва,очікуваний_hex", list(малюнок.КОЛЬОРИ.items()))
def test_українські_назви_кольорів(назва, очікуваний_hex):
    малюнок.полотно(10, 10)
    малюнок.квадрат(0, 0, 1, назва)
    assert малюнок._фігури[-1]["колір"] == очікуваний_hex


def test_колір_у_форматі_hex_приймається_як_є():
    малюнок.полотно(10, 10)
    малюнок.коло(1, 1, 1, "#AB12CD")
    assert малюнок._фігури[-1]["колір"] == "#AB12CD"


def test_невідомий_колір_дає_зрозумілу_помилку():
    малюнок.полотно(10, 10)
    with pytest.raises(ПомилкаВиконання, match="Невідомий колір"):
        малюнок.квадрат(0, 0, 10, "рожевий-в-цяточку")


def test_неправильний_hex_відхиляється():
    малюнок.полотно(10, 10)
    with pytest.raises(ПомилкаВиконання):
        малюнок.квадрат(0, 0, 10, "#GGGGGG")
    with pytest.raises(ПомилкаВиконання):
        малюнок.квадрат(0, 0, 10, "#FFF")  # закороткий — потрібно рівно 6 знаків


