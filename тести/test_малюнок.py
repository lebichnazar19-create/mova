def test_покажи_пише_html_а_не_голий_svg(tmp_path, monkeypatch):
    шлях = tmp_path / "м.html"
    monkeypatch.setattr(малюнок, "ШЛЯХ_ФАЙЛУ", шлях)
    monkeypatch.setattr(пристрій, "відкрий", lambda ш: None)

    малюнок.полотно(50, 50)
    малюнок.квадрат(0, 0, 10, "синій")
    малюнок.покажи()

    вміст = шлях.read_text(encoding="utf-8")
    assert вміст.lower().startswith("<!doctype html>")
    assert "<svg" in вміст and "#1E88E5" in вміст


# ---- покажи(): зберігає файл і кличе пристрій.відкрий ------------------------

def test_покажи_зберігає_файл_і_відкриває(tmp_path, monkeypatch):
    шлях = tmp_path / "тест_малюнок.svg"
    monkeypatch.setattr(малюнок, "ШЛЯХ_ФАЙЛУ", шлях)

    виклики = []
    monkeypatch.setattr(пристрій, "відкрий", lambda ш: виклики.append(ш))

    малюнок.полотно(100, 100)
    малюнок.квадрат(0, 0, 10, "синій")
    результат = малюнок.покажи()

    assert шлях.exists()
    вміст = шлях.read_text(encoding="utf-8")
    assert "<svg" in вміст and "#1E88E5" in вміст
    assert виклики == [str(шлях)]
    assert результат == str(шлях)


def test_покажи_не_чіпає_subprocess_напряму(tmp_path, monkeypatch):
    # у малюнок.py взагалі немає subprocess — увесь запуск іде через
    # пристрій.відкрий(), яку тут підміняємо
    import subprocess

    def заборонено(*а, **кв):
        raise AssertionError("малюнок.py не повинен викликати subprocess напряму")

    monkeypatch.setattr(subprocess, "Popen", заборонено)
    monkeypatch.setattr(subprocess, "run", заборонено)
    monkeypatch.setattr(малюнок, "ШЛЯХ_ФАЙЛУ", tmp_path / "м.svg")
    monkeypatch.setattr(пристрій, "відкрий", lambda ш: None)

    малюнок.полотно(10, 10)
    малюнок.покажи()  # не повинно кинути AssertionError вище


# ---- наскрізно через VM / CALL_NATIVE -----------------------------------------

def test_малюнок_через_call_native_у_vm(tmp_path, monkeypatch):
    monkeypatch.setattr(малюнок, "ШЛЯХ_ФАЙЛУ", tmp_path / "з_вм.svg")

    джерело = (
        'полотно(200, 200)\n'
        'квадрат(50, 50, 100, "синій")\n'
        'покажи()\n'
    )
    байткод = компілювати(парсити_текст(джерело))
    коди = [і[0] for і in байткод["код"]]
    assert коди.count("CALL_NATIVE") == 3  # полотно, квадрат, покажи
    assert "CALL" not in коди  # це все нативні виклики, не власні дії

    вм = ВМ(без_пристрою=True)  # симуляція тільки для пристрій.відкрий()
    вм.виконати(байткод)

    вміст = (tmp_path / "з_вм.svg").read_text(encoding="utf-8")
    assert "#1E88E5" in вміст
    assert 'width="100"' in вміст and 'height="100"' in вміст
