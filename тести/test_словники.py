"""0.5: словники — словник()/{...}, читання-запис за ключем і через крапку,
«у» / «не у», перебір ключів у «для», ключі(), вилучи()."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання, ПомилкаРозбору
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


def test_порожній_словник_і_запис_за_ключем(capsys):
    вивід = запустити(
        "хай д = словник()\n"
        'д["яблуко"] = 3\n'
        'д["груша"] = 5\n'
        'друкуй(д["яблуко"] + д["груша"], довжина(д))\n',
        capsys,
    )
    assert вивід.strip() == "8 2"


def test_словник_з_парами_і_літерал(capsys):
    вивід = запустити(
        'хай а = словник("один", 1, "два", 2)\n'
        'хай б = {"один": 1, "два": 2}\n'
        "друкуй(а == б, а, {})\n",
        capsys,
    )
    assert вивід.strip() == "істина {один: 1, два: 2} {}"


def test_словник_непарні_аргументи_помилка():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст('словник("а")\n')), без_пристрою=True)
    assert "пари" in str(info.value)


def test_доступ_через_крапку_без_лапок(capsys):
    вивід = запустити(
        "хай д = словник()\n"
        "д.імя = \"Оля\"\n"
        "д.вік = 7\n"
        'друкуй(д.імя, д["вік"], д.вік + 1)\n',
        capsys,
    )
    assert вивід.strip() == "Оля 7 8"


def test_перевірка_наявності_ключа_у_і_не_у(capsys):
    вивід = запустити(
        'хай д = {"а": 1}\n'
        'друкуй("а" у д, "б" у д, "б" не у д)\n'
        'якщо "а" у д і "б" не у д\n'
        '    друкуй("так")\n',
        capsys,
    )
    assert вивід.split() == ["істина", "хиба", "істина", "так"]


def test_у_працює_і_для_списку_та_рядка(capsys):
    вивід = запустити(
        'друкуй(2 у [1, 2, 3], 9 не у [1, 2], "ри" у "привіт", "ж" у "привіт")\n',
        capsys,
    )
    assert вивід.split() == ["істина", "істина", "істина", "хиба"]


def test_для_перебирає_ключі_у_порядку_додавання(capsys):
    вивід = запустити(
        "хай д = словник()\n"
        'д["б"] = 2\n'
        'д["а"] = 1\n'
        "для к у д\n"
        '    друкуй(к, д[к])\n',
        capsys,
    )
    assert вивід.strip().split("\n") == ["б 2", "а 1"]


def test_ключі_повертає_список_а_вилучи_ключ(capsys):
    вивід = запустити(
        'хай д = {"а": 1, "б": 2}\n'
        "хай к = ключі(д)\n"
        "сортуй(к)\n"
        'хай з = вилучи(д, "а")\n'
        "друкуй(к, з, д)\n",
        capsys,
    )
    assert вивід.strip() == "[а, б] 1 {б: 2}"


def test_відсутній_ключ_помилка_з_текстом():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(
            компілювати(парсити_текст('хай д = словник()\nдрукуй(д["нема"])\n')),
            без_пристрою=True,
        )
    assert "немає ключа «нема»" in str(info.value)


def test_список_ключем_словника_помилка():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст("хай д = {[1]: 2}\n")), без_пристрою=True)
    assert "Ключем словника" in str(info.value)


def test_вкладені_словники_і_списки(capsys):
    вивід = запустити(
        'хай д = {"люди": [{"імя": "Оля"}, {"імя": "Іван"}]}\n'
        'для л у д.люди\n'
        "    друкуй(л.імя)\n",
        capsys,
    )
    assert вивід.split() == ["Оля", "Іван"]


def test_старий_синтаксис_циклу_для_і_списки_не_зламано(capsys):
    вивід = запустити(
        "для x у [3, 4]\n    друкуй(x)\n"
        'для с у "ab"\n    друкуй(с)\n',
        capsys,
    )
    assert вивід.split() == ["3", "4", "a", "b"]


def test_незакрита_фігурна_дужка_помилка_розбору():
    with pytest.raises(ПомилкаРозбору):
        парсити_текст('хай д = {"а": 1\n')
