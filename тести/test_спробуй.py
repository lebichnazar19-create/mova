"""0.5: обробка помилок — «спробуй» / «якщо помилка», змінна «помилка»,
кинь(), взаємодія з дією/поверни/циклом/перервись, вкладення, REPL."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод, ВМ, ВиконанняЗупинено


def запустити(джерело, capsys):
    вм = виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out, вм


def test_помилка_перехоплюється_і_текст_доступний(capsys):
    вивід, _ = запустити(
        "спробуй\n"
        '    хай х = число("абв")\n'
        '    друкуй("не дійде")\n'
        "якщо помилка\n"
        '    друкуй("сталося:", помилка)\n'
        'друкуй("далі")\n',
        capsys,
    )
    assert вивід.strip().split("\n") == [
        "сталося: Не вдалося перетворити рядок «абв» на число.",
        "далі",
    ]


def test_різні_помилки_виконання(capsys):
    вивід, _ = запустити(
        "спробуй\n    друкуй(1 / 0)\nякщо помилка\n    друкуй(помилка)\n"
        "спробуй\n    друкуй([1][5])\nякщо помилка\n    друкуй(помилка)\n"
        "спробуй\n    друкуй(нема)\nякщо помилка\n    друкуй(помилка)\n"
        'спробуй\n    друкуй("а" < 1)\nякщо помилка\n    друкуй(помилка)\n',
        capsys,
    )
    рядки = вивід.strip().split("\n")
    assert рядки[0] == "Ділення на нуль."
    assert "поза межами" in рядки[1]
    assert "Невідома змінна «нема»" in рядки[2]
    assert "Не можна порівняти" in рядки[3]


def test_без_помилки_обробник_не_виконується(capsys):
    вивід, _ = запустити(
        'спробуй\n    друкуй("ок")\nякщо помилка\n    друкуй("ні")\n', capsys
    )
    assert вивід.strip() == "ок"


def test_спробуй_без_обробника_ковтає_помилку(capsys):
    вивід, _ = запустити('спробуй\n    кинь("х")\nдрукуй("живий")\n', capsys)
    assert вивід.strip() == "живий"


def test_кинь_власну_помилку(capsys):
    вивід, _ = запустити(
        'спробуй\n    кинь("завелике", 5)\nякщо помилка\n    друкуй(помилка)\n', capsys
    )
    assert вивід.strip() == "завелике 5"


def test_кинь_поза_спробуй_зупиняє_програму_як_помилка_виконання():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст('кинь("стоп")\n')), без_пристрою=True)
    assert info.value.повідомлення == "стоп" and info.value.рядок == 1


def test_помилка_в_дії_ловиться_ззовні_і_кадри_знімаються(capsys):
    вивід, вм = запустити(
        "дія глибоко(n)\n"
        "    якщо n == 0\n"
        '        кинь("дно")\n'
        "    поверни глибоко(n - 1)\n"
        "спробуй\n"
        "    глибоко(5)\n"
        "якщо помилка\n"
        "    друкуй(помилка)\n",
        capsys,
    )
    assert вивід.strip() == "дно"
    assert вм.кадри == [] and вм.стек_повернень == [] and вм.обробники == []


def test_поверни_зсередини_спробуй_у_дії(capsys):
    вивід, вм = запустити(
        "дія безпечно(n)\n"
        "    спробуй\n"
        "        якщо n > 1\n"
        '            кинь("завелике")\n'
        "        поверни n\n"
        "    якщо помилка\n"
        '        поверни "помилка: " + помилка\n'
        "друкуй(безпечно(1), безпечно(5))\n"
        # після повернення через «поверни» обробник знято: помилка нижче — справжня
        "спробуй\n"
        "    безпечно(1)\n"
        '    кинь("зовні")\n'
        "якщо помилка\n"
        "    друкуй(помилка)\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["1 помилка: завелике", "зовні"]
    assert вм.обробники == []


def test_перервись_і_продовж_зсередини_спробуй_знімають_обробник(capsys):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(
            компілювати(парсити_текст(
                "для i у діапазон(5)\n"
                "    спробуй\n"
                "        якщо i == 1\n"
                "            продовж\n"
                "        якщо i == 3\n"
                "            перервись\n"
                "        друкуй(i)\n"
                "    якщо помилка\n"
                '        друкуй("ні")\n'
                'кинь("справжня")\n'
            )),
            без_пристрою=True,
        )
    assert info.value.повідомлення == "справжня"
    assert capsys.readouterr().out.split() == ["0", "2"]


def test_вкладені_спробуй_і_помилка_в_обробнику_йде_назовні(capsys):
    вивід, _ = запустити(
        "спробуй\n"
        "    спробуй\n"
        '        кинь("внутрішня")\n'
        "    якщо помилка\n"
        '        кинь("зовнішня після " + помилка)\n'
        "якщо помилка\n"
        "    друкуй(помилка)\n",
        capsys,
    )
    assert вивід.strip() == "зовнішня після внутрішня"


def test_стек_відновлюється_після_помилки_посеред_виразу(capsys):
    вивід, вм = запустити(
        "спробуй\n"
        "    хай х = 1 + (2 * (3 / 0))\n"
        "якщо помилка\n"
        '    друкуй("ок")\n'
        "друкуй(довжина([1, 2]))\n",
        capsys,
    )
    assert вивід.split() == ["ок", "2"]
    assert вм.стек == []


def test_помилка_є_звичайною_змінною_після_блоку(capsys):
    вивід, _ = запустити(
        'спробуй\n    кинь("х")\nякщо помилка\n    хай з = помилка\n'
        "друкуй(помилка, з)\n"
        # звичайне «якщо помилка» з умовою — не обробник
        'якщо помилка == "х"\n    друкуй("так")\n',
        capsys,
    )
    assert вивід.split() == ["х", "х", "так"]


def test_зупинка_ззовні_не_перехоплюється_спробуй():
    вм = ВМ(без_пристрою=True)
    вм.зупинено = True
    with pytest.raises(ВиконанняЗупинено):
        вм.виконати(компілювати(парсити_текст('спробуй\n    друкуй(1)\nякщо помилка\n    друкуй("ні")\n')))


def test_repl_фрагмент_зі_спробуй_переадресовує_обробник(capsys):
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст("хай а = 1\n")))
    вм.виконати_фрагмент(
        компілювати(парсити_текст('спробуй\n    кинь("б")\nякщо помилка\n    друкуй(а, помилка)\n'))
    )
    assert capsys.readouterr().out.strip() == "1 б"


def test_zapusk_спробуй_у_застосунку():
    from zapusk import виконати_код

    вивід, успіх = виконати_код('спробуй\n    друкуй(1 / 0)\nякщо помилка\n    друкуй("є:", помилка)')
    assert успіх and вивід.strip() == "є: Ділення на нуль."
