"""«підключи "файл.мова"» — підключення дій з іншого файлу (ядро/модулі.py).

Перевіряє: щасливий шлях (дії з підключеного файлу доступні), три помилкові
випадки (файл не знайдено, циклічне підключення, конфлікт імен дій),
діамантове підключення (той самий файл підключений з двох місць — не
помилка й не виконується двічі), підключення відносно директорії файлу
(не поточної робочої директорії), і заборону «підключи» не на верхньому
рівні файлу.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from ядро.компілятор import компілювати
from ядро.модулі import завантажити_програму
from ядро.парсер import парсити_текст
from ядро.помилки import ПомилкаПідключення, ПомилкаРозбору
from ядро.вм import виконати_байткод

import мова as мова_cli


def _запустити_файл(шлях, capsys):
    програма, _ = завантажити_програму(шлях)
    байткод = компілювати(програма)
    виконати_байткод(байткод, без_пристрою=True)
    return capsys.readouterr().out


# ---- щасливий шлях ---------------------------------------------------------

def test_підключи_дію_з_іншого_файлу(tmp_path, capsys):
    (tmp_path / "утиліти.мова").write_text(
        'дія привітай(імя)\n    поверни "Привіт, " + імя + "!"\n',
        encoding="utf-8",
    )
    головний = tmp_path / "головний.мова"
    головний.write_text(
        'підключи "утиліти.мова"\n'
        'друкуй(привітай("Оля"))\n',
        encoding="utf-8",
    )
    вивід = _запустити_файл(головний, capsys)
    assert вивід.strip() == "Привіт, Оля!"


def test_підключи_кілька_дій_і_свій_код_після(tmp_path, capsys):
    # навмисно не "квадрат"/"коло" тощо — ці імена зайняті вбудованими
    # функціями малювання (розділ 10 ДОВІДНИК.md), і власна дія з таким
    # іменем — окремий, уже перевірений в іншому місці випадок помилки
    (tmp_path / "мат.мова").write_text(
        "дія у_квадраті(х)\n    поверни х * х\n"
        "дія у_кубі(х)\n    поверни х * х * х\n",
        encoding="utf-8",
    )
    головний = tmp_path / "головний.мова"
    головний.write_text(
        'підключи "мат.мова"\n'
        "друкуй(у_квадраті(3), у_кубі(2))\n",
        encoding="utf-8",
    )
    вивід = _запустити_файл(головний, capsys)
    assert вивід.split() == ["9", "8"]


def test_підключи_відносно_директорії_файлу_а_не_робочої(tmp_path, capsys, monkeypatch):
    тека = tmp_path / "проєкт"
    тека.mkdir()
    (тека / "утиліти.мова").write_text(
        'дія слово()\n    поверни "тут"\n', encoding="utf-8"
    )
    головний = тека / "головний.мова"
    головний.write_text(
        'підключи "утиліти.мова"\n'
        "друкуй(слово())\n",
        encoding="utf-8",
    )
    # робоча директорія — щось зовсім інше; шлях підключення все одно має
    # розв'язатися відносно директорії головний.мова, а не cwd
    інша_тека = tmp_path / "деінде"
    інша_тека.mkdir()
    monkeypatch.chdir(інша_тека)

    вивід = _запустити_файл(головний, capsys)
    assert вивід.strip() == "тут"


