def test_підключи_діамантове_не_помилка_і_не_виконується_двічі(tmp_path, capsys):
    # головний підключає і а.мова, і б.мова; обидва підключають спільний
    # база.мова — база.мова має виконатись (надрукуватись) лише один раз
    (tmp_path / "база.мова").write_text(
        'друкуй("база завантажена")\n'
        "дія основа()\n    поверни 1\n",
        encoding="utf-8",
    )
    (tmp_path / "а.мова").write_text(
        'підключи "база.мова"\n'
        "дія а_дія()\n    поверни основа() + 1\n",
        encoding="utf-8",
    )
    (tmp_path / "б.мова").write_text(
        'підключи "база.мова"\n'
        "дія б_дія()\n    поверни основа() + 2\n",
        encoding="utf-8",
    )
    головний = tmp_path / "головний.мова"
    головний.write_text(
        'підключи "а.мова"\n'
        'підключи "б.мова"\n'
        "друкуй(а_дія(), б_дія())\n",
        encoding="utf-8",
    )
    вивід = _запустити_файл(головний, capsys)
    рядки = вивід.strip().split("\n")
    assert рядки.count("база завантажена") == 1
    assert рядки[-1] == "2 3"


# ---- файл не знайдено -------------------------------------------------------

def test_підключи_файл_не_знайдено(tmp_path):
    головний = tmp_path / "головний.мова"
    головний.write_text('підключи "немає_такого.мова"\n', encoding="utf-8")
    with pytest.raises(ПомилкаПідключення) as info:
        завантажити_програму(головний)
    e = info.value
    assert "не знайдено" in str(e)
    assert "немає_такого.мова" in str(e)
    assert e.рядок == 1


def test_підключи_файл_не_знайдено_через_cli(tmp_path, capsys):
    головний = tmp_path / "головний.мова"
    головний.write_text('підключи "немає_такого.мова"\n', encoding="utf-8")
    with pytest.raises(SystemExit):
        мова_cli.команда_виконати(str(головний), без_пристрою=True)
    err = capsys.readouterr().err
    assert "Помилка підключення" in err
    assert "не знайдено" in err
    assert "^" in err  # текст рядка й стрілка теж мають бути (не гола помилка)


