# ---- розвяжи(): реальна збіжність на прикладі із запиту ------------------------

def test_розвяжи_дві_стійки_з_горизонтальною_перемичкою():
    # дві вертикальні стійки однакової довжини (40), з'єднані зверху
    # горизонтальною перемичкою — початкові координати навмисно неточні
    е.вузол("а1", 0, 0)
    е.вузол("а2", 3, 38)
    е.вузол("б1", 47, 2)
    е.вузол("б2", 53, 41)

    е.сегмент("ліва", "а1", "а2")
    е.сегмент("права", "б1", "б2")
    е.сегмент("верх", "а2", "б2")

    е.вертикально("ліва")
    е.вертикально("права")
    е.рівні("ліва", "права")
    е.горизонтально("верх")
    е.довжина("ліва", 40)

    похибка = е.розвяжи()
    assert похибка < е.ПОРІГ_ПОХИБКИ

    а1, а2 = е.вузол("а1"), е.вузол("а2")
    б1, б2 = е.вузол("б1"), е.вузол("б2")
    assert а1[0] == pytest.approx(а2[0], abs=0.05)     # ліва — вертикальна
    assert б1[0] == pytest.approx(б2[0], abs=0.05)     # права — вертикальна
    assert а2[1] == pytest.approx(б2[1], abs=0.05)     # верх — горизонтальна
    assert math.hypot(а2[0] - а1[0], а2[1] - а1[1]) == pytest.approx(40, abs=0.1)


def test_розвяжи_не_рухає_перший_вузол():
    # опорний вузол тримає ескіз на місці: без нього умови (усі — різниці
    # координат) сходились би з довільним зсувом
    е.вузол("а", 0, 0)
    е.вузол("б", 48, 3)
    е.вузол("в", 51, 29)
    е.сегмент("низ", "а", "б")
    е.сегмент("права", "б", "в")
    е.горизонтально("низ")
    е.вертикально("права")
    е.довжина("низ", 50)
    е.довжина("права", 30)
    е.розвяжи()
    assert е.вузол("а") == [0, 0]
    assert list(е.вузол("б")) == pytest.approx([50, 0], abs=0.05)
    assert list(е.вузол("в")) == pytest.approx([50, 30], abs=0.05)
    # опорний — саме перший створений, навіть якщо його координати не (0, 0)
    е.скинути()
    е.вузол("п", 10, 20)
    е.вузол("к", 13, 21)
    е.сегмент("с", "п", "к")
    е.горизонтально("с")
    е.довжина("с", 5)
    е.розвяжи()
    assert е.вузол("п") == [10, 20] and list(е.вузол("к")) == pytest.approx([15, 20], abs=0.05)


