# ---- "довжина": об'єднання мовної і ескізної версії за арністю (через VM) -----

def test_довжина_одним_аргументом_рахує_список(capsys):
    байткод = компілювати(парсити_текст('друкуй(довжина([1, 2, 3]))\n'))
    вм = ВМ(без_пристрою=True)
    вм.виконати(байткод)
    assert capsys.readouterr().out.strip() == "3"


def test_довжина_двома_аргументами_ставить_умову_ескізу():
    вм = ВМ(без_пристрою=True)
    е.вузол("a", 0, 0)
    е.вузол("b", 3, 0)
    е.сегмент("s", "a", "b")
    до = len(е._умови)
    вм._native["довжина"]("s", 10)
    assert len(е._умови) == до + 1


def test_довжина_з_іншою_кількістю_аргументів_дає_помилку():
    вм = ВМ(без_пристрою=True)
    with pytest.raises(ПомилкаВиконання):
        вм._native["довжина"]()


# ---- наскрізно через CALL_NATIVE у VM: вузол/сегмент не плутаються з екраном --

def test_вузол_і_сегмент_компілюються_у_call_native_окремо_від_екрана():
    джерело = (
        'вузол("а", 0, 0)\n'
        'вузол("б", 10, 0)\n'
        'сегмент("s", "а", "б")\n'
        'горизонтально("s")\n'
        'розвяжи()\n'
    )
    байткод = компілювати(парсити_текст(джерело))
    коди = [і[0] for і in байткод["код"]]
    assert коди.count("CALL_NATIVE") == 5
    assert "CALL" not in коди

    вм = ВМ(без_пристрою=True)
    вм.виконати(байткод)  # не повинно кинути помилку
