"""0.9: кнопка("Напис", дія) — у ВМ, у zapusk (очікування натискань) і приклад."""

import sys
import threading
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод, ВМ
from zapusk import виконати_код, ПОВІДОМЛЕННЯ_ЗУПИНЕНО

ПРОГРАМА = (
    "хай імена = []\n"
    "дія показати()\n"
    '    друкуй("Імена:", імена)\n'
    "дія додати()\n"
    '    додай(імена, питай("Ім я? "))\n'
    '    друкуй("додано")\n'
    'кнопка("Показати", показати)\n'
    'кнопка("Додати", додати)\n'
    'друкуй("готово")\n'
)


def запустити(джерело, capsys):
    вм = виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out, вм


def помилка(джерело):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return str(info.value)


def test_без_пристрою_кнопка_друкує_і_програма_завершується(capsys):
    вивід, вм = запустити(ПРОГРАМА, capsys)
    assert вивід == "[кнопка Показати]\n[кнопка Додати]\nготово\n"
    assert вм.кнопки == [("Показати", "показати"), ("Додати", "додати")]


def test_ім_я_дії_можна_передати_і_рядком(capsys):
    вивід, _ = запустити('дія п()\n    друкуй(1)\nкнопка("П", "п")\n', capsys)
    assert вивід == "[кнопка П]\n"


def test_помилки_кнопки():
    assert "дії «нема» немає" in помилка('кнопка("Н", нема)\n')
    assert "без параметрів" in помилка('дія п(а)\n    поверни а\nкнопка("Н", п)\n')
    assert "напис-рядок" in помилка('дія п()\n    поверни 1\nкнопка(5, п)\n')
    assert "напис-рядок" in помилка('дія п()\n    поверни 1\nкнопка("", п)\n')


def test_викликати_дію_ззовні_повертає_значення_і_відновлює_стан(capsys):
    # присвоєння в дії створює локальну змінну, тож стан — у списку
    _, вм = запустити("хай кроки = []\nдія крок()\n    додай(кроки, 1)\n    поверни довжина(кроки) * 10\n", capsys)
    assert вм.викликати_дію("крок") == 10 and вм.викликати_дію("крок") == 20
    assert вм.кадри == [] and вм.стек == [] and вм.стек_повернень == []
    with pytest.raises(ПомилкаВиконання):
        вм.викликати_дію("нема")


def test_дія_кнопки_може_кинути_помилку_яку_ловить_спробуй(capsys):
    _, вм = запустити(
        'дія п()\n    спробуй\n        кинь("ой")\n    якщо помилка\n        друкуй("зловив", помилка)\n', capsys
    )
    вм.викликати_дію("п")
    assert capsys.readouterr().out.strip() == "зловив ой"


def test_zapusk_чекає_натискань_і_оновлює_вивід():
    натиски = {}
    оновлення = []

    def кнопка(напис, натиснути):
        натиски[напис] = натиснути

    def при_старті(вм):
        def потім():
            time.sleep(0.3)
            натиски["Додати"]()
            натиски["Показати"]()
            time.sleep(0.4)
            вм.зупинено = True

        threading.Thread(target=потім, daemon=True).start()

    вивід, успіх = виконати_код(
        ПРОГРАМА, при_старті=при_старті, питай=lambda з: "Оля",
        кнопка=кнопка, оновити_вивід=оновлення.append,
    )
    assert not успіх and вивід.endswith(ПОВІДОМЛЕННЯ_ЗУПИНЕНО + "\n")
    assert "готово\nІм я? Оля\nдодано\nІмена: [Оля]\n" in вивід
    assert sorted(натиски) == ["Додати", "Показати"]
    assert оновлення[0] == "готово\n" and оновлення[-1].endswith("Імена: [Оля]\n")


def test_zapusk_без_кнопок_не_чекає():
    старт = time.monotonic()
    вивід, успіх = виконати_код('друкуй("а")', кнопка=lambda н, ф: None)
    assert успіх and вивід == "а\n" and time.monotonic() - старт < 1


def test_zapusk_помилка_в_дії_кнопки_завершує_програму():
    натиски = {}

    def при_старті(вм):
        threading.Thread(target=lambda: (time.sleep(0.2), натиски["П"]()), daemon=True).start()

    вивід, успіх = виконати_код(
        'дія п()\n    друкуй(1 / 0)\nкнопка("П", п)\n',
        при_старті=при_старті, кнопка=lambda н, ф: натиски.__setitem__(н, ф),
    )
    assert not успіх and "Ділення на нуль" in вивід


def test_приклад_кнопки_виконується(capsys):
    from yadro import moduli

    шлях = Path(__file__).resolve().parent.parent / "приклади" / "кнопки.мова"
    програма, _ = moduli.завантажити_програму(шлях)
    виконати_байткод(компілювати(програма), без_пристрою=True)
    вивід = capsys.readouterr().out
    assert "[кнопка Показати]" in вивід and "[кнопка Додати]" in вивід
