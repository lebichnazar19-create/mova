@pytest.fixture
def креслення():
    к.скинути()
    к.аркуш(200, 100, 2)
    к.контур([Точка(20, 20), Точка(120, 20), Точка(120, 70), Точка(20, 70)])
    к.розмір(Точка(20, 20), Точка(120, 20), -10)
    к.розмір(Точка(120, 20), Точка(120, 70), 10)
    к.осьова(Точка(10, 45), Точка(130, 45))
    д = к.для_екрана()
    к.скинути()
    return д


def лінії(команди):
    return [c for c in команди if c["тип"] == "лінія"]


def test_товщина_ліній_однакова_при_масштабах_0_1_1_і_10(креслення):
    ширини_за_масштабом = []
    for масштаб in (0.1, 1, 10):
        команди = polotno.команди(креслення, масштаб, (0, 0))
        ширини_за_масштабом.append([c["ширина"] for c in лінії(команди)])
    assert ширини_за_масштабом[0] == ширини_за_масштабом[1] == ширини_за_масштабом[2]
    ширини = ширини_за_масштабом[0]
    assert set(ширини) <= {polotno.ШИРИНА_ТОНКА, polotno.ШИРИНА_КОНТУРУ}


def test_контур_2px_рамка_і_розміри_1px(креслення):
    команди = polotno.команди(креслення, 3.7, (5, 5))
    # контур — замкнена ламана 2 px; рамка аркуша і штамп — замкнені 1 px
    замкнені = [c for c in лінії(команди) if c["замкнена"]]
    assert sorted(c["ширина"] for c in замкнені) == [1, 1, 2]
    # усі фігури розміру — 1 px
    індекси_розміру = [i for i, ф in enumerate(креслення["фігури"]) if ф.get("роль") == "розмір"]
    assert індекси_розміру
    for ф in креслення["фігури"]:
        if ф.get("роль") == "розмір":
            assert polotno.ширина_лінії(ф) == polotno.ШИРИНА_ТОНКА


def test_розмір_має_засічки_замість_стрілок_і_число_з_двома_знаками(креслення):
    трикутники_розміру = [ф for ф in креслення["фігури"] if ф["тип"] == "трикутник" and ф.get("роль") == "розмір"]
    assert len(трикутники_розміру) == 4   # по дві на кожен розмір
    команди = polotno.команди(креслення, 2, (0, 0))
    assert not any(c["тип"] == "заливка" for c in команди)   # жодної залитої стрілки
    засічки = [c for c in лінії(команди) if len(c["точки"]) == 4
               and abs(math.hypot(c["точки"][2] - c["точки"][0], c["точки"][3] - c["точки"][1]) - polotno.ЗАСІЧКА_PX) < 1e-6]
    assert len(засічки) == 4
    тексти = [c for c in команди if c["тип"] == "текст"]
    assert {c["текст"] for c in тексти} >= {"100", "50"}
    assert all(c["розмір"] == polotno.ШРИФТ_PX for c in тексти)


def test_формат_числа_два_знаки_без_зайвих_нулів():
    assert к._форматувати_число(80) == "80"
    assert к._форматувати_число(12.5) == "12.5"
    assert к._форматувати_число(12.345) == "12.35"
    assert к._форматувати_число(0.001) == "0"
    assert к._форматувати_число(-0.001) == "0"
    assert к._форматувати_число(-3.14159) == "-3.14"


def test_шрифт_і_засічки_не_залежать_від_масштабу(креслення):
    for масштаб in (0.1, 1, 10):
        команди = polotno.команди(креслення, масштаб, (0, 0))
        assert all(c["розмір"] == polotno.ШРИФТ_PX for c in команди if c["тип"] == "текст")
        довжини = [math.hypot(c["точки"][2] - c["точки"][0], c["точки"][3] - c["точки"][1])
                   for c in лінії(команди) if len(c["точки"]) == 4]
        assert any(abs(д - polotno.ЗАСІЧКА_PX) < 1e-6 for д in довжини)


def test_вмістити_все_центрує_аркуш(креслення):
    масштаб, (zx, zy) = polotno.вмістити(креслення, 800, 600, 10, 20)
    assert масштаб == pytest.approx((800 - 2 * polotno.ПОЛЕ_PX) / 200)   # обмежує ширина
    assert zx == pytest.approx(10 + polotno.ПОЛЕ_PX)
    assert zy == pytest.approx(20 + (600 - 100 * масштаб) / 2)
    assert polotno.вмістити(креслення, 0, 0) == (1.0, (0.0, 0.0))


def test_щипок_множенням_кроками_1_1_і_з_межами():
    assert polotno.масштаб_щипка(2.0, 100, 100) == 2.0
    assert polotno.масштаб_щипка(2.0, 100, 110) == pytest.approx(2.0 * 1.1)         # один крок ×1.1
    assert polotno.масштаб_щипка(2.0, 100, 121) == pytest.approx(2.0 * 1.21)        # два кроки (1.1²)
    assert polotno.масштаб_щипка(2.0, 100, 115) == pytest.approx(2.0 * 1.1)         # неповний другий крок не рахується
    assert polotno.масштаб_щипка(2.0, 100, 100 / 1.21) == pytest.approx(2.0 / 1.21)  # два кроки ÷1.1
    # при віддаленні чутливість не зникає: те саме відношення — ті самі кроки на будь-якому масштабі
    assert polotno.масштаб_щипка(0.2, 100, 50) / 0.2 == pytest.approx(polotno.масштаб_щипка(20, 100, 50) / 20)
    assert polotno.масштаб_щипка(1.0, 100, 1e9) == polotno.МАКС_МАСШТАБ
    assert polotno.масштаб_щипка(1.0, 1e9, 100) == polotno.МІН_МАСШТАБ
    assert polotno.масштаб_щипка(1.0, 0, 100) == 1.0


def test_зум_навколо_точки_лишає_її_на_місці():
    зсув = polotno.зум_навколо(1.0, 2.0, (10, 10), (50, 30))
    # точка (50,30) відповідала мм (40,20); після зуму ×2 вона має лишитись у (50,30)
    assert (зсув[0] + 40 * 2, зсув[1] + 20 * 2) == (50, 30)
    assert polotno.зум_навколо(0, 2.0, (1, 1), (5, 5)) == (1, 1)
