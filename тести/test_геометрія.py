def test_власний_тип_точка_перекриває_вбудований(capsys):
    вивід = запустити(
        "тип Точка\n    x\n    y\n    дія опис()\n        поверни \"своя \" + я.x\n"
        "друкуй(Точка(7, 8).опис(), Точка(7, 8))\n",
        capsys,
    )
    assert вивід.strip() == "своя 7 Точка(x: 7, y: 8)"


def test_власний_тип_точка_у_repl_фрагментах(capsys):
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст("тип Точка\n    x\n    y = 0\n")))
    вм.виконати_фрагмент(компілювати(парсити_текст("друкуй(Точка(1))\n")))
    assert capsys.readouterr().out.strip() == "Точка(x: 1, y: 0)"


def test_приклад_геометрія_виконується(capsys):
    from yadro import moduli

    шлях = Path(__file__).resolve().parent.parent / "приклади" / "геометрія.мова"
    програма, _ = moduli.завантажити_програму(шлях)
    виконати_байткод(компілювати(програма), без_пристрою=True, тека_файлів=str(шлях.parent))
    вивід = capsys.readouterr().out
    assert "Усього кабелю" in вивід
