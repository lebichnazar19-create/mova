"""0.8: геометрія на площині — Точка, вимірювання, перетворення, прямі."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод, ВМ


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


def помилка(джерело):
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return str(info.value)


# ---- 1. Точка і операції ---------------------------------------------------------

def test_точка_друк_поля_і_порівняння(capsys):
    вивід = запустити(
        "хай а = Точка(3, 4)\n"
        "друкуй(а, а.x, а.y, а == Точка(3, 4), а == Точка(4, 3), а != Точка(0, 0))\n"
        "друкуй(Точка(1.5, -2), Точка(0.1, 0.2) + Точка(0.2, 0.1), [Точка(0, 0)])\n",
        capsys,
    )
    assert вивід.strip().split("\n") == [
        "(3, 4) 3 4 істина хиба істина",
        "(1.5, -2) (0.3, 0.3) [(0, 0)]",
    ]


def test_арифметика_точок(capsys):
    вивід = запустити(
        "хай а = Точка(3, 4)\nхай б = Точка(1, 1)\n"
        "друкуй(а + б, а - б, а * 2, 2 * а, а / 2, -а)\n",
        capsys,
    )
    assert вивід.strip() == "(4, 5) (2, 3) (6, 8) (6, 8) (1.5, 2) (-3, -4)"


def test_помилки_арифметики_і_координат():
    assert "точку можна додати лише до точки" in помилка("друкуй(Точка(1, 1) + 1)\n")
    assert "Не можна відняти" in помилка("друкуй(Точка(1, 1) - 1)\n")
    assert "Не можна помножити" in помилка("друкуй(Точка(1, 1) * Точка(1, 1))\n")
    assert "Ділення точки на нуль" in помилка("друкуй(Точка(1, 1) / 0)\n")
    assert "Координата точки має бути числом" in помилка('Точка("1", 2)\n')


def test_точка_незмінна_і_має_лише_x_y():
    assert "незмінна" in помилка("хай т = Точка(1, 2)\nт.x = 5\n")
    assert "лише поля «x» і «y»" in помилка("друкуй(Точка(1, 2).z)\n")


def test_точка_як_ключ_словника_і_в_списку(capsys):
    вивід = запустити(
        'хай д = {Точка(0, 0): "старт"}\nдрукуй(д[Точка(0, 0)], Точка(1, 1) у [Точка(1, 1)])\n', capsys
    )
    assert вивід.split() == ["старт", "істина"]


def test_довжина_відстань_середина(capsys):
    вивід = запустити(
        "друкуй(довжина(Точка(3, 4)), відстань(Точка(1, 1), Точка(4, 5)), середина(Точка(0, 0), Точка(2, 3)))\n"
        "друкуй(довжина([1, 2]), довжина(\"абв\"))\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["5 5 (1, 1.5)", "2 3"]
    assert "очікує першу точку" in помилка("відстань(1, Точка(0, 0))\n")


def test_кут_і_полярні(capsys):
    вивід = запустити(
        "хай о = Точка(0, 0)\n"
        "друкуй(кут(о, Точка(1, 0)), кут(о, Точка(1, 1)), кут(о, Точка(0, 1)), кут(о, Точка(-1, 0)), кут(о, Точка(0, -1)))\n"
        "друкуй(полярні(2, 90), полярні(1, 0), полярні(2, 180), полярні(1, 45) == Точка(корінь(2) / 2, корінь(2) / 2))\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["0 45 90 180 270", "(0, 2) (1, 0) (-2, 0) істина"]
    assert "однаковими точками" in помилка("кут(Точка(1, 1), Точка(1, 1))\n")


def test_кут_з_чотирма_аргументами_лишається_кресленням():
    assert "аркуш" in помилка("кут(Точка(0, 0), Точка(1, 1), Точка(2, 0), 5)\n").lower()
    assert "2 аргументи" in помилка("кут(Точка(0, 0))\n")


# ---- 2. перетворення -----------------------------------------------------------------

def test_зсунь_оберни_масштабуй_точка(capsys):
    вивід = запустити(
        "хай а = Точка(3, 4)\n"
        "друкуй(зсунь(а, 1, -1), оберни(Точка(1, 0), 90), оберни(Точка(2, 0), 180, Точка(1, 0)))\n"
        "друкуй(масштабуй(а, 2), масштабуй(а, 2, Точка(1, 1)), оберни(Точка(1, 0), -90), оберни(Точка(1, 1), 360))\n"
        "друкуй(а)\n",
        capsys,
    )
    assert вивід.strip().split("\n") == [
        "(4, 3) (0, 1) (0, 0)",
        "(6, 8) (5, 7) (0, -1) (1, 1)",
        "(3, 4)",   # стара точка не змінилась
    ]


def test_перетворення_списку_точок(capsys):
    вивід = запустити(
        "хай к = [Точка(0, 0), Точка(1, 0)]\n"
        "друкуй(зсунь(к, 1, 1), оберни(к, 90), масштабуй(к, 3), оберни(к, 90, Точка(1, 0)))\n"
        "друкуй(к)\n",
        capsys,
    )
    assert вивід.strip().split("\n") == [
        "[(1, 1), (2, 1)] [(0, 0), (0, 1)] [(0, 0), (3, 0)] [(1, -1), (1, 0)]",
        "[(0, 0), (1, 0)]",
    ]
    assert "точку в списку" in помилка("зсунь([Точка(0, 0), 5], 1, 1)\n")
    assert "очікує число як dx" in помилка('зсунь(Точка(0, 0), "1", 1)\n')


def test_зсунь_з_двома_аргументами_лишається_ескізом():
    assert "3 аргументи" in помилка("зсунь(Точка(0, 0))\n")


