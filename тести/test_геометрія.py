def test_перетин_прямих(capsys):
    вивід = запустити(
        "друкуй(перетин_прямих(Точка(0, 0), Точка(2, 2), Точка(0, 2), Точка(2, 0)))\n"
        "друкуй(перетин_прямих(Точка(0, 0), Точка(1, 1), Точка(0, 1), Точка(1, 2)))\n"
        "друкуй(перетин_прямих(Точка(0, 0), Точка(4, 0), Точка(1, 5), Точка(1, 6)))\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["(1, 1)", "ніщо", "(1, 0)"]
    assert "збігаються" in помилка("перетин_прямих(Точка(0, 0), Точка(0, 0), Точка(0, 1), Точка(1, 1))\n")


def test_відстань_до_прямої_і_перпендикуляр(capsys):
    вивід = запустити(
        "хай а = Точка(0, 0)\nхай б = Точка(4, 0)\n"
        "друкуй(відстань_до_прямої(Точка(2, 3), а, б), відстань_до_прямої(Точка(9, 0), а, б), відстань_do(Точка(0, 0)))\n".replace(
            ", відстань_do(Точка(0, 0))", ""
        )
        + "друкуй(перпендикуляр(а, б, Точка(2, 3)), перпендикуляр(а, б, Точка(-5, 7)), перпендикуляр(а, Точка(4, 4), Точка(4, 0)))\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["3 0", "(2, 0) (-5, 0) (2, 2)"]


def test_паралельна(capsys):
    вивід = запустити(
        "друкуй(паралельна(Точка(0, 0), Точка(4, 0), 1), паралельна(Точка(0, 0), Точка(4, 0), -2), паралельна(Точка(0, 0), Точка(0, 3), 1))\n",
        capsys,
    )
    assert вивід.strip() == "[(0, 1), (4, 1)] [(0, -2), (4, -2)] [(-1, 0), (-1, 3)]"


def test_перетин_кола_з_прямою(capsys):
    вивід = запустити(
        "хай ц = Точка(0, 0)\n"
        "друкуй(перетин_кола_з_прямою(ц, 1, Точка(-2, 0), Точка(2, 0)))\n"
        "друкуй(перетин_кола_з_прямою(ц, 1, Точка(-2, 1), Точка(2, 1)))\n"
        "друкуй(перетин_кола_з_прямою(ц, 1, Точка(-2, 5), Точка(2, 5)))\n"
        "друкуй(перетин_кола_з_прямою(Точка(1, 1), 5, Точка(1, -9), Точка(1, 9)))\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["[(-1, 0), (1, 0)]", "[(0, 1)]", "[]", "[(1, -4), (1, 6)]"]
    assert "від'ємним" in помилка("перетин_кола_з_прямою(Точка(0, 0), -1, Точка(0, 0), Точка(1, 0))\n")


