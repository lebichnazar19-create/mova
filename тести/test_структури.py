"""0.5: типи (структури з полями й діями) — тип/поля/типові значення,
створення екземпляра, читання й зміна полів, дії з «я», вкладені типи."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаВиконання, ПомилкаКомпіляції, ПомилкаРозбору
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод, ВМ


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


ТОЧКА = (
    "тип Точка\n"
    "    x\n"
    "    y = 0\n"
    "    дія зсунь(dx, dy)\n"
    "        я.x = я.x + dx\n"
    "        я.y = я.y + dy\n"
    "    дія опис()\n"
    '        поверни "(" + я.x + ", " + я.y + ")"\n'
)


def test_створення_читання_і_зміна_полів(capsys):
    вивід = запустити(
        ТОЧКА + "хай т = Точка(1, 2)\nдрукуй(т.x, т.y)\nт.x = 10\nдрукуй(т.x, т)\n", capsys
    )
    assert вивід.strip().split("\n") == ["1 2", "10 Точка(x: 10, y: 2)"]


def test_типове_значення_поля_і_ніщо_без_нього(capsys):
    вивід = запустити(ТОЧКА + "хай т = Точка(5)\nдрукуй(т.x, т.y, Точка().x)\n", capsys)
    assert вивід.strip() == "5 0 ніщо"


def test_дії_типу_з_я(capsys):
    вивід = запустити(
        ТОЧКА + "хай т = Точка(1, 1)\nт.зсунь(2, 3)\nдрукуй(т.опис())\n", capsys
    )
    assert вивід.strip() == "(3, 4)"


def test_вкладені_типи_лінія_з_точок(capsys):
    вивід = запустити(
        ТОЧКА
        + "тип Лінія\n"
        "    початок\n"
        "    кінець\n"
        "    дія довжина_по_x()\n"
        "        поверни я.кінець.x - я.початок.x\n"
        "хай л = Лінія(Точка(1, 1), Точка(5, 1))\n"
        "л.кінець.x = 11\n"
        "друкуй(л.довжина_по_x(), л)\n",
        capsys,
    )
    assert вивід.strip() == "10 Лінія(початок: Точка(x: 1, y: 1), кінець: Точка(x: 11, y: 1))"


def test_екземпляри_порівнюються_за_полями_і_змінюються_на_місці(capsys):
    вивід = запустити(
        ТОЧКА
        + "хай а = Точка(1, 2)\n"
        "хай б = а\n"
        "б.x = 9\n"
        "друкуй(а.x, Точка(1, 2) == Точка(1, 2), Точка(1, 2) == Точка(2, 1))\n",
        capsys,
    )
    assert вивід.split() == ["9", "істина", "хиба"]


def test_типове_значення_список_окремий_для_кожного_екземпляра(capsys):
    вивід = запустити(
        "тип Кошик\n    речі = []\n"
        "хай а = Кошик()\nхай б = Кошик()\n"
        'додай(а.речі, "х")\n'
        "друкуй(а.речі, б.речі)\n",
        capsys,
    )
    assert вивід.strip() == "[х] []"


def test_екземпляр_у_списку_і_словнику(capsys):
    вивід = запустити(
        ТОЧКА
        + "хай сп = [Точка(1), Точка(2)]\n"
        "хай сума = 0\n"
        "для т у сп\n"
        "    сума = сума + т.x\n"
        'хай д = {"центр": Точка(0, 0)}\n'
        "д.центр.y = 7\n"
        "друкуй(сума, д.центр.y)\n",
        capsys,
    )
    assert вивід.strip() == "3 7"


def test_невідоме_поле_помилка():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(ТОЧКА + "друкуй(Точка(1).z)\n")), без_пристрою=True)
    assert "немає поля «z»" in str(info.value)
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(
            компілювати(парсити_текст(ТОЧКА + "хай т = Точка(1)\nт.z = 1\n")), без_пристрою=True
        )
    assert "немає поля «z»" in str(info.value)


def test_невідома_дія_і_зайві_аргументи_помилка():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(
            компілювати(парсити_текст(ТОЧКА + "Точка(1).стрибни()\n")), без_пристрою=True
        )
    assert "немає дії «стрибни»" in str(info.value)
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст(ТОЧКА + "Точка(1, 2, 3)\n")), без_пристрою=True)
    assert "2 поле(я)" in str(info.value)


def test_поле_у_числа_помилка():
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(компілювати(парсити_текст("хай х = 5\nдрукуй(х.y)\n")), без_пристрою=True)
    assert "не має полів" in str(info.value)


def test_я_у_параметрах_дії_типу_помилка_розбору():
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("тип Т\n    x\n    дія ф(я)\n        поверни 1\n")
    assert "«я»" in str(info.value)


def test_подвійне_поле_помилка_розбору():
    with pytest.raises(ПомилкаРозбору):
        парсити_текст("тип Т\n    x\n    x\n")


def test_ім_я_типу_не_може_бути_вбудованою_функцією():
    with pytest.raises(ПомилкаКомпіляції):
        компілювати(парсити_текст("тип друкуй_це\n    x\n".replace("друкуй_це", "коло")))


def test_тип_як_ключове_слово_недоступне_як_ім_я():
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("хай тип = 1\n")
    assert "ключове слово" in str(info.value)


def test_дія_типу_може_кликати_іншу_дію_типу_і_глобальну(capsys):
    вивід = запустити(
        "дія подвій(n)\n    поверни n * 2\n"
        "тип Лічильник\n"
        "    n = 0\n"
        "    дія крок()\n"
        "        я.n = я.n + 1\n"
        "    дія два_кроки()\n"
        "        я.крок()\n"
        "        я.крок()\n"
        "        поверни подвій(я.n)\n"
        "хай л = Лічильник()\n"
        "друкуй(л.два_кроки(), л.n)\n",
        capsys,
    )
    assert вивід.strip() == "4 2"


def test_repl_фрагменти_тип_живе_між_рядками(capsys):
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст("тип Т\n    a = 1\n")))
    вм.виконати_фрагмент(компілювати(парсити_текст("хай т = Т()\n")))
    вм.виконати_фрагмент(компілювати(парсити_текст("друкуй(т.a)\n")))
    assert capsys.readouterr().out.strip() == "1"
