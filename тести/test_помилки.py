"""Етап 6: 'підсвітка помилок' — формат розділу 8 ТЗ (рядок, позиція, ^)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from ядро.компілятор import компілювати
from ядро.вм import виконати_байткод
from ядро.парсер import парсити_текст
from ядро.помилки import ПомилкаВиконання


def _рядки_помилки(e):
    return str(e).splitlines()


def test_помилка_виконання_має_рядок_позицію_і_стрілку():
    джерело = 'вібруй("довго")\n'
    байткод = компілювати(парсити_текст(джерело))
    with pytest.raises(ПомилкаВиконання) as info:
        виконати_байткод(байткод, без_пристрою=True)

    e = info.value
    # текст рядка джерела в цьому тесті не долитий (це робить лише
    # мова.py), тож форматуємо вручну так само, як CLI
    e.текст_рядка = джерело.split("\n")[e.рядок - 1]
    рядки = _рядки_помилки(e)

    assert рядки[0] == "Помилка виконання в рядку 1, позиція 8:"
    assert рядки[1].strip() == 'вібруй("довго")'
    # стрілка стоїть точно під восьмим символом (лапка після дужки)
    стрілка = рядки[2]
    assert стрілка.rstrip().endswith("^")
    assert стрілка.index("^") == рядки[1].index("в") + (8 - 1)


def test_помилка_компіляції_має_заголовок():
    from ядро.помилки import ПомилкаКомпіляції

    with pytest.raises(ПомилкаКомпіляції) as info:
        компілювати(парсити_текст("перервись\n"))
    assert str(info.value).startswith("Помилка компіляції")


def test_помилка_розбору_має_заголовок():
    from ядро.лексер import токенізувати
    from ядро.помилки import ПомилкаРозбору

    with pytest.raises(ПомилкаРозбору) as info:
        токенізувати("хай х = 1 ~ 2")
    assert str(info.value).startswith("Помилка розбору")


def test_помилка_без_рядка_не_показує_нульовий_рядок():
    # помилки без прив'язки до джерела (наприклад, від розум.py) не повинні
    # друкувати оманливе "в рядку 0, позиція 0"
    e = ПомилкаВиконання("Локальна модель недоступна.")
    assert "рядку 0" not in str(e)
    assert str(e).splitlines()[0] == "Помилка виконання:"


def test_cli_долив_текст_рядка_у_повідомлення(tmp_path, capsys):
    import мова as мова_cli

    джерело = tmp_path / "п.мова"
    джерело.write_text('друкуй(1)\nвібруй("довго")\n', encoding="utf-8")
    with pytest.raises(SystemExit):
        мова_cli.команда_виконати(str(джерело), без_пристрою=True)
    err = capsys.readouterr().err
    assert 'вібруй("довго")' in err
    assert "^" in err
