"""Тести zapusk.виконати_код — запуск коду з рядка для Android-редактора."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from zapusk import виконати_код, ПОВІДОМЛЕННЯ_ПИТАЙ


def test_успішний_вивід():
    вивід, успіх = виконати_код('друкуй("привіт", 1 + 2)')
    assert успіх and вивід == "привіт 3\n"


def test_помилка_розбору_без_вильоту():
    вивід, успіх = виконати_код('друкуй("а"')
    assert not успіх and "Помилка розбору" in вивід


def test_помилка_виконання_після_виводу():
    вивід, успіх = виконати_код('друкуй("до")\nдрукуй(нема)')
    assert not успіх and вивід.startswith("до\n") and "Невідома змінна" in вивід


def test_питай_дає_зрозуміле_повідомлення():
    вивід, успіх = виконати_код('хай х = питай("ім я? ")')
    assert not успіх and ПОВІДОМЛЕННЯ_ПИТАЙ in вивід


def test_пристрій_у_симуляції():
    вивід, успіх = виконати_код("вібруй(100)")
    assert успіх and "симуляція" in вивід
