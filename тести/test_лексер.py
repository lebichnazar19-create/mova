import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from ядро.лексер import токенізувати
from ядро.помилки import ПомилкаРозбору


def типи(джерело):
    return [т.тип for т in токенізувати(джерело)]


def test_числа():
    токени = токенізувати("42 3.14")
    значення = [т.значення for т in токени if т.тип == "ЧИСЛО"]
    assert значення == [42, 3.14]
    assert isinstance(значення[0], int)
    assert isinstance(значення[1], float)


def test_рядок_з_екрануванням():
    токени = токенізувати(r'"привіт\nсвіт"')
    assert токени[0].значення == "привіт\nсвіт"


def test_ключові_слова_розпізнаються():
    т = типи("хай якщо інакше поки для у поверни дія стала")
    assert т[:9] == ["ХАЙ", "ЯКЩО", "ІНАКШЕ", "ПОКИ", "ДЛЯ", "У", "ПОВЕРНИ", "ДІЯ", "СТАЛА"]


def test_ідентифікатор_не_ключове_слово():
    токени = токенізувати("хайдер")
    assert токени[0].тип == "ІМЯ"
    assert токени[0].значення == "хайдер"


def test_складені_оператори():
    т = типи("== != <= >=")
    assert т[:4] == ["РІВНО", "НЕРІВНО", "МЕНШЕ_РІВНО", "БІЛЬШЕ_РІВНО"]


def test_відступи_породжують_блокові_токени():
    джерело = "якщо істина\n    друкуй(1)\nдрукуй(2)\n"
    т = типи(джерело)
    assert "ВІДСТУП_ВПЕРЕД" in т
    assert "ВІДСТУП_НАЗАД" in т


def test_коментар_ігнорується():
    токени = токенізувати("# коментар\nхай х = 1\n")
    типи_без_нр = [т.тип for т in токени if т.тип not in ("НОВИЙ_РЯДОК", "КІНЕЦЬ")]
    assert типи_без_нр == ["ХАЙ", "ІМЯ", "ПРИСВОЄННЯ", "ЧИСЛО"]


def test_невідомий_символ_дає_помилку_розбору():
    with pytest.raises(ПомилкаРозбору):
        токенізувати("хай х = 1 ~ 2")


def test_незакритий_рядок_дає_помилку():
    with pytest.raises(ПомилкаРозбору):
        токенізувати('"незакритий')
