"""0.9: помилки розбору кажуть не лише що не так, а як має бути."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro.errors import ПомилкаРозбору
from yadro.parser import парсити_текст


def помилка(код):
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст(код if код.endswith("\n") else код + "\n")
    return str(info.value)


@pytest.mark.parametrize("код, очікуване", [
    ("словник а (1)", "«словник» — це вбудована дія, її викликають з дужками: хай д = словник("),
    ("корінь 4", "«корінь» — це вбудована дія, її викликають з дужками: корінь(16)"),
    ('друкуй "привіт"', "«друкуй» — це вбудована дія, її викликають з дужками: друкуй("),
    ("Точка т", "«Точка» — це тип, значення створюють викликом з дужками і зберігають у змінну: хай т = Точка(3, 4)"),
    ("список а = 5", "Схоже, ти хотів створити змінну «а». Змінну оголошують словом «хай»: хай а = ..."),
    ("х 5", "Після «х» очікувався кінець рядка, «=» або дужки виклику, а тут «5». Щоб створити змінну: хай х = значення"),
    ("друкуй(1) 2", "Після виклику «друкуй(...)» очікувався кінець рядка, а тут «2». Усі аргументи — всередині дужок через кому"),
    ("корінь(4) 2", "Результат виклику можна зберегти: хай х = корінь(...)"),
])
def test_вбудована_дія_чи_ім_я_без_дужок(код, очікуване):
    assert очікуване in помилка(код)


@pytest.mark.parametrize("код, очікуване", [
    ("інакше\n    друкуй(1)", "«інакше» ставлять одразу після блоку «якщо»"),
    ("у", "«у» — частина циклу «для»"),
    ("і", "«і» з'єднує дві умови"),
    ("або", "«або» з'єднує дві умови"),
    ("= 5", "Ліворуч від «=» має бути ім'я змінної. Щоб створити змінну: хай х = 5"),
    (")", "Зайва «)» — для неї немає відкривної дужки"),
    ("хай х = якщо", "«якщо» — ключове слово, воно не може стояти всередині виразу. Як його використовують: якщо х > 5"),
    ("хай для = 5", "«для» — ключове слово мови, його не можна використати як ім'я змінної"),
])
def test_ключове_слово_не_на_своєму_місці(код, очікуване):
    assert очікуване in помилка(код)


@pytest.mark.parametrize("код, очікуване", [
    ("хай х", "Після «хай х» має бути «=» і значення: хай х = 5"),
    ("стала К", "Після «стала К» має бути «=» і значення: стала К = 5"),
    ("хай х =", "Після «=» має бути значення (число, рядок, список чи виклик): хай х = 5"),
    ("хай х = 5 6", "Після значення для «х» очікувався кінець рядка, а тут «6»"),
    ("хай х = 1 +", "Тут очікувалось значення (число, рядок, ім'я змінної або виклик дії), а рядок закінчився"),
    ("якщо\n    друкуй(1)", "Після «якщо» має бути умова: якщо х > 5"),
    ("поки\n    друкуй(1)", "Після «поки» має бути умова: поки х < 10"),
    ("для х список\n    друкуй(х)", "У циклі «для» після імені має бути «у» і список: для х у [1, 2, 3]"),
    ("дія ф\n    поверни 1", "Після імені дії мають бути дужки з параметрами (можна порожні): дія ф(а, б)"),
    ("якщо х > 1\nдрукуй(2)", "Наступний рядок має бути тілом блоку — глибше на 4 пробіли"),
])
def test_обірвана_конструкція_підказує_форму(код, очікуване):
    assert очікуване in помилка(код)


def test_помилка_має_рядок_і_стрілку():
    текст = помилка('друкуй(1)\nсловник а\n')
    assert текст.startswith("Помилка розбору в рядку 2, позиція 1:")
    assert "^" in текст


def test_правильний_код_не_зачеплено():
    for код in (
        "х = 5\n", 'друкуй("а", 1)\n', "хай д = словник()\n", "хай т = Точка(1, 2)\n",
        "якщо а > 1 і б < 2\n    друкуй(1)\nінакше\n    друкуй(2)\n",
        "для х у [1]\n    продовж\n", 'кнопка("П", п)\n',
    ):
        парсити_текст(код)
