"""1.5: бібліотеки — підключи("геометрія") (yadro/biblioteka.py, biblioteky/).

Без підключення дій бібліотеки немає (зрозуміла підказка, як підключити);
після — є, спільні імена (кут/зсунь/довжина) розрізняються за
аргументами; невідома бібліотека — помилка компіляції; форма з дужками
лише на верхньому рівні; REPL і байткод, зібраний без знання про
бібліотеку, працюють через реєстрацію у VM; власний «тип Точка» має
перевагу над бібліотечним; довідка й підсвітка знають імена бібліотек.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pytest

from yadro import biblioteka
from yadro.errors import ПомилкаВиконання, ПомилкаКомпіляції, ПомилкаРозбору, ПомилкаПідключення
from yadro.kompilyator import компілювати
from yadro.parser import парсити_текст
from yadro.vm import виконати_байткод, ВМ


def запустити(джерело, capsys):
    виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return capsys.readouterr().out


def помилка(джерело, тип=ПомилкаВиконання):
    with pytest.raises(тип) as info:
        виконати_байткод(компілювати(парсити_текст(джерело)), без_пристрою=True)
    return str(info.value)


def test_без_підключення_геометрії_немає_а_підказка_є():
    текст = помилка("хай т = Точка(1, 2)\n")
    assert "Невідома дія «Точка»" in текст and 'підключи("геометрія")' in текст
    текст = помилка("друкуй(відстань(1, 2))\n")
    assert "«відстань»" in текст and 'підключи("геометрія")' in текст
    # спільне ім'я з іншою кількістю аргументів — теж підказка
    текст = помилка("друкуй(зсунь(1, 2, 3))\n")
    assert 'підключи("геометрія")' in текст


def test_після_підключення_все_працює(capsys):
    вивід = запустити(
        'підключи("геометрія")\n'
        "хай а = Точка(3, 4)\n"
        "друкуй(а, довжина(а), довжина([1, 2]), відстань(а, Точка(0, 0)), кут(Точка(0, 0), Точка(0, 1)))\n"
        "друкуй(зсунь(а, 1, 1), а + а, 2 * а, -а, а.x, а[1])\n",
        capsys,
    )
    assert вивід.strip().split("\n") == ["(3, 4) 5 2 5 90", "(4, 5) (6, 8) (6, 8) (-3, -4) 3 4"]


def test_дія_вище_за_підключи_і_подвійне_підключення(capsys):
    вивід = запустити(
        "дія центр(а, б)\n    поверни середина(а, б)\n\n"
        'підключи("геометрія")\nпідключи("геометрія")\n'
        "друкуй(центр(Точка(0, 0), Точка(2, 2)))\n",
        capsys,
    )
    assert вивід.strip() == "(1, 1)"


def test_невідома_бібліотека_помилка_компіляції():
    текст = помилка('підключи("хімія")\n', ПомилкаКомпіляції)
    assert "«хімія» немає" in текст and "«геометрія»" in текст


def test_підключи_лише_на_верхньому_рівні():
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст('якщо істина\n    підключи("геометрія")\n')
    assert "верхньому рівні" in str(info.value)
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("підключи(геометрія)\n")
    assert "в лапках" in str(info.value)


def test_файлова_форма_з_назвою_бібліотеки_підказує_дужки(tmp_path):
    from yadro.moduli import завантажити_програму
    (tmp_path / "п.мова").write_text('підключи "геометрія"\n', encoding="utf-8")
    with pytest.raises(ПомилкаПідключення) as info:
        завантажити_програму(tmp_path / "п.мова")
    assert 'підключи("геометрія")' in str(info.value)


def test_repl_підключи_в_попередньому_фрагменті(capsys):
    # REPL компілює кожен рядок окремо: другий фрагмент не знає про
    # бібліотеку, але VM уже зареєструвала її дії
    вм = ВМ(без_пристрою=True)
    вм.виконати_фрагмент(компілювати(парсити_текст('підключи("геометрія")\n')))
    вм.виконати_фрагмент(компілювати(парсити_текст("друкуй(відстань(Точка(0, 0), Точка(3, 4)))\n")))
    assert capsys.readouterr().out.strip() == "5"


def test_власний_тип_точка_має_перевагу(capsys):
    вивід = запустити(
        'підключи("геометрія")\n'
        "тип Точка\n    x\n    y\n\n"
        "хай т = Точка(1, 2)\nт.x = 10\nдрукуй(т)\n",
        capsys,
    )
    assert вивід.strip() == "Точка(x: 10, y: 2)"
    # а дію з ім'ям бібліотеки оголосити не можна — як і з вбудованим
    текст = помилка('підключи("геометрія")\nдія відстань(а)\n    поверни 1\n', ПомилкаКомпіляції)
    assert "бібліотеки «геометрія»" in текст


def test_реєстр_довідка_і_підсвітка():
    assert biblioteka.де("Точка") == "геометрія" and biblioteka.де("друкуй") is None
    assert biblioteka.усі_типи() == {"Точка": "геометрія"}
    from yadro import dovidka
    assert any("геометрія" in г for г, _ in dovidka.ГРУПИ)
    assert 'підключи("геометрія")' in dovidka.приклад("підключи")
    import redaktor
    if getattr(redaktor, "RegexLexer", None) is not None:
        токени = list(redaktor.МоваLexer().get_tokens('підключи("геометрія")\nхай т = Точка(1, 2)\n'))
        assert any(т == "Точка" and str(тип) == "Token.Name.Builtin" for тип, т in токени)


def test_підказка_коли_точка_без_дужок():
    with pytest.raises(ПомилкаРозбору) as info:
        парсити_текст("Точка т\n")
    assert "це тип" in str(info.value)
