# ---- відрізок: алгоритм Брезенхема, точні послідовності клітинок ---------------

def _клітинки_кольору(колір_хекс):
    return sorted(
        (x, y)
        for y, рядок in enumerate(екран._буфер)
        for x, клітинка in enumerate(рядок)
        if клітинка == колір_хекс
    )


def test_відрізок_горизонтальний():
    екран.екран(10, 10)
    екран.відрізок(0, 0, 4, 0, "чорний")
    assert _клітинки_кольору("#000000") == [(0, 0), (1, 0), (2, 0), (3, 0), (4, 0)]


def test_відрізок_вертикальний():
    екран.екран(10, 10)
    екран.відрізок(0, 0, 0, 4, "чорний")
    assert _клітинки_кольору("#000000") == [(0, 0), (0, 1), (0, 2), (0, 3), (0, 4)]


def test_відрізок_діагональ_45_градусів():
    екран.екран(10, 10)
    екран.відрізок(0, 0, 4, 4, "чорний")
    assert _клітинки_кольору("#000000") == [(0, 0), (1, 1), (2, 2), (3, 3), (4, 4)]


def test_відрізок_довільний_нахил_класичний_приклад_брезенхема():
    # хрестоматійний приклад: (0,0)->(4,2) дає саме таку послідовність
    екран.екран(10, 10)
    екран.відрізок(0, 0, 4, 2, "чорний")
    assert _клітинки_кольору("#000000") == [(0, 0), (1, 1), (2, 1), (3, 2), (4, 2)]


def test_відрізок_у_зворотному_напрямку_теж_з_яднує_обидва_кінці():
    # Брезенхем із простим правилом розв'язання нічиїх не зобов'язаний
    # давати дзеркально ту саму послідовність клітинок у зворотному напрямку
    # (це нормально) — але лінія так само має з'єднати обидві точки без
    # розривів і без зайвих клітинок
    екран.екран(10, 10)
    екран.відрізок(4, 2, 0, 0, "чорний")
    клітинки = _клітинки_кольору("#000000")
    assert (0, 0) in клітинки and (4, 2) in клітинки
    assert len(клітинки) == 5
    клітинки_за_x = sorted(клітинки)
    for (x1, y1), (x2, y2) in zip(клітинки_за_x, клітинки_за_x[1:]):
        assert abs(x2 - x1) <= 1 and abs(y2 - y1) <= 1  # без розривів


# ---- намалюй(): точний ANSI-вивід --------------------------------------------

def test_намалюй_виводить_ansi_фон_і_скидання_в_кінці_рядка(capsys):
    екран.екран(2, 1)
    екран.точка(0, 0, "синій")
    екран.намалюй()
    вивід = capsys.readouterr().out
    очікуваний_рядок = "\033[48;2;30;136;229m  \033[48;2;255;255;255m  \033[0m"
    assert вивід == очікуваний_рядок + "\n"


def test_намалюй_кожна_клітинка_це_два_пробіли():
    екран.екран(3, 2)
    # прибираємо всі escape-коди — має лишитись рівно 3*2*2 пробіли на 2 рядки
    рядок1 = "".join(екран._код_фону(к) + "  " for к in екран._буфер[0])
    assert рядок1.count("  ") == 3


# ---- наскрізно через VM / CALL_NATIVE -----------------------------------------

def test_екран_через_call_native_у_vm(capsys):
    джерело = (
        'екран(3, 3)\n'
        'запов_квадрат(0, 0, 1, "синій")\n'
        'намалюй()\n'
    )
    байткод = компілювати(парсити_текст(джерело))
    коди = [і[0] for і in байткод["код"]]
    assert коди.count("CALL_NATIVE") == 3  # екран, запов_квадрат, намалюй
    assert "CALL" not in коди

    вм = ВМ(без_пристрою=True)
    вм.виконати(байткод)

    вивід = capsys.readouterr().out
    assert "\033[48;2;30;136;229m" in вивід
    assert вивід.count("\033[0m") == 3  # по одному скиданню на кожен з 3 рядків
