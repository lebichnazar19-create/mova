@pytest.fixture(autouse=True)
def _чистий_екран():
    екран._екран = None
    екран._буфер = []
    yield
    екран._екран = None
    екран._буфер = []


def _розмір_буфера():
    return len(екран._буфер), (len(екран._буфер[0]) if екран._буфер else 0)


# ---- базова логіка ------------------------------------------------------------

def test_малювання_без_екрана_дає_помилку():
    with pytest.raises(ПомилкаВиконання, match="екран"):
        екран.точка(0, 0, "синій")


def test_намалюй_без_екрана_дає_помилку():
    with pytest.raises(ПомилкаВиконання, match="екран"):
        екран.намалюй()


def test_екран_створює_буфер_потрібного_розміру_заповнений_білим():
    екран.екран(5, 3)
    рядки, стовпці = _розмір_буфера()
    assert (рядки, стовпці) == (3, 5)
    assert all(клітинка == екран.БІЛИЙ_ФОН for рядок in екран._буфер for клітинка in рядок)


def test_екран_вимагає_додатні_розміри():
    with pytest.raises(ПомилкаВиконання):
        екран.екран(0, 10)
    with pytest.raises(ПомилкаВиконання):
        екран.екран(10, -1)


def test_новий_екран_скидає_старий_буфер():
    екран.екран(5, 5)
    екран.точка(1, 1, "синій")
    екран.екран(3, 3)  # новий виклик — усе спочатку
    assert _розмір_буфера() == (3, 3)
    assert all(клітинка == екран.БІЛИЙ_ФОН for рядок in екран._буфер for клітинка in рядок)


