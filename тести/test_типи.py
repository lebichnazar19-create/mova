"""Етап 5: списки, словники (через JSON з пристрою), рядкові операції, для."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ядро.компілятор import компілювати
from ядро.парсер import парсити_текст
from ядро.вм import виконати_байткод, ВМ


def запустити(джерело, capsys):
    байткод = компілювати(парсити_текст(джерело))
    виконати_байткод(байткод, без_пристрою=True)
    return capsys.readouterr().out


def test_рядкова_індексація(capsys):
    вивід = запустити('хай с = "привіт"\nдрукуй(с[0], с[5])\n', capsys)
    assert вивід.split() == ["п", "т"]


def test_довжина_рядка_і_списку(capsys):
    вивід = запустити('друкуй(довжина("привіт"), довжина([1, 2, 3, 4]))\n', capsys)
    assert вивід.split() == ["6", "4"]


def test_конкатенація_списків(capsys):
    вивід = запустити("друкуй([1, 2] + [3, 4])\n", capsys)
    assert вивід.strip() == "[1, 2, 3, 4]"


def test_каст_рядок_число_цілий(capsys):
    вивід = запустити(
        'друкуй(рядок(5), число("3.5") + 1, цілий("7"), цілий(3.9))\n', capsys
    )
    assert вивід.split() == ["5", "4.5", "7", "3"]


def test_для_у_діапазон(capsys):
    вивід = запустити("для x у діапазон(3)\n    друкуй(x)\n", capsys)
    assert вивід.split() == ["0", "1", "2"]


def test_для_у_діапазон_з_межами(capsys):
    вивід = запустити("для x у діапазон(2, 5)\n    друкуй(x)\n", capsys)
    assert вивід.split() == ["2", "3", "4"]


def test_для_змінює_список_через_індекс(capsys):
    вивід = запустити(
        "хай сп = [0, 0, 0]\n"
        "для i у діапазон(3)\n"
        "    сп[i] = i * i\n"
        "друкуй(сп)\n",
        capsys,
    )
    assert вивід.strip() == "[0, 1, 4]"


def test_словник_із_json_пристрою_читається_і_пишеться(capsys):
    # датчик()/батарея()/місце() повертають словник (розділ 7 ТЗ) —
    # перевіряємо читання за ключем і запис у вкладений список через
    # реальний рушій VM, підмінивши лише саму нативну функцію "батарея"
    вм = ВМ(без_пристрою=False)
    вм._native["батарея"] = lambda: {"percentage": 42, "рівні": [1, 2, 3]}
    байткод = компілювати(
        парсити_текст(
            'хай д = батарея()\n'
            'хай сп = д["рівні"]\n'
            'сп[0] = 99\n'
            'друкуй(д["percentage"], сп)\n'
        )
    )
    вм.виконати(байткод)
    assert capsys.readouterr().out.strip() == "42 [99, 2, 3]"
