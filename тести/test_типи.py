def test_зріз_списку(capsys):
    вивід = запустити(
        'хай а = [1, 2, 3, 4, 5]\n'
        'друкуй(а[1:3])\n'
        'друкуй(а[:2])\n'
        'друкуй(а[3:])\n'
        'друкуй(а[:])\n'
        'друкуй(а[-3:-1])\n',
        capsys,
    )
    assert вивід.strip().split("\n") == [
        "[2, 3]",
        "[1, 2]",
        "[4, 5]",
        "[1, 2, 3, 4, 5]",
        "[3, 4]",
    ]


