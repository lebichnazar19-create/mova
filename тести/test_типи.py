def test_словник_із_json_пристрою_читається_і_пишеться(capsys):
    # датчик()/батарея()/місце() повертають словник (розділ 7 ТЗ) —
    # перевіряємо читання за ключем і запис у вкладений список через
    # реальний рушій VM, підмінивши лише саму нативну функцію "батарея"
    вм = ВМ(без_пристрою=False)
    вм._native["батарея"] = lambda: {"percentage": 42, "рівні": [1, 2, 3]}
    байткод = компілювати(
        парсити_текст(
            'хай д = батарея()\n'
            'хай сп = д["рівні"]\n'
            'сп[0] = 99\n'
            'друкуй(д["percentage"], сп)\n'
        )
    )
    вм.виконати(байткод)
    assert capsys.readouterr().out.strip() == "42 [99, 2, 3]"
