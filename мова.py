#!/usr/bin/env python3
"""Точка входу: мова файл.мова

    мова                         # інтерактивний режим (REPL)
    мова програма.мова          # скомпілювати і виконати
    мова -к програма.мова       # тільки скомпілювати -> програма.байт
    мова -б програма.байт       # виконати готовий байткод
    мова -д програма.мова       # показати дизасембльований байткод
    мова -л "команда українською" [--без-пристрою]  # з людської мови в код
    (додати --без-пристрою до будь-якої команди — усі виклики пристрою/моделі
     лише друкуються в консоль, реального виконання не буде)
"""

import json
import sys
from pathlib import Path

сюди = Path(__file__).resolve().parent
if str(сюди) not in sys.path:
    sys.path.insert(0, str(сюди))

from yadro import vm as вм_модуль
from yadro import disasm, kompilyator, moduli, rozum, repl
from yadro.keywords import КЛЮЧОВІ_СЛОВА
from yadro.natives import ІМЕНА_NATIVE
from yadro.parser import парсити_текст
from yadro.errors import (
    ПомилкаВиконання,
    ПомилкаКомпіляції,
    ПомилкаМови,
    ПомилкаПідключення,
    ПомилкаРозбору,
)

ДОВІДКА = __doc__


def _прочитати(шлях):
    return Path(шлях).read_text(encoding="utf-8")


def _долити_текст_рядка(e: ПомилкаМови, джерело):
    if джерело and not e.текст_рядка and e.рядок:
        рядки = джерело.split("\n")
        if 1 <= e.рядок <= len(рядки):
            e.текст_рядка = рядки[e.рядок - 1]


def _скомпілювати_або_вихід(шлях):
    try:
        програма, джерела = moduli.завантажити_програму(шлях)
        байткод = kompilyator.компілювати(програма)
    except (ПомилкаРозбору, ПомилкаКомпіляції, ПомилкаПідключення) as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
    джерело = джерела.get(Path(шлях).resolve(), "")
    return джерело, байткод


def _виконати_байткод_або_вихід(байткод, джерело, без_пристрою, тека_файлів=None):
    try:
        вм_модуль.виконати_байткод(
            байткод, без_пристрою=без_пристрою, тека_файлів=тека_файлів
        )
    except ПомилкаВиконання as e:
        _долити_текст_рядка(e, джерело)
        print(str(e), file=sys.stderr)
        sys.exit(1)


def команда_виконати(шлях, без_пристрою):
    джерело, байткод = _скомпілювати_або_вихід(шлях)
    # файлові функції мови рахують відносні шляхи від теки програми
    _виконати_байткод_або_вихід(
        байткод, джерело, без_пристрою, тека_файлів=str(Path(шлях).resolve().parent)
    )


def команда_компілювати(шлях):
    _, байткод = _скомпілювати_або_вихід(шлях)
    вихід = Path(шлях).with_suffix(".байт")
    вихід.write_text(json.dumps(байткод, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Скомпільовано -> {вихід}")


def команда_виконати_байткод(шлях, без_пристрою):
    try:
        байткод = json.loads(_прочитати(шлях))
    except json.JSONDecodeError as e:
        print(f"Помилка: файл байткоду пошкоджено ({e})", file=sys.stderr)
        sys.exit(1)
    _виконати_байткод_або_вихід(
        байткод, None, без_пристрою, тека_файлів=str(Path(шлях).resolve().parent)
    )


def команда_дизасемблювати(шлях):
    _, байткод = _скомпілювати_або_вихід(шлях)
    print(disasm.дизасемблювати(байткод))


def _системна_інструкція():
    ключові = ", ".join(sorted(КЛЮЧОВІ_СЛОВА))
    функції = ", ".join(sorted(ІМЕНА_NATIVE))
    return (
        "Ти перетворюєш команду українською мовою на код мовою програмування "
        "«Мова». Відповідай ЛИШЕ кодом, без пояснень і без markdown-огорож.\n"
        "Правила синтаксису:\n"
        "- блоки визначаються відступом (як у Python), без двокрапок і крапок з комою\n"
        "- оголошення змінної: хай імя = вираз\n"
        "- умова: якщо вираз / інакше якщо вираз / інакше\n"
        "- цикли: поки вираз; для імя у список\n"
        "- дія: дія імя(параметри) ... поверни вираз\n"
        f"Ключові слова: {ключові}\n"
        f"Вбудовані функції: {функції}\n"
        "Приклад:\n"
        "хай заряд = батарея()\n"
        "якщо заряд < 20\n"
        "    вібруй(200)\n"
        "    сповісти(\"Батарея\", \"Заряд низький\")\n"
    )


def _видобути_код(текст):
    текст = текст.strip()
    if текст.startswith("```"):
        рядки = текст.split("\n")
        рядки = рядки[1:]
        if рядки and рядки[-1].strip().startswith("```"):
            рядки = рядки[:-1]
        текст = "\n".join(рядки)
    return текст.strip() + "\n"


def команда_людською_мовою(фраза, без_пристрою):
    try:
        відповідь = rozum.спитай(фраза, _системна_інструкція())
    except ПомилкаВиконання as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)

    код = _видобути_код(відповідь)
    print("Згенерований код:\n")
    print(код)
    try:
        підтвердження = input("\nВиконати цей код? (так/ні): ").strip().lower()
    except EOFError:
        підтвердження = ""
    if підтвердження not in ("так", "т", "y", "yes"):
        print("Скасовано.")
        return

    try:
        програма = парсити_текст(код)
        байткод = kompilyator.компілювати(програма)
    except (ПомилкаРозбору, ПомилкаКомпіляції) as e:
        _долити_текст_рядка(e, код)
        print(str(e), file=sys.stderr)
        sys.exit(1)
    _виконати_байткод_або_вихід(байткод, код, без_пристрою)


def main(argv=None):
    argv = list(argv if argv is not None else sys.argv[1:])
    без_пристрою = "--без-пристрою" in argv
    if без_пристрою:
        argv.remove("--без-пристрою")

    if argv and argv[0] in ("--допомога", "-h", "--help"):
        print(ДОВІДКА)
        sys.exit(0)

    if not argv:
        repl.запустити(без_пристрою=без_пристрою)
        return

    прапор = argv[0]
    if прапор == "-к":
        if len(argv) < 2:
            print("Використання: мова -к файл.мова", file=sys.stderr)
            sys.exit(1)
        команда_компілювати(argv[1])
    elif прапор == "-б":
        if len(argv) < 2:
            print("Використання: мова -б файл.байт", file=sys.stderr)
            sys.exit(1)
        команда_виконати_байткод(argv[1], без_пристрою)
    elif прапор == "-д":
        if len(argv) < 2:
            print("Використання: мова -д файл.мова", file=sys.stderr)
            sys.exit(1)
        команда_дизасемблювати(argv[1])
    elif прапор == "-л":
        if len(argv) < 2:
            print('Використання: мова -л "команда українською"', file=sys.stderr)
            sys.exit(1)
        команда_людською_мовою(" ".join(argv[1:]), без_пристрою)
    else:
        команда_виконати(argv[0], без_пристрою)


if __name__ == "__main__":
    main()
