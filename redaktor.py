"""Логіка редактора коду для Android-застосунку — без Kivy, щоб її можна
було тестувати на комп'ютері (тести/test_редактор.py).

Тут:
- КАРКАСИ і каркас(): що вставляє кнопка швидкого вводу (не голе слово, а
  заготовку блоку з відступом і виділеним місцем для заповнення);
- автовідступ(): що вставити на Enter (перенос + відступ; після рядка,
  що відкриває блок, — на один рівень глибше);
- автозакриття(): пара для ( [ { " і «перестрибування» вже наявної
  закривної дужки/лапки;
- МоваLexer: лексер pygments для підсвітки (ключові слова, рядки, числа,
  коментарі, вбудовані функції) — його використовує Kivy CodeInput;
- перевірити(): чи компілюється текст, і якщо ні — рядок і пояснення;
- помилка_з_виводу(): рядок і пояснення з тексту помилки виконання.

Ядро мови (yadro/) тут лише читається: таблиця ключових слів, імена
вбудованих функцій, парсер+компілятор для перевірки.
"""

import re

ВІДСТУП = "    "

# Рядок, що починається з цього слова, відкриває блок: наступний рядок
# має бути глибше на один відступ (у мові немає двокрапок — блок
# визначають лише відступи).
БЛОКОВІ_СЛОВА = ("якщо", "інакше", "поки", "для", "дія", "тип", "спробуй")

ПАРИ = {"(": ")", "[": "]", "{": "}", '"': '"'}
ЗАКРИВНІ = {")", "]", "}"}

# Шаблони каркасів. Позначки:
#   @        — відступ поточного рядка (для продовжень каркаса);
#   «…»      — те, що буде виділено після вставки (набір одразу замінить);
#   |        — куди поставити курсор, якщо виділяти нічого.
КАРКАСИ = {
    "хай": "хай «назва» = ",
    "друкуй": 'друкуй("|")',
    "якщо": "якщо «умова»\n@    ",
    "інакше": "інакше\n@    ",
    "поки": "поки «умова»\n@    ",
    "для": "для «елемент» у список\n@    ",
    "дія": "дія «назва»()\n@    ",
    "поверни": "поверни ",
    "тип": "тип «Назва»\n@    поле\n@    ",
    "спробуй": "спробуй\n@    |\n@якщо помилка\n@    друкуй(помилка)",
    "якщо помилка": "якщо помилка\n@    ",
    "словник": "словник(|)",
    "кинь": 'кинь("|")',
}

# Кнопки, що вставляють текст як є (для ( [ { " спрацьовує автозакриття).
ПРОСТІ_ВСТАВКИ = {
    "(": "(", "[": "[", "{": "{", '"': '"',
    "=": " = ", ".": ".", "відступ": ВІДСТУП,
}

# Порядок кнопок на панелі швидкого вводу.
КНОПКИ = [
    "(", "[", "{", '"', "=", ".", "відступ",
    "хай", "друкуй", "якщо", "інакше", "поки", "для", "дія", "поверни",
    "тип", "спробуй", "якщо помилка", "словник", "кинь",
]


# ---- відступи --------------------------------------------------------------

def _початок_рядка(текст, курсор):
    return текст.rfind("\n", 0, курсор) + 1


def відступ_рядка(текст, курсор):
    """Пробіли на початку рядка, в якому стоїть курсор."""
    поч = _початок_рядка(текст, курсор)
    кін = текст.find("\n", поч)
    рядок = текст[поч:] if кін < 0 else текст[поч:кін]
    return рядок[: len(рядок) - len(рядок.lstrip(" "))]


def відкриває_блок(рядок):
    """Чи наступний рядок після цього має бути глибше."""
    зміст = рядок.split("#", 1)[0].strip()
    if not зміст:
        return False
    перше = зміст.split()[0]
    return перше in БЛОКОВІ_СЛОВА or зміст.endswith(":")


def автовідступ(текст, курсор):
    """Що вставити замість голого Enter: перенос + відступ поточного рядка,
    плюс один рівень, якщо рядок відкриває блок."""
    поч = _початок_рядка(текст, курсор)
    до_курсора = текст[поч:курсор]
    відступ = до_курсора[: len(до_курсора) - len(до_курсора.lstrip(" "))]
    if відкриває_блок(до_курсора):
        відступ += ВІДСТУП
    return "\n" + відступ


# ---- автозакриття ----------------------------------------------------------

def _словесний(ч):
    return bool(ч) and (ч.isalnum() or ч == "_")


def автозакриття(текст, курсор, символ):
    """Повертає (що_вставити, новий_курсор) або None, якщо символ треба
    вставити як є. Для відкривної дужки — пара з курсором усередині;
    для закривної, що вже стоїть праворуч, — лише крок уперед; для лапки —
    пара, окрім як усередині слова (апостроф у «П'ятниця» — не лапка)."""
    наступний = текст[курсор] if курсор < len(текст) else ""
    попередній = текст[курсор - 1] if курсор > 0 else ""
    if символ in ЗАКРИВНІ:
        if наступний == символ:
            return ("", курсор + 1)
        return None
    if символ == '"':
        if наступний == '"':
            return ("", курсор + 1)
        if _словесний(попередній) or _словесний(наступний):
            return None
        return ('""', курсор + 1)
    if символ in ПАРИ:
        return (символ + ПАРИ[символ], курсор + 1)
    return None


# ---- каркаси ---------------------------------------------------------------

def каркас(ключ, текст, курсор):
    """(вставка, початок_виділення, кінець_виділення) — індекси в тексті
    після вставки. Якщо виділяти нічого, початок == кінець == позиція
    курсора."""
    шаблон = КАРКАСИ[ключ].replace("@", відступ_рядка(текст, курсор))
    поч = кін = None
    if "«" in шаблон:
        а = шаблон.index("«")
        б = шаблон.index("»")
        поч, кін = курсор + а, курсор + б - 1
        шаблон = шаблон[:а] + шаблон[а + 1:б] + шаблон[б + 1:]
    elif "|" in шаблон:
        а = шаблон.index("|")
        поч = кін = курсор + а
        шаблон = шаблон[:а] + шаблон[а + 1:]
    else:
        поч = кін = курсор + len(шаблон)
    return шаблон, поч, кін


# ---- перевірка помилок -----------------------------------------------------

def _коротко(e):
    return f"{e.ЗАГОЛОВОК}: {e.повідомлення}"


def перевірити(текст):
    """None, якщо текст компілюється; інакше (рядок, пояснення). Ядро
    не запускається — лише розбір і компіляція."""
    try:
        from yadro.errors import ПомилкаМови
        from yadro.kompilyator import компілювати
        from yadro.parser import парсити_текст
    except Exception:
        return None
    try:
        компілювати(парсити_текст(текст))
        return None
    except ПомилкаМови as e:
        кількість = текст.count("\n") + 1
        рядок = min(max(e.рядок or 1, 1), кількість)
        return рядок, _коротко(e)
    except Exception:
        return None


_ШАПКА = re.compile(r"^(Помилка[^\n]*?) в рядку (\d+), позиція \d+:$", re.M)


def помилка_з_виводу(вивід):
    """Знайти в тексті виводу програми помилку з номером рядка:
    (рядок, пояснення) або None. Пояснення — заголовок і повідомлення без
    цитати рядка джерела зі стрілкою."""
    з = _ШАПКА.search(вивід or "")
    if not з:
        return None
    заголовок, рядок = з.group(1), int(з.group(2))
    решта = вивід[з.end():].split("\n")
    повідомлення = []
    минули_стрілку = False
    for р in решта[1:]:
        if not минули_стрілку:
            if р.strip() == "^":
                минули_стрілку = True
            continue
        if not р.strip():
            break
        повідомлення.append(р.strip())
    if not повідомлення and len(решта) > 1:
        повідомлення = [р.strip() for р in решта[1:] if р.strip()][:1]
    return рядок, f"{заголовок}: {' '.join(повідомлення)}"


# ---- підсвітка (pygments) --------------------------------------------------

try:
    from pygments.lexer import RegexLexer, words
    from pygments.token import (
        Comment, Keyword, Name, Number, Operator, Punctuation, String, Text,
    )
except Exception:  # pragma: no cover — без pygments підсвітки просто немає
    RegexLexer = None

if RegexLexer is not None:
    from yadro.keywords import КЛЮЧОВІ_СЛОВА
    from yadro.natives import ІМЕНА_NATIVE
    from yadro import biblioteka

    # дії бібліотек (Точка, відстань, …) підсвічуються як вбудовані
    _ВБУДОВАНІ = ІМЕНА_NATIVE | set(biblioteka.усі_імена())

    _СТАЛІ = ("істина", "хиба", "ніщо")
    _КЛЮЧОВІ = tuple(с for с in КЛЮЧОВІ_СЛОВА if с not in _СТАЛІ)

    class МоваLexer(RegexLexer):
        """Стандартна схема: ключові слова / рядки / числа / коментарі /
        вбудовані функції — різними класами токенів; кольори дає стиль
        pygments (у застосунку — «default»)."""

        name = "Мова"
        aliases = ["mova", "мова"]
        filenames = ["*.мова"]

        tokens = {
            "root": [
                (r"#[^\n]*", Comment.Single),
                (r'"(\\.|[^"\\\n])*"', String.Double),
                (r"'(\\.|[^'\\\n])*'", String.Single),
                (r'"[^"\n]*', String.Double),      # незакритий рядок
                (r"\d+\.\d+", Number.Float),
                (r"\d+", Number.Integer),
                (words(_СТАЛІ, suffix=r"\b"), Keyword.Constant),
                (words(tuple(sorted(_ВБУДОВАНІ)), suffix=r"\b"), Name.Builtin),
                (words(_КЛЮЧОВІ, suffix=r"\b"), Keyword),
                (r"[^\W\d]\w*", Name),
                (r"[+\-*/%=<>!]+", Operator),
                (r"[()\[\]{}:,.]", Punctuation),
                (r"\s+", Text),
                (r".", Text),
            ],
        }
else:
    МоваLexer = None


# ---- збережені програми (тека застосунку / «програми») -----------------------

import re as _re
from pathlib import Path as _Path

ТЕКА_ПРОГРАМ = "програми"
_ЗАБОРОНЕНО_В_НАЗВІ = _re.compile(r'[\\/:*?"<>|\x00-\x1f]')


def безпечна_назва(назва):
    """Назва програми -> ім'я файлу без розширення: без роздільників шляху
    і службових символів, обрізана; порожня -> None."""
    назва = _ЗАБОРОНЕНО_В_НАЗВІ.sub("", (назва or "")).strip().strip(".")
    if назва.endswith(".мова"):
        назва = назва[: -len(".мова")].strip()
    return назва[:60] or None


def _тека_програм(тека):
    return _Path(тека) / ТЕКА_ПРОГРАМ


def список_програм(тека):
    """Імена збережених програм (без .мова), за абеткою."""
    т = _тека_програм(тека)
    if not т.is_dir():
        return []
    return sorted(ф.stem for ф in т.glob("*.мова") if ф.is_file())


def зберегти_програму(тека, назва, текст):
    """Зберегти текст під назвою; повертає ім'я файлу або None, якщо назва
    порожня/непридатна."""
    ім_я = безпечна_назва(назва)
    if ім_я is None:
        return None
    т = _тека_програм(тека)
    т.mkdir(parents=True, exist_ok=True)
    (т / f"{ім_я}.мова").write_text(текст, encoding="utf-8")
    return f"{ім_я}.мова"


def прочитати_програму(тека, назва):
    """Текст збереженої програми або None, якщо такої немає."""
    ім_я = безпечна_назва(назва)
    if ім_я is None:
        return None
    ф = _тека_програм(тека) / f"{ім_я}.мова"
    if not ф.is_file():
        return None
    return ф.read_text(encoding="utf-8")
