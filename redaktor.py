"""Логіка редактора коду для Android-застосунку — без Kivy, щоб її можна
було тестувати на комп'ютері (тести/test_редактор.py).

Тут:
- КАРКАСИ і каркас(): що вставляє кнопка швидкого вводу (не голе слово, а
  заготовку блоку з відступом і виділеним місцем для заповнення);
- автовідступ(): що вставити на Enter (перенос + відступ; після рядка,
  що відкриває блок, — на один рівень глибше);
- автозакриття(): пара для ( [ { " і «перестрибування» вже наявної
  закривної дужки/лапки;
- МоваLexer: лексер pygments для підсвітки (ключові слова, рядки, числа,
  коментарі, вбудовані функції) — його використовує Kivy CodeInput;
- перевірити(): чи компілюється текст, і якщо ні — рядок і пояснення;
- помилка_з_виводу(): рядок і пояснення з тексту помилки виконання;
- пошук і заміна: знайти_збіги(), найближчий_збіг(), замінити_збіг(),
  замінити_всі(), напис_збігів(); перехід до рядка: номер_рядка(),
  початок_рядка(); куди прокрутити поле, щоб збіг було видно:
  прокрутка_до_рядка(), прокрутка_вбік(); що підсвітити: видимі_збіги().
  Панель із полями й кнопками — panel_poshuku.py.

Ядро мови (yadro/) тут лише читається: таблиця ключових слів, імена
вбудованих функцій, парсер+компілятор для перевірки.
"""

import bisect
import re

ВІДСТУП = "    "

# Рядок, що починається з цього слова, відкриває блок: наступний рядок
# має бути глибше на один відступ (у мові немає двокрапок — блок
# визначають лише відступи).
БЛОКОВІ_СЛОВА = ("якщо", "інакше", "поки", "для", "дія", "тип", "спробуй")

ПАРИ = {"(": ")", "[": "]", "{": "}", '"': '"'}
ЗАКРИВНІ = {")", "]", "}"}

# Шаблони каркасів. Позначки:
#   @        — відступ поточного рядка (для продовжень каркаса);
#   «…»      — те, що буде виділено після вставки (набір одразу замінить);
#   |        — куди поставити курсор, якщо виділяти нічого.
КАРКАСИ = {
    "хай": "хай «назва» = ",
    "друкуй": 'друкуй("|")',
    "запитай": 'хай відповідь = запитай("|")',
    "якщо": "якщо «умова»\n@    ",
    "інакше": "інакше\n@    ",
    "поки": "поки «умова»\n@    ",
    "для": "для «елемент» у список\n@    ",
    "дія": "дія «назва»()\n@    ",
    "поверни": "поверни ",
    "тип": "тип «Назва»\n@    поле\n@    ",
    "спробуй": "спробуй\n@    |\n@якщо помилка\n@    друкуй(помилка)",
    "якщо помилка": "якщо помилка\n@    ",
    "словник": "словник(|)",
    "кинь": 'кинь("|")',
}

# Кнопки, що вставляють текст як є (для ( [ { " спрацьовує автозакриття).
ПРОСТІ_ВСТАВКИ = {
    "(": "(", "[": "[", "{": "{", '"': '"',
    "=": " = ", ".": ".", "відступ": ВІДСТУП,
}

# Порядок кнопок на панелі швидкого вводу.
КНОПКИ = [
    "(", "[", "{", '"', "=", ".", "відступ",
    "хай", "друкуй", "запитай", "якщо", "інакше", "поки", "для", "дія", "поверни",
    "тип", "спробуй", "якщо помилка", "словник", "кинь",
]


# ---- відступи --------------------------------------------------------------

def _початок_рядка(текст, курсор):
    return текст.rfind("\n", 0, курсор) + 1


def відступ_рядка(текст, курсор):
    """Пробіли на початку рядка, в якому стоїть курсор."""
    поч = _початок_рядка(текст, курсор)
    кін = текст.find("\n", поч)
    рядок = текст[поч:] if кін < 0 else текст[поч:кін]
    return рядок[: len(рядок) - len(рядок.lstrip(" "))]


def відкриває_блок(рядок):
    """Чи наступний рядок після цього має бути глибше."""
    зміст = рядок.split("#", 1)[0].strip()
    if not зміст:
        return False
    перше = зміст.split()[0]
    return перше in БЛОКОВІ_СЛОВА or зміст.endswith(":")


def автовідступ(текст, курсор):
    """Що вставити замість голого Enter: перенос + відступ поточного рядка,
    плюс один рівень, якщо рядок відкриває блок."""
    поч = _початок_рядка(текст, курсор)
    до_курсора = текст[поч:курсор]
    відступ = до_курсора[: len(до_курсора) - len(до_курсора.lstrip(" "))]
    if відкриває_блок(до_курсора):
        відступ += ВІДСТУП
    return "\n" + відступ


# ---- автозакриття ----------------------------------------------------------

def _словесний(ч):
    return bool(ч) and (ч.isalnum() or ч == "_")


def автозакриття(текст, курсор, символ):
    """Повертає (що_вставити, новий_курсор) або None, якщо символ треба
    вставити як є. Для відкривної дужки — пара з курсором усередині;
    для закривної, що вже стоїть праворуч, — лише крок уперед; для лапки —
    пара, окрім як усередині слова (апостроф у «П'ятниця» — не лапка)."""
    наступний = текст[курсор] if курсор < len(текст) else ""
    попередній = текст[курсор - 1] if курсор > 0 else ""
    if символ in ЗАКРИВНІ:
        if наступний == символ:
            return ("", курсор + 1)
        return None
    if символ == '"':
        if наступний == '"':
            return ("", курсор + 1)
        if _словесний(попередній) or _словесний(наступний):
            return None
        return ('""', курсор + 1)
    if символ in ПАРИ:
        return (символ + ПАРИ[символ], курсор + 1)
    return None


# ---- каркаси ---------------------------------------------------------------

def каркас(ключ, текст, курсор):
    """(вставка, початок_виділення, кінець_виділення) — індекси в тексті
    після вставки. Якщо виділяти нічого, початок == кінець == позиція
    курсора."""
    шаблон = КАРКАСИ[ключ].replace("@", відступ_рядка(текст, курсор))
    поч = кін = None
    if "«" in шаблон:
        а = шаблон.index("«")
        б = шаблон.index("»")
        поч, кін = курсор + а, курсор + б - 1
        шаблон = шаблон[:а] + шаблон[а + 1:б] + шаблон[б + 1:]
    elif "|" in шаблон:
        а = шаблон.index("|")
        поч = кін = курсор + а
        шаблон = шаблон[:а] + шаблон[а + 1:]
    else:
        поч = кін = курсор + len(шаблон)
    return шаблон, поч, кін


# ---- пошук і заміна --------------------------------------------------------

def _зразок(шукане, регістр):
    return re.compile(re.escape(шукане), 0 if регістр else re.IGNORECASE)


def знайти_збіги(текст, шукане, регістр=False):
    """Індекси початків усіх збігів «шукане» в тексті, за зростанням.
    Збіги не перекриваються (як і при заміні всіх); без «регістр» великі
    й малі літери не розрізняються. Порожнє шукане — збігів немає."""
    if not шукане:
        return []
    return [з.start() for з in _зразок(шукане, регістр).finditer(текст)]


def найближчий_збіг(збіги, курсор):
    """Номер (з 0) першого збігу від курсора й далі; після останнього —
    знову перший. -1, якщо збігів немає."""
    if not збіги:
        return -1
    і = bisect.bisect_left(збіги, курсор)
    return і if і < len(збіги) else 0


def сусідній_збіг(поточний, кількість, крок):
    """Номер наступного (крок 1) чи попереднього (-1) збігу — по колу."""
    if кількість <= 0:
        return -1
    if поточний < 0:
        return 0 if крок > 0 else кількість - 1
    return (поточний + крок) % кількість


def замінити_збіг(текст, початок, довжина, заміна):
    """Замінити один збіг: (новий_текст, індекс_одразу_після_заміни)."""
    новий = текст[:початок] + заміна + текст[початок + довжина:]
    return новий, початок + len(заміна)


def замінити_всі(текст, шукане, заміна, регістр=False):
    """Замінити всі збіги: (новий_текст, скільки_замінено). Заміна
    вставляється як є (жодних \\1 чи \\n)."""
    if not шукане:
        return текст, 0
    return _зразок(шукане, регістр).subn(lambda з: заміна, текст)


def напис_збігів(шукане, поточний, кількість):
    """Лічильник біля поля пошуку: «2 з 7», «немає» або порожньо."""
    if not шукане:
        return ""
    if кількість <= 0:
        return "немає"
    return f"{поточний + 1} з {кількість}"


def початки_рядків(текст):
    """Індекси, з яких починаються рядки тексту (перший — 0)."""
    початки = [0]
    і = текст.find("\n")
    while і >= 0:
        початки.append(і + 1)
        і = текст.find("\n", і + 1)
    return початки


def рядок_і_стовпчик(текст, індекс, початки=None):
    """(рядок, стовпчик) індексу в тексті, обидва з 0."""
    if початки is None:
        початки = початки_рядків(текст)
    індекс = min(max(індекс, 0), len(текст))
    рядок = bisect.bisect_right(початки, індекс) - 1
    return рядок, індекс - початки[рядок]


def видимі_збіги(збіги, початки, перший, останній, найбільше=400):
    """Збіги, що починаються в рядках перший..останній (з 0, включно):
    список (рядок, стовпчик, номер_збігу). Не більше «найбільше» — щоб
    пошук однієї літери не малював тисячі прямокутників."""
    if not збіги or останній < перший or перший >= len(початки):
        return []
    перший = max(перший, 0)
    від = початки[перший]
    до = початки[останній + 1] if останній + 1 < len(початки) else float("inf")
    результат = []
    for номер in range(bisect.bisect_left(збіги, від), len(збіги)):
        індекс = збіги[номер]
        if індекс >= до or len(результат) >= найбільше:
            break
        рядок = bisect.bisect_right(початки, індекс) - 1
        результат.append((рядок, індекс - початки[рядок], номер))
    return результат


def номер_рядка(ввід, рядків):
    """Номер рядка (з 1) з того, що набрано в полі «До рядка»: число
    поза межами стає першим чи останнім рядком; не число — None."""
    try:
        номер = int(str(ввід).strip())
    except ValueError:
        return None
    return min(max(номер, 1), max(рядків, 1))


def початок_рядка(текст, номер):
    """Індекс першого знака рядка «номер» (з 1; поза межами — найближчий)."""
    початки = початки_рядків(текст)
    return початки[min(max(номер, 1), len(початки)) - 1]


def прокрутка_до_рядка(рядок, висота_рядка, висота_вікна, рядків):
    """scroll_y поля коду, за якого рядок (з 0) опиняється посередині
    вікна — наскільки дозволяють початок і кінець тексту."""
    найбільша = max(0, рядків * висота_рядка - висота_вікна)
    бажана = рядок * висота_рядка - (висота_вікна - висота_рядка) / 2
    return min(max(бажана, 0), найбільша)


def прокрутка_вбік(ліво, право, прокрутка, ширина):
    """scroll_x, за якого проміжок ліво..право (пікселі від початку рядка)
    видно у вікні завширшки «ширина». Якщо його й так видно — прокрутка
    не міняється; інакше початок стає за чверть вікна від лівого краю."""
    if ліво >= прокрутка and право <= прокрутка + ширина:
        return прокрутка
    return max(0, ліво - ширина / 4)


# ---- перевірка помилок -----------------------------------------------------

def _коротко(e):
    return f"{e.ЗАГОЛОВОК}: {e.повідомлення}"


def перевірити(текст):
    """None, якщо текст компілюється; інакше (рядок, пояснення). Ядро
    не запускається — лише розбір і компіляція."""
    try:
        from yadro.errors import ПомилкаМови
        from yadro.kompilyator import компілювати
        from yadro.parser import парсити_текст
    except Exception:
        return None
    try:
        компілювати(парсити_текст(текст))
        return None
    except ПомилкаМови as e:
        кількість = текст.count("\n") + 1
        рядок = min(max(e.рядок or 1, 1), кількість)
        return рядок, _коротко(e)
    except Exception:
        return None


_ШАПКА = re.compile(r"^(Помилка[^\n]*?) в рядку (\d+), позиція \d+:$", re.M)


def помилка_з_виводу(вивід):
    """Знайти в тексті виводу програми помилку з номером рядка:
    (рядок, пояснення) або None. Пояснення — заголовок і повідомлення без
    цитати рядка джерела зі стрілкою."""
    з = _ШАПКА.search(вивід or "")
    if not з:
        return None
    заголовок, рядок = з.group(1), int(з.group(2))
    решта = вивід[з.end():].split("\n")
    повідомлення = []
    минули_стрілку = False
    for р in решта[1:]:
        if not минули_стрілку:
            if р.strip() == "^":
                минули_стрілку = True
            continue
        if not р.strip():
            break
        повідомлення.append(р.strip())
    if not повідомлення and len(решта) > 1:
        повідомлення = [р.strip() for р in решта[1:] if р.strip()][:1]
    return рядок, f"{заголовок}: {' '.join(повідомлення)}"


# ---- підсвітка (pygments) --------------------------------------------------

try:
    from pygments.lexer import RegexLexer, words
    from pygments.token import (
        Comment, Keyword, Name, Number, Operator, Punctuation, String, Text,
    )
except Exception:  # pragma: no cover — без pygments підсвітки просто немає
    RegexLexer = None

if RegexLexer is not None:
    from yadro.keywords import КЛЮЧОВІ_СЛОВА
    from yadro.natives import ІМЕНА_NATIVE
    from yadro import biblioteka

    # дії бібліотек (Точка, відстань, …) підсвічуються як вбудовані
    _ВБУДОВАНІ = ІМЕНА_NATIVE | set(biblioteka.усі_імена())

    _СТАЛІ = ("істина", "хиба", "ніщо")
    _КЛЮЧОВІ = tuple(с for с in КЛЮЧОВІ_СЛОВА if с not in _СТАЛІ)

    class МоваLexer(RegexLexer):
        """Стандартна схема: ключові слова / рядки / числа / коментарі /
        вбудовані функції — різними класами токенів; кольори дає стиль
        pygments (у застосунку — «default»)."""

        name = "Мова"
        aliases = ["mova", "мова"]
        filenames = ["*.мова"]

        tokens = {
            "root": [
                (r"#[^\n]*", Comment.Single),
                (r'"(\\.|[^"\\\n])*"', String.Double),
                (r"'(\\.|[^'\\\n])*'", String.Single),
                (r'"[^"\n]*', String.Double),      # незакритий рядок
                (r"\d+\.\d+", Number.Float),
                (r"\d+", Number.Integer),
                (words(_СТАЛІ, suffix=r"\b"), Keyword.Constant),
                (words(tuple(sorted(_ВБУДОВАНІ)), suffix=r"\b"), Name.Builtin),
                (words(_КЛЮЧОВІ, suffix=r"\b"), Keyword),
                (r"[^\W\d]\w*", Name),
                (r"[+\-*/%=<>!]+", Operator),
                (r"[()\[\]{}:,.]", Punctuation),
                (r"\s+", Text),
                (r".", Text),
            ],
        }
else:
    МоваLexer = None
