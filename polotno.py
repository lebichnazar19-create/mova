"""Полотно креслення без Kivy: перетворює фігури drafting.для_екрана()
(мм аркуша, Y вгору) на команди малювання в пікселях екрана. Тут уся
геометрія показу — масштаб, зсув, товщини, засічки розмірів, шрифт —
тому це тестується на комп'ютері (тести/test_полотно.py); vidzhety.py лише
виконує команди на Kivy-canvas і ловить дотики.

Товщини ліній — сталі в пікселях і не залежать від масштабу: контур
(основна лінія) — 2 px, рамка аркуша, розміри, осьові — 1 px. Шрифт —
сталий у пікселях. Масштаб пальцями — множенням (крок ×1.1 / ÷1.1), з
межами МІН_МАСШТАБ..МАКС_МАСШТАБ (пікселів на мм).
"""

import math

МІН_МАСШТАБ = 0.05     # px/мм — весь аркуш А0 ~ 60 px
МАКС_МАСШТАБ = 80.0    # px/мм — 1 мм = 80 px
КРОК_МАСШТАБУ = 1.1
ШИРИНА_КОНТУРУ = 2     # px — основна лінія (контур, ламані, 3D-види)
ШИРИНА_ТОНКА = 1       # px — рамка, розміри, осьові, невидимі, дуги
ШРИФТ_PX = 13
ЗАСІЧКА_PX = 8         # довжина засічки на кінці розмірної лінії
ПОЛЕ_PX = 8            # відступ від країв при «вмістити все»


def ширина_лінії(фігура):
    """Товщина в пікселях за роллю/типом фігури — незалежно від масштабу."""
    if фігура["тип"] == "прямокутник" or фігура.get("роль") == "розмір":
        return ШИРИНА_ТОНКА
    if фігура["тип"] in ("ламана",) or фігура.get("товщина", 0) >= 0.4:
        return ШИРИНА_КОНТУРУ
    return ШИРИНА_ТОНКА


def обмежити_масштаб(масштаб):
    return max(МІН_МАСШТАБ, min(МАКС_МАСШТАБ, масштаб))


def вмістити(креслення, ширина_px, висота_px, x0=0.0, y0=0.0):
    """(масштаб, зсув): аркуш повністю в полотні (ширина_px × висота_px з
    кутом у (x0, y0)), по центру."""
    ш, в = креслення["ширина"], креслення["висота"]
    if ширина_px <= 0 or висота_px <= 0 or ш <= 0 or в <= 0:
        return 1.0, (x0, y0)
    масштаб = обмежити_масштаб(min((ширина_px - 2 * ПОЛЕ_PX) / ш, (висота_px - 2 * ПОЛЕ_PX) / в))
    зсув = (x0 + (ширина_px - ш * масштаб) / 2, y0 + (висота_px - в * масштаб) / 2)
    return масштаб, зсув


def масштаб_щипка(масштаб_старт, відстань_старт, відстань_зараз):
    """Масштаб для щипка двома пальцями: кожен крок — ×1.1 або ÷1.1
    (кількість кроків — за логарифмом відношення відстаней), з межами."""
    if відстань_старт <= 0 or відстань_зараз <= 0:
        return обмежити_масштаб(масштаб_старт)
    # round(…, 6) прибирає шум float (1.9999999 -> 2), int обрізає неповний крок
    кроків = int(round(math.log(відстань_зараз / відстань_старт) / math.log(КРОК_МАСШТАБУ), 6))
    return обмежити_масштаб(масштаб_старт * КРОК_МАСШТАБУ ** кроків)


def зум_навколо(масштаб_старий, масштаб_новий, зсув, точка_px):
    """Новий зсув, щоб точка екрана лишилась на місці після зміни масштабу."""
    if масштаб_старий <= 0:
        return зсув
    к = масштаб_новий / масштаб_старий
    return (точка_px[0] - (точка_px[0] - зсув[0]) * к, точка_px[1] - (точка_px[1] - зсув[1]) * к)


def _засічка(точки_трикутника, масштаб, зсув):
    """Замість стрілки розміру — коротка засічка під 45° через вістря."""
    ax, ay = точки_трикутника[0], точки_трикутника[1]
    bx = (точки_трикутника[2] + точки_трикутника[4]) / 2
    by = (точки_трикутника[3] + точки_трикутника[5]) / 2
    dx, dy = ax - bx, ay - by
    L = math.hypot(dx, dy) or 1.0
    dx, dy = dx / L, dy / L
    # напрямок лінії розміру повернути на 45° — засічка «навскіс»
    c, s = math.cos(math.radians(45)), math.sin(math.radians(45))
    tx, ty = dx * c - dy * s, dx * s + dy * c
    px, py = зсув[0] + ax * масштаб, зсув[1] + ay * масштаб
    h = ЗАСІЧКА_PX / 2
    return [px - tx * h, py - ty * h, px + tx * h, py + ty * h]


def команди(креслення, масштаб, зсув=(0.0, 0.0)):
    """Список команд у пікселях: фон, лінія (точки, ширина, штрих,
    замкнена), заливка (трикутник), дуга, текст (розмір — ШРИФТ_PX)."""
    м = масштаб
    zx, zy = зсув

    def т(x, y):
        return zx + x * м, zy + y * м

    def пл(точки):
        вих = []
        for i in range(0, len(точки), 2):
            вих.extend(т(точки[i], точки[i + 1]))
        return вих

    вихід = [{"тип": "фон", "x": zx, "y": zy, "ш": креслення["ширина"] * м, "в": креслення["висота"] * м,
              "колір": креслення["фон"]}]
    for ф in креслення["фігури"]:
        тип = ф["тип"]
        if тип == "лінія":
            штрих = [max(2.0, ф["штрих"][0] * м), max(2.0, ф["штрих"][1] * м)] if ф.get("штрих") else None
            вихід.append({"тип": "лінія", "точки": пл(ф["точки"]), "ширина": ширина_лінії(ф), "штрих": штрих, "замкнена": False})
        elif тип == "ламана":
            вихід.append({"тип": "лінія", "точки": пл(ф["точки"]), "ширина": ширина_лінії(ф), "штрих": None,
                          "замкнена": bool(ф.get("замкнена"))})
        elif тип == "прямокутник":
            x, y, ш, в = ф["x"], ф["y"], ф["ш"], ф["в"]
            вихід.append({"тип": "лінія", "точки": пл([x, y, x + ш, y, x + ш, y + в, x, y + в]),
                          "ширина": ширина_лінії(ф), "штрих": None, "замкнена": True})
        elif тип == "трикутник":
            if ф.get("роль") == "розмір":
                вихід.append({"тип": "лінія", "точки": _засічка(ф["точки"], м, зсув), "ширина": ШИРИНА_ТОНКА,
                              "штрих": None, "замкнена": False})
            else:
                вихід.append({"тип": "заливка", "точки": пл(ф["точки"])})
        elif тип == "дуга":
            cx, cy = т(ф["cx"], ф["cy"])
            вихід.append({"тип": "дуга", "cx": cx, "cy": cy, "r": ф["r"] * м, "від": ф["від"], "до": ф["до"],
                          "ширина": ширина_лінії(ф)})
        elif тип == "текст":
            x, y = т(ф["x"], ф["y"])
            вихід.append({"тип": "текст", "x": x, "y": y, "текст": ф["текст"], "розмір": ШРИФТ_PX,
                          "кут": ф.get("кут", 0), "вирівнювання": ф.get("вирівнювання", "середина")})
    return вихід
