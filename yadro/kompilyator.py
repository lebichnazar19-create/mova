"""Компілятор: AST -> байткод для стекової VM.

Формат результату описаний у ТЗ (розділ 5):
    {"версія": 1, "константи": [...], "код": [[опкод, аргумент], ...]}

Опкоди ADD/SUB/.../CALL/CALL_NATIVE/HALT — точно за ТЗ. Додатково введені
(бо потрібні для дій і списків, яких немає в мінімальному наборі ТЗ):
    MAKE_FUNCTION [ім'я, параметри, адреса_тіла]  — реєструє дію
    MAKE_LIST     кількість_елементів             — збирає список зі стека
    INDEX_GET / INDEX_SET                         — робота з елементом списку
    SLICE_GET                                     — зріз списку/рядка [a:b]
    MAKE_DICT     кількість_пар                   — збирає словник зі стека (0.5)
    CONTAINS      [прапорець_заперечення]         — `х у колекція` / `х не у колекція` (0.5)
    GET_FIELD / SET_FIELD  ім'я                   — обʼєкт.поле (екземпляр типу або словник) (0.5)
    MAKE_TYPE     [ім'я, [поля]]                  — реєструє тип; типові значення полів бере зі стека (0.5)
    CALL_METHOD   [ім'я, кількість_аргументів]    — обʼєкт.дія(...) (0.5)
    TRY_BEGIN     адреса_обробника / TRY_END      — блок «спробуй» (0.5)
"""

import dataclasses

from . import biblioteka
from . import syntax as А
from .natives import ІМЕНА_NATIVE
from .errors import ПомилкаКомпіляції

# сталі, які ВМ задає на старті (yadro/vm.py); «ПІ = 3» — помилка
# компіляції, але «хай ПІ = 3.14» / «стала ПІ = 3.14» у власній програмі
# дозволені (старі програми так робили)
ВБУДОВАНІ_СТАЛІ = ("ПІ", "вихід", "вхід", "вхід_підтяжка")


_БІНАРНІ_ОПКОДИ = {
    "+": "ADD", "-": "SUB", "*": "MUL", "/": "DIV", "%": "MOD",
    "==": "EQ", "!=": "NEQ", "<": "LT", ">": "GT", "<=": "LTE", ">=": "GTE",
}
_ЛОГІЧНІ_ОПКОДИ = {"і": "AND", "або": "OR"}


class Компілятор:
    def __init__(self):
        self.константи = []
        self.код = []
        self.позиції = []        # [рядок, позиція] для кожної інструкції в self.код — для повідомлень VM
        self.цикли = []          # стек активних циклів: {"перерви": [...], "продовж": [...], "спроби": n}
        self.сталі_поточні = set(ВБУДОВАНІ_СТАЛІ)  # ПІ = 3.14159… задає ВМ на старті
        self.глибина_дій = 0
        self.спроби = 0          # скільки блоків «спробуй» відкрито в поточній дії/на верхньому рівні
        self._лічильник_тимч = 0
        self._поточний_рядок = 0
        self._поточна_кол = 0
        self._поточний_текст = ""  # текст рядка джерела для поточного вузла (якщо позначено yadro/moduli.py)
        # вбудовані імена цієї програми: ядро + підключені бібліотеки
        # (підключи("геометрія") додає імена бібліотеки; yadro/biblioteka.py)
        self.імена_native = set(ІМЕНА_NATIVE)
        # типи бібліотек (Точка), які власне «тип Точка» у програмі може
        # перекрити (ВМ віддає перевагу типу з програми)
        self.типи_бібліотек = set()
        self.бібліотеки = set()

    # ---- допоміжне -------------------------------------------------------

    def _константа(self, значення):
        for i, наявна in enumerate(self.константи):
            if type(наявна) is type(значення) and наявна == значення:
                return i
        self.константи.append(значення)
        return len(self.константи) - 1

    def _emit(self, опкод, аргумент=None):
        self.код.append([опкод, аргумент])
        self.позиції.append([self._поточний_рядок, self._поточна_кол, self._поточний_текст])
        return len(self.код) - 1

    def _тут(self):
        return len(self.код)

    def _патч(self, idx, ціль):
        self.код[idx][1] = ціль

    def _помилка(self, повідомлення, вузол):
        raise ПомилкаКомпіляції(
            повідомлення,
            getattr(вузол, "рядок", 0),
            getattr(вузол, "позиція", 0),
            getattr(вузол, "_рядок_джерела_текст", ""),
        )

    # ---- вхідна точка ------------------------------------------------------

    def компілювати(self, програма: А.Програма):
        # імена бібліотек — наперед, щоб дія, оголошена вище за «підключи»,
        # уже компілювала їх виклики як CALL_NATIVE
        for інстр in програма.тіло:
            if isinstance(інстр, А.ПідключиБібліотеку):
                self._підключити_бібліотеку(інстр)
        for інстр in програма.тіло:
            self._інструкція(інстр)
        self._emit("HALT", None)
        return {
            "версія": 1,
            "константи": self.константи,
            "код": self.код,
            "позиції": self.позиції,
        }

    # ---- інструкції ----------------------------------------------------------

    def _інструкція(self, вузол):
        self._поточний_рядок = getattr(вузол, "рядок", self._поточний_рядок)
        self._поточна_кол = getattr(вузол, "позиція", self._поточна_кол)
        self._поточний_текст = getattr(вузол, "_рядок_джерела_текст", self._поточний_текст)
        тип = type(вузол)
        обробник = getattr(self, f"_і_{тип.__name__}", None)
        if обробник is None:
            self._помилка(f"Компілятор не вміє обробляти вузол {тип.__name__}", вузол)
        обробник(вузол)

    def _і_Хай(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)
        self.сталі_поточні.discard(вузол.імя)

    def _і_Стала(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)
        self.сталі_поточні.add(вузол.імя)

    def _і_Присвоєння(self, вузол):
        if вузол.імя in self.сталі_поточні:
            self._помилка(f"Не можна змінити сталу «{вузол.імя}»", вузол)
        self._вираз(вузол.вираз)
        self._emit("STORE_VAR", вузол.імя)

    def _і_ПрисвоєнняІндекс(self, вузол):
        self._вираз(вузол.колекція)
        self._вираз(вузол.індекс)
        self._вираз(вузол.вираз)
        self._emit("INDEX_SET", None)

    def _і_ВиразІнструкція(self, вузол):
        self._вираз(вузол.вираз)
        self._emit("POP", None)

    def _і_Якщо(self, вузол):
        self._вираз(вузол.умова)
        jf = self._emit("JUMP_FALSE", None)
        for s in вузол.тіло:
            self._інструкція(s)
        if вузол.інакше is None:
            self._патч(jf, self._тут())
            return
        j_кінець = self._emit("JUMP", None)
        self._патч(jf, self._тут())
        if isinstance(вузол.інакше, list):
            for s in вузол.інакше:
                self._інструкція(s)
        else:
            self._інструкція(вузол.інакше)  # вкладений Якщо — «інакше якщо»
        self._патч(j_кінець, self._тут())

    def _і_Поки(self, вузол):
        старт = self._тут()
        self._вираз(вузол.умова)
        jf = self._emit("JUMP_FALSE", None)
        self.цикли.append({"перерви": [], "продовж": [], "спроби": self.спроби})
        for s in вузол.тіло:
            self._інструкція(s)
        цикл = self.цикли.pop()
        self._emit("JUMP", старт)
        кінець = self._тут()
        self._патч(jf, кінець)
        for idx in цикл["перерви"]:
            self._патч(idx, кінець)
        for idx in цикл["продовж"]:
            self._патч(idx, старт)

    def _і_Для(self, вузол):
        n = self._лічильник_тимч
        self._лічильник_тимч += 1
        список_var = f"@список_{n}"
        індекс_var = f"@індекс_{n}"

        self._вираз(вузол.ітерований)
        # словник -> список його ключів; список/рядок лишаються як є
        self._emit("CALL_NATIVE", ["@перелік", 1])
        self._emit("STORE_VAR", список_var)
        self._emit("PUSH_CONST", self._константа(0))
        self._emit("STORE_VAR", індекс_var)

        старт = self._тут()
        self._emit("PUSH_VAR", індекс_var)
        self._emit("PUSH_VAR", список_var)
        self._emit("CALL_NATIVE", ["довжина", 1])
        self._emit("LT", None)
        jf = self._emit("JUMP_FALSE", None)

        self._emit("PUSH_VAR", список_var)
        self._emit("PUSH_VAR", індекс_var)
        self._emit("INDEX_GET", None)
        self._emit("STORE_VAR", вузол.імя)

        self.цикли.append({"перерви": [], "продовж": [], "спроби": self.спроби})
        for s in вузол.тіло:
            self._інструкція(s)
        цикл = self.цикли.pop()

        продовж_ціль = self._тут()
        self._emit("PUSH_VAR", індекс_var)
        self._emit("PUSH_CONST", self._константа(1))
        self._emit("ADD", None)
        self._emit("STORE_VAR", індекс_var)
        self._emit("JUMP", старт)

        кінець = self._тут()
        self._патч(jf, кінець)
        for idx in цикл["перерви"]:
            self._патч(idx, кінець)
        for idx in цикл["продовж"]:
            self._патч(idx, продовж_ціль)

    def _закрити_спроби(self, до_рівня):
        """Стрибок із середини «спробуй» (перервись/продовж/поверни) минає
        TRY_END, тож обробник лишився б зареєстрованим — знімаємо явно."""
        for _ in range(self.спроби - до_рівня):
            self._emit("TRY_END", None)

    def _і_Перервись(self, вузол):
        if not self.цикли:
            self._помилка("«перервись» використано поза циклом", вузол)
        self._закрити_спроби(self.цикли[-1]["спроби"])
        idx = self._emit("JUMP", None)
        self.цикли[-1]["перерви"].append(idx)

    def _і_Продовж(self, вузол):
        if not self.цикли:
            self._помилка("«продовж» використано поза циклом", вузол)
        self._закрити_спроби(self.цикли[-1]["спроби"])
        idx = self._emit("JUMP", None)
        self.цикли[-1]["продовж"].append(idx)

    def _і_Дія(self, вузол):
        if вузол.імя in self.імена_native:
            self._помилка(
                f"Не можна оголосити дію «{вузол.імя}»: це ім'я вже зайняте "
                f"{self._чиє_імя(вузол.імя)}. Оберіть інше ім'я для власної дії.",
                вузол,
            )
        аргумент = [вузол.імя, list(вузол.параметри), None]
        if getattr(вузол, "швидко", False):
            # опис дії (серіалізований AST) — ВМ віддає його yadro/mashyna.py
            аргумент.append(_серіалізувати({"імя": вузол.імя, "параметри": list(вузол.параметри), "тіло": вузол.тіло}))
        зробити = self._emit("MAKE_FUNCTION", аргумент)
        j = self._emit("JUMP", None)
        старт_тіла = self._тут()
        self.код[зробити][1][2] = старт_тіла

        попередні_сталі, попередні_цикли, попередня_глибина, попередні_спроби = (
            self.сталі_поточні, self.цикли, self.глибина_дій, self.спроби
        )
        self.сталі_поточні, self.цикли, self.спроби = set(), [], 0
        self.глибина_дій += 1

        for s in вузол.тіло:
            self._інструкція(s)

        self.глибина_дій = попередня_глибина
        self.цикли = попередні_цикли
        self.сталі_поточні = попередні_сталі
        self.спроби = попередні_спроби

        # неявне «поверни ніщо», якщо тіло дії доходить до кінця
        self._emit("PUSH_CONST", self._константа(None))
        self._emit("RETURN", None)
        self._патч(j, self._тут())

    def _і_Поверни(self, вузол):
        if self.глибина_дій == 0:
            self._помилка("«поверни» використано поза дією", вузол)
        if вузол.вираз is not None:
            self._вираз(вузол.вираз)
        else:
            self._emit("PUSH_CONST", self._константа(None))
        self._закрити_спроби(0)
        self._emit("RETURN", None)

    def _і_Тип(self, вузол):
        if вузол.імя in self.імена_native and вузол.імя not in self.типи_бібліотек:
            self._помилка(
                f"Не можна оголосити тип «{вузол.імя}»: це ім'я вже зайняте "
                f"{self._чиє_імя(вузол.імя)}. Оберіть інше ім'я.",
                вузол,
            )
        # типові значення полів рахуються один раз — при оголошенні типу
        for _, типове in вузол.поля:
            if типове is not None:
                self._вираз(типове)
            else:
                self._emit("PUSH_CONST", self._константа(None))
        self._emit("MAKE_TYPE", [вузол.імя, [імя for імя, _ in вузол.поля]])
        # дії типу — звичайні дії з іменем «Тип.дія» (таке ім'я не можна
        # написати в коді, тож воно не конфліктує ні з чим) і неявним
        # першим параметром «я»
        for метод in вузол.методи:
            self._і_Дія(А.Дія(
                f"{вузол.імя}.{метод.імя}", ["я"] + list(метод.параметри), метод.тіло,
                рядок=метод.рядок, позиція=метод.позиція,
            ))

    def _і_ПрисвоєнняПоля(self, вузол):
        self._вираз(вузол.обʼєкт)
        self._вираз(вузол.вираз)
        self._emit("SET_FIELD", вузол.імя)

    def _і_Спробуй(self, вузол):
        # TRY_BEGIN обробник
        #   тіло
        # TRY_END
        # JUMP кінець
        # обробник: STORE_VAR помилка   (VM кладе текст помилки на стек)
        #   тіло обробника
        # кінець:
        try_begin = self._emit("TRY_BEGIN", None)
        self.спроби += 1
        for s in вузол.тіло:
            self._інструкція(s)
        self.спроби -= 1
        self._emit("TRY_END", None)
        j_кінець = self._emit("JUMP", None)
        self._патч(try_begin, self._тут())
        self._emit("STORE_VAR", "помилка")
        for s in вузол.обробник or []:
            self._інструкція(s)
        self._патч(j_кінець, self._тут())

    def _чиє_імя(self, імя):
        назва = biblioteka.де(імя) if імя not in ІМЕНА_NATIVE else None
        return f"дією бібліотеки «{назва}»" if назва else "вбудованою функцією"

    def _підключити_бібліотеку(self, вузол):
        if not biblioteka.є(вузол.назва):
            self._помилка(
                f"Бібліотеки «{вузол.назва}» немає. Є: {biblioteka.перелік()}.",
                вузол,
            )
        if вузол.назва in self.бібліотеки:
            return
        self.бібліотеки.add(вузол.назва)
        self.імена_native |= biblioteka.імена(вузол.назва)
        self.типи_бібліотек |= biblioteka.типи(вузол.назва)

    def _і_ПідключиБібліотеку(self, вузол):
        # імена вже додано в компілювати(); тут — виклик у VM, щоб вона
        # зареєструвала реалізації (yadro/vm.py:_підключи)
        self._підключити_бібліотеку(вузол)
        self._emit("PUSH_CONST", self._константа(вузол.назва))
        self._emit("CALL_NATIVE", ["підключи", 1])
        self._emit("POP", None)

    def _і_Підключи(self, вузол):
        # сюди компілятор доходить лише якщо вузол Підключи не був розгорнутий
        # yadro/moduli.py до компіляції (наприклад, компілювали AST напряму,
        # як робить REPL — «підключи» підтримується лише для файлів)
        self._помилка(
            "«підключи» підтримується лише при запуску/компіляції файлу "
            "(мова файл.мова), не в REPL і не при компіляції AST напряму.",
            вузол,
        )

    # ---- вирази ------------------------------------------------------------

    def _вираз(self, вузол):
        self._поточний_рядок = getattr(вузол, "рядок", self._поточний_рядок)
        self._поточна_кол = getattr(вузол, "позиція", self._поточна_кол)
        self._поточний_текст = getattr(вузол, "_рядок_джерела_текст", self._поточний_текст)
        тип = type(вузол)
        обробник = getattr(self, f"_в_{тип.__name__}", None)
        if обробник is None:
            self._помилка(f"Компілятор не вміє обробляти вираз {тип.__name__}", вузол)
        обробник(вузол)

    def _в_ЧислоЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_РядокЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_БулЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(вузол.значення))

    def _в_НіщоЛіт(self, вузол):
        self._emit("PUSH_CONST", self._константа(None))

    def _в_СписокЛіт(self, вузол):
        for е in вузол.елементи:
            self._вираз(е)
        self._emit("MAKE_LIST", len(вузол.елементи))

    def _в_СловникЛіт(self, вузол):
        for ключ, значення in вузол.пари:
            self._вираз(ключ)
            self._вираз(значення)
        self._emit("MAKE_DICT", len(вузол.пари))

    def _в_Змінна(self, вузол):
        self._emit("PUSH_VAR", вузол.імя)

    def _в_Поле(self, вузол):
        self._вираз(вузол.обʼєкт)
        self._emit("GET_FIELD", вузол.імя)

    def _в_МетодВиклик(self, вузол):
        self._вираз(вузол.обʼєкт)
        for а in вузол.аргументи:
            self._вираз(а)
        self._emit("CALL_METHOD", [вузол.імя, len(вузол.аргументи)])

    def _в_Унарний(self, вузол):
        self._вираз(вузол.операнд)
        self._emit("NEG" if вузол.оп == "-" else "NOT", None)

    def _в_Бінарний(self, вузол):
        self._вираз(вузол.ліво)
        self._вираз(вузол.право)
        if вузол.оп in ("у", "не у"):
            self._emit("CONTAINS", вузол.оп == "не у")
            return
        self._emit(_БІНАРНІ_ОПКОДИ[вузол.оп], None)

    def _в_Логічний(self, вузол):
        self._вираз(вузол.ліво)
        self._вираз(вузол.право)
        self._emit(_ЛОГІЧНІ_ОПКОДИ[вузол.оп], None)

    def _в_Індекс(self, вузол):
        self._вираз(вузол.колекція)
        self._вираз(вузол.індекс)
        self._emit("INDEX_GET", None)

    def _в_Зріз(self, вузол):
        self._вираз(вузол.колекція)
        if вузол.початок is not None:
            self._вираз(вузол.початок)
        else:
            self._emit("PUSH_CONST", self._константа(None))
        if вузол.кінець is not None:
            self._вираз(вузол.кінець)
        else:
            self._emit("PUSH_CONST", self._константа(None))
        self._emit("SLICE_GET", None)

    def _в_Виклик(self, вузол):
        if (
            вузол.імя == "кнопка"
            and len(вузол.аргументи) == 2
            and isinstance(вузол.аргументи[1], А.Змінна)
        ):
            # кнопка("Напис", показати): другий аргумент — ім'я дії, а не
            # змінна; передається ВМ як рядок
            self._вираз(вузол.аргументи[0])
            self._emit("PUSH_CONST", self._константа(вузол.аргументи[1].імя))
            self._emit("CALL_NATIVE", ["кнопка", 2])
            return
        for а in вузол.аргументи:
            self._вираз(а)
        if вузол.імя in self.імена_native:
            self._emit("CALL_NATIVE", [вузол.імя, len(вузол.аргументи)])
        else:
            self._emit("CALL", [вузол.імя, len(вузол.аргументи)])


def _серіалізувати(вузол):
    """AST -> словники/списки (для байткоду JSON): dataclass -> {"тип": Ім'яКласу, поля…}."""
    if dataclasses.is_dataclass(вузол):
        д = {"тип": type(вузол).__name__}
        for поле in dataclasses.fields(вузол):
            if поле.name in ("рядок", "позиція"):
                continue
            д[поле.name] = _серіалізувати(getattr(вузол, поле.name))
        return д
    if isinstance(вузол, (list, tuple)):
        return [_серіалізувати(е) for е in вузол]
    if isinstance(вузол, dict):
        return {к: _серіалізувати(в) for к, в in вузол.items()}
    return вузол


