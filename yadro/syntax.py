"""Вузли абстрактного синтаксичного дерева (AST) мови «Мова».

Кожен вузол — простий dataclass з полями `рядок`/`позиція` для повідомлень
про помилки на етапі компіляції.
"""

from dataclasses import dataclass, field


# ---- вирази -----------------------------------------------------------

@dataclass
class Вираз:
    рядок: int = field(default=0, kw_only=True)
    позиція: int = field(default=0, kw_only=True)


@dataclass
class ЧислоЛіт(Вираз):
    значення: object = 0


@dataclass
class РядокЛіт(Вираз):
    значення: str = ""


@dataclass
class БулЛіт(Вираз):
    значення: bool = False


@dataclass
class НіщоЛіт(Вираз):
    pass


@dataclass
class СписокЛіт(Вираз):
    елементи: list = field(default_factory=list)


@dataclass
class СловникЛіт(Вираз):
    """`{ключ: значення, ...}` — пари (вираз_ключа, вираз_значення)."""
    пари: list = field(default_factory=list)


@dataclass
class Змінна(Вираз):
    імя: str = ""


@dataclass
class Унарний(Вираз):
    оп: str = ""
    операнд: object = None


@dataclass
class Бінарний(Вираз):
    оп: str = ""
    ліво: object = None
    право: object = None


@dataclass
class Логічний(Вираз):
    """`і` / `або` — з коротким замиканням, тому окремо від Бінарний."""
    оп: str = ""
    ліво: object = None
    право: object = None


@dataclass
class Виклик(Вираз):
    імя: str = ""
    аргументи: list = field(default_factory=list)


@dataclass
class Індекс(Вираз):
    колекція: object = None
    індекс: object = None


@dataclass
class Поле(Вираз):
    """`обʼєкт.імя` — поле екземпляра типу або ключ словника (без лапок)."""
    обʼєкт: object = None
    імя: str = ""


@dataclass
class МетодВиклик(Вираз):
    """`обʼєкт.імя(аргументи)` — виклик дії, оголошеної всередині `тип`."""
    обʼєкт: object = None
    імя: str = ""
    аргументи: list = field(default_factory=list)


@dataclass
class Зріз(Вираз):
    """`колекція[початок:кінець]` — обидва боки необов'язкові (`None`, якщо
    пропущені: `а[:3]`, `а[1:]`, `а[:]`)."""
    колекція: object = None
    початок: object = None
    кінець: object = None


# ---- інструкції ---------------------------------------------------------

@dataclass
class Хай:
    імя: str
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class Стала:
    імя: str
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class Присвоєння:
    імя: str
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class ПрисвоєнняІндекс:
    колекція: object
    індекс: object
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class ПрисвоєнняПоля:
    обʼєкт: object
    імя: str
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class ВиразІнструкція:
    вираз: object
    рядок: int = 0
    позиція: int = 0


@dataclass
class Якщо:
    умова: object
    тіло: list
    інакше: object  # list[інструкція] | Якщо | None
    рядок: int = 0
    позиція: int = 0


@dataclass
class Поки:
    умова: object
    тіло: list
    рядок: int = 0
    позиція: int = 0


@dataclass
class Для:
    імя: str
    ітерований: object
    тіло: list
    рядок: int = 0
    позиція: int = 0


@dataclass
class Перервись:
    рядок: int = 0
    позиція: int = 0


@dataclass
class Продовж:
    рядок: int = 0
    позиція: int = 0


@dataclass
class Дія:
    імя: str
    параметри: list
    тіло: list
    рядок: int = 0
    позиція: int = 0
    швидко: bool = False  # «швидко дія …»: спробувати зібрати в машинний код


@dataclass
class Поверни:
    вираз: object  # може бути None
    рядок: int = 0
    позиція: int = 0


@dataclass
class Тип:
    """`тип Ім'я` з блоком: рядки-поля (`x` або `x = типове`) і дії-методи
    (`дія назва(параметри)`, всередині яких перший неявний параметр «я» —
    сам екземпляр). `поля` — список (ім'я, вираз_типового | None)."""
    імя: str
    поля: list
    методи: list
    рядок: int = 0
    позиція: int = 0


@dataclass
class Спробуй:
    """`спробуй` + блок, далі необов'язково `якщо помилка` + блок. Помилка
    виконання всередині тіла не зупиняє програму: виконання переходить у
    блок обробника, де змінна «помилка» містить текст помилки. Без
    обробника (`обробник is None`) помилка просто ковтається."""
    тіло: list
    обробник: object  # list[інструкція] | None
    рядок: int = 0
    позиція: int = 0


# ---- підключення файлів -------------------------------------------------

@dataclass
class Підключи:
    """`підключи "файл.мова"` — лише на верхньому рівні файлу (парсер
    забороняє всередині дії/умови/циклу). Розгортається в yadro/moduli.py
    ще до компіляції: дії/змінні підключеного файлу зливаються в програму
    так, ніби їх написано прямо тут. Компілятор цей вузол не обробляє —
    якщо він все ж доходить до `_і_Підключи`, це помилка (не пройшов
    розгортання через yadro/moduli.py)."""
    шлях: str
    рядок: int = 0
    позиція: int = 0


@dataclass
class ПідключиБібліотеку:
    """`підключи("геометрія")` — підключити бібліотеку (yadro/biblioteka.py,
    модулі в biblioteky/). Теж лише на верхньому рівні. На відміну від
    файлу, не розгортається в moduli.py: компілятор додає імена бібліотеки
    до вбудованих і емітить CALL_NATIVE «підключи», а VM при виконанні
    реєструє її дії."""
    назва: str
    рядок: int = 0
    позиція: int = 0


@dataclass
class Програма:
    тіло: list
