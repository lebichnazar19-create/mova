"""Рядкові вбудовані дії: розбий, з'єднай, заміни, великими, малими,
обріж, починається, містить; перетворення: дробове (текст — у vm.py, це
до_рядка за арністю; число — теж у vm.py)."""

from .errors import ПомилкаВиконання


def _тип(x):
    from .vm import _тип_укр
    return _тип_укр(x)


def _рядок(x, дія, що="рядок"):
    if not isinstance(x, str):
        raise ПомилкаВиконання(f"Функція «{дія}» очікує {що}, а отримала {_тип(x)}.")
    return x


def розбий(рядок, роздільник=None):
    """розбий("а, б", ", ") -> ["а", "б"]; без роздільника — за пробілами."""
    _рядок(рядок, "розбий")
    if роздільник is None:
        return рядок.split()
    _рядок(роздільник, "розбий", "рядок-роздільник")
    if роздільник == "":
        return list(рядок)
    return рядок.split(роздільник)


def зєднай(список, роздільник=""):
    """з'єднай(["а", "б"], "-") -> "а-б"; елементи будь-якого типу."""
    if not isinstance(список, list):
        raise ПомилкаВиконання(f"Функція «з'єднай» очікує список, а отримала {_тип(список)}.")
    _рядок(роздільник, "з'єднай", "рядок-роздільник")
    from .vm import до_рядка
    return роздільник.join(до_рядка(е) for е in список)


def заміни(рядок, що, на_що):
    _рядок(рядок, "заміни")
    _рядок(що, "заміни", "рядок «що»")
    _рядок(на_що, "заміни", "рядок «на що»")
    if що == "":
        raise ПомилкаВиконання("Функція «заміни»: не можна замінювати порожній рядок.")
    return рядок.replace(що, на_що)


def великими(рядок):
    return _рядок(рядок, "великими").upper()


def малими(рядок):
    return _рядок(рядок, "малими").lower()


def обріж(рядок):
    return _рядок(рядок, "обріж").strip()


def починається(рядок, з):
    _рядок(рядок, "починається")
    _рядок(з, "починається", "рядок-початок")
    return рядок.startswith(з)


def містить(де, що):
    if isinstance(де, str):
        _рядок(що, "містить", "рядок для пошуку в рядку")
        return що in де
    if isinstance(де, (list, dict)):
        return що in де
    raise ПомилкаВиконання(f"Функція «містить» очікує рядок, список або словник, а отримала {_тип(де)}.")


def дробове(x):
    if isinstance(x, bool):
        raise ПомилкаВиконання("Не вдалося перетворити логічне значення на дробове число.")
    if isinstance(x, (int, float)):
        return float(x)
    if isinstance(x, str):
        try:
            return float(x.strip().replace(",", "."))
        except ValueError:
            raise ПомилкаВиконання(f"Не вдалося перетворити рядок «{x}» на дробове число.")
    raise ПомилкаВиконання(f"Не вдалося перетворити {_тип(x)} на дробове число.")
