"""Перший крок до машинного коду (версія 1.2): компілятор простих дій у
ARM64 і виконання їх через mmap(PROT_EXEC) + ctypes.

Що збирається (решта — НеПідтримується з поясненням, і дія виконується VM):
- дія приймає й повертає лише цілі числа (перевіряється під час виклику:
  не-цілий аргумент або число поза int64 — виклик іде у VM);
- усередині: цілі літерали, локальні змінні (до 9), + - * %, унарний мінус,
  порівняння, і/або/не в умовах, якщо/інакше, поки, перервись/продовж,
  поверни з виразом; без «/» (у мові дає дробове), без викликів, списків,
  рядків, словників, полів.

Семантика збігається з VM: + - * перевіряються на переповнення int64,
% — як у Python (знак дільника); при переповненні, діленні на нуль чи
доході до кінця дії без «поверни» машинний код повертає код збою, і VM
виконує виклик сама (дія без побічних ефектів, тож повтор безпечний).

ABI згенерованої функції: int64 f(const int64* аргументи, int64* результат)
-> статус (0 — ок, 1 — ділення на нуль, 2 — переповнення, 3 — без поверни).
Змінні живуть у x19..x27, x28 — вказівник на результат, x0/x1 — тимчасові,
проміжні значення виразів — на стеку. Кожна дія отримує свою свіжу
сторінку mmap (ніколи не перезаписується — так не потрібне скидання
кешу інструкцій).
"""

import ctypes
import mmap
import platform
import struct

from .errors import ПомилкаВиконання

МАКС_ЗМІННИХ = 9          # x19..x27
_РЕГ_РЕЗУЛЬТАТ = 28
_INT64_MIN, _INT64_MAX = -(1 << 63), (1 << 63) - 1

СТАТУС_ОК, СТАТУС_ДІЛЕННЯ_НА_НУЛЬ, СТАТУС_ПЕРЕПОВНЕННЯ, СТАТУС_БЕЗ_ПОВЕРНИ = 0, 1, 2, 3

_УМОВИ = {"EQ": 0, "NE": 1, "MI": 4, "PL": 5, "VS": 6, "VC": 7, "GE": 10, "LT": 11, "GT": 12, "LE": 13}
# порівняння -> умова переходу на «хиба» (протилежна)
_СТРИБОК_ЯКЩО_ХИБА = {"==": "NE", "!=": "EQ", "<": "GE", ">": "LE", "<=": "GT", ">=": "LT"}


class НеПідтримується(Exception):
    """Дію не можна зібрати в машинний код — причина українською."""


def доступно():
    """Чи це середовище може виконувати згенерований ARM64-код."""
    return platform.machine() in ("aarch64", "arm64") and hasattr(mmap, "PROT_EXEC")


def _є_ціле(x):
    return isinstance(x, int) and not isinstance(x, bool) and _INT64_MIN <= x <= _INT64_MAX


# ---- кодування інструкцій ------------------------------------------------------

def _mov_imm(rd, значення):
    """movz/movk — довільне 64-бітне число (доповняльний код)."""
    v = значення & 0xFFFFFFFFFFFFFFFF
    інстр = []
    перша = True
    for hw in range(4):
        шмат = (v >> (16 * hw)) & 0xFFFF
        if шмат == 0 and not (перша and hw == 3):
            continue
        if перша:
            інстр.append(0xD2800000 | (hw << 21) | (шмат << 5) | rd)  # movz
            перша = False
        else:
            інстр.append(0xF2800000 | (hw << 21) | (шмат << 5) | rd)  # movk
    if перша:
        інстр.append(0xD2800000 | rd)  # movz rd, #0
    return інстр


def _mov(rd, rm):            # ORR Xd, XZR, Xm
    return 0xAA0003E0 | (rm << 16) | rd


def _adds(rd, rn, rm):
    return 0xAB000000 | (rm << 16) | (rn << 5) | rd


def _subs(rd, rn, rm):
    return 0xEB000000 | (rm << 16) | (rn << 5) | rd


def _add(rd, rn, rm):
    return 0x8B000000 | (rm << 16) | (rn << 5) | rd


def _mul(rd, rn, rm):        # MADD Xd, Xn, Xm, XZR
    return 0x9B007C00 | (rm << 16) | (rn << 5) | rd


def _smulh(rd, rn, rm):
    return 0x9B407C00 | (rm << 16) | (rn << 5) | rd


def _sdiv(rd, rn, rm):
    return 0x9AC00C00 | (rm << 16) | (rn << 5) | rd


def _msub(rd, rn, rm, ra):
    return 0x9B008000 | (rm << 16) | (ra << 10) | (rn << 5) | rd


def _eor(rd, rn, rm):
    return 0xCA000000 | (rm << 16) | (rn << 5) | rd


def _cmp(rn, rm):            # SUBS XZR, Xn, Xm
    return 0xEB000000 | (rm << 16) | (rn << 5) | 31


def _cmp_asr63(rn, rm):      # SUBS XZR, Xn, Xm, ASR #63
    return 0xEB800000 | (rm << 16) | (63 << 10) | (rn << 5) | 31


def _cmp_imm0(rn):           # SUBS XZR, Xn, #0
    return 0xF100001F | (rn << 5)


def _push(rt):               # STR Xt, [SP, #-16]!
    return 0xF81F0FE0 | rt


def _pop(rt):                # LDR Xt, [SP], #16
    return 0xF84107E0 | rt


def _stp(rt1, rt2, зсув):    # STP Xt1, Xt2, [SP, #зсув]
    return 0xA9000000 | (((зсув // 8) & 0x7F) << 15) | (rt2 << 10) | (31 << 5) | rt1


def _ldp(rt1, rt2, зсув):
    return 0xA9400000 | (((зсув // 8) & 0x7F) << 15) | (rt2 << 10) | (31 << 5) | rt1


def _sub_sp(байтів):
    return 0xD10003FF | (байтів << 10)


def _add_sp(байтів):
    return 0x910003FF | (байтів << 10)


def _ldr_x0_off(rd, індекс):  # LDR Xd, [X0, #8*індекс]
    return 0xF9400000 | (індекс << 10) | rd


def _str_x28(rt):             # STR Xt, [X28]
    return 0xF9000000 | (_РЕГ_РЕЗУЛЬТАТ << 5) | rt


_RET = 0xD65F03C0


# ---- збирач ----------------------------------------------------------------------

class _Збирач:
    def __init__(self, опис):
        self.опис = опис
        self.імя = опис["імя"]
        self.параметри = list(опис["параметри"])
        self.код = []                 # 32-бітні слова
        self.мітки = {}               # мітка -> індекс слова
        self.латки = []               # (індекс, вид, мітка)
        self.лічильник = 0
        self.регістри = {}            # змінна -> регістр
        self.відомі = set()           # змінні, які вже мали присвоєння (лінійний прохід)
        self.цикли = []               # [(мітка_продовж, мітка_кінець)]

    # -- допоміжне --

    def _мітка(self, назва):
        self.лічильник += 1
        return f"{назва}_{self.лічильник}"

    def _тут(self, мітка):
        self.мітки[мітка] = len(self.код)

    def _emit(self, *слова):
        self.код.extend(слова)

    def _стрибок(self, вид, мітка, умова=None, регістр=None):
        self.латки.append((len(self.код), вид, мітка, умова, регістр))
        self.код.append(0)

    def _регістр(self, імя):
        if імя not in self.регістри:
            if len(self.регістри) >= МАКС_ЗМІННИХ:
                raise НеПідтримується(f"забагато змінних (більше {МАКС_ЗМІННИХ}) у дії «{self.імя}»")
            self.регістри[імя] = 19 + len(self.регістри)
        return self.регістри[імя]

    def _ні(self, що):
        raise НеПідтримується(f"{що} у дії «{self.імя}»")

    # -- вирази: результат у x0 --

    def _вираз(self, в):
        тип = в["тип"]
        if тип == "ЧислоЛіт":
            з = в["значення"]
            if isinstance(з, bool) or not isinstance(з, int):
                self._ні("дробове число")
            if not _є_ціле(з):
                self._ні("число поза межами 64 біт")
            self._emit(*_mov_imm(0, з))
        elif тип == "Змінна":
            імя = в["імя"]
            if імя not in self.відомі:
                self._ні(f"змінна «{імя}» читається до присвоєння або є зовнішньою")
            self._emit(_mov(0, self._регістр(імя)))
        elif тип == "Унарний":
            if в["оп"] != "-":
                self._ні("«не» як значення (лише в умовах)")
            self._вираз(в["операнд"])
            self._emit(_subs(0, 31, 0))                 # negs x0, x0
            self._стрибок("b.cond", "збій_переповнення", умова="VS")
        elif тип == "Бінарний":
            оп = в["оп"]
            if оп not in ("+", "-", "*", "%"):
                if оп == "/":
                    self._ні("ділення «/» (у мові воно дає дробове число)")
                self._ні(f"порівняння «{оп}» як значення (лише в умовах)")
            self._вираз(в["ліво"])
            self._emit(_push(0))
            self._вираз(в["право"])
            self._emit(_mov(1, 0), _pop(0))
            if оп == "+":
                self._emit(_adds(0, 0, 1))
                self._стрибок("b.cond", "збій_переповнення", умова="VS")
            elif оп == "-":
                self._emit(_subs(0, 0, 1))
                self._стрибок("b.cond", "збій_переповнення", умова="VS")
            elif оп == "*":
                self._emit(_mul(2, 0, 1), _smulh(3, 0, 1), _cmp_asr63(3, 2))
                self._стрибок("b.cond", "збій_переповнення", умова="NE")
                self._emit(_mov(0, 2))
            else:  # % як у Python
                self._стрибок("cbz", "збій_ділення", регістр=1)
                пропуск = self._мітка("остача_готова")
                self._emit(_sdiv(2, 0, 1), _msub(0, 2, 1, 0))   # x0 = a - (a/b)*b
                self._стрибок("cbz", пропуск, регістр=0)
                self._emit(_eor(3, 0, 1))
                self._стрибок("tbz63", пропуск, регістр=3)      # знаки збігаються — готово
                self._emit(_add(0, 0, 1))
                self._тут(пропуск)
        elif тип == "Логічний":
            self._ні("«і»/«або» як значення (лише в умовах)")
        elif тип == "БулЛіт":
            self._ні("логічне значення (лише цілі числа)")
        elif тип == "Виклик":
            self._ні(f"виклик «{в['імя']}» (виклики інших дій)")
        elif тип == "РядокЛіт":
            self._ні("рядок")
        elif тип in ("СписокЛіт", "СловникЛіт", "Індекс", "Зріз"):
            self._ні("список/словник")
        elif тип in ("Поле", "МетодВиклик"):
            self._ні("поле чи дія типу")
        elif тип == "НіщоЛіт":
            self._ні("«ніщо»")
        else:
            self._ні(f"конструкція {тип}")

    # -- умови: стрибок на мітку, коли хиба --

    def _умова(self, в, хиба):
        тип = в["тип"]
        if тип == "Логічний":
            if в["оп"] == "і":
                self._умова(в["ліво"], хиба)
                self._умова(в["право"], хиба)
            else:
                правда = self._мітка("або_правда")
                self._умова_істина(в["ліво"], правда)
                self._умова(в["право"], хиба)
                self._тут(правда)
        elif тип == "Унарний" and в["оп"] == "не":
            self._умова_істина(в["операнд"], хиба)
        elif тип == "Бінарний" and в["оп"] in _СТРИБОК_ЯКЩО_ХИБА:
            self._вираз(в["ліво"])
            self._emit(_push(0))
            self._вираз(в["право"])
            self._emit(_mov(1, 0), _pop(0), _cmp(0, 1))
            self._стрибок("b.cond", хиба, умова=_СТРИБОК_ЯКЩО_ХИБА[в["оп"]])
        elif тип == "БулЛіт":
            if not в["значення"]:
                self._стрибок("b", хиба)
        else:
            self._вираз(в)                      # ціле як умова: 0 — хиба
            self._emit(_cmp_imm0(0))
            self._стрибок("b.cond", хиба, умова="EQ")

    def _умова_істина(self, в, істина):
        далі = self._мітка("далі")
        self._умова(в, далі)
        self._стрибок("b", істина)
        self._тут(далі)

    # -- інструкції --

    def _тіло(self, інструкції):
        for і in інструкції:
            self._інструкція(і)

    def _інструкція(self, і):
        тип = і["тип"]
        if тип in ("Хай", "Стала", "Присвоєння"):
            self._вираз(і["вираз"])
            self.відомі.add(і["імя"])
            self._emit(_mov(self._регістр(і["імя"]), 0))
        elif тип == "Поверни":
            if і["вираз"] is None:
                self._ні("«поверни» без значення")
            self._вираз(і["вираз"])
            self._emit(_str_x28(0), *_mov_imm(0, СТАТУС_ОК))
            self._стрибок("b", "епілог")
        elif тип == "Якщо":
            хиба = self._мітка("якщо_хиба")
            кінець = self._мітка("якщо_кінець")
            self._умова(і["умова"], хиба)
            self._тіло(і["тіло"])
            if і["інакше"] is not None:
                self._стрибок("b", кінець)
            self._тут(хиба)
            if і["інакше"] is not None:
                if isinstance(і["інакше"], list):
                    self._тіло(і["інакше"])
                else:
                    self._інструкція(і["інакше"])
            self._тут(кінець)
        elif тип == "Поки":
            старт, кінець = self._мітка("поки"), self._мітка("поки_кінець")
            self._тут(старт)
            self._умова(і["умова"], кінець)
            self.цикли.append((старт, кінець))
            self._тіло(і["тіло"])
            self.цикли.pop()
            self._стрибок("b", старт)
            self._тут(кінець)
        elif тип == "Перервись":
            if not self.цикли:
                self._ні("«перервись» поза циклом")
            self._стрибок("b", self.цикли[-1][1])
        elif тип == "Продовж":
            if not self.цикли:
                self._ні("«продовж» поза циклом")
            self._стрибок("b", self.цикли[-1][0])
        elif тип == "Для":
            self._ні("цикл «для» (лише «поки»)")
        elif тип == "ВиразІнструкція":
            self._ні("виклик чи вираз без присвоєння")
        elif тип == "Спробуй":
            self._ні("«спробуй»")
        elif тип in ("ПрисвоєнняІндекс", "ПрисвоєнняПоля"):
            self._ні("запис у список/поле")
        else:
            self._ні(f"конструкція {тип}")

    # -- усе разом --

    def зібрати(self):
        if len(self.параметри) > МАКС_ЗМІННИХ:
            self._ні(f"забагато параметрів (більше {МАКС_ЗМІННИХ})")
        # пролог
        self._emit(_sub_sp(96), _stp(29, 30, 0), _stp(19, 20, 16), _stp(21, 22, 32),
                   _stp(23, 24, 48), _stp(25, 26, 64), _stp(27, 28, 80), _mov(_РЕГ_РЕЗУЛЬТАТ, 1))
        for і, п in enumerate(self.параметри):
            self.відомі.add(п)
            self._emit(_ldr_x0_off(self._регістр(п), і))
        self._тіло(self.опис["тіло"])
        self._emit(*_mov_imm(0, СТАТУС_БЕЗ_ПОВЕРНИ))
        self._стрибок("b", "епілог")
        self._тут("збій_ділення")
        self._emit(*_mov_imm(0, СТАТУС_ДІЛЕННЯ_НА_НУЛЬ))
        self._стрибок("b", "епілог")
        self._тут("збій_переповнення")
        self._emit(*_mov_imm(0, СТАТУС_ПЕРЕПОВНЕННЯ))
        self._тут("епілог")
        self._emit(_ldp(29, 30, 0), _ldp(19, 20, 16), _ldp(21, 22, 32), _ldp(23, 24, 48),
                   _ldp(25, 26, 64), _ldp(27, 28, 80), _add_sp(96), _RET)
        # латки переходів
        for індекс, вид, мітка, умова, регістр in self.латки:
            зсув = self.мітки[мітка] - індекс
            if вид == "b":
                self.код[індекс] = 0x14000000 | (зсув & 0x03FFFFFF)
            elif вид == "b.cond":
                self.код[індекс] = 0x54000000 | ((зсув & 0x7FFFF) << 5) | _УМОВИ[умова]
            elif вид == "cbz":
                self.код[індекс] = 0xB4000000 | ((зсув & 0x7FFFF) << 5) | регістр
            elif вид == "tbz63":
                self.код[індекс] = 0xB6F80000 | ((зсув & 0x3FFF) << 5) | регістр
        return struct.pack("<%dI" % len(self.код), *self.код)


class МашиннаДія:
    """Зібрана дія: тримає сторінку mmap живою й викликає код через ctypes."""

    def __init__(self, імя, параметри, байти):
        self.імя = імя
        self.кількість = len(параметри)
        self.байти = байти
        розмір = max(mmap.PAGESIZE, (len(байти) + mmap.PAGESIZE - 1) // mmap.PAGESIZE * mmap.PAGESIZE)
        self._память = mmap.mmap(
            -1, розмір, prot=mmap.PROT_READ | mmap.PROT_WRITE | mmap.PROT_EXEC,
            flags=mmap.MAP_PRIVATE | mmap.MAP_ANONYMOUS,
        )
        self._память.write(байти)
        адреса = ctypes.addressof(ctypes.c_char.from_buffer(self._память))
        self._функція = ctypes.CFUNCTYPE(
            ctypes.c_int64, ctypes.POINTER(ctypes.c_int64), ctypes.POINTER(ctypes.c_int64)
        )(адреса)
        self._масив = ctypes.c_int64 * max(1, self.кількість)

    def підходить(self, args):
        return len(args) == self.кількість and all(_є_ціле(а) for а in args)

    def виклик(self, args):
        """(статус, значення). Викликати лише якщо підходить(args)."""
        масив = self._масив(*args)
        результат = ctypes.c_int64(0)
        статус = self._функція(масив, ctypes.byref(результат))
        return статус, результат.value


def зібрати(опис):
    """Зібрати дію з опису (серіалізований AST від компілятора:
    {"імя", "параметри", "тіло": [вузли з полем "тип"]}). Повертає
    МашиннаДія або кидає НеПідтримується."""
    if not доступно():
        raise НеПідтримується(f"машинний код підтримується лише на ARM64 (тут {platform.machine()})")
    байти = _Збирач(опис).зібрати()
    try:
        return МашиннаДія(опис["імя"], опис["параметри"], байти)
    except (OSError, ValueError, ctypes.ArgumentError) as e:
        raise НеПідтримується(f"не вдалося виділити пам'ять для коду ({e})")


def причина_збою(статус):
    return {
        СТАТУС_ДІЛЕННЯ_НА_НУЛЬ: "ділення на нуль",
        СТАТУС_ПЕРЕПОВНЕННЯ: "переповнення 64-бітного числа",
        СТАТУС_БЕЗ_ПОВЕРНИ: "дія дійшла до кінця без «поверни»",
    }.get(статус, f"статус {статус}")
