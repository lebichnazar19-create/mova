"""Бібліотеки мови: `підключи("геометрія")` (з 1.5).

Бібліотека — модуль Python у теці biblioteky/ поруч із yadro/. Компілятор
і VM нічого не знають про її дії, поки програма не виконає «підключи»:
компілятор тоді компілює виклики її імен як CALL_NATIVE, а VM реєструє
реалізації в себе (ВМ._native). Так ядро лишається невеликим, а список
бібліотек — один: БІБЛІОТЕКИ нижче.

Протокол модуля бібліотеки (див. biblioteky/geometriya.py):
    НАЗВА    — назва в мові («геометрія»)
    ІМЕНА    — {ім'я дії: функція}
    ТИПИ     — {ім'я типу: клас} — класи-значення, підкласи Значення;
               «тип Точка» у самій програмі має перевагу над бібліотечним
    СПІЛЬНІ  — {ім'я: предикат(args)} для імен, що вже є у VM (кут — і в
               кресленні, зсунь — і в ескізі, довжина — мовна): коли
               предикат істинний, працює бібліотечна версія, інакше — та,
               що була до підключення
    ДОВІДКА  — [(ім'я, приклад, опис)] для «Довідки» (yadro/dovidka.py)
    ЗАГОЛОВОК_ДОВІДКИ — назва групи в довідці
"""

import importlib
import sys
from pathlib import Path

from .errors import ПомилкаВиконання

# назва в мові -> модуль у biblioteky/
БІБЛІОТЕКИ = {
    "геометрія": "geometriya",
}

_КОРІНЬ = str(Path(__file__).resolve().parent.parent)  # тека з yadro/ і biblioteky/


class Значення:
    """Базовий клас значень бібліотечних типів (Точка у геометрії). VM
    працює з ними узагальнено: арифметика — через оператори Python
    (+ - * / унарний мінус; ==), друк — str(), поля — ПОЛЯ, індекси —
    __getitem__, ім'я типу для повідомлень — ТИП. Присвоєння полів чи
    індексів заборонене (значення незмінні), підклас може дати своє
    пояснення, перевизначивши __setattr__/__setitem__."""

    ТИП = "значення"
    ПОЛЯ = ()

    def __setattr__(self, імя, значення):
        raise ПомилкаВиконання(f"Значення типу «{self.ТИП}» незмінне: поле «{імя}» не можна присвоїти.")

    def __setitem__(self, індекс, значення):
        raise ПомилкаВиконання(f"Значення типу «{self.ТИП}» незмінне: елемент [{індекс}] не можна присвоїти.")


_кеш = {}


def є(назва):
    return назва in БІБЛІОТЕКИ


def перелік():
    return ", ".join(f"«{н}»" for н in БІБЛІОТЕКИ)


def модуль(назва):
    """Модуль бібліотеки за назвою в мові; ПомилкаВиконання, якщо такої немає."""
    if назва not in БІБЛІОТЕКИ:
        raise ПомилкаВиконання(f"Бібліотеки «{назва}» немає. Є: {перелік()}.")
    if назва not in _кеш:
        if _КОРІНЬ not in sys.path:
            sys.path.append(_КОРІНЬ)
        _кеш[назва] = importlib.import_module("biblioteky." + БІБЛІОТЕКИ[назва])
    return _кеш[назва]


def імена(назва):
    return set(модуль(назва).ІМЕНА)


def типи(назва):
    return set(модуль(назва).ТИПИ)


def усі_імена():
    """{ім'я дії: назва бібліотеки} по всіх бібліотеках — для підказок,
    підсвітки в редакторі й довідки."""
    return {імя: назва for назва in БІБЛІОТЕКИ for імя in модуль(назва).ІМЕНА}


def усі_типи():
    return {імя: назва for назва in БІБЛІОТЕКИ for імя in модуль(назва).ТИПИ}


def де(імя):
    """Назва бібліотеки, у якій є дія/тип з таким ім'ям, або None."""
    return усі_імена().get(імя)


def підказка(імя):
    """«… є в бібліотеці «геометрія» — додай на початку програми:
    підключи("геометрія")» або порожній рядок."""
    назва = де(імя)
    if назва is None:
        return ""
    return f" Вона є в бібліотеці «{назва}» — додай на початку програми: підключи(\"{назва}\")."
