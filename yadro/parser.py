"""Парсер: перетворює потік токенів на AST."""

from .lexer import токенізувати
from .keywords import КЛЮЧОВІ_СЛОВА
from .natives import ІМЕНА_NATIVE
from .errors import ПомилкаРозбору
from . import syntax as А
from . import dovidka

# ключові слова, з яких не може починатись інструкція, — і як має бути
_НЕ_НА_ПОЧАТКУ = {
    "ІНАКШЕ": "«інакше» ставлять одразу після блоку «якщо», з тим самим відступом, що й «якщо»:\n"
              "    якщо х > 5\n        друкуй(\"багато\")\n    інакше\n        друкуй(\"мало\")",
    "У": "«у» — частина циклу «для» (або перевірки наявності): для х у список / якщо ключ у словник",
    "І": "«і» з'єднує дві умови всередині «якщо» чи «поки»: якщо а > 1 і б < 2",
    "АБО": "«або» з'єднує дві умови всередині «якщо» чи «поки»: якщо а > 1 або б < 2",
}

_ВБУДОВАНІ_ТИПИ = ("Точка",)


class Парсер:
    def __init__(self, токени, рядки_джерела=None):
        self.токени = токени
        self.і = 0
        self.рядки_джерела = рядки_джерела or []
        self._глибина_блоку = 0  # >0 всередині дії/умови/циклу — там «підключи» заборонено

    # ---- допоміжне -----------------------------------------------------

    def _поточний(self):
        return self.токени[self.і]

    def _пік(self, зсув=1):
        j = self.і + зсув
        if j < len(self.токени):
            return self.токени[j]
        return self.токени[-1]

    def _далі(self):
        tok = self.токени[self.і]
        if tok.тип != "КІНЕЦЬ":
            self.і += 1
        return tok

    def _збіг(self, *типи):
        if self._поточний().тип in типи:
            return self._далі()
        return None

    def _текст_рядка(self, номер):
        if 1 <= номер <= len(self.рядки_джерела):
            return self.рядки_джерела[номер - 1]
        return ""

    def _помилка(self, повідомлення, tok=None):
        tok = tok or self._поточний()
        raise ПомилкаРозбору(повідомлення, tok.рядок, tok.позиція, self._текст_рядка(tok.рядок))

    def _очікувати(self, тип, повідомлення):
        if self._поточний().тип != тип:
            self._помилка(повідомлення)
        return self._далі()

    def _очікувати_імя(self, що):
        """Як _очікувати("ІМЯ", ...), але якщо замість імені стоїть ключове
        слово («хай для = 5»), пояснює саме це, а не «очікувалось ім'я»."""
        tok = self._поточний()
        if tok.тип != "ІМЯ":
            if tok.значення in КЛЮЧОВІ_СЛОВА:
                self._помилка(
                    f"«{tok.значення}» — ключове слово мови, його не можна "
                    f"використати як {що}. Обери інше ім'я, наприклад «{tok.значення}_»."
                )
            self._помилка(f"Очікувалось {що}")
        return self._далі()

    # ---- вхідна точка ---------------------------------------------------

    def парсити(self):
        інструкції = []
        while self._поточний().тип != "КІНЕЦЬ":
            інструкції.append(self._інструкція())
        return А.Програма(інструкції)

    def _блок(self):
        self._очікувати(
            "ВІДСТУП_ВПЕРЕД",
            "Наступний рядок має бути тілом блоку — глибше на 4 пробіли:\n"
            "    якщо х > 5\n        друкуй(\"багато\")",
        )
        self._глибина_блоку += 1
        інструкції = []
        while self._поточний().тип not in ("ВІДСТУП_НАЗАД", "КІНЕЦЬ"):
            інструкції.append(self._інструкція())
        self._глибина_блоку -= 1
        self._очікувати("ВІДСТУП_НАЗАД", "Очікувалось завершення блоку (менший відступ)")
        return інструкції

    # ---- інструкції -------------------------------------------------------

    def _інструкція(self):
        tok = self._поточний()
        якщо_тип = tok.тип
        if якщо_тип in _НЕ_НА_ПОЧАТКУ:
            self._помилка(_НЕ_НА_ПОЧАТКУ[якщо_тип])
        if якщо_тип == "ПРИСВОЄННЯ":
            self._помилка("Ліворуч від «=» має бути ім'я змінної. Щоб створити змінну: хай х = 5")
        if якщо_тип in ("ППАР", "ПДУЖКА", "ПФІГ"):
            self._помилка(f"Зайва «{tok.значення}» — для неї немає відкривної дужки.")
        if якщо_тип == "ХАЙ":
            return self._хай_чи_стала(А.Хай, "ХАЙ")
        if якщо_тип == "СТАЛА":
            return self._хай_чи_стала(А.Стала, "СТАЛА")
        if якщо_тип == "ДІЯ":
            return self._дія()
        if якщо_тип == "ШВИДКО":
            self._далі()
            if self._поточний().тип != "ДІЯ":
                self._помилка("«швидко» ставлять перед «дія»: швидко дія сума(н)", tok)
            дія = self._дія()
            дія.швидко = True
            дія.рядок, дія.позиція = tok.рядок, tok.позиція
            return дія
        if якщо_тип == "ПОВЕРНИ":
            return self._поверни()
        if якщо_тип == "ЯКЩО":
            return self._якщо()
        if якщо_тип == "ПОКИ":
            return self._поки()
        if якщо_тип == "ДЛЯ":
            return self._для()
        if якщо_тип == "ПЕРЕРВИСЬ":
            self._далі()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «перервись»")
            return А.Перервись(рядок=tok.рядок, позиція=tok.позиція)
        if якщо_тип == "ПРОДОВЖ":
            self._далі()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «продовж»")
            return А.Продовж(рядок=tok.рядок, позиція=tok.позиція)
        if якщо_тип == "ПІДКЛЮЧИ":
            return self._підключи()
        if якщо_тип == "ТИП":
            return self._тип()
        if якщо_тип == "СПРОБУЙ":
            return self._спробуй()

        return self._вираз_чи_присвоєння()

    def _тип(self):
        """тип Точка
               x
               y = 0
               дія зсунь(dx, dy)
                   я.x = я.x + dx
        Поля — голі імена (можна з типовим значенням після «=», можна з
        «хай» попереду — необов'язково), дії — звичайні «дія» всередині."""
        tok = self._далі()  # ТИП
        імя_tok = self._очікувати_імя("ім'я типу")
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «тип Ім'я»")
        self._очікувати(
            "ВІДСТУП_ВПЕРЕД",
            "Очікувався блок з відступом: поля і дії типу (наступний рядок має бути глибше)",
        )
        self._глибина_блоку += 1
        поля, методи, імена_полів = [], [], set()
        while self._поточний().тип not in ("ВІДСТУП_НАЗАД", "КІНЕЦЬ"):
            т = self._поточний()
            if т.тип == "ДІЯ":
                методи.append(self._дія())
                continue
            if т.тип == "ХАЙ":
                self._далі()
            поле_tok = self._очікувати_імя("ім'я поля (або «дія» для дії типу)")
            if поле_tok.значення in імена_полів:
                self._помилка(f"Поле «{поле_tok.значення}» у типі «{імя_tok.значення}» оголошено двічі", поле_tok)
            імена_полів.add(поле_tok.значення)
            типове = None
            if self._збіг("ПРИСВОЄННЯ"):
                типове = self._вираз()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після поля типу")
            поля.append((поле_tok.значення, типове))
        self._глибина_блоку -= 1
        self._очікувати("ВІДСТУП_НАЗАД", "Очікувалось завершення блоку типу (менший відступ)")
        for м in методи:
            if "я" in м.параметри:
                self._помилка(
                    f"У дії «{м.імя}» типу «{імя_tok.значення}» не треба вказувати «я» "
                    "серед параметрів: «я» — це сам екземпляр, він доступний завжди.",
                    м,
                )
        return А.Тип(імя_tok.значення, поля, методи, рядок=tok.рядок, позиція=tok.позиція)

    def _спробуй(self):
        """спробуй
               ...
           якщо помилка
               друкуй(помилка)
        Друга частина необов'язкова. «якщо помилка» впізнається лише
        безпосередньо після блоку «спробуй» і лише як рядок з двох слів."""
        tok = self._далі()  # СПРОБУЙ
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «спробуй»")
        тіло = self._блок()
        обробник = None
        if (
            self._поточний().тип == "ЯКЩО"
            and self._пік(1).тип == "ІМЯ"
            and self._пік(1).значення == "помилка"
            and self._пік(2).тип == "НОВИЙ_РЯДОК"
        ):
            self._далі()  # ЯКЩО
            self._далі()  # помилка
            self._далі()  # НОВИЙ_РЯДОК
            обробник = self._блок()
        return А.Спробуй(тіло, обробник, рядок=tok.рядок, позиція=tok.позиція)

    def _підключи(self):
        tok = self._далі()  # ПІДКЛЮЧИ
        if self._глибина_блоку > 0:
            self._помилка(
                "«підключи» дозволено лише на верхньому рівні файлу "
                "(не всередині дії/умови/циклу)",
                tok,
            )
        шлях_tok = self._очікувати(
            "РЯДОК", "Очікувався шлях до файлу в лапках після «підключи»"
        )
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «підключи»")
        return А.Підключи(шлях_tok.значення, рядок=tok.рядок, позиція=tok.позиція)

    def _хай_чи_стала(self, клас, тип_токена):
        tok = self._далі()  # ХАЙ / СТАЛА
        імя_tok = self._очікувати_імя("ім'я змінної")
        слово = tok.значення
        self._очікувати(
            "ПРИСВОЄННЯ",
            f"Після «{слово} {імя_tok.значення}» має бути «=» і значення: {слово} {імя_tok.значення} = 5",
        )
        if self._поточний().тип in ("НОВИЙ_РЯДОК", "КІНЕЦЬ"):
            self._помилка(
                f"Після «=» має бути значення (число, рядок, список чи виклик): {слово} {імя_tok.значення} = 5"
            )
        вираз = self._вираз()
        if self._поточний().тип != "НОВИЙ_РЯДОК":
            зайве = self._поточний()
            self._помилка(
                f"Після значення для «{імя_tok.значення}» очікувався кінець рядка, а тут "
                f"«{зайве.значення if зайве.значення is not None else зайве.тип}». "
                "Перевір дужки й коми: аргументи дії — в дужках через кому."
            )
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
        return клас(імя_tok.значення, вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _вираз_чи_присвоєння(self):
        tok = self._поточний()
        вираз = self._вираз()
        if self._поточний().тип == "ПРИСВОЄННЯ":
            self._далі()
            права = self._вираз()
            self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
            if isinstance(вираз, А.Змінна):
                return А.Присвоєння(вираз.імя, права, рядок=tok.рядок, позиція=tok.позиція)
            if isinstance(вираз, А.Індекс):
                return А.ПрисвоєнняІндекс(
                    вираз.колекція, вираз.індекс, права, рядок=tok.рядок, позиція=tok.позиція
                )
            if isinstance(вираз, А.Поле):
                return А.ПрисвоєнняПоля(
                    вираз.обʼєкт, вираз.імя, права, рядок=tok.рядок, позиція=tok.позиція
                )
            self._помилка("Ліворуч від «=» має бути змінна, елемент списку або поле (обʼєкт.поле)", tok)
        if self._поточний().тип != "НОВИЙ_РЯДОК":
            self._підказка_після_виразу(вираз, tok)
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка")
        return А.ВиразІнструкція(вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _підказка_після_виразу(self, вираз, tok):
        """Рядок починається з виразу, а далі щось зайве. Кажемо не лише
        «що не так», а і як має бути."""
        зайве = self._поточний()
        зайве_текст = зайве.значення if зайве.значення is not None else зайве.тип
        if isinstance(вираз, А.Змінна):
            імя = вираз.імя
            if імя in _ВБУДОВАНІ_ТИПИ:
                self._помилка(
                    f"«{імя}» — це тип, значення створюють викликом з дужками і зберігають у змінну: "
                    f"{dovidka.приклад(імя) or f'хай т = {імя}(0, 0)'}",
                    tok,
                )
            if імя in ІМЕНА_NATIVE or імя in ("друкуй", "питай"):
                зразок = dovidka.приклад(імя) or f"хай результат = {імя}(...)"
                self._помилка(
                    f"«{імя}» — це вбудована дія, її викликають з дужками: {зразок}",
                    tok,
                )
            if зайве.тип == "ІМЯ" and self._пік(1).тип == "ПРИСВОЄННЯ":
                self._помилка(
                    f"Схоже, ти хотів створити змінну «{зайве.значення}». Змінну оголошують словом «хай»: "
                    f"хай {зайве.значення} = ...  (а «{імя}» тут зайве)",
                    tok,
                )
            self._помилка(
                f"Після «{імя}» очікувався кінець рядка, «=» або дужки виклику, а тут «{зайве_текст}». "
                f"Щоб створити змінну: хай {імя} = значення; щоб викликати дію: {імя}(...)",
                зайве,
            )
        if isinstance(вираз, А.Виклик):
            if вираз.імя in ("друкуй", "питай") or dovidka.опис(вираз.імя) is None:
                порада = f"Усі аргументи — всередині дужок через кому: {вираз.імя}(а, б)"
            else:
                порада = f"Результат виклику можна зберегти: хай х = {вираз.імя}(...)"
            self._помилка(
                f"Після виклику «{вираз.імя}(...)» очікувався кінець рядка, а тут «{зайве_текст}». {порада}",
                зайве,
            )
        self._помилка(
            f"Очікувався кінець рядка, а тут «{зайве_текст}». "
            "Один рядок — одна інструкція; аргументи дії — в дужках через кому.",
            зайве,
        )

    def _дія(self):
        tok = self._далі()  # ДІЯ
        імя_tok = self._очікувати_імя("ім'я дії")
        self._очікувати(
            "ЛПАР",
            f"Після імені дії мають бути дужки з параметрами (можна порожні): дія {імя_tok.значення}(а, б)",
        )
        параметри = []
        if self._поточний().тип != "ППАР":
            параметри.append(self._очікувати_імя("ім'я параметра").значення)
            while self._збіг("КОМА"):
                параметри.append(self._очікувати_імя("ім'я параметра").значення)
        self._очікувати("ППАР", "Очікувалась «)»")
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після оголошення дії")
        тіло = self._блок()
        return А.Дія(імя_tok.значення, параметри, тіло, рядок=tok.рядок, позиція=tok.позиція)

    def _поверни(self):
        tok = self._далі()  # ПОВЕРНИ
        вираз = None
        if self._поточний().тип != "НОВИЙ_РЯДОК":
            вираз = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «поверни»")
        return А.Поверни(вираз, рядок=tok.рядок, позиція=tok.позиція)

    def _якщо(self):
        tok = self._далі()  # ЯКЩО
        if self._поточний().тип in ("НОВИЙ_РЯДОК", "КІНЕЦЬ"):
            self._помилка("Після «якщо» має бути умова: якщо х > 5", tok)
        умова = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після умови «якщо»")
        тіло = self._блок()
        інакше = None
        if self._поточний().тип == "ІНАКШЕ":
            self._далі()
            if self._поточний().тип == "ЯКЩО":
                інакше = self._якщо()
            else:
                self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «інакше»")
                інакше = self._блок()
        return А.Якщо(умова, тіло, інакше, рядок=tok.рядок, позиція=tok.позиція)

    def _поки(self):
        tok = self._далі()  # ПОКИ
        if self._поточний().тип in ("НОВИЙ_РЯДОК", "КІНЕЦЬ"):
            self._помилка("Після «поки» має бути умова: поки х < 10", tok)
        умова = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після умови «поки»")
        тіло = self._блок()
        return А.Поки(умова, тіло, рядок=tok.рядок, позиція=tok.позиція)

    def _для(self):
        tok = self._далі()  # ДЛЯ
        імя_tok = self._очікувати_імя("ім'я змінної циклу")
        self._очікувати(
            "У",
            f"У циклі «для» після імені має бути «у» і список: для {імя_tok.значення} у [1, 2, 3]",
        )
        ітерований = self._вираз()
        self._очікувати("НОВИЙ_РЯДОК", "Очікувався кінець рядка після «для ... у ...»")
        тіло = self._блок()
        return А.Для(імя_tok.значення, ітерований, тіло, рядок=tok.рядок, позиція=tok.позиція)

    # ---- вирази (за пріоритетом, знизу вгору) -----------------------------

    def _вираз(self):
        return self._або()

    def _або(self):
        ліво = self._і()
        while self._поточний().тип == "АБО":
            tok = self._далі()
            право = self._і()
            ліво = А.Логічний("або", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _і(self):
        ліво = self._не()
        while self._поточний().тип == "І":
            tok = self._далі()
            право = self._не()
            ліво = А.Логічний("і", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _не(self):
        if self._поточний().тип == "НЕ":
            tok = self._далі()
            операнд = self._не()
            return А.Унарний("не", операнд, рядок=tok.рядок, позиція=tok.позиція)
        return self._порівняння()

    _ПОРІВНЯННЯ = {
        "РІВНО": "==",
        "НЕРІВНО": "!=",
        "МЕНШЕ": "<",
        "БІЛЬШЕ": ">",
        "МЕНШЕ_РІВНО": "<=",
        "БІЛЬШЕ_РІВНО": ">=",
    }

    def _порівняння(self):
        ліво = self._додавання()
        while True:
            тип = self._поточний().тип
            if тип in self._ПОРІВНЯННЯ:
                tok = self._далі()
                право = self._додавання()
                ліво = А.Бінарний(self._ПОРІВНЯННЯ[tok.тип], ліво, право, рядок=tok.рядок, позиція=tok.позиція)
            elif тип == "У":
                # `ключ у словник`, `елемент у список`, `підрядок у рядок`
                tok = self._далі()
                право = self._додавання()
                ліво = А.Бінарний("у", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
            elif тип == "НЕ" and self._пік(1).тип == "У":
                tok = self._далі()
                self._далі()  # У
                право = self._додавання()
                ліво = А.Бінарний("не у", ліво, право, рядок=tok.рядок, позиція=tok.позиція)
            else:
                break
        return ліво

    def _додавання(self):
        ліво = self._множення()
        while self._поточний().тип in ("ПЛЮС", "МІНУС"):
            tok = self._далі()
            право = self._множення()
            оп = "+" if tok.тип == "ПЛЮС" else "-"
            ліво = А.Бінарний(оп, ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _множення(self):
        ліво = self._унарний()
        while self._поточний().тип in ("ЗІРКА", "СЛЕШ", "ВІДСОТОК"):
            tok = self._далі()
            оп = {"ЗІРКА": "*", "СЛЕШ": "/", "ВІДСОТОК": "%"}[tok.тип]
            право = self._унарний()
            ліво = А.Бінарний(оп, ліво, право, рядок=tok.рядок, позиція=tok.позиція)
        return ліво

    def _унарний(self):
        if self._поточний().тип == "МІНУС":
            tok = self._далі()
            операнд = self._унарний()
            return А.Унарний("-", операнд, рядок=tok.рядок, позиція=tok.позиція)
        return self._постфікс()

    def _постфікс(self):
        вираз = self._первинний()
        while True:
            if self._поточний().тип == "ЛДУЖКА":
                tok = self._далі()
                if self._поточний().тип == "ДВОКРАПКА":
                    # [:кінець] або [:] — початок пропущено
                    self._далі()
                    кінець = None
                    if self._поточний().тип != "ПДУЖКА":
                        кінець = self._вираз()
                    self._очікувати("ПДУЖКА", "Очікувалась «]»")
                    вираз = А.Зріз(вираз, None, кінець, рядок=tok.рядок, позиція=tok.позиція)
                else:
                    перший = self._вираз()
                    if self._поточний().тип == "ДВОКРАПКА":
                        self._далі()
                        кінець = None
                        if self._поточний().тип != "ПДУЖКА":
                            кінець = self._вираз()
                        self._очікувати("ПДУЖКА", "Очікувалась «]»")
                        вираз = А.Зріз(вираз, перший, кінець, рядок=tok.рядок, позиція=tok.позиція)
                    else:
                        self._очікувати("ПДУЖКА", "Очікувалась «]»")
                        вираз = А.Індекс(вираз, перший, рядок=tok.рядок, позиція=tok.позиція)
            elif self._поточний().тип == "КРАПКА":
                tok = self._далі()
                імя_tok = self._очікувати_імя("ім'я поля або дії після «.»")
                if self._поточний().тип == "ЛПАР":
                    аргументи = self._аргументи_виклику()
                    вираз = А.МетодВиклик(вираз, імя_tok.значення, аргументи, рядок=tok.рядок, позиція=tok.позиція)
                else:
                    вираз = А.Поле(вираз, імя_tok.значення, рядок=tok.рядок, позиція=tok.позиція)
            else:
                break
        return вираз

    def _аргументи_виклику(self):
        аргументи = []
        self._очікувати("ЛПАР", "Очікувалась «(»")
        if self._поточний().тип != "ППАР":
            аргументи.append(self._вираз())
            while self._збіг("КОМА"):
                аргументи.append(self._вираз())
        self._очікувати("ППАР", "Очікувалась «)»")
        return аргументи

    def _пара_словника(self):
        ключ = self._вираз()
        self._очікувати("ДВОКРАПКА", "Очікувалась «:» між ключем і значенням у словнику")
        значення = self._вираз()
        return (ключ, значення)

    def _первинний(self):
        tok = self._поточний()

        if tok.тип == "ЧИСЛО":
            self._далі()
            return А.ЧислоЛіт(tok.значення, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "РЯДОК":
            self._далі()
            return А.РядокЛіт(tok.значення, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ІСТИНА":
            self._далі()
            return А.БулЛіт(True, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ХИБА":
            self._далі()
            return А.БулЛіт(False, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "НІЩО":
            self._далі()
            return А.НіщоЛіт(рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ЛПАР":
            self._далі()
            вираз = self._вираз()
            self._очікувати("ППАР", "Очікувалась «)»")
            return вираз
        if tok.тип == "ЛДУЖКА":
            self._далі()
            елементи = []
            if self._поточний().тип != "ПДУЖКА":
                елементи.append(self._вираз())
                while self._збіг("КОМА"):
                    елементи.append(self._вираз())
            self._очікувати("ПДУЖКА", "Очікувалась «]»")
            return А.СписокЛіт(елементи, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип == "ЛФІГ":
            self._далі()
            пари = []
            if self._поточний().тип != "ПФІГ":
                пари.append(self._пара_словника())
                while self._збіг("КОМА"):
                    if self._поточний().тип == "ПФІГ":
                        break  # кома в кінці дозволена
                    пари.append(self._пара_словника())
            self._очікувати("ПФІГ", "Очікувалась «}»")
            return А.СловникЛіт(пари, рядок=tok.рядок, позиція=tok.позиція)
        if tok.тип in ("ІМЯ", "ДРУКУЙ", "ПИТАЙ"):
            self._далі()
            if self._поточний().тип == "ЛПАР":
                аргументи = self._аргументи_виклику()
                return А.Виклик(tok.значення, аргументи, рядок=tok.рядок, позиція=tok.позиція)
            return А.Змінна(tok.значення, рядок=tok.рядок, позиція=tok.позиція)

        if tok.тип in ("НОВИЙ_РЯДОК", "КІНЕЦЬ", "ВІДСТУП_НАЗАД"):
            self._помилка(
                "Тут очікувалось значення (число, рядок, ім'я змінної або виклик дії), а рядок закінчився."
            )
        if tok.тип in _НЕ_НА_ПОЧАТКУ:
            self._помилка(_НЕ_НА_ПОЧАТКУ[tok.тип])
        if tok.значення in КЛЮЧОВІ_СЛОВА:
            зразок = dovidka.приклад(tok.значення)
            self._помилка(
                f"«{tok.значення}» — ключове слово, воно не може стояти всередині виразу"
                + (f". Як його використовують: {зразок.splitlines()[0]}" if зразок else ".")
            )
        self._помилка(f"Неочікуваний символ у виразі: «{tok.значення if tok.значення is not None else tok.тип}»")


def парсити_текст(джерело):
    токени = токенізувати(джерело)
    парсер = Парсер(токени, джерело.split("\n"))
    return парсер.парсити()
