"""Розв'язання «підключи "файл.мова"» — до компіляції, не в ній.

Компілятор і VM нічого не знають про файли/модулі: вони бачать одну плоску
`Програма`. Цей модуль — окремий крок між парсингом і компіляцією, який:

1. Читає головний файл, парсить його.
2. Для кожної інструкції `підключи "х.мова"` (лише на верхньому рівні —
   парсер забороняє інше) рекурсивно читає й парсить файл `х.мова`
   **відносно директорії файлу, що його підключає** (не поточної робочої
   директорії), і вставляє його інструкції на місце `підключи`.
3. Один і той самий файл підключається (виконується) лише один раз, навіть
   якщо на нього посилаються з кількох місць («діамантове» підключення) —
   повторне `підключи` того самого файлу мовчки нічого не додає вдруге.
4. Виявляє три помилкові випадки, усі — `ПомилкаПідключення` з
   рядком/позицією/текстом рядка саме інструкції `підключи`, що спричинила
   помилку:
   - файл не знайдено;
   - циклічне підключення (A підключає B, B підключає A, включно з
     A, що підключає сам себе);
   - конфлікт імен: та сама дія визначена у двох різних файлах.

Результат — одна плоска `Програма`, яку далі компілює звичайний
`yadro/kompilyator.py` так, ніби все це було написано в одному файлі.

Додатково: кожен вузол AST з кожного підключеного файлу позначається
атрибутом `_рядок_джерела_текст` — текстом його власного рядка джерела.
Компілятор (`yadro/kompilyator.py`) читає цей атрибут для повідомлень про
помилки компіляції, тому помилка в підключеному файлі показує текст саме
з того файлу, а не з головного.
"""

import dataclasses
from pathlib import Path

from . import biblioteka
from . import syntax as А
from .lexer import токенізувати
from .parser import Парсер
from .errors import ПомилкаПідключення


def _позначити_джерело(вузол, рядки):
    """Рекурсивно проставити `_рядок_джерела_текст` на вузлі та всіх його
    вкладених полях (списки інструкцій/виразів), використовуючи рядки саме
    того файлу, з якого вузол розпарсено."""
    if вузол is None:
        return
    if isinstance(вузол, (list, tuple)):
        for елемент in вузол:
            _позначити_джерело(елемент, рядки)
        return
    if not dataclasses.is_dataclass(вузол):
        return
    рядок = getattr(вузол, "рядок", 0)
    if рядок and 1 <= рядок <= len(рядки):
        вузол._рядок_джерела_текст = рядки[рядок - 1]
    for поле in dataclasses.fields(вузол):
        _позначити_джерело(getattr(вузол, поле.name), рядки)


def завантажити_програму(головний_шлях):
    """Прочитати й розпарсити `головний_шлях`, рекурсивно розгорнути всі
    `підключи`, повернути (Програма, {абсолютний_шлях: текст_джерела})."""
    головний_шлях = Path(головний_шлях).resolve()
    джерела = {}          # абсолютний шлях -> текст файлу (для CLI/дебагу)
    кеш_парсингу = {}      # абсолютний шлях -> вже розпарсена Програма файлу
    включені = {}          # абсолютний шлях -> вже сплощений список інструкцій
    у_процесі = []          # стек шляхів, що резолвляться прямо зараз (цикли)
    визначені_дії = {}      # ім'я дії -> шлях файлу, де вона вперше визначена

    def _розпарсити_файл(шлях):
        if шлях in кеш_парсингу:
            return кеш_парсингу[шлях]
        if not шлях.is_file():
            raise ПомилкаПідключення(f"Файл «{шлях}» не знайдено.")
        текст = шлях.read_text(encoding="utf-8")
        джерела[шлях] = текст
        рядки = текст.split("\n")
        програма = Парсер(токенізувати(текст), рядки).парсити()
        for інстр in програма.тіло:
            _позначити_джерело(інстр, рядки)
        кеш_парсингу[шлях] = програма
        return програма

    def _перевірити_конфлікт(інстр, шлях):
        if not isinstance(інстр, (А.Дія, А.Тип)):
            return
        що = "дія" if isinstance(інстр, А.Дія) else "тип"
        наявний = визначені_дії.get(інстр.імя)
        if наявний is not None and наявний != шлях:
            raise ПомилкаПідключення(
                f"Конфлікт імен: {що} «{інстр.імя}» вже визначена у файлі "
                f"«{наявний.name}», а тепер визначається ще й у «{шлях.name}». "
                "Перейменуйте одну з них.",
                інстр.рядок, інстр.позиція,
                getattr(інстр, "_рядок_джерела_текст", ""),
            )
        визначені_дії[інстр.імя] = шлях

    def _обробити(шлях):
        if шлях in включені:
            return []  # вже підключено раніше з іншого місця — не вдруге
        у_процесі.append(шлях)
        програма = _розпарсити_файл(шлях)

        сплощено = []
        for інстр in програма.тіло:
            if isinstance(інстр, А.Підключи):
                цільовий = (шлях.parent / інстр.шлях).resolve()
                if not цільовий.is_file():
                    підказка = (
                        f" Якщо мали на увазі бібліотеку — у дужках: підключи(\"{інстр.шлях}\")."
                        if biblioteka.є(інстр.шлях) else ""
                    )
                    raise ПомилкаПідключення(
                        f"Файл «{інстр.шлях}» не знайдено (шукав: «{цільовий}»).{підказка}",
                        інстр.рядок, інстр.позиція,
                        getattr(інстр, "_рядок_джерела_текст", ""),
                    )
                if цільовий in у_процесі:
                    цикл = " -> ".join(p.name for p in у_процесі) + f" -> {цільовий.name}"
                    raise ПомилкаПідключення(
                        f"Циклічне підключення файлів: {цикл}.",
                        інстр.рядок, інстр.позиція,
                        getattr(інстр, "_рядок_джерела_текст", ""),
                    )
                сплощено.extend(_обробити(цільовий))
            else:
                _перевірити_конфлікт(інстр, шлях)
                сплощено.append(інстр)

        у_процесі.pop()
        включені[шлях] = сплощено
        return сплощено

    головні_інструкції = _обробити(головний_шлях)
    return А.Програма(головні_інструкції), джерела
