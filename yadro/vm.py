class Екземпляр:
    """Значення, створене з `тип` (Точка(1, 2)): ім'я типу + словник полів.
    Порівнюється за значенням полів; змінюється на місці (як список)."""

    __slots__ = ("тип", "поля")

    def __init__(self, тип, поля):
        self.тип = тип
        self.поля = поля

    def __eq__(self, інший):
        return isinstance(інший, Екземпляр) and self.тип == інший.тип and self.поля == інший.поля

    __hash__ = None

    def __repr__(self):
        return до_рядка(self)


def _є_число(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def _є_список(x):
    return isinstance(x, list)


def до_рядка(x):
    """Як значення мови показуються текстом (друкуй, конкатенація рядків)."""
    if x is None:
        return "ніщо"
    if x is True:
        return "істина"
    if x is False:
        return "хиба"
    if isinstance(x, list):
        return "[" + ", ".join(до_рядка(е) for е in x) + "]"
    if isinstance(x, dict):
        return "{" + ", ".join(f"{до_рядка(к)}: {до_рядка(в)}" for к, в in x.items()) + "}"
    if isinstance(x, Екземпляр):
        return x.тип + "(" + ", ".join(f"{к}: {до_рядка(в)}" for к, в in x.поля.items()) + ")"
    if isinstance(x, Точка):
        return f"({до_рядка(x.x)}, {до_рядка(x.y)})"
    return str(x)


def _тип_укр(x):
    if x is None:
        return "ніщо"
    if isinstance(x, bool):
        return "логічне значення"
    if isinstance(x, (int, float)):
        return "число"
    if isinstance(x, str):
        return "рядок"
    if isinstance(x, list):
        return "список"
    if isinstance(x, dict):
        return "словник"
    if isinstance(x, Екземпляр):
        return x.тип
    if isinstance(x, Точка):
        return "Точка"
    return type(x).__name__


class ВМ:
    # Прапорець зупинки. Його можна виставити з іншого потоку; головний
    # цикл перевіряє його перед кожною інструкцією й кидає ВиконанняЗупинено.
    зупинено = False

    def __init__(self, без_пристрою=False, тека_файлів=None):
        self.глобальні = {}
        self.функції = {}
        self.типи = {}             # ім'я типу -> {"поля": [...], "типові": [...]}
        self.стек = []
        self.кадри = []            # стек словників локальних змінних
        self.стек_повернень = []   # адреси повернення, паралельно self.кадри
        self.обробники = []        # активні «спробуй»: (адреса_обробника, len(стек), len(кадри))
        self.тека_файлів = тека_файлів  # база для відносних шляхів у файлових функціях
        self.кнопки = []           # [(напис, імя_дії)] — оголошені кнопка("…", дія)
        self.при_кнопці = None     # застосунок: callback(напис, імя_дії) — показати кнопку
        self.pc = 0
        self.код = []
        self.константи = []
        self.позиції = []

        if без_пристрою:
            prystriy.увімкнути_симуляцію(True)
            rozum.увімкнути_симуляцію(True)

        self._native = {
            "друкуй": self._друкуй,
            "питай": self._питай,
            "спи": self._спи,
            "довжина": self._довжина,
            "рядок": до_рядка,
            "число": self._число,
            "цілий": self._цілий,
            "діапазон": self._діапазон,
            "додай": self._додай,
            "вилучи": self._вилучи,
            "сортуй": self._сортуй,
            "словник": self._словник,
            "ключі": self._ключі,
            "кинь": self._кинь,
            "кнопка": self._кнопка,
            "@перелік": self._перелік,  # службова: «для» перебирає словник за ключами
            "прочитай_файл": lambda імя: fayly.прочитай_файл(імя, self.тека_файлів),
            "запиши_файл": lambda імя, текст: fayly.запиши_файл(імя, до_рядка(текст), self.тека_файлів),
            "допиши_файл": lambda імя, текст: fayly.допиши_файл(імя, до_рядка(текст), self.тека_файлів),
            "є_файл": lambda імя: fayly.є_файл(імя, self.тека_файлів),
            "рядки_файлу": lambda імя: fayly.рядки_файлу(імя, self.тека_файлів),
            "файли_в_теці": lambda імя=".": fayly.файли_в_теці(імя, self.тека_файлів),
            "видали_файл": lambda імя: fayly.видали_файл(імя, self.тека_файлів),
        }
        for ім_я in _ІМЕНА_МАТЕМАТИКА:
            self._native[ім_я] = getattr(matematyka, ім_я)
        for ім_я in _ІМЕНА_ЧАС:
            self._native[ім_я] = getattr(chas, ім_я)
        for ім_я in _ІМЕНА_ГЕОМЕТРІЯ:
            if ім_я in ("кут", "зсунь"):
                continue  # об'єднуються з drafting.кут / sketch.зсунь нижче, за арністю
            self._native[ім_я] = getattr(heometriya, "точка" if ім_я == "Точка" else ім_я)
        for ім_я in _ІМЕНА_РЯДКИ:
            if ім_я == "текст":
                continue  # об'єднується з drawing.текст нижче, за арністю
            self._native[ім_я] = getattr(ryadky, ім_я.replace("'", ""))
        for ім_я in _ІМЕНА_ПРИСТРІЙ:
            self._native[ім_я] = getattr(prystriy, ім_я)
        for ім_я in _ІМЕНА_РОЗУМ:
            self._native[ім_я] = getattr(rozum, ім_я)
        for ім_я in _ІМЕНА_МАЛЮНОК:
            if ім_я == "покажи":
                continue  # об'єднується з drafting.покажи() нижче, за активним режимом
            self._native[ім_я] = getattr(drawing, ім_я)
        for ім_я in _ІМЕНА_ЕКРАН:
            self._native[ім_я] = getattr(ekran, ім_я)
        for ім_я in _ІМЕНА_КРЕСЛЕННЯ:
            if ім_я == "покажи":
                continue
            self._native[ім_я] = getattr(drafting, ім_я)
        for ім_я in _ІМЕНА_ЕСКІЗ:
            if ім_я == "довжина":
                continue  # об'єднується з мовним довжина() нижче, за арністю
            self._native[ім_я] = getattr(sketch, ім_я)

        # "покажи": drawing.py і drafting.py обидва описують «завершити й
        # показати малюнок» (див. докстрінг yadro/drafting.py) — реальний
        # режим визначається за тим, який з двох станів насправді
        # ініціалізований (полотно(...) чи аркуш(...)), а не порядком
        # реєстрації, інакше один із режимів був би назавжди недосяжним
        def _покажи_обʼєднане():
            if drafting._аркуш is not None:
                return drafting.покажи()
            if drawing._полотно is not None:
                return drawing.покажи()
            raise ПомилкаВиконання(
                "Спершу виклич полотно(ширина, висота) (малювання) або "
                "аркуш(ширина, висота, масштаб) (креслення) — перед покажи()."
            )

        self._native["покажи"] = _покажи_обʼєднане

        # "довжина": мовна версія (1 аргумент — список/рядок) і ескізна
        # (2 аргументи — сегмент, значення) мирно співіснують під одним
        # іменем, розрізняючись кількістю аргументів виклику
        _довжина_мовна = self._native["довжина"]
        _довжина_ескіз = sketch.довжина

        def _довжина_обʼєднана(*args):
            if len(args) == 1:
                if isinstance(args[0], Точка):
                    return heometriya.довжина(args[0])
                return _довжина_мовна(*args)
            if len(args) == 2:
                return _довжина_ескіз(*args)
            raise ПомилкаВиконання("Функція «довжина» приймає 1 або 2 аргументи.")

        self._native["довжина"] = _довжина_обʼєднана

        # "текст": з одним аргументом — перетворення у рядок (як рядок()),
        # з п'ятьма — напис на малюнку (drawing.текст)
        def _текст_обʼєднаний(*args):
            if len(args) == 1:
                return до_рядка(args[0])
            if len(args) == 5:
                return drawing.текст(*args)
            raise ПомилкаВиконання(
                "Функція «текст» приймає 1 аргумент (перетворити у рядок) "
                "або 5 (напис на малюнку: x, y, напис, розмір, колір)."
            )

        self._native["текст"] = _текст_обʼєднаний

        # "кут": 2 аргументи — геометрія (кут напрямку а->б у градусах),
        # 4 — креслення (розмір кута на аркуші); "зсунь": 3 аргументи —
        # геометрія (нова точка/список), 2 — ескіз (зсув усієї геометрії)
        def _кут_обʼєднаний(*args):
            if len(args) == 2:
                return heometriya.кут(*args)
            if len(args) == 4:
                return drafting.кут(*args)
            raise ПомилкаВиконання(
                "Функція «кут» приймає 2 аргументи (кут від а до б у градусах) "
                "або 4 (кут на кресленні: точка1, вершина, точка2, радіус)."
            )

        def _зсунь_обʼєднаний(*args):
            if len(args) == 3:
                return heometriya.зсунь(*args)
            if len(args) == 2:
                return sketch.зсунь(*args)
            raise ПомилкаВиконання(
                "Функція «зсунь» приймає 3 аргументи (точка або список, dx, dy) "
                "або 2 (зсув усього ескізу: dx, dy)."
            )

        self._native["кут"] = _кут_обʼєднаний
        self._native["зсунь"] = _зсунь_обʼєднаний

    # ---- вбудовані мовні функції ------------------------------------------

    def _друкуй(self, *args):
        print(" ".join(до_рядка(а) for а in args))
        return None

    def _питай(self, *args):
        if args:
            print(до_рядка(args[0]), end="", flush=True)
        try:
            return input()
        except EOFError:
            raise ПомилкаВиконання("«питай» не отримав вводу (немає доступного stdin).")

    def _спи(self, сек):
        if not _є_число(сек):
            raise ПомилкаВиконання("Функція «спи» очікує число секунд.")
        # Спимо шматками, щоб кнопка «Стоп» (ВМ.зупинено) спрацьовувала
        # і посеред довгого спи(60), а не після нього.
        кінець = time.monotonic() + сек
        while True:
            if self.зупинено:
                raise ВиконанняЗупинено()
            лишилось = кінець - time.monotonic()
            if лишилось <= 0:
                return None
            time.sleep(min(лишилось, 0.1))

    def _довжина(self, x):
        if isinstance(x, (list, str, dict)):
            return len(x)
        raise ПомилкаВиконання(f"Функція «довжина» не працює для типу «{_тип_укр(x)}».")

    def _число(self, x):
        if _є_число(x):
            return x
        if isinstance(x, str):
            try:
                if "." in x:
                    return float(x)
                return int(x)
            except ValueError:
                raise ПомилкаВиконання(f"Не вдалося перетворити рядок «{x}» на число.")
        raise ПомилкаВиконання(f"Не вдалося перетворити {_тип_укр(x)} на число.")

    def _цілий(self, x):
        return int(self._число(x))

    def _діапазон(self, *args):
        if len(args) == 1:
            return list(range(int(args[0])))
        if len(args) == 2:
            return list(range(int(args[0]), int(args[1])))
        if len(args) == 3:
            return list(range(int(args[0]), int(args[1]), int(args[2])))
        raise ПомилкаВиконання("Функція «діапазон» приймає від 1 до 3 аргументів.")

    def _додай(self, список, значення):
        if not isinstance(список, list):
            raise ПомилкаВиконання(f"Функція «додай» очікує список, отримала {_тип_укр(список)}.")
        список.append(значення)
        return None

    def _вилучи(self, список, idx):
        if isinstance(список, dict):
            if idx not in список:
                raise ПомилкаВиконання(f"У словнику немає ключа «{до_рядка(idx)}».")
            return список.pop(idx)
        if not isinstance(список, list):
            raise ПомилкаВиконання(f"Функція «вилучи» очікує список або словник, отримала {_тип_укр(список)}.")
        if not isinstance(idx, int) or isinstance(idx, bool):
            raise ПомилкаВиконання("Індекс для «вилучи» має бути цілим числом.")
        i = self._норм_індекс(idx, len(список))
        if i is None:
            raise ПомилкаВиконання(f"Індекс {idx} поза межами (довжина {len(список)}).")
        return список.pop(i)

    def _сортуй(self, список):
        if not isinstance(список, list):
            raise ПомилкаВиконання(f"Функція «сортуй» очікує список, отримала {_тип_укр(список)}.")
        try:
            список.sort()
        except TypeError:
            raise ПомилкаВиконання(
                "Функцію «сортуй» можна застосувати лише до однорідного списку "
                "(усі елементи — числа, або усі — рядки)."
            )
        return None

    def _словник(self, *args):
        """словник() — порожній; словник(к1, з1, к2, з2, ...) — з парами."""
        if len(args) % 2:
            raise ПомилкаВиконання(
                "Функція «словник» очікує пари «ключ, значення» — непарна кількість аргументів."
            )
        д = {}
        for i in range(0, len(args), 2):
            self._перевірити_ключ(args[i])
            д[args[i]] = args[i + 1]
        return д

    def _перевірити_ключ(self, ключ):
        if isinstance(ключ, (list, dict, Екземпляр)):
            raise ПомилкаВиконання(
                f"Ключем словника не може бути {_тип_укр(ключ)} — лише рядок, число або логічне значення."
            )

    def _ключі(self, д):
        if not isinstance(д, dict):
            raise ПомилкаВиконання(f"Функція «ключі» очікує словник, отримала {_тип_укр(д)}.")
        return list(д.keys())

    def _кинь(self, *args):
        текст = " ".join(до_рядка(а) for а in args) if args else "Помилка."
        raise ПомилкаВиконання(текст)

    def _кнопка(self, напис, імя_дії):
        """кнопка("Показати", показати): у застосунку — кнопка під виводом,
        натискання виконує дію без параметрів (ВМ.викликати_дію); без
        застосунку лише друкує «[кнопка Напис]»."""
        if not isinstance(напис, str) or not напис.strip() or not isinstance(імя_дії, str):
            raise ПомилкаВиконання(
                "«кнопка» очікує напис-рядок і назву дії без дужок: кнопка(\"Показати\", показати)."
            )
        fn = self.функції.get(імя_дії)
        if fn is None:
            raise ПомилкаВиконання(
                f"«кнопка»: дії «{імя_дії}» немає — оголоси її вище: дія {імя_дії}() з тілом, "
                f"а потім кнопка(\"{напис}\", {імя_дії})."
            )
        if fn["параметри"]:
            raise ПомилкаВиконання(
                f"«кнопка»: дія «{імя_дії}» має бути без параметрів — натискання нічого не передає."
            )
        self.кнопки.append((напис, імя_дії))
        if self.при_кнопці is not None:
            self.при_кнопці(напис, імя_дії)
        else:
            print(f"[кнопка {напис}]")
        return None

    def _перелік(self, x):
        if isinstance(x, dict):
            return list(x.keys())
        if isinstance(x, (list, str)):
            return x
        raise ПомилкаВиконання(f"Не можна перебирати «для» значення типу «{_тип_укр(x)}».")

    # ---- допоміжне -----------------------------------------------------------

    def _поточна_позиція(self):
        """(рядок, колонка, текст_рядка). Позиції старого формату (2 елементи,
        напр. з .байт-файлу, скомпільованого до підтримки «підключи») теж
        підтримуються — текст_рядка тоді просто порожній."""
        if 0 <= self.pc < len(self.позиції):
            поз = self.позиції[self.pc]
            рядок = поз[0] if len(поз) > 0 else 0
            кол = поз[1] if len(поз) > 1 else 0
            текст = поз[2] if len(поз) > 2 else ""
            return (рядок, кол, текст)
        return (0, 0, "")

    def _помилка(self, повідомлення):
        рядок, кол, текст = self._поточна_позиція()
        raise ПомилкаВиконання(повідомлення, рядок, кол, текст)

    def _push(self, значення):
        self.стек.append(значення)

    def _pop(self):
        if not self.стек:
            self._помилка("Внутрішня помилка VM: стек порожній.")
        return self.стек.pop()

    def _push_var(self, імя):
        if self.кадри:
            локальні = self.кадри[-1]
            if імя in локальні:
                return локальні[імя]
        if імя in self.глобальні:
            return self.глобальні[імя]
        self._помилка(f"Невідома змінна «{імя}».")

    def _store_var(self, імя, значення):
        if self.кадри:
            self.кадри[-1][імя] = значення
        else:
            self.глобальні[імя] = значення

    # ---- запуск --------------------------------------------------------------

    def виконати(self, байткод):
        """Виконати самостійну програму «з нуля» — скидає весь стан VM."""
        self.глобальні.setdefault("ПІ", matematyka.ПІ)
        self.код = байткод["код"]
        self.константи = байткод.get("константи", [])
        self.позиції = байткод.get("позиції", [])
        self.pc = 0
        self.стек = []
        self.кадри = []
        self.стек_повернень = []
        self.обробники = []
        self._цикл_виконання()

    def виконати_фрагмент(self, байткод):
        """Додати ще один шматок байткоду до вже наявного (з переадресацією
        стрибків/констант) і виконати лише його — не чіпаючи self.глобальні
        й self.функції. Потрібно для REPL: кожен введений рядок компілюється
        окремо, але змінні й дії мають жити між рядками сеансу."""
        зсув_коду = len(self.код)
        зсув_конст = len(self.константи)

        новий_код = []
        for опкод, аргумент in байткод["код"]:
            if опкод in ("JUMP", "JUMP_FALSE", "TRY_BEGIN"):
                аргумент = аргумент + зсув_коду
            elif опкод == "MAKE_FUNCTION":
                імя, параметри, адреса = аргумент[:3]
                аргумент = [імя, параметри, адреса + зсув_коду] + list(аргумент[3:])
            elif опкод == "PUSH_CONST":
                аргумент = аргумент + зсув_конст
            новий_код.append([опкод, аргумент])

        self.код.extend(новий_код)
        self.константи.extend(байткод.get("константи", []))
        позиції = байткод.get("позиції") or [[0, 0, ""]] * len(новий_код)
        self.позиції.extend(позиції)

        self.глобальні.setdefault("ПІ", matematyka.ПІ)
        self.pc = зсув_коду
        self._цикл_виконання()

    def викликати_дію(self, імя, args=()):
        """Виконати дію програми ззовні (натискання кнопки) вже після того,
        як основна програма дійшла до HALT. Повертає значення «поверни»."""
        fn = self.функції.get(імя)
        if fn is None:
            raise ПомилкаВиконання(f"Невідома дія «{імя}».")
        if len(fn["параметри"]) != len(args):
            raise ПомилкаВиконання(
                f"Дія «{імя}» очікує {len(fn['параметри'])} аргумент(и), а отримала {len(args)}."
            )
        старий_pc = self.pc
        self.кадри.append(dict(zip(fn["параметри"], args)))
        self.стек_повернень.append(None)
        self.pc = fn["адреса"]
        try:
            self._цикл_виконання()
        except _КінецьВиклику:
            self.pc = старий_pc
            return self._pop()
        # тіло дії завжди завершується RETURN — сюди не доходимо
        self.pc = старий_pc
        return None

    def _цикл_виконання(self):
        довжина_коду = len(self.код)
        while self.pc < довжина_коду:
            if self.зупинено:
                raise ВиконанняЗупинено()
            опкод, аргумент = self.код[self.pc]
            if опкод == "HALT":
                return
            try:
                self._виконати_інструкцію(опкод, аргумент)
            except ПомилкаВиконання as e:
                if not e.рядок:
                    рядок, кол, текст = self._поточна_позиція()
                    e.рядок, e.позиція = рядок, кол
                    if not e.текст_рядка:
                        e.текст_рядка = текст
                if self._перехопити(e):
                    continue
                raise
            except (ZeroDivisionError, IndexError, KeyError, ValueError, TypeError) as e:
                рядок, кол, текст = self._поточна_позиція()
                помилка = ПомилкаВиконання(f"Помилка під час виконання: {e}", рядок, кол, текст)
                if self._перехопити(помилка):
                    continue
                raise помилка from e

    def _перехопити(self, e):
        """Якщо є активний «спробуй» — розмотати стек/кадри до його стану,
        покласти текст помилки на стек (обробник починається зі STORE_VAR
        помилка) і перейти на обробник. Повертає True, якщо перехопили."""
        if not self.обробники:
            return False
        адреса, довж_стеку, довж_кадрів = self.обробники.pop()
        del self.стек[довж_стеку:]
        del self.кадри[довж_кадрів:]
        del self.стек_повернень[довж_кадрів:]
        self._push(e.повідомлення)
        self.pc = адреса
        return True

    def _виконати_інструкцію(self, опкод, аргумент):
        # більшість інструкцій просто переходять до наступної; переходи й
        # виклики самі виставляють self.pc і повертаються через return
        if опкод == "PUSH_CONST":
            self._push(self.константи[аргумент])
        elif опкод == "PUSH_VAR":
            self._push(self._push_var(аргумент))
        elif опкод == "STORE_VAR":
            self._store_var(аргумент, self._pop())
        elif опкод == "POP":
            self._pop()

        elif опкод == "ADD":
            self._push(self._додати(self._pop2()))
        elif опкод == "SUB":
            a, b = self._pop2()
            if isinstance(a, Точка) and isinstance(b, Точка):
                self._push(a - b)
                self.pc += 1
                return
            self._числа(a, b, "відняти")
            self._push(a - b)
        elif опкод == "MUL":
            a, b = self._pop2()
            if isinstance(a, Точка) and _є_число(b):
                self._push(a * b)
                self.pc += 1
                return
            if _є_число(a) and isinstance(b, Точка):
                self._push(b * a)
                self.pc += 1
                return
            self._числа(a, b, "помножити")
            self._push(a * b)
        elif опкод == "DIV":
            a, b = self._pop2()
            if isinstance(a, Точка) and _є_число(b):
                self._push(a / b)
                self.pc += 1
                return
            self._числа(a, b, "поділити")
            if b == 0:
                self._помилка("Ділення на нуль.")
            r = a / b
            if isinstance(a, int) and isinstance(b, int) and r == int(r):
                r = int(r)
            self._push(r)
        elif опкод == "MOD":
            a, b = self._pop2()
            self._числа(a, b, "знайти остачу від ділення")
            if b == 0:
                self._помилка("Ділення на нуль (остача).")
            self._push(a % b)
        elif опкод == "NEG":
            x = self._pop()
            if isinstance(x, Точка):
                self._push(-x)
                self.pc += 1
                return
            if not _є_число(x):
                self._помилка(f"Не можна застосувати унарний мінус до {_тип_укр(x)}.")
            self._push(-x)

        elif опкод == "EQ":
            a, b = self._pop2()
            self._push(a == b)
        elif опкод == "NEQ":
            a, b = self._pop2()
            self._push(a != b)
        elif опкод in ("LT", "GT", "LTE", "GTE"):
            a, b = self._pop2()
            self._push(self._порівняти(опкод, a, b))

        elif опкод == "AND":
            a, b = self._pop2()
            self._push(bool(a) and bool(b))
        elif опкод == "OR":
            a, b = self._pop2()
            self._push(bool(a) or bool(b))
        elif опкод == "NOT":
            self._push(not bool(self._pop()))

        elif опкод == "JUMP":
            self.pc = аргумент
            return
        elif опкод == "JUMP_FALSE":
            умова = self._pop()
            if not bool(умова):
                self.pc = аргумент
                return

        elif опкод == "MAKE_LIST":
            n = аргумент
            елементи = [self._pop() for _ in range(n)]
            елементи.reverse()
            self._push(елементи)
        elif опкод == "INDEX_GET":
            idx = self._pop()
            колекція = self._pop()
            self._push(self._індекс_get(колекція, idx))
        elif опкод == "INDEX_SET":
            значення = self._pop()
            idx = self._pop()
            колекція = self._pop()
            self._індекс_set(колекція, idx, значення)
        elif опкод == "SLICE_GET":
            кінець = self._pop()
            початок = self._pop()
            колекція = self._pop()
            self._push(self._зріз_get(колекція, початок, кінець))
        elif опкод == "MAKE_DICT":
            пари = [self._pop() for _ in range(2 * аргумент)]
            пари.reverse()
            д = {}
            for i in range(0, len(пари), 2):
                self._перевірити_ключ(пари[i])
                д[пари[i]] = пари[i + 1]
            self._push(д)
        elif опкод == "CONTAINS":
            колекція = self._pop()
            елемент = self._pop()
            є = self._належить(елемент, колекція)
            self._push(not є if аргумент else є)

        elif опкод == "GET_FIELD":
            self._push(self._поле_get(self._pop(), аргумент))
        elif опкод == "SET_FIELD":
            значення = self._pop()
            обʼєкт = self._pop()
            self._поле_set(обʼєкт, аргумент, значення)
        elif опкод == "MAKE_TYPE":
            імя, поля = аргумент
            типові = [self._pop() for _ in range(len(поля))]
            типові.reverse()
            self.типи[імя] = {"поля": list(поля), "типові": типові}
        elif опкод == "CALL_METHOD":
            self._виклик_методу(аргумент)
            return

        elif опкод == "TRY_BEGIN":
            self.обробники.append((аргумент, len(self.стек), len(self.кадри)))
        elif опкод == "TRY_END":
            if self.обробники:
                self.обробники.pop()

        elif опкод == "MAKE_FUNCTION":
            імя, параметри, адреса = аргумент[:3]
            self.функції[імя] = {"параметри": параметри, "адреса": адреса}
            if len(аргумент) > 3 and аргумент[3]:
                self._зібрати_швидко(імя, аргумент[3])
        elif опкод == "CALL":
            self._виклик_дії(аргумент)
            return
        elif опкод == "RETURN":
            значення = self._pop()
            if not self.стек_повернень:
                self._помилка("«поверни» без активного виклику дії.")
            адреса = self.стек_повернень.pop()
            self.кадри.pop()
            while self.обробники and self.обробники[-1][2] > len(self.кадри):
                self.обробники.pop()
            self._push(значення)
            if адреса is None:
                raise _КінецьВиклику()  # дію викликано ззовні (ВМ.викликати_дію)
            self.pc = адреса
            return
        elif опкод == "CALL_NATIVE":
            self._виклик_native(аргумент)

        else:
            self._помилка(f"Невідомий опкод «{опкод}».")

        self.pc += 1

    # ---- арифметика / порівняння -----------------------------------------------

    def _pop2(self):
        b = self._pop()
        a = self._pop()
        return a, b

    def _додати(self, пара):
        a, b = пара
        if isinstance(a, Точка) or isinstance(b, Точка):
            if isinstance(a, Точка) and isinstance(b, Точка):
                return a + b
            self._помилка(f"Не можна скласти {_тип_укр(a)} і {_тип_укр(b)} — точку можна додати лише до точки.")
        if isinstance(a, str) or isinstance(b, str):
            return до_рядка(a) + до_рядка(b)
        if _є_список(a) and _є_список(b):
            return a + b
        if _є_число(a) and _є_число(b):
            return a + b
        self._помилка(f"Не можна скласти {_тип_укр(a)} і {_тип_укр(b)}.")

    def _числа(self, a, b, дія):
        if not (_є_число(a) and _є_число(b)):
            self._помилка(f"Не можна {дія} {_тип_укр(a)} і {_тип_укр(b)} — потрібні числа.")
        return True

    def _порівняти(self, опкод, a, b):
        if _є_число(a) and _є_число(b):
            pass
        elif isinstance(a, str) and isinstance(b, str):
            pass
        else:
            self._помилка(f"Не можна порівняти {_тип_укр(a)} і {_тип_укр(b)}.")
        if опкод == "LT":
            return a < b
        if опкод == "GT":
            return a > b
        if опкод == "LTE":
            return a <= b
        return a >= b  # GTE

    # ---- списки -------------------------------------------------------------

    def _норм_індекс(self, idx, n):
        """Від'ємний індекс рахується з кінця (як у Python): -1 — останній
        елемент. Повертає вже приведений до [0, n) індекс або None, якщо
        поза межами навіть після приведення."""
        i = idx + n if idx < 0 else idx
        if i < 0 or i >= n:
            return None
        return i

    def _індекс_get(self, колекція, idx):
        if isinstance(колекція, Точка):
            if idx in (0, 1, -1, -2):
                return колекція[idx]
            self._помилка("У Точки є лише т[0] (x) і т[1] (y).")
        if isinstance(колекція, (list, str)):
            if not isinstance(idx, int) or isinstance(idx, bool):
                self._помилка("Індекс має бути цілим числом.")
            i = self._норм_індекс(idx, len(колекція))
            if i is None:
                self._помилка(f"Індекс {idx} поза межами (довжина {len(колекція)}).")
            return колекція[i]
        if isinstance(колекція, dict):
            if idx not in колекція:
                self._помилка(f"У словнику немає ключа «{idx}».")
            return колекція[idx]
        self._помилка(f"Не можна індексувати значення типу «{_тип_укр(колекція)}».")

    def _індекс_set(self, колекція, idx, значення):
        if isinstance(колекція, Точка):
            self._помилка("Точка незмінна: замість «т[0] = …» створи нову Точка(x, y).")
        if isinstance(колекція, list):
            if not isinstance(idx, int) or isinstance(idx, bool):
                self._помилка("Індекс має бути цілим числом.")
            i = self._норм_індекс(idx, len(колекція))
            if i is None:
                self._помилка(f"Індекс {idx} поза межами (довжина {len(колекція)}).")
            колекція[i] = значення
            return
        if isinstance(колекція, dict):
            колекція[idx] = значення
            return
        self._помилка(f"Не можна записати за індексом у значення типу «{_тип_укр(колекція)}».")

    def _зріз_get(self, колекція, початок, кінець):
        """Python-подібний зріз: обидві межі — прапорці None («не задано»)
        або ціле число (від'ємне — з кінця); на відміну від звичайної
        індексації, межі зрізу лагідно обрізаються до [0, довжина], а не
        падають з помилкою."""
        if not isinstance(колекція, (list, str)):
            self._помилка(f"Не можна зробити зріз значення типу «{_тип_укр(колекція)}».")
        n = len(колекція)

        def межа(x, типове):
            if x is None:
                return типове
            if not isinstance(x, int) or isinstance(x, bool):
                self._помилка("Межа зрізу має бути цілим числом.")
            if x < 0:
                x += n
            return max(0, min(x, n))

        п = межа(початок, 0)
        к = межа(кінець, n)
        return колекція[п:к]

    # ---- словники, поля, типи ------------------------------------------------------

    def _належить(self, елемент, колекція):
        if isinstance(колекція, dict):
            self._перевірити_ключ(елемент)
            return елемент in колекція
        if isinstance(колекція, list):
            return елемент in колекція
        if isinstance(колекція, str):
            if not isinstance(елемент, str):
                self._помилка(f"Шукати в рядку можна лише рядок, а не {_тип_укр(елемент)}.")
            return елемент in колекція
        self._помилка(f"«у» працює зі словником, списком або рядком, а не з {_тип_укр(колекція)}.")

    def _поле_get(self, обʼєкт, імя):
        if isinstance(обʼєкт, Точка):
            if імя in ("x", "y"):
                return getattr(обʼєкт, імя)
            self._помилка(f"У Точки є лише поля «x» і «y», а не «{імя}».")
        if isinstance(обʼєкт, Екземпляр):
            if імя not in обʼєкт.поля:
                self._помилка(f"У типі «{обʼєкт.тип}» немає поля «{імя}».")
            return обʼєкт.поля[імя]
        if isinstance(обʼєкт, dict):
            if імя not in обʼєкт:
                self._помилка(f"У словнику немає ключа «{імя}».")
            return обʼєкт[імя]
        self._помилка(f"Значення типу «{_тип_укр(обʼєкт)}» не має полів (просили «.{імя}»).")

    def _поле_set(self, обʼєкт, імя, значення):
        if isinstance(обʼєкт, Точка):
            self._помилка(
                f"Точка незмінна: поле «{імя}» не можна присвоїти. Створи нову точку — "
                "Точка(…, …), зсунь(т, dx, dy) тощо."
            )
        if isinstance(обʼєкт, Екземпляр):
            if імя not in обʼєкт.поля:
                self._помилка(
                    f"У типі «{обʼєкт.тип}» немає поля «{імя}» — поля перелічені в оголошенні «тип {обʼєкт.тип}»."
                )
            обʼєкт.поля[імя] = значення
            return
        if isinstance(обʼєкт, dict):
            обʼєкт[імя] = значення
            return
        self._помилка(f"Значення типу «{_тип_укр(обʼєкт)}» не має полів (присвоєння «.{імя}»).")

    def _створити_екземпляр(self, імя, argc):
        опис = self.типи[імя]
        поля = опис["поля"]
        if argc > len(поля):
            self._помилка(
                f"Тип «{імя}» має {len(поля)} поле(я) ({', '.join(поля)}), а передано {argc} значень."
            )
        args = [self._pop() for _ in range(argc)]
        args.reverse()
        значення = {}
        for i, поле in enumerate(поля):
            if i < argc:
                значення[поле] = args[i]
            else:
                типове = опис["типові"][i]
                # список/словник як типове значення — свій для кожного екземпляра
                значення[поле] = copy.deepcopy(типове) if isinstance(типове, (list, dict)) else типове
        self._push(Екземпляр(імя, значення))

    def _виклик_методу(self, аргумент):
        імя, argc = аргумент
        args = [self._pop() for _ in range(argc)]
        args.reverse()
        обʼєкт = self._pop()
        if not isinstance(обʼєкт, Екземпляр):
            self._помилка(
                f"Дію «.{імя}()» можна викликати лише на екземплярі типу, а не на {_тип_укр(обʼєкт)}."
            )
        fn = self.функції.get(f"{обʼєкт.тип}.{імя}")
        if fn is None:
            self._помилка(f"У типі «{обʼєкт.тип}» немає дії «{імя}».")
        очікує = len(fn["параметри"]) - 1
        if очікує != argc:
            self._помилка(f"Дія «{обʼєкт.тип}.{імя}» очікує {очікує} аргумент(и), а отримала {argc}.")
        if len(self.кадри) >= ГЛИБИНА_ВИКЛИКІВ_МАКС:
            self._помилка(f"Забагато вкладених викликів (можлива нескінченна рекурсія в «{імя}»).")
        self.кадри.append(dict(zip(fn["параметри"], [обʼєкт] + args)))
        self.стек_повернень.append(self.pc + 1)
        self.pc = fn["адреса"]

    # ---- виклики ----------------------------------------------------------------

    def _зібрати_швидко(self, імя, опис):
        """«швидко дія …»: спробувати зібрати в машинний код; якщо ні —
        попередження з причиною, дія працює через VM."""
        try:
            self.функції[імя]["машинна"] = mashyna.зібрати(опис)
        except mashyna.НеПідтримується as e:
            print(f"Попередження: дію «{імя}» не зібрано в машинний код — {e}. Виконується через VM.")

    def _виклик_дії(self, аргумент):
        імя, argc = аргумент
        fn = self.функції.get(імя)
        if fn is None:
            if імя in self.типи:
                self._створити_екземпляр(імя, argc)
                self.pc += 1
                return
            self._помилка(f"Невідома дія «{імя}».")
        якщо_очікує = len(fn["параметри"])
        if якщо_очікує != argc:
            self._помилка(
                f"Дія «{імя}» очікує {якщо_очікує} аргумент(и), а отримала {argc}."
            )
        args = [self._pop() for _ in range(argc)]
        args.reverse()
        машинна = fn.get("машинна")
        if машинна is not None and машинна.підходить(args):
            статус, значення = машинна.виклик(args)
            if статус == mashyna.СТАТУС_ОК:
                self._push(значення)
                self.pc += 1
                return
            # збій (ділення на нуль, переповнення, без поверни) — VM виконає
            # виклик сама: у машинній дії немає побічних ефектів
        if len(self.кадри) >= ГЛИБИНА_ВИКЛИКІВ_МАКС:
            self._помилка(f"Забагато вкладених викликів (можлива нескінченна рекурсія в «{імя}»).")
        self.кадри.append(dict(zip(fn["параметри"], args)))
        self.стек_повернень.append(self.pc + 1)
        self.pc = fn["адреса"]

    def _виклик_native(self, аргумент):
        імя, argc = аргумент
        if імя in self.типи:
            # власний «тип Точка» у програмі має перевагу над вбудованим
            self._створити_екземпляр(імя, argc)
            return
        fn = self._native.get(імя)
        if fn is None:
            self._помилка(f"Невідома вбудована функція «{імя}».")
        args = [self._pop() for _ in range(argc)]
        args.reverse()
        try:
            результат = fn(*args)
        except ПомилкаВиконання:
            raise
        except TypeError as e:
            self._помилка(f"Функція «{імя}» викликана з неправильними аргументами ({e}).")
        self._push(результат)


def виконати_байткод(байткод, без_пристрою=False, тека_файлів=None):
    вм = ВМ(без_пристрою=без_пристрою, тека_файлів=тека_файлів)
    вм.виконати(байткод)
    return вм
