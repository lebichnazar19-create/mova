"""Зв'язок з платами (етап 1: пульт). Телефон керує платою в реальному часі
по серіалу; на платі — агент-скетч (agent/), що приймає команди
протоколу з PROTOCOL.md (4 байти запит, 3 байти відповідь).

Вбудовані дії мови: плати(), підключись(назва), відключись(), пін(номер,
режим), пиши(номер, значення), читай(номер), аналог(номер), шим(номер,
значення), зачекай(мс) — зачекай виконується на платі, не на телефоні.

Транспорти під одним інтерфейсом Transport (send/recv/close):
- UsbSerial — pyjnius + usb-serial-for-android (CH340, CP2102, FTDI,
  CDC-ACM); лише в Android-застосунку;
- WifiTcp — TCP-сокет, порт 5555 (ESP32 у режимі точки доступу,
  типово 192.168.4.1); без зовнішніх залежностей;
- Симуляція — агент у пам'яті для тестів і `мова.py --без-пристрою`.

Вибір транспорту — за назвою плати: «USB» / «USB: …» — UsbSerial,
«Wi-Fi» / «tcp://host[:port]» / «192.168.4.1» — WifiTcp, «Симуляція» —
симуляція; після увімкнути_симуляцію(True) будь-яка назва йде в симуляцію.

Усі збої — ПомилкаВиконання українською (плата не підключена, не
відповідає, немає дозволу USB тощо), а не винятки Python.
"""

import socket
import struct
import time

from .errors import ПомилкаВиконання

ПОРТ_TCP = 5555
ХОСТ_ESP32_AP = "192.168.4.1"
ШВИДКІСТЬ_UART = 115200
ТАЙМАУТ_С = 2.0
ВЕРСІЯ_ПРОТОКОЛУ = 1

# ---- протокол (PROTOCOL.md) -------------------------------------------------
КОМАНДА = {
    "пін": 1,      # значення: режим 0/1/2
    "пиши": 2,     # значення: 0/1
    "читай": 3,    # відповідь: 0/1
    "аналог": 4,   # відповідь: 0..4095
    "шим": 5,      # значення: 0..255
    "зачекай": 6,  # значення: мс (0..65535), відповідь після паузи
    "пінг": 7,     # відповідь: версія протоколу
    "блимай": 8,   # значення: кількість блимань вбудованим світлодіодом
}
РЕЖИМ = {"вихід": 0, "вхід": 1, "вхід_підтяжка": 2}
СТАТУС_ОК, СТАТУС_НЕВІДОМА_КОМАНДА, СТАТУС_ПОГАНИЙ_ПІН, СТАТУС_ПОГАНЕ_ЗНАЧЕННЯ = 0, 1, 2, 3
_ТЕКСТ_СТАТУСУ = {
    СТАТУС_НЕВІДОМА_КОМАНДА: "плата не знає такої команди (застарілий агент?)",
    СТАТУС_ПОГАНИЙ_ПІН: "на платі немає такого піна",
    СТАТУС_ПОГАНЕ_ЗНАЧЕННЯ: "плата відхилила значення",
}


def запакувати(команда, пін=0, значення=0):
    """4 байти: [команда][пін][значення_hi][значення_lo]."""
    if not 0 <= значення <= 0xFFFF:
        raise ПомилкаВиконання(f"Значення {значення} не вміщається у 16 біт протоколу.")
    if not 0 <= пін <= 255:
        raise ПомилкаВиконання(f"Номер піна {пін} має бути в межах 0..255.")
    return struct.pack(">BBH", команда, пін, значення)


def розпакувати(відповідь):
    """3 байти: [статус][значення_hi][значення_lo] -> (статус, значення)."""
    if len(відповідь) != 3:
        raise ПомилкаВиконання("Плата відповіла неповно (очікувалось 3 байти).")
    статус, значення = struct.unpack(">BH", відповідь)
    return статус, значення


# ---- транспорти ----------------------------------------------------------------

class Transport:
    """Спільний інтерфейс: send(bytes) / recv(n) -> bytes / close()."""

    назва = "?"

    def send(self, дані):
        raise NotImplementedError

    def recv(self, n, таймаут=ТАЙМАУТ_С):
        raise NotImplementedError

    def close(self):
        pass


class Симуляція(Transport):
    """Агент у пам'яті — поводиться як скетч з agent/: піни, АЦП, ШІМ,
    зачекай (справді спить), блимай."""

    назва = "Симуляція"

    def __init__(self):
        self.режими = {}
        self.піни = {}
        self.шім = {}
        self.аналогові = {}      # пін -> значення, яке віддає «АЦП»
        self.журнал = []         # усі запити (для тестів)
        self._відповідь = b""

    def send(self, дані):
        if len(дані) != 4:
            raise ПомилкаВиконання("Симуляція: запит має бути 4 байти.")
        команда, пін, значення = struct.unpack(">BBH", дані)
        self.журнал.append((команда, пін, значення))
        статус, результат = СТАТУС_ОК, 0
        if команда == КОМАНДА["пін"]:
            if значення not in (0, 1, 2):
                статус = СТАТУС_ПОГАНЕ_ЗНАЧЕННЯ
            else:
                self.режими[пін] = значення
        elif команда == КОМАНДА["пиши"]:
            if значення not in (0, 1):
                статус = СТАТУС_ПОГАНЕ_ЗНАЧЕННЯ
            else:
                self.піни[пін] = значення
        elif команда == КОМАНДА["читай"]:
            результат = self.піни.get(пін, 1 if self.режими.get(пін) == 2 else 0)
        elif команда == КОМАНДА["аналог"]:
            результат = self.аналогові.get(пін, 0)
        elif команда == КОМАНДА["шим"]:
            if значення > 255:
                статус = СТАТУС_ПОГАНЕ_ЗНАЧЕННЯ
            else:
                self.шім[пін] = значення
        elif команда == КОМАНДА["зачекай"]:
            time.sleep(значення / 1000)
        elif команда == КОМАНДА["пінг"]:
            результат = ВЕРСІЯ_ПРОТОКОЛУ
        elif команда == КОМАНДА["блимай"]:
            self.піни["LED"] = значення
        else:
            статус = СТАТУС_НЕВІДОМА_КОМАНДА
        self._відповідь = struct.pack(">BH", статус, результат)

    def recv(self, n, таймаут=ТАЙМАУТ_С):
        дані, self._відповідь = self._відповідь[:n], self._відповідь[n:]
        return дані


class WifiTcp(Transport):
    """TCP до агента ESP32 (точка доступу, порт 5555)."""

    def __init__(self, хост=ХОСТ_ESP32_AP, порт=ПОРТ_TCP):
        self.назва = f"Wi-Fi: {хост}:{порт}"
        try:
            self._сокет = socket.create_connection((хост, порт), timeout=ТАЙМАУТ_С)
        except OSError as e:
            raise ПомилкаВиконання(
                f"Не вдалося з'єднатись із платою по Wi-Fi ({хост}:{порт}): {e}. "
                "Перевір, що телефон підключений до точки доступу плати."
            )
        self._сокет.settimeout(ТАЙМАУТ_С)

    def send(self, дані):
        try:
            self._сокет.sendall(дані)
        except OSError as e:
            raise ПомилкаВиконання(f"Зв'язок із платою по Wi-Fi обірвався: {e}")

    def recv(self, n, таймаут=ТАЙМАУТ_С):
        self._сокет.settimeout(таймаут)
        дані = b""
        try:
            while len(дані) < n:
                шмат = self._сокет.recv(n - len(дані))
                if not шмат:
                    break
                дані += шмат
        except socket.timeout:
            pass
        except OSError as e:
            raise ПомилкаВиконання(f"Зв'язок із платою по Wi-Fi обірвався: {e}")
        return дані

    def close(self):
        try:
            self._сокет.close()
        except OSError:
            pass


class UsbSerial(Transport):
    """USB-серіал через pyjnius і usb-serial-for-android (лише в
    Android-застосунку; на комп'ютері — зрозуміла помилка)."""

    ДОЗВІЛ = "org.mova.USB_PERMISSION"

    def __init__(self, індекс=0):
        jnius = _jnius()
        autoclass = jnius.autoclass
        активність = autoclass("org.kivy.android.PythonActivity").mActivity
        менеджер = активність.getSystemService("usb")
        Prober = autoclass("com.hoho.android.usbserial.driver.UsbSerialProber")
        драйвери = Prober.getDefaultProber().findAllDrivers(менеджер)
        if драйвери.size() == 0:
            raise ПомилкаВиконання(
                "USB-плату не знайдено. Підключи плату кабелем (OTG) і дозволь застосунку доступ."
            )
        if індекс >= драйвери.size():
            raise ПомилкаВиконання(f"USB-плати з номером {індекс} немає (знайдено {драйвери.size()}).")
        драйвер = драйвери.get(індекс)
        пристрій = драйвер.getDevice()
        if not менеджер.hasPermission(пристрій):
            Intent = autoclass("android.content.Intent")
            PendingIntent = autoclass("android.app.PendingIntent")
            прапорці = 0x04000000  # FLAG_IMMUTABLE (Android 12+ вимагає)
            менеджер.requestPermission(пристрій, PendingIntent.getBroadcast(активність, 0, Intent(self.ДОЗВІЛ), прапорці))
            raise ПомилкаВиконання(
                "Немає дозволу на USB-пристрій. Підтвердь запит Android і виклич підключись(\"USB\") ще раз."
            )
        зʼєднання = менеджер.openDevice(пристрій)
        if зʼєднання is None:
            raise ПомилкаВиконання("Android не відкрив USB-пристрій (немає дозволу або пристрій зайнятий).")
        Port = autoclass("com.hoho.android.usbserial.driver.UsbSerialPort")
        self._порт = драйвер.getPorts().get(0)
        self._порт.open(зʼєднання)
        self._порт.setParameters(ШВИДКІСТЬ_UART, 8, Port.STOPBITS_1, Port.PARITY_NONE)
        self.назва = f"USB: {пристрій.getProductName() or драйвер.getClass().getSimpleName()}"

    def send(self, дані):
        try:
            # pyjnius: bytearray/bytes -> byte[]
            self._порт.write(bytearray(дані), int(ТАЙМАУТ_С * 1000))
        except Exception as e:  # jnius.JavaException
            raise ПомилкаВиконання(f"Не вдалося надіслати дані на USB-плату: {e}")

    def recv(self, n, таймаут=ТАЙМАУТ_С):
        буфер = bytearray(64)
        дані = b""
        кінець = time.monotonic() + таймаут
        while len(дані) < n and time.monotonic() < кінець:
            try:
                прочитано = self._порт.read(буфер, 200)
            except Exception as e:
                raise ПомилкаВиконання(f"Зв'язок із USB-платою обірвався: {e}")
            if прочитано > 0:
                дані += bytes(буфер[:прочитано])
        return дані[:n]

    def close(self):
        try:
            self._порт.close()
        except Exception:
            pass


def _jnius():
    try:
        import jnius
        return jnius
    except ImportError:
        raise ПомилкаВиконання(
            "USB-плати доступні лише в застосунку на Android. На комп'ютері спробуй "
            "підключись(\"Wi-Fi\") або підключись(\"Симуляція\")."
        )


# ---- вибір і стан підключення ----------------------------------------------------------

_СИМУЛЯЦІЯ = False
_підключення = None    # Transport або None
_транспорт_вручну = None


def увімкнути_симуляцію(увімкнено=True):
    """Будь-яка назва плати підключається до симуляції (тести, --без-пристрою)."""
    global _СИМУЛЯЦІЯ
    _СИМУЛЯЦІЯ = bool(увімкнено)


def задати_транспорт(транспорт):
    """Задати транспорт вручну (об'єкт Transport) — підключись() візьме його."""
    global _транспорт_вручну
    _транспорт_вручну = транспорт


def обрати_транспорт(назва):
    """За назвою плати -> (вид, аргументи): «usb» / «wifi» / «симуляція»."""
    if not isinstance(назва, str) or not назва.strip():
        raise ПомилкаВиконання('підключись() очікує назву плати: підключись("USB"), підключись("Wi-Fi") або підключись("Симуляція").')
    н = назва.strip()
    низ = н.lower()
    if _СИМУЛЯЦІЯ or низ.startswith("симуляц"):
        return "симуляція", {}
    if низ.startswith("usb"):
        індекс = 0
        if ":" in н and н.split(":", 1)[1].strip().isdigit():
            індекс = int(н.split(":", 1)[1])
        return "usb", {"індекс": індекс}
    if низ.startswith("tcp://"):
        адреса = н[6:]
    elif низ.startswith("wi-fi") or низ.startswith("wifi"):
        адреса = н.split(":", 1)[1].strip() if ":" in н and н.split(":", 1)[1].strip() else ХОСТ_ESP32_AP
    elif н[0].isdigit():
        адреса = н
    else:
        raise ПомилкаВиконання(
            f"Невідома плата «{назва}». Варіанти: \"USB\", \"Wi-Fi\", \"192.168.4.1\", \"tcp://хост:порт\", \"Симуляція\"."
        )
    хост, _, порт = адреса.partition(":")
    return "wifi", {"хост": хост or ХОСТ_ESP32_AP, "порт": int(порт) if порт.isdigit() else ПОРТ_TCP}


def _є_wifi_плата(хост=ХОСТ_ESP32_AP, порт=ПОРТ_TCP, таймаут=0.3):
    try:
        with socket.create_connection((хост, порт), timeout=таймаут):
            return True
    except OSError:
        return False


def плати():
    """Список назв доступних плат: USB (в Android), Wi-Fi (якщо точка доступу
    ESP32 відповідає) і завжди «Симуляція» в кінці."""
    список = []
    if _СИМУЛЯЦІЯ:
        return ["Симуляція"]
    try:
        jnius = _jnius()
        autoclass = jnius.autoclass
        активність = autoclass("org.kivy.android.PythonActivity").mActivity
        менеджер = активність.getSystemService("usb")
        драйвери = autoclass("com.hoho.android.usbserial.driver.UsbSerialProber").getDefaultProber().findAllDrivers(менеджер)
        for і in range(драйвери.size()):
            пристрій = драйвери.get(і).getDevice()
            назва = пристрій.getProductName() or драйвери.get(і).getClass().getSimpleName()
            список.append(f"USB: {назва}" if і == 0 else f"USB:{і} {назва}")
    except ПомилкаВиконання:
        pass
    except Exception:
        pass
    if _є_wifi_плата():
        список.append(f"Wi-Fi: {ХОСТ_ESP32_AP}")
    список.append("Симуляція")
    return список


def підключись(назва="USB"):
    global _підключення
    відключись()
    if _транспорт_вручну is not None:
        _підключення = _транспорт_вручну
    else:
        вид, арг = обрати_транспорт(назва)
        if вид == "симуляція":
            _підключення = Симуляція()
        elif вид == "usb":
            _підключення = UsbSerial(**арг)
        else:
            _підключення = WifiTcp(**арг)
    # перевірка зв'язку: пінг має повернути версію протоколу
    статус, версія = _обмін("пінг")
    if версія != ВЕРСІЯ_ПРОТОКОЛУ:
        назва_ = _підключення.назва
        відключись()
        raise ПомилкаВиконання(
            f"Плата «{назва_}» відповідає, але протокол інший (версія {версія}, потрібна {ВЕРСІЯ_ПРОТОКОЛУ}). Онови агент на платі."
        )
    return _підключення.назва


def відключись():
    global _підключення
    if _підключення is not None:
        _підключення.close()
        _підключення = None
    return None


def підключено():
    return _підключення.назва if _підключення is not None else None


def _обмін(команда, пін=0, значення=0, таймаут=None):
    if _підключення is None:
        raise ПомилкаВиконання('Плата не підключена. Спершу: підключись("USB") або підключись("Wi-Fi").')
    _підключення.send(запакувати(КОМАНДА[команда], пін, значення))
    відповідь = _підключення.recv(3, таймаут if таймаут is not None else ТАЙМАУТ_С)
    if len(відповідь) < 3:
        raise ПомилкаВиконання(
            f"Плата «{_підключення.назва}» не відповідає на «{команда}». Перевір кабель/Wi-Fi і чи залитий агент."
        )
    статус, результат = розпакувати(відповідь)
    if статус != СТАТУС_ОК:
        raise ПомилкаВиконання(f"Плата відхилила «{команда}»: {_ТЕКСТ_СТАТУСУ.get(статус, f'статус {статус}')}.")
    return статус, результат


def _ціле(x, що, від=0, до=0xFFFF):
    if isinstance(x, bool) or not isinstance(x, int):
        raise ПомилкаВиконання(f"{що} має бути цілим числом, а не {type(x).__name__}.")
    if not від <= x <= до:
        raise ПомилкаВиконання(f"{що} має бути в межах {від}..{до}, а не {x}.")
    return x


# ---- вбудовані дії мови ---------------------------------------------------------

def пін(номер, режим):
    _ціле(номер, "Номер піна", 0, 255)
    if isinstance(режим, str):
        if режим not in РЕЖИМ:
            raise ПомилкаВиконання('Режим піна — вихід, вхід або вхід_підтяжка: пін(2, вихід).')
        код = РЕЖИМ[режим]
    else:
        код = _ціле(режим, "Режим піна", 0, 2)
    _обмін("пін", номер, код)
    return None


def пиши(номер, значення):
    _ціле(номер, "Номер піна", 0, 255)
    if значення is True or значення is False:
        значення = int(значення)
    _ціле(значення, "Значення для пиши()", 0, 1)
    _обмін("пиши", номер, значення)
    return None


def читай(номер):
    _ціле(номер, "Номер піна", 0, 255)
    return _обмін("читай", номер)[1]


def аналог(номер):
    _ціле(номер, "Номер піна", 0, 255)
    return _обмін("аналог", номер)[1]


def шим(номер, значення):
    _ціле(номер, "Номер піна", 0, 255)
    _ціле(значення, "Значення ШІМ", 0, 255)
    _обмін("шим", номер, значення)
    return None


def зачекай(мс):
    """Пауза на платі (агент робить delay і лише тоді відповідає)."""
    _ціле(мс, "Час у мс", 0, 0xFFFF)
    _обмін("зачекай", 0, мс, таймаут=ТАЙМАУТ_С + мс / 1000)
    return None


def перевірити(разів=3):
    """«Перевірити» в редакторі: блимнути вбудованим світлодіодом."""
    _ціле(разів, "Кількість блимань", 1, 255)
    _обмін("блимай", 0, разів, таймаут=ТАЙМАУТ_С + разів * 0.5)
    return None
