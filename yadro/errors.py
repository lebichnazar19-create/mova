"""Спільні класи помилок мови «Вуж».

Усі повідомлення — українською, з номером рядка і колонки та стрілкою під
проблемним місцем, коли відомий текст рядка джерела.
"""


class ПомилкаМови(Exception):
    ЗАГОЛОВОК = "Помилка"

    def __init__(self, повідомлення, рядок=0, позиція=0, текст_рядка="", приклад=None, пояснення=None):
        self.повідомлення = повідомлення
        self.рядок = рядок
        self.позиція = позиція
        self.текст_рядка = текст_рядка
        # підказка (помилки розбору): приклад правильного запису конструкції
        # (може бути кілька рядків) і коротке пояснення людською мовою
        self.приклад = приклад
        self.пояснення = пояснення
        super().__init__(self.форматувати())

    def форматувати(self):
        """Заголовок, рядок джерела зі стрілкою, повідомлення (що очікувалось);
        далі, якщо є, блок «Правильно:» з прикладом і рядок пояснення."""
        if self.рядок:
            частини = [f"{self.ЗАГОЛОВОК} в рядку {self.рядок}, позиція {self.позиція}:"]
            if self.текст_рядка:
                частини.append("    " + self.текст_рядка)
                зсув = max(0, self.позиція - 1)
                частини.append("    " + " " * зсув + "^")
        else:
            частини = [f"{self.ЗАГОЛОВОК}:"]
        частини.append(self.повідомлення)
        if self.приклад:
            частини.append("Правильно:")
            частини.extend("    " + р for р in self.приклад.splitlines())
        if self.пояснення:
            частини.append("Пояснення: " + self.пояснення)
        return "\n".join(частини)

    def __str__(self):
        return self.форматувати()


class ПомилкаРозбору(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка розбору"


class ПомилкаКомпіляції(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка компіляції"


class ПомилкаВиконання(ПомилкаМови):
    ЗАГОЛОВОК = "Помилка виконання"


class ПомилкаПідключення(ПомилкаМови):
    """Розв'язання `підключи "файл.вуж"` (yadro/moduli.py) до компіляції:
    файл не знайдено, циклічне підключення, конфлікт імен дій між файлами."""
    ЗАГОЛОВОК = "Помилка підключення"
