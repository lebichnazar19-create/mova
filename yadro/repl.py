"""Інтерактивний режим (REPL): `мова` без файлу.

Кожен введений фрагмент компілюється окремо і додається до вже виконаного
байткоду в тій самій VM (yadro/vm.py: ВМ.виконати_фрагмент) — тому змінні й
дії, оголошені в одному рядку сеансу, лишаються доступні в наступних.
"""

from .kompilyator import компілювати
from .parser import парсити_текст
from .errors import ПомилкаМови
from .vm import ВМ

# слова, після яких обов'язково йде блок з відступом — після такого рядка
# REPL перемикається в режим "продовження" і чекає порожній рядок
_ПОЧАТОК_БЛОКУ = ("якщо", "інакше", "поки", "для", "дія", "тип", "спробуй", "швидко")

ВИХІД = ("вихід", "exit", "quit", ".вихід")


def _чекає_блок(рядок):
    перше = рядок.strip().split(" ", 1)[0] if рядок.strip() else ""
    return перше in _ПОЧАТОК_БЛОКУ


def запустити(без_пристрою=False):
    print("Мова — інтерактивний режим (REPL).")
    print("Порожній рядок завершує багаторядкову конструкцію (якщо/поки/для/дія/тип/спробуй).")
    print(f"Команда «{ВИХІД[0]}» завершує сеанс.\n")

    вм = ВМ(без_пристрою=без_пристрою)

    while True:
        try:
            рядок = input(">>> ")
        except (EOFError, KeyboardInterrupt):
            print()
            break

        if рядок.strip() in ВИХІД:
            break
        if not рядок.strip():
            continue

        буфер = [рядок]
        if _чекає_блок(рядок):
            while True:
                try:
                    продовження = input("... ")
                except (EOFError, KeyboardInterrupt):
                    print()
                    break
                if продовження.strip() == "":
                    break
                буфер.append(продовження)

        джерело = "\n".join(буфер) + "\n"
        try:
            байткод = компілювати(парсити_текст(джерело))
            вм.виконати_фрагмент(байткод)
        except ПомилкаМови as e:
            if not e.текст_рядка and e.рядок:
                рядки_джерела = джерело.split("\n")
                if 1 <= e.рядок <= len(рядки_джерела):
                    e.текст_рядка = рядки_джерела[e.рядок - 1]
            print(str(e))
            # виконання могло обірватись посеред виразу — прибрати сміття
            # зі стека операндів, щоб наступний рядок сеансу почав чисто
            вм.стек.clear()
            вм.кадри.clear()
            вм.стек_повернень.clear()
