"""Параметричний ескіз із прив'язками (constraint solver).

Про імена вузол()/сегмент(): у первинному запиті вони називались
точка()/відрізок(), але ці імена вже зайняті в yadro/ekran.py (термінальне
малювання: точка(x, y, колір), відрізок(x1, y1, x2, y2, колір)) — причому
для «точки» навіть арність (3 аргументи) однакова, тож колізія була б не
просто «остання реєстрація виграє», а реальний ризик мовчки викликати не
ту функцію з аргументами не того типу. Тому тут — вузол()/сегмент().

Вузли й сегменти називаються рядками-іменами; умови (вертикально,
горизонтально, рівні, довжина, кут_між, на_лінії) — це рівняння, кожне з
яких має дорівнювати нулю. розвяжи() підправляє координати всіх вільних
точок числовим градієнтним спуском (з відкатом кроку назад, якщо стає
гірше), поки сума квадратів усіх похибок не стане меншою за 0.001.

Якщо після всіх ітерацій похибка так і лишилась вище порогу (умови
суперечать одна одній або система недовизначена так, що спуск застряг) —
розвяжи() кидає ПомилкаВиконання, а не повертає криву геометрію мовчки.

Після розвяжи() координати читаються назад через точка(імя) (без x, y —
це форма читання) і йдуть, наприклад, у контур()/розмір() з
yadro/drafting.py.

Про збіг(): це НЕ м'яка умова для розв'язувача — дві точки одразу й
назавжди стають одним і тим самим записом координат (структура
"псевдонім", як у union-find). Це надійніше, ніж чекати, поки градієнтний
спуск підтягне їх одна до одної з похибкою, що ніколи не буде рівно нулем.

Про ім'я довжина(): у мові вже є вбудована функція «довжина»
(список_або_рядок) — довжина списку/рядка (yadro/vm.py). Замість тихого
перезаписування одного з них при реєстрації нативних функцій, yadro/vm.py
явно об'єднує обидві версії під одним іменем і вибирає потрібну за
кількістю аргументів: один аргумент — це довжина списку/рядка, два —
розмірна умова для ескізу.
"""

import math

from .errors import ПомилкаВиконання
from .biblioteka import модуль as _бібліотека

_гео = _бібліотека("геометрія")   # biblioteky/geometriya.py: Точка і [x, y]
Точка, _xy = _гео.Точка, _гео.xy

ПОРІГ_ПОХИБКИ = 0.001
МАКС_ІТЕРАЦІЙ = 20000
ЕПСИЛОН_ПОХІДНОЇ = 1e-6
ПОЧАТКОВИЙ_КРОК = 0.5
МАКС_ВІДКОТІВ_КРОКУ = 30

_точки = {}       # ім'я (канонічне) -> [x, y] (мутується на місці)
_псевдонім = {}   # ім'я -> канонічне ім'я (після збіг())
_відрізки = {}    # ім'я -> (ім'я_точки1, ім'я_точки2)
_умови = []       # список функцій без аргументів, що повертають похибку


def скинути():
    """Забути всі вузли, відрізки й умови (застосунок — перед кожним запуском)."""
    _точки.clear()
    _псевдонім.clear()
    _відрізки.clear()
    _умови.clear()


# ---- допоміжне -------------------------------------------------------------

def _число(значення, назва):
    if not isinstance(значення, (int, float)) or isinstance(значення, bool):
        raise ПомилкаВиконання(f"«{назва}» має бути числом.")
    return значення


def _існує_точка(імя):
    return імя in _точки or імя in _псевдонім


def _корінь(імя):
    бачені = set()
    while імя in _псевдонім:
        if імя in бачені:
            raise ПомилкаВиконання(f"Циклічний збіг() навколо точки «{імя}».")
        бачені.add(імя)
        імя = _псевдонім[імя]
    return імя


def _координати(імя):
    if not _існує_точка(імя):
        raise ПомилкаВиконання(f"Немає точки з іменем «{імя}».")
    корінь = _корінь(імя)
    if корінь not in _точки:
        raise ПомилкаВиконання(f"Немає точки з іменем «{імя}».")
    return _точки[корінь]


def _отримати_відрізок(імя):
    if імя not in _відрізки:
        raise ПомилкаВиконання(f"Немає відрізка з іменем «{імя}».")
    return _відрізки[імя]


def _вільні_канонічні_імена():
    return [імя for імя in _точки if імя not in _псевдонім]


def _сума_квадратів_похибок():
    return sum(похибка() ** 2 for похибка in _умови)


# ---- вбудовані функції мови --------------------------------------------------

def вузол(імя, x=None, y=None):
    """вузол("а", 0, 0) або вузол("а", Точка(0, 0)) — створити; вузол("а") —
    прочитати координати як Точку (після розвяжи())."""
    if not isinstance(імя, str):
        raise ПомилкаВиконання("вузол(): ім'я має бути рядком.")
    if x is None and y is None:
        координати = _координати(імя)
        return Точка(координати[0], координати[1])
    if y is None:
        x, y = _xy(x, f"вузол «{імя}»")
    _число(x, "x")
    _число(y, "y")
    _точки[імя] = [x, y]
    _псевдонім.pop(імя, None)
    return None


def сегмент(імя, точка1, точка2):
    if not isinstance(імя, str):
        raise ПомилкаВиконання("сегмент(): ім'я має бути рядком.")
    if not _існує_точка(точка1):
        raise ПомилкаВиконання(f"Немає точки з іменем «{точка1}».")
    if not _існує_точка(точка2):
        raise ПомилкаВиконання(f"Немає точки з іменем «{точка2}».")
    _відрізки[імя] = (точка1, точка2)
    return None


def вертикально(відрізок_імя):
    a, b = _отримати_відрізок(відрізок_імя)

    def похибка():
        return _координати(a)[0] - _координати(b)[0]

    _умови.append(похибка)
    return None


def горизонтально(відрізок_імя):
    a, b = _отримати_відрізок(відрізок_імя)

    def похибка():
        return _координати(a)[1] - _координати(b)[1]

    _умови.append(похибка)
    return None


def рівні(відрізок1_імя, відрізок2_імя):
    a1, b1 = _отримати_відрізок(відрізок1_імя)
    a2, b2 = _отримати_відрізок(відрізок2_імя)

    def похибка():
        pa1, pb1 = _координати(a1), _координати(b1)
        pa2, pb2 = _координати(a2), _координати(b2)
        d1 = math.hypot(pb1[0] - pa1[0], pb1[1] - pa1[1])
        d2 = math.hypot(pb2[0] - pa2[0], pb2[1] - pa2[1])
        return d1 - d2

    _умови.append(похибка)
    return None


def довжина(відрізок_імя, значення):
    """Прив'язка для розв'язувача: довжина відрізка = значення (мм). Не
    плутати з мовною вбудованою довжина(список/рядок) — yadro/vm.py об'єднує
    обидві під одним іменем за кількістю аргументів."""
    _число(значення, "значення")
    a, b = _отримати_відрізок(відрізок_імя)

    def похибка():
        pa, pb = _координати(a), _координати(b)
        return math.hypot(pb[0] - pa[0], pb[1] - pa[1]) - значення

    _умови.append(похибка)
    return None


def кут_між(відрізок1_імя, відрізок2_імя, градуси):
    """Прив'язка: кут між напрямними векторами двох відрізків = градуси
    (0..180, беззнаковий — відрізок як напрямлений вектор точка1->точка2)."""
    _число(градуси, "градуси")
    a1, b1 = _отримати_відрізок(відрізок1_імя)
    a2, b2 = _отримати_відрізок(відрізок2_імя)

    def похибка():
        pa1, pb1 = _координати(a1), _координати(b1)
        pa2, pb2 = _координати(a2), _координати(b2)
        v1x, v1y = pb1[0] - pa1[0], pb1[1] - pa1[1]
        v2x, v2y = pb2[0] - pa2[0], pb2[1] - pa2[1]
        L1, L2 = math.hypot(v1x, v1y), math.hypot(v2x, v2y)
        if L1 < 1e-12 or L2 < 1e-12:
            return 0.0
        косинус = max(-1.0, min(1.0, (v1x * v2x + v1y * v2y) / (L1 * L2)))
        поточний_кут = math.degrees(math.acos(косинус))
        return поточний_кут - градуси

    _умови.append(похибка)
    return None


def збіг(точка1, точка2):
    if not _існує_точка(точка1):
        raise ПомилкаВиконання(f"Немає точки з іменем «{точка1}».")
    if not _існує_точка(точка2):
        raise ПомилкаВиконання(f"Немає точки з іменем «{точка2}».")
    корінь1, корінь2 = _корінь(точка1), _корінь(точка2)
    if корінь1 == корінь2:
        return None
    _псевдонім[корінь2] = корінь1
    return None


def на_лінії(точка_імя, відрізок_імя):
    """Прив'язка: точка лежить на прямій через відрізок (може ковзати
    вздовж неї). Рівняння — векторний добуток (точка−початок)×(кінець−
    початок) = 0."""
    if not _існує_точка(точка_імя):
        raise ПомилкаВиконання(f"Немає точки з іменем «{точка_імя}».")
    a, b = _отримати_відрізок(відрізок_імя)

    def похибка():
        px, py = _координати(точка_імя)
        ax, ay = _координати(a)
        bx, by = _координати(b)
        vx, vy = px - ax, py - ay
        wx, wy = bx - ax, by - ay
        return vx * wy - vy * wx

    _умови.append(похибка)
    return None


# ---- прив'язки простими словами (обгортки над розв'язувачем) ----------------

def _вузол_чи_відрізок(імя, дія):
    if not isinstance(імя, str):
        raise ПомилкаВиконання(f"{дія}(): очікується ім'я вузла або відрізка (рядок).")
    if _існує_точка(імя):
        return "вузол"
    if імя in _відрізки:
        return "відрізок"
    raise ПомилкаВиконання(f"{дія}(): немає ні вузла, ні відрізка з іменем «{імя}».")


def на_відстані(що, від_чого, скільки):
    """Прив'язка: вузол «що» на відстані «скільки» від вузла або від прямої
    відрізка «від_чого». на_відстані("розетка", "щиток", 120) або
    на_відстані("розетка", "підлога", 300)."""
    _число(скільки, "скільки")
    if скільки < 0:
        raise ПомилкаВиконання("на_відстані(): відстань не може бути від'ємною.")
    if _вузол_чи_відрізок(що, "на_відстані") != "вузол":
        raise ПомилкаВиконання(f"на_відстані(): «{що}» має бути вузлом (точкою), а не відрізком.")
    вид = _вузол_чи_відрізок(від_чого, "на_відстані")
    if вид == "вузол":
        def похибка():
            p, q = _координати(що), _координати(від_чого)
            return math.hypot(p[0] - q[0], p[1] - q[1]) - скільки
    else:
        a, b = _відрізки[від_чого]

        def похибка():
            px, py = _координати(що)
            ax, ay = _координати(a)
            bx, by = _координати(b)
            wx, wy = bx - ax, by - ay
            L = math.hypot(wx, wy)
            if L < 1e-12:
                return 0.0
            return abs((px - ax) * wy - (py - ay) * wx) / L - скільки
    _умови.append(похибка)
    return None


def паралельно_до(що, чого):
    """Прив'язка: відрізок «що» паралельний відрізку «чого» (у будь-який бік)."""
    a1, b1 = _отримати_відрізок(що)
    a2, b2 = _отримати_відрізок(чого)

    def похибка():
        pa1, pb1 = _координати(a1), _координати(b1)
        pa2, pb2 = _координати(a2), _координати(b2)
        v1x, v1y = pb1[0] - pa1[0], pb1[1] - pa1[1]
        v2x, v2y = pb2[0] - pa2[0], pb2[1] - pa2[1]
        L1, L2 = math.hypot(v1x, v1y), math.hypot(v2x, v2y)
        if L1 < 1e-12 or L2 < 1e-12:
            return 0.0
        # синус кута між напрямками; масштабуємо до «мм», щоб похибка була співмірна з іншими
        return (v1x * v2y - v1y * v2x) / (L1 * L2) * max(L1, L2)

    _умови.append(похибка)
    return None


def під_кутом(що, чого, градуси):
    """Прив'язка: кут між відрізками «що» і «чого» = градуси (0..180).
    Те саме, що кут_між — простішими словами."""
    return кут_між(що, чого, градуси)


def на_стіні(що, стіна, від_кута):
    """Прив'язка: вузол «що» лежить на відрізку «стіна» на відстані
    «від_кута» від його першої точки. на_стіні("розетка", "південна", 1200)."""
    _число(від_кута, "від_кута")
    if від_кута < 0:
        raise ПомилкаВиконання("на_стіні(): відстань від кута не може бути від'ємною.")
    if _вузол_чи_відрізок(що, "на_стіні") != "вузол":
        raise ПомилкаВиконання(f"на_стіні(): «{що}» має бути вузлом (точкою).")
    a, b = _отримати_відрізок(стіна)
    на_лінії(що, стіна)

    def похибка():
        p, q = _координати(що), _координати(a)
        return math.hypot(p[0] - q[0], p[1] - q[1]) - від_кута

    _умови.append(похибка)
    return None


def габарити():
    """Габаритний прямокутник усієї геометрії — [xmin, ymin, xmax, ymax]
    (мм), по координатах усіх вузлів (аліаси через збіг() вже ведуть на ту
    саму пару координат, тож окремо їх рахувати не треба). Кидає
    ПомилкаВиконання, якщо жодного вузла ще не створено."""
    if not _точки:
        raise ПомилкаВиконання("габарити(): ще немає жодного вузла — спершу створи їх через вузол().")
    іксі = [p[0] for p in _точки.values()]
    ігреки = [p[1] for p in _точки.values()]
    return [min(іксі), min(ігреки), max(іксі), max(ігреки)]


def зсунь(dx, dy):
    """Зсунути (перемістити, без обертання чи масштабування) усю геометрію
    на (dx, dy) мм. Усі умови розвяжи() — різниці координат, довжини або
    кути між напрямними векторами — інваріантні до зсуву, тож викликати
    зсунь() після розвяжи() безпечно: жодна умова через це не «розв'яжеться»
    гірше."""
    _число(dx, "dx")
    _число(dy, "dy")
    for координати in _точки.values():
        координати[0] += dx
        координати[1] += dy
    return None


def _розвязати_лінійну(A, b):
    """Розв'язок A·x = b методом Гаусса з вибором головного елемента
    (A — квадратна, список списків). None, якщо матриця вироджена."""
    n = len(A)
    M = [рядок[:] + [b[i]] for i, рядок in enumerate(A)]
    for k in range(n):
        p = max(range(k, n), key=lambda i: abs(M[i][k]))
        if abs(M[p][k]) < 1e-14:
            return None
        M[k], M[p] = M[p], M[k]
        for i in range(k + 1, n):
            f = M[i][k] / M[k][k]
            if f:
                for j in range(k, n + 1):
                    M[i][j] -= f * M[k][j]
    x = [0.0] * n
    for i in range(n - 1, -1, -1):
        s_ = M[i][n] - sum(M[i][j] * x[j] for j in range(i + 1, n))
        x[i] = s_ / M[i][i]
    return x


def _уточнити(координати_змінних, похибка):
    """Уточнення Левенберга–Марквардта після градієнтного спуску: кілька
    кроків за лінеаризованими умовами дають похибку ~1e-10 там, де спуск
    зупиняється біля 1e-3. Демпфування λ рятує недовизначені системи
    (вільний зсув/поворот усього ескізу). Повертає нову похибку."""
    n = len(координати_змінних)
    λ = 1e-3
    for _ in range(60):
        if похибка < 1e-16:
            break
        r = [у() for у in _умови]
        J = []
        for у in _умови:
            рядок = []
            for імя, i in координати_змінних:
                оригінал = _точки[імя][i]
                _точки[імя][i] = оригінал + ЕПСИЛОН_ПОХІДНОЇ
                плюс = у()
                _точки[імя][i] = оригінал
                рядок.append((плюс - r[len(J)]) / ЕПСИЛОН_ПОХІДНОЇ)
            J.append(рядок)
        A = [[sum(J[k][a] * J[k][b] for k in range(len(J))) for b in range(n)] for a in range(n)]
        g = [sum(J[k][a] * r[k] for k in range(len(J))) for a in range(n)]
        збережені = {імя: list(_точки[імя]) for імя, _ in координати_змінних}
        покращено = False
        for _спроба in range(12):
            A_λ = [[A[a][b] + (λ if a == b else 0.0) for b in range(n)] for a in range(n)]
            Δ = _розвязати_лінійну(A_λ, [-x for x in g])
            if Δ is not None:
                for (імя, i), d in zip(координати_змінних, Δ):
                    _точки[імя][i] = збережені[імя][i] + d
                нова = _сума_квадратів_похибок()
                if нова < похибка:
                    похибка = нова
                    λ = max(λ / 3, 1e-9)
                    покращено = True
                    break
                for імя, i in координати_змінних:
                    _точки[імя][i] = збережені[імя][i]
            λ *= 4
        if not покращено:
            break
    return похибка


def розвяжи():
    """Числовий градієнтний спуск із відкатом кроку, потім уточнення
    Левенберга–Марквардта (_уточнити). Повертає підсумкову суму квадратів
    похибок (0, якщо умов не було взагалі); кидає ПомилкаВиконання, якщо
    не вдалось зійтись нижче порога — це ознака того, що умови суперечать
    одна одній або система недовизначена так, що спуск застряг."""
    координати_змінних = [(імя, i) for імя in _вільні_канонічні_імена() for i in (0, 1)]
    if not координати_змінних or not _умови:
        return _сума_квадратів_похибок()

    # спершу швидке уточнення з початкового наближення — зазвичай цього досить
    похибка = _уточнити(координати_змінних, _сума_квадратів_похибок())
    if похибка < ПОРІГ_ПОХИБКИ:
        return похибка

    крок = ПОЧАТКОВИЙ_КРОК

    for _ in range(МАКС_ІТЕРАЦІЙ):
        if похибка < ПОРІГ_ПОХИБКИ:
            return похибка

        градієнт = []
        for імя, i in координати_змінних:
            оригінал = _точки[імя][i]
            _точки[імя][i] = оригінал + ЕПСИЛОН_ПОХІДНОЇ
            плюс = _сума_квадратів_похибок()
            _точки[імя][i] = оригінал
            градієнт.append((плюс - похибка) / ЕПСИЛОН_ПОХІДНОЇ)

        збережені = {імя: list(_точки[імя]) for імя, _ in координати_змінних}

        покращено = False
        for _спроба in range(МАКС_ВІДКОТІВ_КРОКУ):
            for (імя, i), g in zip(координати_змінних, градієнт):
                _точки[імя][i] = збережені[імя][i] - крок * g
            нова_похибка = _сума_квадратів_похибок()
            if нова_похибка < похибка:
                похибка = нова_похибка
                крок *= 1.2
                покращено = True
                break
            крок *= 0.5

        if not покращено:
            for імя, i in координати_змінних:
                _точки[імя][i] = збережені[імя][i]
            break

    похибка = _уточнити(координати_змінних, похибка)

    if похибка >= ПОРІГ_ПОХИБКИ:
        raise ПомилкаВиконання(
            "Не вдалося розв'язати ескіз: умови суперечать одна одній або "
            f"недостатньо узгоджені (залишкова похибка {похибка:.4f}, поріг "
            f"{ПОРІГ_ПОХИБКИ}). Перевір, чи не задано зайвих або "
            "взаємовиключних умов (наприклад, довжину відрізка і водночас "
            "обидві його точки — фіксованими якимось іншим способом)."
        )
    return похибка
