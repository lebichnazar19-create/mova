"""Дизасемблер: показує байткод у читабельному вигляді (мова -д файл.мова)."""


def дизасемблювати(байткод):
    константи = байткод.get("константи", [])
    код = байткод.get("код", [])
    позиції = байткод.get("позиції", [])
    рядки = [f"; версія {байткод.get('версія', 1)}, {len(константи)} констант(и), {len(код)} інструкцій"]
    rядки_конст = ["; константи:"]
    for i, з in enumerate(константи):
        rядки_конст.append(f";   [{i}] {з!r}")
    рядки += rядки_конст
    рядки.append(";")
    рядки.append("; код:")
    for i, (опкод, аргумент) in enumerate(код):
        префікс = f"{i:5d}  {опкод:<14}"
        if опкод == "PUSH_CONST" and 0 <= аргумент < len(константи):
            суфікс = f"{аргумент}   ; {константи[аргумент]!r}"
        elif аргумент is not None:
            суфікс = f"{аргумент}"
        else:
            суфікс = ""
        позиція = ""
        if i < len(позиції) and позиції[i] and позиції[i][0]:
            позиція = f"   ; рядок {позиції[i][0]}"
        рядки.append(f"{префікс}{суфікс}{позиція}")
    return "\n".join(рядки)
