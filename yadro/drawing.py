"""Малювання: накопичує намальовані фігури, а `покажи()` збирає з них одну
HTML-сторінку (з вбудованим SVG усередині) і відкриває її на екрані
пристрою (через yadro/prystriy.py — subprocess лишається лише там, тут його
немає).

Порядок використання в програмі мовою «Мова»:
    полотно(300, 200)
    квадрат(10, 10, 50, "синій")
    покажи()

Два практичні застереження, обидва — наслідок того, що ця мова часто
працює всередині proot-Ubuntu поверх Termux:
  * `Path.home()` тут — це дім proot-дистрибутива (наприклад, /root), а не
    справжній Termux-дім. Android/termux-open бачить лише файли під
    /data/data/com.termux/files/home, тому файл малюнка зберігається саме
    туди, якщо цей шлях існує (інакше — як і раніше, у Path.home()).
  * Розширення файлу — .html, а не .svg: на реальному пристрої Android за
    типом файлу .svg іноді відкриває його не браузером, а стороннім
    застосунком на кшталт Google Документів. .html однозначно відкриває
    браузер.
"""

import html
import re
from pathlib import Path

from . import prystriy
from .errors import ПомилкаВиконання

_TERMUX_ДІМ = Path("/data/data/com.termux/files/home")


def _базова_директорія():
    """Справжній дім Termux, якщо він видний з-під proot; інакше — як було."""
    if _TERMUX_ДІМ.is_dir():
        return _TERMUX_ДІМ
    return Path.home()


ШЛЯХ_ФАЙЛУ = _базова_директорія() / ".мова" / "малюнок.html"

КОЛЬОРИ = {
    "синій": "#1E88E5",
    "червоний": "#E53935",
    "зелений": "#43A047",
    "жовтий": "#FDD835",
    "чорний": "#000000",
    "білий": "#FFFFFF",
    "сірий": "#9E9E9E",
}

_ШІСТНАДЦЯТКОВИЙ = re.compile(r"^#[0-9A-Fa-f]{6}$")

_полотно = None   # {"ширина": int, "висота": int} після виклику полотно(...)
_фігури = []


def скинути():
    global _полотно, _фігури
    _полотно = None
    _фігури = []


# ---- допоміжне -------------------------------------------------------------

def _число(значення, назва):
    if not isinstance(значення, (int, float)) or isinstance(значення, bool):
        raise ПомилкаВиконання(f"«{назва}» має бути числом.")
    return значення


def _колір(текст_кольору):
    if not isinstance(текст_кольору, str):
        raise ПомилкаВиконання("Колір має бути рядком.")
    if текст_кольору in КОЛЬОРИ:
        return КОЛЬОРИ[текст_кольору]
    if _ШІСТНАДЦЯТКОВИЙ.match(текст_кольору):
        return текст_кольору
    підтримувані = ", ".join(f"«{к}»" for к in КОЛЬОРИ)
    raise ПомилкаВиконання(
        f"Невідомий колір «{текст_кольору}». Підтримуються: {підтримувані}, "
        f"або запис у форматі #RRGGBB (наприклад, #FF00AA)."
    )


def _перевірити_полотно():
    if _полотно is None:
        raise ПомилкаВиконання("Спершу виклич полотно(ширина, висота) — перед тим, як щось малювати.")


# ---- вбудовані функції мови --------------------------------------------------

def полотно(ширина, висота):
    global _полотно, _фігури
    _число(ширина, "ширина")
    _число(висота, "висота")
    if ширина <= 0 or висота <= 0:
        raise ПомилкаВиконання("Розміри полотна мають бути додатними числами.")
    _полотно = {"ширина": ширина, "висота": висота}
    _фігури = []
    return None


def квадрат(x, y, розмір, колір):
    _перевірити_полотно()
    _число(x, "x")
    _число(y, "y")
    _число(розмір, "розмір")
    _фігури.append({"тип": "rect", "x": x, "y": y, "w": розмір, "h": розмір, "колір": _колір(колір)})
    return None


def коло(x, y, радіус, колір):
    _перевірити_полотно()
    _число(x, "x")
    _число(y, "y")
    _число(радіус, "радіус")
    _фігури.append({"тип": "circle", "cx": x, "cy": y, "r": радіус, "колір": _колір(колір)})
    return None


def лінія(x1, y1, x2, y2, колір, товщина):
    _перевірити_полотно()
    for назва, зн in (("x1", x1), ("y1", y1), ("x2", x2), ("y2", y2), ("товщина", товщина)):
        _число(зн, назва)
    _фігури.append({
        "тип": "line", "x1": x1, "y1": y1, "x2": x2, "y2": y2,
        "колір": _колір(колір), "товщина": товщина,
    })
    return None


def текст(x, y, напис, розмір, колір):
    _перевірити_полотно()
    _число(x, "x")
    _число(y, "y")
    _число(розмір, "розмір")
    if not isinstance(напис, str):
        raise ПомилкаВиконання("Функція «текст» очікує рядок як напис.")
    _фігури.append({
        "тип": "text", "x": x, "y": y, "напис": напис, "розмір": розмір, "колір": _колір(колір),
    })
    return None


def _svg():
    _перевірити_полотно()
    рядки = [
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{_полотно["ширина"]}" height="{_полотно["висота"]}" '
        f'viewBox="0 0 {_полотно["ширина"]} {_полотно["висота"]}">',
        '<rect width="100%" height="100%" fill="#FFFFFF"/>',
    ]
    for ф in _фігури:
        if ф["тип"] == "rect":
            рядки.append(
                f'<rect x="{ф["x"]}" y="{ф["y"]}" width="{ф["w"]}" height="{ф["h"]}" '
                f'fill="{ф["колір"]}"/>'
            )
        elif ф["тип"] == "circle":
            рядки.append(
                f'<circle cx="{ф["cx"]}" cy="{ф["cy"]}" r="{ф["r"]}" fill="{ф["колір"]}"/>'
            )
        elif ф["тип"] == "line":
            рядки.append(
                f'<line x1="{ф["x1"]}" y1="{ф["y1"]}" x2="{ф["x2"]}" y2="{ф["y2"]}" '
                f'stroke="{ф["колір"]}" stroke-width="{ф["товщина"]}"/>'
            )
        elif ф["тип"] == "text":
            рядки.append(
                f'<text x="{ф["x"]}" y="{ф["y"]}" font-size="{ф["розмір"]}" '
                f'fill="{ф["колір"]}">{html.escape(ф["напис"])}</text>'
            )
    рядки.append("</svg>")
    return "\n".join(рядки)


def _html():
    """Загорнути SVG у мінімальну HTML-сторінку — щоб файл відкривався саме
    браузером, а не, наприклад, Google Документами за розширенням .svg."""
    return (
        "<!doctype html>\n"
        '<html><head><meta charset="utf-8"><title>Малюнок</title></head>\n'
        '<body style="margin:0;display:flex;align-items:center;'
        'justify-content:center;min-height:100vh;background:#f2f2f2">\n'
        f"{_svg()}\n"
        "</body></html>\n"
    )


def покажи():
    """Зберегти накопичені фігури в HTML-файл (з SVG усередині) і відкрити
    його на екрані."""
    _перевірити_полотно()
    ШЛЯХ_ФАЙЛУ.parent.mkdir(parents=True, exist_ok=True)
    ШЛЯХ_ФАЙЛУ.write_text(_html(), encoding="utf-8")
    prystriy.відкрий(str(ШЛЯХ_ФАЙЛУ))
    return str(ШЛЯХ_ФАЙЛУ)
