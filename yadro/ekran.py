"""Малювання прямо в терміналі: символьний буфер у пам'яті, кожна клітинка —
два пробіли з ANSI-фоном 24-bit. Ніякого subprocess — просто друк у stdout.

Порядок використання в програмі мовою «Мова»:
    екран(60, 30)
    запов_квадрат(10, 10, 5, "синій")
    намалюй()

Кольори — ті самі, що й у малюванні SVG (yadro/drawing.py:КОЛЬОРИ і
_колір()) — навмисно перевикористані звідти, щоб назви кольорів і формат
#RRGGBB поводились однаково в обох способах малювання.
"""

import os
import select
import shutil
import sys
import time

try:
    import termios
    import tty
except ImportError:  # не-POSIX середовище (не Termux) — живий режим просто вимкнеться
    termios = None
    tty = None

from . import drawing
from .errors import ПомилкаВиконання

БІЛИЙ_ФОН = "#FFFFFF"

# керуючі ANSI-послідовності для живого режиму (тримай())
_ДОДОМУ = "\033[H"
# 3J — очистити буфер прокрутки (scrollback), 2J — видиму частину екрана,
# і додому: без 3J під щойно намальованим полотном лишався б видимий старий
# вивід попередніх команд (він не в поточному екрані, а саме в прокрутці)
_ОЧИСТИТИ_ВСЕ = "\033[3J\033[2J" + _ДОДОМУ
_ОЧИСТИТИ_ДО_КІНЦЯ_РЯДКА = "\033[K"
_ПРИХОВАТИ_КУРСОР = "\033[?25l"
_ПОКАЗАТИ_КУРСОР = "\033[?25h"
_СКИДАННЯ = "\033[0m"

_екран = None   # {"ширина": int, "висота": int} після виклику екран(...)
_буфер = []     # список рядків; рядок — список hex-кольорів довжиною "ширина"


# ---- допоміжне -------------------------------------------------------------

def _число(значення, назва):
    if not isinstance(значення, (int, float)) or isinstance(значення, bool):
        raise ПомилкаВиконання(f"«{назва}» має бути числом.")
    return значення


def _перевірити_екран():
    if _екран is None:
        raise ПомилкаВиконання("Спершу виклич екран(ширина, висота) — перед тим, як щось малювати.")


def _встановити(x, y, колір_хекс):
    """Пофарбувати одну клітинку. Координати за межами екрана просто
    ігноруються (як фігура, що виходить за межі SVG-полотна) — жодної
    помилки, щоб не змушувати рахувати межі вручну для кожної фігури."""
    xi, yi = int(x), int(y)
    if 0 <= yi < _екран["висота"] and 0 <= xi < _екран["ширина"]:
        _буфер[yi][xi] = колір_хекс


def _код_фону(колір_хекс):
    r = int(колір_хекс[1:3], 16)
    g = int(колір_хекс[3:5], 16)
    b = int(колір_хекс[5:7], 16)
    return f"\033[48;2;{r};{g};{b}m"


# ---- вбудовані функції мови --------------------------------------------------

def екран(ширина, висота):
    global _екран, _буфер
    _число(ширина, "ширина")
    _число(висота, "висота")
    if ширина <= 0 or висота <= 0:
        raise ПомилкаВиконання("Розміри екрана мають бути додатними числами.")
    ш, в = int(ширина), int(висота)
    _екран = {"ширина": ш, "висота": в}
    _буфер = [[БІЛИЙ_ФОН for _ in range(ш)] for _ in range(в)]
    return None


def точка(x, y, колір):
    _перевірити_екран()
    _число(x, "x")
    _число(y, "y")
    _встановити(x, y, drawing._колір(колір))
    return None


def запов_квадрат(x, y, розмір, колір):
    _перевірити_екран()
    _число(x, "x")
    _число(y, "y")
    _число(розмір, "розмір")
    колір_хекс = drawing._колір(колір)
    for dy in range(int(розмір)):
        for dx in range(int(розмір)):
            _встановити(x + dx, y + dy, колір_хекс)
    return None


def запов_коло(x, y, радіус, колір):
    _перевірити_екран()
    _число(x, "x")
    _число(y, "y")
    _число(радіус, "радіус")
    колір_хекс = drawing._колір(колір)
    r2 = радіус * радіус
    xi, yi, ri = int(x), int(y), int(round(радіус))
    for dy in range(-ri, ri + 1):
        for dx in range(-ri, ri + 1):
            if dx * dx + dy * dy <= r2:
                _встановити(xi + dx, yi + dy, колір_хекс)
    return None


def відрізок(x1, y1, x2, y2, колір):
    """Пряма лінія за алгоритмом Брезенхема (цілочисельний, без округлень)."""
    _перевірити_екран()
    for назва, зн in (("x1", x1), ("y1", y1), ("x2", x2), ("y2", y2)):
        _число(зн, назва)
    колір_хекс = drawing._колір(колір)

    x1, y1, x2, y2 = int(x1), int(y1), int(x2), int(y2)
    dx = abs(x2 - x1)
    dy = -abs(y2 - y1)
    sx = 1 if x1 < x2 else -1
    sy = 1 if y1 < y2 else -1
    помилка = dx + dy
    x, y = x1, y1

    while True:
        _встановити(x, y, колір_хекс)
        if x == x2 and y == y2:
            break
        e2 = 2 * помилка
        if e2 >= dy:
            помилка += dy
            x += sx
        if e2 <= dx:
            помилка += dx
            y += sy
    return None


def намалюй():
    """Вивести накопичений буфер у термінал."""
    _перевірити_екран()
    рядки = []
    for рядок_клітинок in _буфер:
        частини = [_код_фону(колір_хекс) + "  " for колір_хекс in рядок_клітинок]
        рядки.append("".join(частини) + "\033[0m")
    print("\n".join(рядки))
    return None


# ---- живий режим (тримай()) --------------------------------------------------
#
# намалюй() вище нічим не зачіпається — тримай() працює поруч, окремим
# набором функцій, і використовує свій власний рендер (_відрендерити_кадр),
# бо йому потрібне обрізання по краю термінала й позиціювання курсора, чого
# намалюй() не робить і не повинен.

def _позиція(рядок, колонка=1):
    return f"\033[{рядок};{колонка}H"


def _відрендерити_кадр(розмір_терміналу):
    """Зібрати один кадр живого режиму під конкретний розмір термінала.

    Повертає ОДИН рядок без жодного символу нового рядка — кожен рядок
    полотна позиціюється абсолютним кодом курсора (\\033[N;1H), а не "\\n".
    Причина: sys.stdout для tty — рядково-буферизований, і кожен "\\n"
    усередині одного write() спричиняв би проміжний автоматичний flush
    (а отже видиме мигання) ще до явного flush() у тримай(). Без "\\n"
    увесь кадр іде одним записом і рендериться терміналом за раз.

    Ширші за термінал полотна НЕ переносяться на новий рядок —
    обрізаються по краю, і внизу дописується, скільки клітинок не влізло
    (по ширині і/або по висоті)."""
    стовпців = max(0, розмір_терміналу.columns)
    рядків_термінала = max(0, розмір_терміналу.lines)
    ширина_кл, висота_кл = _екран["ширина"], _екран["висота"]

    клітинок_влазить_по_ширині = стовпців // 2
    видимих_стовпців_кл = min(ширина_кл, клітинок_влазить_по_ширині)
    обрізано_по_ширині = max(0, ширина_кл - видимих_стовпців_кл)

    # якщо доведеться дописувати повідомлення знизу — воно забирає один
    # рядок термінала, тому спершу прикидаємо без нього, а тоді, якщо
    # повідомлення таки потрібне, перераховуємо доступну висоту ще раз
    обрізано_по_висоті = max(0, висота_кл - рядків_термінала)
    потрібне_повідомлення = обрізано_по_ширині > 0 or обрізано_по_висоті > 0
    доступно_рядків = рядків_термінала - (1 if потрібне_повідомлення else 0)
    видимих_рядків_кл = max(0, min(висота_кл, доступно_рядків))
    обрізано_по_висоті = max(0, висота_кл - видимих_рядків_кл)
    потрібне_повідомлення = обрізано_по_ширині > 0 or обрізано_по_висоті > 0

    частини_кадру = []
    for y in range(видимих_рядків_кл):
        клітинки = _буфер[y][:видимих_стовпців_кл]
        вміст = "".join(_код_фону(колір_хекс) + "  " for колір_хекс in клітинки)
        частини_кадру.append(
            _позиція(y + 1) + вміст + _СКИДАННЯ + _ОЧИСТИТИ_ДО_КІНЦЯ_РЯДКА
        )

    if потрібне_повідомлення:
        частини_повідомлення = []
        if обрізано_по_ширині > 0:
            частини_повідомлення.append(f"{обрізано_по_ширині} кл. праворуч")
        if обрізано_по_висоті > 0:
            частини_повідомлення.append(f"{обрізано_по_висоті} кл. знизу")
        частини_кадру.append(
            _позиція(видимих_рядків_кл + 1)
            + "Термінал замалий, не влізло: " + ", ".join(частини_повідомлення)
            + _СКИДАННЯ + _ОЧИСТИТИ_ДО_КІНЦЯ_РЯДКА
        )

    return "".join(частини_кадру)


def _налаштувати_термінал():
    """Увімкнути cbreak-режим (читати клавіші одразу, без Enter), лишаючи
    Ctrl+C робочим (ISIG не чіпається). Якщо stdin — не справжній термінал
    (тести, перенаправлений ввід тощо), просто нічого не робити."""
    if termios is None or tty is None:
        return None
    try:
        fd = sys.stdin.fileno()
        if not os.isatty(fd):
            return None
        старі_налаштування = termios.tcgetattr(fd)
        tty.setcbreak(fd)
        return (fd, старі_налаштування)
    except Exception:
        return None


def _відновити_термінал(налаштування):
    if налаштування is None:
        return
    fd, старі_налаштування = налаштування
    try:
        termios.tcsetattr(fd, termios.TCSADRAIN, старі_налаштування)
    except Exception:
        pass


def _клавіша_q_натиснута(затримка):
    """Почекати щонайбільше `затримка` секунд на клавішу і сказати, чи це
    було «q» (або «Q»). Якщо клавіатуру взагалі не вдається опитати
    (немає справжнього термінала) — просто почекати ту саму затримку, щоб
    цикл не крутився вхолосту, і сказати, що клавішу не натиснуто."""
    try:
        готові, _, _ = select.select([sys.stdin], [], [], затримка)
        if готові:
            символ = sys.stdin.read(1)
            return символ.lower() == "q"
        return False
    except Exception:
        try:
            time.sleep(затримка)
        except Exception:
            pass
        return False


def тримай(затримка=0.15):
    """Як намалюй(), але не завершується одразу: тримає намальоване на
    екрані й перемальовує його щоразу, коли міняється розмір термінала
    (наприклад, від повороту телефона). Вихід — Ctrl+C або клавіша «q».

    Курсор і кольори термінала гарантовано повертаються до звичайного
    стану при виході, навіть якщо всередині циклу сталася помилка."""
    _перевірити_екран()

    налаштування = _налаштувати_термінал()
    # 3J чистить і буфер прокрутки — без цього під полотном (якщо воно не
    # займає весь термінал) лишався б видимий старий вивід попередніх команд
    sys.stdout.write(_ОЧИСТИТИ_ВСЕ + _ПРИХОВАТИ_КУРСОР)
    sys.stdout.flush()

    try:
        попередній_розмір = None
        while True:
            поточний_розмір = shutil.get_terminal_size()
            if поточний_розмір != попередній_розмір:
                попередній_розмір = поточний_розмір
                sys.stdout.write(_відрендерити_кадр(поточний_розмір))
                sys.stdout.flush()

            if _клавіша_q_натиснута(затримка):
                break
    except KeyboardInterrupt:
        pass
    finally:
        _відновити_термінал(налаштування)
        sys.stdout.write(_СКИДАННЯ + _ПОКАЗАТИ_КУРСОР + "\n")
        sys.stdout.flush()

    return None
