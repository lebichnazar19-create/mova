"""Симулятор ROM-завантажувача ESP32 — відповідає на команди так, як
відповідала б реальна плата (SYNC кількома відповідями, READ_REG магії
чипа/eFuse MAC/регістрів SPI, FLASH_BEGIN/DATA/END зі статусами і
контрольними сумами, імітація затримок стирання/запису), а також умисні
відмови: збій="контрольна_сума" (плата відповідає «bad checksum» на один
блок), збій="таймаут" (ніколи не відповідає на SYNC), збій="обрив"
(замовкає після N блоків). Реагує на DTR/RTS: у режим завантажувача
входить лише після послідовності EN/GPIO0, як справжня ESP32.
"""

import struct
import time

from . import proshyvka as п

ФЛЕШ_ID_4МБ = 0x001640C8      # RDID: виробник C8, тип 40, розмір 16 (4 МБ)


class СимуляторESP32:
    назва = "Симуляція ESP32"

    def __init__(self, збій=None, обрив_після=2, mac="24:0A:C4:12:34:56", магія=0x00F01D83,
                 затримка=0.0):
        self.збій = збій
        self.обрив_після = обрив_після
        self.затримка = затримка
        self._вхід = b""
        self._вихід = b""
        self.dtr = False
        self.rts = False
        self.у_завантажувачі = False
        self._gpio0_low_при_старті = False
        self.флеш = {}                # зсув блоку -> дані
        self.стертo = 0
        self.журнал = []              # назви команд
        self.регістри = {п.РЕГ_МАГІЯ: магія}
        m = [int(x, 16) for x in mac.split(":")]
        self.регістри[п.РЕГ_EFUSE_MAC0] = (m[2] << 24) | (m[3] << 16) | (m[4] << 8) | m[5]
        self.регістри[п.РЕГ_EFUSE_MAC1] = (m[0] << 8) | m[1]
        self._блоків_очікується = 0
        self._блоків_записано = 0
        self._зсув = 0
        self._збій_суми_спрацював = False
        self.перезавантажень = 0

    # ---- інтерфейс порту ----

    def set_dtr(self, стан):
        self.dtr = bool(стан)

    def set_rts(self, стан):
        # RTS=True — EN низько (скид). При відпусканні EN чип стартує; якщо
        # в цей момент GPIO0 низько (DTR=True) — у завантажувач.
        стан = bool(стан)
        if self.rts and not стан:
            self.у_завантажувачі = self.dtr
            if not self.у_завантажувачі:
                self.перезавантажень += 1
            self._вхід = b""
        self.rts = стан

    def write(self, дані):
        self._вхід += bytes(дані)
        self._обробити()

    def read(self, n, таймаут):
        if not self._вихід:
            if self.затримка:
                time.sleep(min(self.затримка, таймаут))
            return b""
        дані, self._вихід = self._вихід[:n], self._вихід[n:]
        return дані

    def close(self):
        pass

    # ---- завантажувач ----

    def _обробити(self):
        while True:
            поч = self._вхід.find(b"\xC0")
            if поч < 0:
                return
            кін = self._вхід.find(b"\xC0", поч + 1)
            if кін < 0:
                return
            кадр = self._вхід[поч + 1:кін]
            self._вхід = self._вхід[кін + 1:]
            if not кадр:
                continue
            self._команда(п.slip_розкодувати(кадр))

    def _відповісти(self, команда, значення=0, дані=b"", статус=0, помилка=0):
        тіло = дані + bytes([статус, помилка, 0, 0])
        self._вихід += п.slip_закодувати(struct.pack("<BBHI", п.НАПРЯМ_ВІДПОВІДЬ, команда, len(тіло), значення) + тіло)

    def _команда(self, пакет):
        if not self.у_завантажувачі:
            return                                    # програма користувача, а не ROM — мовчить
        напрям, команда, довжина, сума = struct.unpack("<BBHI", пакет[:8])
        дані = пакет[8:8 + довжина]
        назва = {v: k for k, v in п.CMD.items()}.get(команда, f"0x{команда:02X}")
        self.журнал.append(назва)
        if self.збій == "таймаут":
            return
        if self.збій == "обрив" and self._блоків_записано >= self.обрив_після and назва == "FLASH_DATA":
            return
        if назва == "SYNC":
            for _ in range(8):                       # ROM відповідає на SYNC кілька разів
                self._відповісти(команда)
        elif назва == "READ_REG":
            (адреса,) = struct.unpack("<I", дані)
            self._відповісти(команда, значення=self.регістри.get(адреса, 0))
        elif назва == "WRITE_REG":
            адреса, значення, маска, _ = struct.unpack("<IIII", дані)
            self.регістри[адреса] = (self.регістри.get(адреса, 0) & ~маска) | (значення & маска)
            if адреса == п.SPI_CMD and значення & п.SPI_CMD_USR:
                # виконати SPI-команду з USR2: RDID -> W0 = flash id
                if self.регістри.get(п.SPI_USR2, 0) & 0xFF == 0x9F:
                    self.регістри[п.SPI_W0] = ФЛЕШ_ID_4МБ
                self.регістри[п.SPI_CMD] &= ~п.SPI_CMD_USR
            self._відповісти(команда)
        elif назва in ("SPI_ATTACH", "SPI_SET_PARAMS"):
            self._відповісти(команда)
        elif назва == "FLASH_BEGIN":
            стерти, блоків, розмір_блоку, зсув = struct.unpack("<IIII", дані[:16])
            if розмір_блоку != п.БЛОК:
                return self._відповісти(команда, статус=1, помилка=0x05)
            time.sleep(min(self.затримка, 0.05))
            self.стерто = стерти
            for з in list(self.флеш):
                if зсув <= з < зсув + стерти:
                    del self.флеш[з]
            self._блоків_очікується, self._блоків_записано, self._зсув = блоків, 0, зсув
            self._відповісти(команда)
        elif назва == "FLASH_DATA":
            розмір, номер, _, _ = struct.unpack("<IIII", дані[:16])
            блок = дані[16:16 + розмір]
            if self.збій == "контрольна_сума" and not self._збій_суми_спрацював:
                self._збій_суми_спрацював = True
                return self._відповісти(команда, статус=1, помилка=0x07)
            if сума != п.контрольна_сума(блок) or розмір != len(блок):
                return self._відповісти(команда, статус=1, помилка=0x07)
            if номер != self._блоків_записано or номер >= self._блоків_очікується:
                return self._відповісти(команда, статус=1, помилка=0x05)
            self.флеш[self._зсув + номер * п.БЛОК] = блок
            self._блоків_записано += 1
            if self.затримка:
                time.sleep(min(self.затримка, 0.01))
            self._відповісти(команда)
        elif назва == "FLASH_END":
            (прапорець,) = struct.unpack("<I", дані[:4])
            if self._блоків_записано != self._блоків_очікується:
                return self._відповісти(команда, статус=1, помилка=0x06)
            self._відповісти(команда)
            if прапорець == 0:
                self.у_завантажувачі = False
                self.перезавантажень += 1
        else:
            self._відповісти(команда, статус=1, помилка=0x05)

    # ---- для тестів ----

    def образ(self, зсув=0):
        """Зібрати записаний флеш від зсуву як bytes (без хвостових 0xFF-блоків)."""
        ключі = sorted(з for з in self.флеш if з >= зсув)
        return b"".join(self.флеш[з] for з in ключі)
