"""Робота з файлами з програми мовою «Мова»: прочитай_файл / запиши_файл /
допиши_файл / є_файл.

Відносні шляхи рахуються від «теки файлів» ВМ (`ВМ(тека_файлів=...)`):
для `мова.py програма.мова` це тека самої програми, у Android-застосунку —
`user_data_dir` (єдине місце, куди APK гарантовано може писати), у REPL —
поточна робоча тека. Абсолютні шляхи використовуються як є.

Усі збої (файл не знайдено, немає прав, не текст) — ПомилкаВиконання, тож
їх можна перехопити блоком «спробуй».
"""

from pathlib import Path

from .errors import ПомилкаВиконання


def шлях(імя, тека=None):
    if not isinstance(імя, str) or not імя:
        raise ПомилкаВиконання("Ім'я файлу має бути непорожнім рядком.")
    p = Path(імя)
    if not p.is_absolute():
        p = Path(тека) / p if тека else Path.cwd() / p
    return p


def прочитай_файл(імя, тека=None):
    p = шлях(імя, тека)
    try:
        return p.read_text(encoding="utf-8")
    except FileNotFoundError:
        raise ПомилкаВиконання(f"Файл «{імя}» не знайдено.")
    except IsADirectoryError:
        raise ПомилкаВиконання(f"«{імя}» — це тека, а не файл.")
    except UnicodeDecodeError:
        raise ПомилкаВиконання(f"Файл «{імя}» — не текст у кодуванні UTF-8.")
    except OSError as e:
        raise ПомилкаВиконання(f"Не вдалося прочитати файл «{імя}»: {e.strerror or e}.")


def _записати(імя, текст, тека, режим):
    if not isinstance(текст, str):
        raise ПомилкаВиконання("У файл можна записати лише рядок.")
    p = шлях(імя, тека)
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, режим, encoding="utf-8") as f:
            f.write(текст)
    except IsADirectoryError:
        raise ПомилкаВиконання(f"«{імя}» — це тека, а не файл.")
    except OSError as e:
        raise ПомилкаВиконання(f"Не вдалося записати у файл «{імя}»: {e.strerror or e}.")
    return None


def запиши_файл(імя, текст, тека=None):
    """Створити/перезаписати файл рядком `текст`."""
    return _записати(імя, текст, тека, "w")


def допиши_файл(імя, текст, тека=None):
    """Дописати `текст` у кінець файлу (створити, якщо його немає)."""
    return _записати(імя, текст, тека, "a")


def є_файл(імя, тека=None):
    return шлях(імя, тека).is_file()


def рядки_файлу(імя, тека=None):
    """Список рядків файлу без символів кінця рядка."""
    return прочитай_файл(імя, тека).splitlines()


def файли_в_теці(імя=".", тека=None):
    """Відсортований список імен файлів і тек у теці (типово — тека
    застосунку/програми)."""
    p = шлях(імя, тека)
    if not p.is_dir():
        raise ПомилкаВиконання(f"Теку «{імя}» не знайдено.")
    try:
        return sorted(е.name for е in p.iterdir())
    except OSError as e:
        raise ПомилкаВиконання(f"Не вдалося прочитати теку «{імя}»: {e.strerror or e}.")


def видали_файл(імя, тека=None):
    p = шлях(імя, тека)
    if p.is_dir():
        raise ПомилкаВиконання(f"«{імя}» — це тека, а не файл; «видали_файл» тек не видаляє.")
    try:
        p.unlink()
    except FileNotFoundError:
        raise ПомилкаВиконання(f"Файл «{імя}» не знайдено.")
    except OSError as e:
        raise ПомилкаВиконання(f"Не вдалося видалити файл «{імя}»: {e.strerror or e}.")
    return None
