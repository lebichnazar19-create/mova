"""Міст до локальної мовної моделі (ollama / llama.cpp).

Модель не бере участі в розробці мови — вона є вбудованою функцією самої
мови (`спитай`, `переклади`, `стисни`), щоб програми могли працювати з
текстом офлайн. Єдине місце, яке знає про модель.
"""

import os
import shutil
import subprocess

from .errors import ПомилкаВиконання

ТАЙМАУТ_СЕК = 120
ЗМІННА_МОДЕЛІ = "МОВА_МОДЕЛЬ"

_СИМУЛЯЦІЯ = False


def увімкнути_симуляцію(увімкнено=True):
    global _СИМУЛЯЦІЯ
    _СИМУЛЯЦІЯ = увімкнено


def _рушій():
    if shutil.which("ollama"):
        return "ollama"
    if shutil.which("llama-cli"):
        return "llama-cli"
    if shutil.which("llama.cpp"):
        return "llama.cpp"
    return None


def _помилка_недоступності():
    return ПомилкаВиконання(
        "Локальна модель недоступна. Встанови ollama (`pkg install ollama` "
        "або з офіційного скрипта) чи llama.cpp/llama-cli, і переконайся, "
        "що модель завантажена. Назву моделі можна задати через змінну "
        f"середовища {ЗМІННА_МОДЕЛІ}."
    )


def _модель_ollama():
    назва = os.environ.get(ЗМІННА_МОДЕЛІ)
    if назва:
        return назва
    try:
        результат = subprocess.run(
            ["ollama", "list"], capture_output=True, text=True, timeout=10
        )
    except (subprocess.TimeoutExpired, OSError) as e:
        raise ПомилкаВиконання(f"Не вдалося отримати список моделей ollama: {e}")
    рядки = [р for р in результат.stdout.splitlines()[1:] if р.strip()]
    if not рядки:
        raise ПомилкаВиконання(
            f"У ollama немає жодної моделі. Завантаж модель (`ollama pull "
            f"<назва>`) або вкажи {ЗМІННА_МОДЕЛІ}."
        )
    return рядки[0].split()[0]


def _запит(промпт, системна_роль=None):
    if _СИМУЛЯЦІЯ:
        return f"[симуляція моделі] відповідь на: {промпт[:60]}"

    рушій = _рушій()
    if рушій is None:
        raise _помилка_недоступності()

    повний_промпт = f"{системна_роль}\n\n{промпт}" if системна_роль else промпт

    if рушій == "ollama":
        модель = _модель_ollama()
        команда = ["ollama", "run", модель, повний_промпт]
    else:
        модель = os.environ.get(ЗМІННА_МОДЕЛІ)
        if not модель:
            raise ПомилкаВиконання(
                f"Для llama.cpp потрібно вказати шлях до моделі через {ЗМІННА_МОДЕЛІ}."
            )
        команда = [рушій, "-m", модель, "-p", повний_промпт, "--no-display-prompt"]

    try:
        результат = subprocess.run(
            команда, capture_output=True, text=True, timeout=ТАЙМАУТ_СЕК
        )
    except subprocess.TimeoutExpired:
        raise ПомилкаВиконання(
            f"Локальна модель не відповіла за {ТАЙМАУТ_СЕК} секунд (таймаут)."
        )
    except OSError as e:
        raise ПомилкаВиконання(f"Не вдалося запустити модель: {e}")

    if результат.returncode != 0:
        повідомлення = (результат.stderr or "").strip()
        raise ПомилкаВиконання(
            "Помилка локальної моделі" + (f": {повідомлення}" if повідомлення else ".")
        )
    return результат.stdout.strip()


# ---- функції мови ------------------------------------------------------------

def спитай(текст, роль=None):
    return _запит(str(текст), str(роль) if роль is not None else None)


def переклади(текст, мова):
    промпт = f"Переклади цей текст на {мова}, виведи лише переклад без пояснень:\n{текст}"
    return _запит(промпт)


def стисни(текст):
    промпт = f"Стисло перекажи наступний текст у 2-3 реченнях українською:\n{текст}"
    return _запит(промпт)
